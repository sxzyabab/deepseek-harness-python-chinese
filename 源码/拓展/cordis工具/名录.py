def 查询事件目录(名=None,事件表=None):
    """把事件目录投影为压缩目录或一份精确监听契约。"""
    if 事件表 is None:
        事件表=事件目录
    if 名 is None:
        return {
            'mode':'catalog',
            'events':[{
                'name':事件项['name'],
                'description':事件项['summary'],
                'mode':事件项['mode'],
                'signature':事件项['signature'],
            } for 事件项 in 事件表],
        }
    事件项=None
    for 候选 in 事件表:
        if 候选['name']==名:
            事件项=候选
            break
    if 事件项 is None:
        raise 巡检错误('没有名为 "'+名+'" 的已编目事件')
    return {
        'mode':'event',
        'event':{
            'name':事件项['name'],
            'description':事件项['description'],
            'mode':事件项['mode'],
            'signature':事件项['signature'],
            'parameters':事件项['parameters'],
        },
        'referencedTypes':引用类型闭包([事件项['signature']]),
    }

