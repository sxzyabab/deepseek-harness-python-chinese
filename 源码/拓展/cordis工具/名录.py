def 引用类型闭包(种子):
    """从签名种子收集被引用类型及其传递闭包。"""
    已含=set()
    前沿=list(种子)
    while len(前沿)>0:
        下一=[]
        for 条目 in 类型目录:
            if 条目['name'] in 已含:
                continue
            形态=类型名形态[条目['name']]
            命中=False
            for 文本 in 前沿:
                if 形态.search(文本) is not None:
                    命中=True
                    break
            if not 命中:
                continue
            已含.add(条目['name'])
            下一.append(条目['declaration'])
        前沿=下一
    return [条目 for 条目 in 类型目录 if 条目['name'] in 已含]

