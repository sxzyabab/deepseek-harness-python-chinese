def 方法(签名,说明,参数表=None,返回=None,抛出=None):
    """组装一条公开方法契约。"""
    项={'signature':签名,'description':说明,'parameters':[] if 参数表 is None else 参数表}
    if 返回 is not None:
        项['returns']=返回
    if 抛出 is not None:
        项['throws']=抛出
    return 项

