"""进程本地动态插件注册表及其不透明身份铸造。

对齐上游 `拓展/cordis-host-runner/src/registry.ts`。公开面仅中文名。
"""

__all__=['动态插件注册表','动态Cordis注册表']#仅中文公开名

class 动态插件注册表:#动态插件注册表
    """注册表、身份铸造与待审批索引。"""
    def __init__(自身):#空注册表
        """初始化插件表与序号。"""
        自身.插件们={}#插件表
        自身.挂起请求={}#待审批
        自身.下一插件=1#插件序号
        自身.下一包=1#包序号
        自身.下一运行=1#运行序号
        自身.下一审批=1#审批序号

    def 铸造插件标识(自身,前缀):#铸造插件 id
        """铸造语义插件 id，不复用先前后缀。"""
        while True:#直到唯一
            标识=f'{前缀}-{自身.下一插件}'#前缀加序号
            自身.下一插件+=1#推进
            if 标识 not in 自身.插件们:#唯一
                return 标识#唯一 id

    def 铸造包标识(自身):#铸造包 id
        """铸造不可变包 id。"""
        标识=f'pkg-{自身.下一包}'#pkg- 加序号
        自身.下一包+=1#推进
        return 标识#包 id

    def 铸造运行标识(自身):#铸造运行 id
        """铸造激活 id。"""
        标识=f'run-{自身.下一运行}'#run- 加序号
        自身.下一运行+=1#推进
        return 标识#运行 id

    def 铸造审批标识(自身):#铸造审批 id
        """铸造审批 id。"""
        标识=f'approval-{自身.下一审批}'#approval- 加序号
        自身.下一审批+=1#推进
        return 标识#审批 id

    def 加入(自身,插件):#加入
        """按稳定 id 保留的插件记录。"""
        自身.插件们[插件['pluginId']]=插件#写入

    def 获取(自身,标识):#读取
        """按 id 取；缺席则为 None。"""
        return 自身.插件们.get(标识)#按 id 取

    def 删除(自身,标识):#删除
        """从表拿掉；是否移除了一条。"""
        return 自身.插件们.pop(标识,None) is not None#从表拿掉

    def 全部(自身):#全部
        """按创建顺序读全部插件。"""
        return list(自身.插件们.values())#按插入顺序

    def 按会话(自身,会话标识):#按会话
        """按创建顺序读某会话的插件。"""
        return [插件 for 插件 in 自身.全部() if 插件.get('sessionId')==会话标识]#过滤所属

    def 挂起(自身,标识,挂起项):#挂起请求
        """发布一条待审批。"""
        自身.挂起请求[标识]=挂起项#写入

    def 武装请求(自身,标识,挂起项):#武装挂起请求（运行器别名）
        """与挂起同义，对齐运行器用语。"""
        自身.挂起(标识,挂起项)#写入

    def 窥视请求(自身,标识):#窥视
        """读一条待审批但不认领。"""
        return 自身.挂起请求.get(标识)#按 id 取

    def 认领请求(自身,标识):#认领
        """认领一条待审批；先到的回答获胜。"""
        return 自身.挂起请求.pop(标识,None)#有则从表拿掉

    def 取消请求(自身,标识):#取消
        """取消一条待审批。"""
        自身.挂起请求.pop(标识,None)#从表拿掉

    def 插件挂起请求(自身,插件标识):#按插件找待审批
        """其审批请求 id；没有待处理则为 None。"""
        for 请求标识,请求 in 自身.挂起请求.items():#每条
            if 请求.get('pluginId')==插件标识:#命中
                return 请求标识#请求 id
        return None#没有

动态Cordis注册表=动态插件注册表#历史别名
DynamicCordisRegistry=动态插件注册表#上游名
