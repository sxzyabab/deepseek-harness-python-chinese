"""宿主半纤程生命周期：把沙箱产出的插件落成子纤程，并报告仍缺的服务。"""
from .门面规则 import 受护插件
from .类型 import 动态cordis错误

__all__=['启动宿主半','缺席服务列表']

def 启动宿主半(组,插件,报告守卫失败):
    """等待组就绪，启动并落定一个受守卫的子纤程；启动失败则先拆除再重抛。"""
    组.等待()
    纤程=组.所属上下文.启动插件(受护插件(插件,报告守卫失败))
    try:
        纤程.等待()
    except Exception as 错误:
        纤程.拆除()
        消息=str(错误)
        if 'already registered' in 消息 or '已经由' in 消息:
            raise 动态cordis错误(
                消息+' — 若要替换先前动态包已登记的内容，请先通过运行器或 Cordis 面板停止该包，再运行新版本。'
            )
        raise
    return 纤程

def 缺席服务列表(上下文,纤程):
    """声明了但此刻还不存在的服务名，按声明顺序。"""
    return [服务名 for 服务名 in 纤程.依赖表 if 上下文.获取服务(服务名,False) is None]
