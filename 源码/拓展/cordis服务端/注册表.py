"""进程本地动态插件注册表及其不透明身份铸造。"""

__all__=['动态cordis注册表']

class 动态cordis注册表:
    """注册表、身份铸造与待审批索引。插件记录是线协议 dict。"""
    def __init__(自身):
        """空表，序号从 1 起。"""
        自身._插件表={}
        自身._待处理请求={}
        自身._下一插件=1
        自身._下一包=1
        自身._下一运行=1
        自身._下一审批=1

    def 铸造插件标识(自身,前缀):
        """铸造语义插件标识，不复用先前后缀。"""
        while True:
            标识=f'{前缀}-{自身._下一插件}'
            自身._下一插件+=1
            if 标识 not in 自身._插件表:
                return 标识

    def 铸造包标识(自身):
        """铸造不可变包标识。"""
        标识=f'pkg-{自身._下一包}'
        自身._下一包+=1
        return 标识

    def 铸造运行标识(自身):
        """铸造激活标识。"""
        标识=f'run-{自身._下一运行}'
        自身._下一运行+=1
        return 标识

    def 铸造审批标识(自身):
        """铸造审批请求标识。"""
        标识=f'approval-{自身._下一审批}'
        自身._下一审批+=1
        return 标识

    def 加入(自身,插件):
        """按稳定标识加入一个插件。"""
        自身._插件表[插件['pluginId']]=插件

    def 获取(自身,标识):
        """读一个插件；缺席则为 None。"""
        if 标识 not in 自身._插件表:
            return None
        return 自身._插件表[标识]

    def 删除(自身,标识):
        """删除一个插件及其全部包版本，返回是否移除了记录。"""
        if 标识 not in 自身._插件表:
            return False
        del 自身._插件表[标识]
        return True

    def 全部(自身):
        """按创建顺序读全部插件。"""
        return list(自身._插件表.values())

    def 会话下(自身,会话标识):
        """按创建顺序读某会话的插件。"""
        return [插件 for 插件 in 自身.全部() if 插件['sessionId']==会话标识]

    def 武装请求(自身,标识,待处理):
        """发布一条待审批。"""
        自身._待处理请求[标识]=待处理

    def 窥视请求(自身,标识):
        """读一条待审批但不认领；缺席则为 None。"""
        if 标识 not in 自身._待处理请求:
            return None
        return 自身._待处理请求[标识]

    def 认领请求(自身,标识):
        """认领一条待审批；先到的回答获胜。已落定则 None。"""
        if 标识 not in 自身._待处理请求:
            return None
        待处理=自身._待处理请求[标识]
        del 自身._待处理请求[标识]
        return 待处理

    def 卸下请求(自身,标识):
        """取消一条待审批。"""
        if 标识 in 自身._待处理请求:
            del 自身._待处理请求[标识]

    def 待决请求(自身,插件标识):
        """查找某插件的待审批标识；没有则为 None。"""
        for 请求标识,请求 in 自身._待处理请求.items():
            if 请求['pluginId']==插件标识:
                return 请求标识
        return None
