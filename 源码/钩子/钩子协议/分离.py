    '在飞登记；接线方式见模块文档'
    def __init__(自身):
        '创建空登记与中止控制器'
        自身._在飞=set()#在飞的运行链
        自身._控制器=中止控制器()#排空时中止仍在跑的钩子
        自身.信号=自身._控制器.信号#交给执行钩子的中止信号

    def 登记(自身,运行):
        '登记一条分离运行直到落地。传入整条链——钩子运行及其后续。运行是期约；拒绝也算落地，拒绝的处理仍归调用方'
        自身._在飞.add(运行)#记入在飞集合
        def 落地(落定值=None):
            '运行结算（成败都算）后清登记'
            自身._在飞.discard(运行)#剔除
        运行.然后(落地,落地)#结算后清登记

    def 排空(自身):
        '中止信号，然后等到每条已跟踪链都落地——包括排空进行中新登记的链。返回期约，兑现于登记表被观察到为空'
        自身._控制器.中止(钩子协议错误('钩子桥已拆除'))#拆桥时杀掉仍在执行的钩子
