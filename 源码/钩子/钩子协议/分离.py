        def 再看一波(落定值=None):
            '上一波结算后，登记表还有就再等一波，空了才完成'
            if len(自身._在飞)==0:#登记表已空
                排空完成.解决(None)#完成
                return#结束
            快照=list(自身._在飞)#当前快照
            def 这一波落地(波值=None):
                '这一波都结算后剔除它们并再看一次'
                for 链 in 快照:#逐条剔除
                    自身._在飞.discard(链)#剔除
                再看一波()#再看
            期约.全部已结算(快照).然后(这一波落地)#等这一波全部结算
        再看一波()#开始
        return 排空完成#期约

