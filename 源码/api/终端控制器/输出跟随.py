'一条远程流代际的有界输出队列'
from threading import Condition as 条件变量#队列与唤醒
from threading import RLock as 可重入锁#推入时可以再关掉
from collections import deque#有界帧队列
from ...基础设施.通用工具 import 启动守护线程,紧凑json编码,utf8字节数#守护线程与帧字节
from ..网关.流协议 import 已中止#取消
from ...客户端.连接.rpc import 中止信号,中止控制器#取消

__all__=['终端跟随']#仅这一类


class 终端跟随:
    '过慢的跟随者明确失败。稍后附着从屏幕恢复'
    def __init__(自身,最大字节):
        '记下这一路跟随者的排队上限'
        自身._最大字节=最大字节#上限
        自身._队列=deque()#有序帧
        自身._条件=条件变量(可重入锁())#等待与互斥
        自身._字节=0#已排队字节
        自身._已关=False#已停止
        自身._已结束=False#最后一帧已入队
        自身._失败=None#交给读者的错误

    @property
    def 仍活动(自身):
        '这条附着是否还接受输入和输出'
        开着=not 自身._已关#还没关
        未完=not 自身._已结束#还没交完
        return 开着 and 未完#两者都要

    def 推入(自身,帧):
        '排队一帧。超过字节上限则让这一路失败'
        with 自身._条件:#与读者互斥
            if 自身._已关 or 自身._已结束:#已经停了
                return#丢掉这一帧
            字节=utf8字节数(紧凑json编码(帧))#这一帧的 UTF-8
            if 自身._字节+字节>自身._最大字节:#超限
                自身.失败(RuntimeError('Terminal output consumer exceeded its buffer; reconnect to recover the current screen'))#明确失败
                return#不再排队
            自身._队列.append({'frame':帧,'bytes':字节})#入队
            自身._字节+=字节#累加
            自身._条件.notify_all()#唤醒读者

    def 失败(自身,错误):
        '这条附着失败，终端本身不停。结束后的失败忽略'
        with 自身._条件:#与读者互斥
            if 自身._已关 or 自身._已结束:#已经不活动
                return#忽略
            自身._失败=错误#留给读者
            自身._已关=True#停止
            自身._队列.clear()#丢掉未读
            自身._字节=0#清零
            自身._条件.notify_all()#唤醒读者

    def 完结(自身):
        '交完已排队的帧再结束，包括最后的退出状态'
        with 自身._条件:#与读者互斥
            自身._已结束=True#标记结束
            自身._条件.notify_all()#唤醒读者

    def 关闭(自身):
        '停掉这一路跟随，不停终端'
        with 自身._条件:#与读者互斥
            自身._已关=True#停止
            自身._队列.clear()#丢掉未读
            自身._字节=0#清零
            自身._条件.notify_all()#唤醒读者

    def 读取(自身,信号):
        '排出有序帧，直到拆开或失败'
        停止=中止控制器()#读取结束时解开等待
        融合=中止信号.任一([信号,停止.信号])#取消或读取结束

        def 听到取消():
            '调用方取消则关掉这一路'
            融合._事件.wait()#阻塞到融合信号
            if 已中止(信号):#是调用方取消
                自身.关闭()#停读

        启动守护线程(听到取消)#听取消
        if 已中止(信号):#进来时已经取消
            自身.关闭()#停读
        try:#读到关或失败
            while not 自身._已关:#还开着
                with 自身._条件:#等下一帧
                    while len(自身._队列)==0 and not 自身._已关 and not 自身._已结束:#队列空且未结束
                        自身._条件.wait()#等推入、结束或关闭
                    if 自身._已关:#被关掉
                        break#停止
                    if len(自身._队列)==0 and 自身._已结束:#已交完
                        break#停止
                    下一项=自身._队列.popleft()#取出
                    自身._字节-=下一项['bytes']#减掉字节
                yield 下一项['frame']#交给附着
            if 自身._失败 is not None:#有失败
                raise 自身._失败#报告给消费者
        finally:#无论读者是否走完
            停止.中止配套信号()#让监听线程退出
            自身.关闭()#保证队列被清掉
