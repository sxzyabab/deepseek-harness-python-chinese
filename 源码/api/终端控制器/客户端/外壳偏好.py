__all__=['首选外壳','记住外壳']#仅中文公开名

外壳键='dsh.terminal.shell'#站点偏好键
本地存储=None#无浏览器存储

def 首选外壳():#读上次选择
    """没有存储则空。"""
    if 本地存储 is None:#不可用
        return None#空
    return 本地存储.get(外壳键)#路径

def 记住外壳(路径):#记下已验证路径
    """存储失败不影响本次启动。"""
    if 本地存储 is None:#不可用
        return#跳
    本地存储[外壳键]=路径#写下
