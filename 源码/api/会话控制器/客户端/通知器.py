'微任务／帧批处理的结构更新通知器'
import threading#微任务近似
from ....基础设施.通用工具 import 观察者集合

__all__=['通知器']#仅中文公开名

class 通知器:
    '在微任务中批处理结构更新；读取可在不消费待定通知时重建脏快照'

    def __init__(自身,重建):
        '保存所有者依赖的快照重建函数'
        自身._重建=重建#重建器
        自身._监听者=观察者集合()#订阅者
        自身._脏=False#快照是否脏
        自身._待通知=False#是否有待通知
        自身._已调度=None#none|microtask|frame
        自身._调度代=0#调度代
        自身._锁=threading.Lock()#调度锁

    def 订阅(自身,监听者):
        '登记变更回调，返回取消函数'
        return 自身._监听者.订阅(监听者)#取消

    def 标脏(自身):
        '标记快照脏并在微任务中通知'
        自身._脏=True#置脏
        自身._待通知=True#待通知
        if 自身._已调度=='microtask':#已调度
            return#合并
        自身._调度('microtask')#调度

    def 标帧脏(自身):
        '标记快照脏，并至多每帧发布一次。无 rAF 时等同微任务'
        自身._脏=True#置脏
        自身._待通知=True#待通知
        if 自身._已调度 is not None:#已有调度
            return#合并
        自身._调度('microtask')#无 DOM 帧则微任务

    def 立即通知(自身):
        '同步刷新：与写入同 tick 通知'
        自身._脏=True#置脏
        自身._待通知=True#待通知
        自身._作废调度()#作废
        自身._冲刷()#立即派发

    def 确保新鲜(自身):
        'getSnapshot 前：脏时同步重建，通知保持待定'
        if not 自身._脏:#不脏
            return#跳过
        自身._脏=False#清脏
        自身._重建()#重建

    def _调度(自身,种类):
        '调度发布'
        with 自身._锁:#锁
            自身._调度代+=1#本代
            代=自身._调度代#记下
            自身._已调度=种类#种类
        def 发布():
            '发布回调'
            with 自身._锁:#锁
                if 代!=自身._调度代:#已作废
                    return#停
                自身._已调度=None#清除
            自身._冲刷()#派发
        定时器=threading.Timer(0,发布)#近似微任务
        定时器.daemon=True#守护
        定时器.start()

    def _作废调度(自身):
        '作废已调度'
        with 自身._锁:#锁
            自身._调度代+=1#升代
            自身._已调度=None#清除

    def _冲刷(自身):
        '派发通知'
        if not 自身._待通知:#无待办
            return#停
        if len(自身._监听者)==0:#无人观察
            return#懒：脏留给下次 getSnapshot
        自身._待通知=False#清除
        if 自身._脏:#需重建
            自身._脏=False#清脏
            自身._重建()#重建
        自身._监听者.通知()#通知
