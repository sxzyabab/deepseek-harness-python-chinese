"""对齐会话历史记录的客户端范围访问。"""
__all__=['历史条目','历史记录首序号','历史记录末序号']#仅中文公开名

def 历史条目(记录列表):
    """把对齐线上记录收窄为其客户端事件条目。"""
    return list(记录列表)#同构列表

def 历史记录首序号(记录):
    """读取一条线上记录所代表的首个逻辑序号。记录为 dict。"""
    return 记录['event']['seq']#首序号

def 历史记录末序号(记录):
    """读取一条线上记录所代表的最终逻辑序号。记录为 dict。"""
    return 记录['event']['seq']#末序号
