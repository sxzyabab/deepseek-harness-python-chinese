"""合并权威基线，不移动客户端已可见的身份。"""
__all__=['合并有序基线']#仅中文公开名

def 合并有序基线(当前,基线,取键):
    """合并有序基线。

    仅出现在基线中的身份相对最近的后续已知身份插入；基线中缺席的身份被移除。
    当前／基线为序列；取键为 (值) -> 稳定身份。
    """
    基线按键={}#按键索引基线
    for 值 in 基线:#填充
        基线按键[取键(值)]=值#写入
    已合并=[]#结果
    for 值 in 当前:#保留当前顺序中仍在基线的项
        键=取键(值)#键
        if 键 in 基线按键:#仍在
            已合并.append(基线按键[键])#收下基线值
    已合并键=set(取键(值) for 值 in 已合并)#已合并键集
    for 下标,值 in enumerate(基线):#插入仅基线有的项
        键=取键(值)#键
        if 键 in 已合并键:#已有
            continue#跳过
        插入点=len(已合并)#默认末尾
        for 后续 in range(下标+1,len(基线)):#找后续已知锚点
            候选=基线[后续]#候选
            候选键=取键(候选)#键
            for 已知下标,项 in enumerate(已合并):#已合并中找
                if 取键(项)==候选键:#锚点
                    插入点=已知下标#插到锚点前
                    break#停内层
            else:#未找到继续
                continue#下一后续
            break#找到锚点
        已合并.insert(插入点,值)#插入
        已合并键.add(键)#记入
    return 已合并#合并结果
