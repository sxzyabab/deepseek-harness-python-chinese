class 跟随者:
    '一个跟随者的有序通知，由消费方拉取'
    def __init__(自身,离开):
        '记下注销回调'
        自身._离开=离开#注销
        自身._待发=[]#尚未拉取的通知
        自身._条件=threading.Condition()#队列
        自身._已结束=False#不再有新通知
        自身._宿主键=None#绑定后的绝对路径
        自身._就绪事件=threading.Event()#宿主是否确认
        自身._就绪值=False#确认成功还是提前结束
        自身._就绪锁=threading.Lock()#只结算一次就绪

    def 绑定(自身,绝对路径):
        '选定排队和以后变更所用的宿主路径'
        自身._宿主键=路径转正斜杠(绝对路径)#统一斜杠

    def 启动(自身):
        '宿主已经确认订阅'
        with 自身._就绪锁:#只写一次
            if 自身._就绪事件.is_set():#已经结算
                return#保持第一次
            自身._就绪值=True#确认
            自身._就绪事件.set()#放行

    def 推入(自身,通知,键):
        '排队一则通知。键是归一后的宿主路径'
        with 自身._条件:#与拉取互斥
            自身._待发.append({'key':键,'notice':通知})#入队
            自身._条件.notify()#唤醒

    def 结束(自身):
        '先交完已经排队的，然后结束。就绪若还没结算则是假'
        with 自身._条件:#结束旗
            自身._已结束=True#标记
            自身._条件.notify()#唤醒
        with 自身._就绪锁:#就绪
            if not 自身._就绪事件.is_set():#还没确认
                自身._就绪值=False#提前结束
                自身._就绪事件.set()#放行

    def 拆除(自身):
        '即使消费方还没开始拉取也注销'
        自身._离开()#离开

    def 就绪(自身):
        '阻塞到宿主确认，或本跟随者在确认前结束'
        自身._就绪事件.wait()#等结算
        return 自身._就绪值#真或假

    def __iter__(自身):
        '按顺序产出通知。刷新、尚未绑定、或路径相同才交出'
        try:#结束时也要注销
            while True:#直到结束且队列空
                with 自身._条件:#取一条
                    while len(自身._待发)==0 and not 自身._已结束:#还可能有
                        自身._条件.wait()#等
                    if len(自身._待发)==0:#结束且空
                        return#停
                    下一条=自身._待发.pop(0)#取头
                通知=下一条['notice']#通知
                if 通知['kind']=='refresh' or 自身._宿主键 is None or 下一条['key']==自身._宿主键:#要交
                    yield 通知#交给消费方
        finally:#break 或返回都注销
            自身.拆除()#离开


class 会话供给:
    '一个会话加一条请求路径的流和跟随者'
    def __init__(自身,远程,会话标识,路径,前任,关闭后):
        '建好监督流，泵要等调用方把它放进活表后再启动'
        自身._远程=远程#远程面
        自身._会话标识=会话标识#诊断名和宿主调用
        自身._路径=路径#交给宿主的路径
        自身._前任=前任#还在关闭的前一条
        自身._关闭后=关闭后#流没了时通知
        自身._跟随者集合=set()#跟随者
        自身._锁=threading.Lock()#跟随者集合和启动旗
        自身._已关闭=False#已经拆除
        自身._已启动=False#收到过 ready
        自身._已确认=False#不是第一条 ready
        自身._泵完=threading.Event()#消费线程结束
        自身._流=远程.打开逻辑流({#监督流
            'name':'workspace file changes of '+str(会话标识),#诊断名
            'open':自身._打开,#开一代
            'ended':自身._已结束,#正常结束
        })#流

    def 启动泵(自身):
        '活表已经记下这一条之后再开始消费'
        启动守护线程(自身._跑)#后台

    def _打开(自身,信号):
        '前任关闭后再向宿主打开这一路径'
        with 自身._锁:#新一代还没 ready
            自身._已启动=False#等这一代的 ready
        if 自身._前任 is not None:#有前任
            自身._前任.wait()#等它卸完
        yield from 自身._远程.workspaceFiles.changes(自身._会话标识,自身._路径,信号)#宿主帧

    def _已结束(自身,已接受):
        '宿主正常关掉这条流。开口前和开口后都不再重开，文案不看已接受'
        if 已接受:#曾经交付过帧
            return Exception('workspace file changes of '+str(自身._会话标识)+' ended')#终态
        return Exception('workspace file changes of '+str(自身._会话标识)+' ended')#终态

    def 加入(自身,跟随者):
        '宿主路径还不知道时就登记'
        with 自身._锁:#登记
            自身._跟随者集合.add(跟随者)#登记
            已启动=自身._已启动#是否已经 ready
        if 已启动:#已经 ready
            跟随者.启动()#立刻就绪

    def 移除(自身,跟随者):
        '注销。最后一个离开就拆掉流'
        with 自身._锁:#摘掉
            自身._跟随者集合.discard(跟随者)#移除
            空了=len(自身._跟随者集合)==0#是否最后一个
        if 空了:#空了
            自身.关闭()#拆流

    def _跑(自身):
        '消费完再标记泵结束'
        try:#泵
            自身._泵()#读帧
        finally:#无论成败
            自身._泵完.set()#后继可以开

    def _泵(自身):
        '把 ready 和 change 分给跟随者。终态失败安静结束'
        try:#读监督流
            for 项 in 自身._流:#逐项
                帧=项.value#宿主帧
                if 帧['kind']=='ready':#就绪
                    项.accept()#这一代健康
                    with 自身._锁:#启动旗和跟随者快照
                        自身._已启动=True#已启动
                        跟随者列表=list(自身._跟随者集合)#当前跟随者
                        要刷新=自身._已确认#重连后的又一次 ready
                        自身._已确认=True#下一次 ready 才刷新
                    for 跟随者 in 跟随者列表:#逐个
                        跟随者.启动()#确认
                        if 要刷新:#不是第一条 ready
                            跟随者.推入({'kind':'refresh'},'')#要求重新 stat
                elif 帧['kind']=='change':#变更
                    键=路径转正斜杠(帧['change']['absolutePath'])#归一路径
                    if 'absent' in 帧['change']:#缺失
                        通知={'kind':'absent'}#没有版本
                    else:#仍在
                        通知={'kind':'changed','version':帧['change']['version']}#版本
                    with 自身._锁:#快照
                        跟随者列表=list(自身._跟随者集合)#当前跟随者
                    for 跟随者 in 跟随者列表:#扇出
                        跟随者.推入(通知,键)#排队
                else:#不认识的帧
                    raise Exception('Unexpected workspace file watch frame: '+json.dumps(帧,ensure_ascii=False,separators=(',',':')))#终态
        except BaseException:#终态失败或宿主结束
            pass#跟随者安静结束，元数据停在最后已知
        finally:#一定拆除
            自身.关闭()#结束跟随者

    def 关闭(自身):
        '拆掉流并结束跟随者。重复调用是空操作'
        with 自身._锁:#只关一次
            if 自身._已关闭:#已关
                return#停
            自身._已关闭=True#标记
            跟随者列表=list(自身._跟随者集合)#当前跟随者
            自身._跟随者集合.clear()#清空
        自身._流.dispose()#停监督流
        for 跟随者 in 跟随者列表:#结束
            跟随者.结束()#交完队列
        自身._关闭后(自身._泵完)#等泵线程结束


class 变更供给:
    '按会话和路径共享宿主工作区文件变更流'
    def __init__(自身,远程):
        '记下远程面'
        自身._远程=远程#带 打开逻辑流 和 workspaceFiles
        自身._会话表={}#活着的供给
        自身._关闭中={}#还在关闭的泵

    def 跟随(自身,会话标识,路径,信号):
        '调用时就登记，不是等到第一次拉取。先等就绪为真，再绑定 stat 的绝对路径'
        if 信号.aborted:#已经取消
            供给=None#不开流
        else:#还活着
            供给=自身._供给于(会话标识,路径)#取或建
        盒={'已离开':False}#离开只跑一次

        def 离开():
            '结束通知并从供给摘掉'
            if 盒['已离开']:#已经离开
                return#一次
            盒['已离开']=True#标记
            盒['跟随者'].结束()#不再等
            if 供给 is not None:#有供给
                供给.移除(盒['跟随者'])#可能拆流

        跟随者对象=跟随者(离开)#新建
        盒['跟随者']=跟随者对象#回填
        if 供给 is None:#已经取消
            跟随者对象.结束()#就绪为假
            return 跟随者对象#空订阅
        供给.加入(跟随者对象)#登记

        def 盯中止():
            '信号置位后离开'
            信号.wait()#流信号是 Event
            离开()#注销

        启动守护线程(盯中止)#不等待
        return 跟随者对象#订阅

    def 结算(自身):
        '等到仍在关闭的流都结束'
        for 完成 in list(自身._关闭中.values()):#当前这一批
            完成.wait()#等

    def _供给于(自身,会话标识,路径):
        '取或建这一会话和路径的供给'
        键=json.dumps([会话标识,路径],ensure_ascii=False,separators=(',',':'))#同一目标同一条
        已有=自身._会话表.get(键)#活着的
        if 已有 is not None:#还在
            return 已有#共享
        前任=自身._关闭中.get(键)#可能还在关

        def 关闭后(泵完):
            '从活表摘掉，后继要等泵结束'
            自身._会话表.pop(键,None)#摘掉
            追踪=threading.Event()#后继等这个

            def 收尾():
                '泵结束就结清。还是自己才从关闭表删除'
                泵完.wait()#等消费线程
                if 自身._关闭中.get(键) is 追踪:#没有被后继覆盖
                    自身._关闭中.pop(键,None)#摘掉
                追踪.set()#放行后继

            自身._关闭中[键]=追踪#先记下
            启动守护线程(收尾)#等泵

        供给=会话供给(自身._远程,会话标识,路径,前任,关闭后)#新建
        自身._会话表[键]=供给#先入表再泵，避免泵立刻关闭时表里还没有
        供给.启动泵()#开始消费
        return 供给#供给
