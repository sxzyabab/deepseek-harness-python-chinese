"""`changes` 流生产者：落在一代工作区根内的每次 `fs/observed` 成为一帧。

观察由工具在各自文件系统操作后发出，因此只覆盖 Agent 写入；操作系统不被监视。
每一代在产出任何排队或实时变更前，先以 `ready` 确认观察队列与已解析工作区根。
"""
import threading#唤醒
from ...工具.双端队列 import 双端队列#观察队列
from .类型 import 已中止,若已中止则抛出#中止查询

__all__=['工作区变更供给']#仅中文公开名


class 工作区变更供给:
    """拥有 `fs/observed` 订阅与每一个打开的 `changes` 代。"""

    def __init__(自身,上下文):
        """订阅观察；拆除时关闭全部代。"""
        自身._上下文=上下文#Cordis
        自身._跟随者集合=set()#活跃代
        def 观察(目标,观测,*_余):
            """转发到各代。目标与观测为跨包 dict。"""
            for 跟随者 in list(自身._跟随者集合):#快照
                跟随者.推((目标,观测))#入队
        def 拆除供给():
            """关闭全部代。"""
            for 跟随者 in list(自身._跟随者集合):#逐个
                跟随者.关()#关闭
            自身._跟随者集合.clear()#清空
        上下文.监听('fs/observed',观察)#订阅
        上下文.副作用(拆除供给,'workspace-files.changes')#拆除

    def 跟随(自身,工作区根,信号):
        """打开一代，报告 `工作区根` 内的观察。

        先登记再解析根，以免解析期间的观察丢失；根只在排空时过滤。
        产出 `ready`，随后按发射顺序产出变更帧。
        """
        若已中止则抛出(信号)#入口检查
        跟随者=_变更跟随者()#本代
        自身._跟随者集合.add(跟随者)#登记
        try:
            根=None#解析结果
            try:
                根=自身._上下文.fs.解析(工作区根,{'signal':信号})#解析根
            except BaseException:
                if 已中止(信号):#中止导致
                    return#静默结束
                raise#其他失败
            if 根 is None or 已中止(信号) or 跟随者.是否已关闭:#中途取消
                return
            yield {'kind':'ready'}#就绪
            for 目标,观测 in 跟随者.读(信号):#排空
                if not 自身._上下文.fs.包含(根,目标):#根外
                    continue#跳过
                绝对路径=自身._上下文.fs.进程路径(目标)#绝对路径
                if 观测['kind']=='present':#存在
                    变更={'absolutePath':绝对路径,'version':观测['version']}#带版本
                else:#缺失
                    变更={'absolutePath':绝对路径,'absent':True}#消失
                yield {'kind':'change','change':变更}#变更帧
        finally:
            自身._跟随者集合.discard(跟随者)#移除
            跟随者.关()#关闭


class _变更跟随者:
    """一代的观察队列：消费方拉取前观察在此等待。"""

    def __init__(自身):
        """空队列。"""
        自身._队列=双端队列()#观察
        自身._事件=threading.Event()#唤醒
        自身._已关闭=False#关闭

    @property
    def 是否已关闭(自身):
        """根解析期间是否已关闭。"""
        return 自身._已关闭#标志

    def 推(自身,观察):
        """入队并唤醒。观察为 (目标,观测) 元组。"""
        自身._队列.尾推(观察)#入队
        自身._事件.set()#唤醒

    def 关(自身):
        """结束本代。"""
        自身._已关闭=True#标记
        自身._事件.set()#唤醒

    def 读(自身,信号):
        """直到关闭或中止；仍排队者随代丢弃。"""
        while not 自身._已关闭:#未关
            if 已中止(信号):#取消
                自身.关()#关
                return#停
            观察=自身._队列.头弹()#取
            if 观察 is not None:#有
                yield 观察#产出
                continue#继续
            自身._事件.clear()#清
            if 自身._队列.大小>0 or 自身._已关闭 or 已中止(信号):#竞态
                continue#重试
            自身._事件.wait(0.05)#短等
