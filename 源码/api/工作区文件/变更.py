class 变更跟随者:
    '一代的观察队列。消费方拉取之前，观察停在这里'
    def __init__(自身,释放):
        '记下摘掉本代的回调，监视拆除函数等初始化之后才有'
        自身._释放=释放#摘掉跟随者
        自身.控制器=中止控制器()#本代中止
        自身.错误=None#监视回调报来的失败
        自身._队列=双端队列()#观察元组
        自身._条件=threading.Condition()#队列与关闭
        自身._已关闭=False#不再接收观察
        自身._初始化锁=threading.Lock()#只记下第一次拆除函数
        自身._已初始化=threading.Event()#监视结果已经知道
        自身._拆除监视=None#监视返回的关闭函数
        自身._关闭完成=None#关闭已经开始
        自身._关闭错误=None#卸监视或释放时的失败

    @property
    def 是否已关闭(自身):
        '这一代是否已经停止接收失效通知'
        return 自身._已关闭#关闭旗

    def 推入(自身,观察):
        '未关闭时入队并唤醒。观察是 (目标,) 或 (目标, 观测)'
        with 自身._条件:#与读取互斥
            if 自身._已关闭:#已停
                return#丢掉
            自身._队列.尾推(观察)#入队
            自身._条件.notify()#唤醒

    def 解决初始化(自身,拆除监视):
        '记下监视的关闭函数。重复调用保持第一次的值'
        with 自身._初始化锁:#只写一次
            if 自身._已初始化.is_set():#已经有结果
                return#保持
            自身._拆除监视=拆除监视#可能为空
            自身._已初始化.set()#放行关闭

    def 关闭(自身):
        '停止接收，等初始化后卸掉监视并释放。重复调用是空操作'
        with 自身._条件:#只开始一次
            if 自身._关闭完成 is not None:#已经在关
                return#空操作
            自身._已关闭=True#停收
            自身._关闭完成=threading.Event()#落定点
            自身._条件.notify()#叫醒读取
        自身.控制器.中止配套信号()#融合信号随之中止

        def 收尾():
            '初始化之后卸监视，再释放这一代。释放失败覆盖卸监视的失败'
            try:#卸监视
                自身._已初始化.wait()#等监视结果
                if 自身._拆除监视 is not None:#有关闭函数
                    自身._拆除监视()#卸掉
            except BaseException as 错误:#卸监视失败
                自身._关闭错误=错误#先记下
            try:#释放
                自身._释放()#摘掉
            except BaseException as 错误:#释放失败覆盖前一个
                自身._关闭错误=错误#最后的失败
            finally:#落定
                自身._关闭完成.set()#等待方可以走

        if 自身._已初始化.is_set():#结果已知
            收尾()#当场卸
            return#已落定
        启动守护线程(收尾)#等初始化的那条线程去卸

    def 等待关闭(自身):
        '等到这一代卸完。卸的时候失败则抛出'
        自身.关闭()#确保已经开始
        自身._关闭完成.wait()#等落定
        if 自身._关闭错误 is not None:#卸失败
            raise 自身._关闭错误#交给调用方

    def 失败(自身,错误):
        '记下监视错误并中止本代'
        自身.错误=错误#留给读取
        自身.控制器.中止配套信号()#结束等待

    def 读取(自身):
        '拉到关闭为止。关闭时还排着的观察随本代丢掉'
        while True:#直到关闭
            with 自身._条件:#取一条
                if 自身._已关闭:#已关
                    break#剩下的丢掉
                观察=自身._队列.头弹()#取头
                if 观察 is None:#空
                    自身._条件.wait()#等推入或关闭
                    continue#再看
            yield 观察#交给消费方
        if 自身.错误 is not None:#监视失败
            raise 自身.错误#在排空点抛出


class 工作区变更供给:
    '拥有目标监视、fs/observed 和每一代 changes'
    def __init__(自身,上下文):
        '订阅观察。拆除时关闭仍然打开的代'
        自身._上下文=上下文#宿主上下文
        自身._跟随者集合=set()#活着的代

        def 观察(目标,观测,*其余):
            '把一次 fs/observed 推进每一代'
            for 跟随者 in list(自身._跟随者集合):#快照，避免关闭时改集合
                跟随者.推入((目标,观测))#目标在元组第一位

        def 登记拆除():
            '拆除时关闭全部分代'
            def 拆除供给():
                '先全部开始关闭，再等它们卸完'
                跟随者列表=list(自身._跟随者集合)#快照
                for 跟随者 in 跟随者列表:#逐个开始
                    跟随者.关闭()#开始关
                for 跟随者 in 跟随者列表:#再等
                    跟随者.等待关闭()#卸完
                自身._跟随者集合.clear()#清空
            return 拆除供给#拆除器

        上下文.监听('fs/observed',观察)#订阅观察
        上下文.副作用(登记拆除,'workspace-files.changes')#寿命结束时关闭

    def 跟随(自身,工作区根,路径,信号):
        '打开一个目标监视。目录必须落在工作区根里。先产出 ready，再产出当前元数据'
        若已中止则抛出(信号)#入口已取消则立刻失败

        def 释放():
            '从活着的代里摘掉这一代'
            自身._跟随者集合.discard(跟随者)#幂等

        跟随者=变更跟随者(释放)#本代
        融合=中止信号.任一([信号,跟随者.控制器.信号])#任一路中止都算
        已取消=[False]#取消回调只跑一次

        def 取消():
            '中止后关闭本代，关闭失败记到日志'
            if 已取消[0]:#已经取消
                return#一次
            已取消[0]=True#标记
            跟随者.关闭()#开始关

            def 记下():
                '关闭落定后把失败记到日志'
                跟随者._关闭完成.wait()#等落定
                if 跟随者._关闭错误 is not None:#有失败
                    自身._上下文.日志.错误(跟随者._关闭错误)#记日志

            启动守护线程(记下)#不等待，和取消回调一样

        def 盯中止():
            '融合信号置位后取消本代'
            融合._事件.wait()#阻塞到中止
            取消()#关闭

        自身._跟随者集合.add(跟随者)#先登记，解析期间的观察不丢
        启动守护线程(盯中止)#等中止
        拆除监视=None#监视还没建立
        try:#建立、产出、最后一定关闭
            try:#解析根
                根=自身._上下文.fs.解析(工作区根,{'signal':融合})#工作区根目标
            except BaseException:#解析失败
                if 已中止(融合):#中止造成的
                    return#安静结束
                raise#其他失败原样
            if 根 is None or 已中止(融合) or 跟随者.是否已关闭:#中途停了
                return#不建立监视
            try:#解析目标
                目标=自身._上下文.fs.解析(路径,{'cwd':工作区根,'signal':融合})#目标
            except BaseException:#解析失败
                if 已中止(融合):#中止造成的
                    return#安静结束
                raise#其他失败原样
            if 目标 is None or 已中止(融合):#没有目标
                return#不建立监视

            def 状态():
                '读当前元数据。目录落在工作区外则拒绝'
                try:#stat
                    信息=自身._上下文.fs.状态(目标,融合)#元数据
                except BaseException:#stat 失败
                    if 已中止(融合):#中止造成的
                        return None#当缺失
                    raise#其他失败原样
                if 信息 is not None and 信息['type']=='directory' and not 自身._上下文.fs.包含(根,目标):#目录越界
                    raise 远程错误('workspace-file/outside-workspace','Directory is outside the workspace',{'path':路径})#拒绝
                return 信息#元数据或空

            状态()#建监视前先看一次
            if 已中止(融合):#看的期间取消了
                return#不建立监视

            def 变更回调(错误=None):
                '监视失效。有错误则失败，否则把目标推进队列'
                if 错误 is not None:#监视报错
                    跟随者.失败(错误)#记下并中止
                    return#不再推
                if not 跟随者.是否已关闭:#仍活着
                    跟随者.推入((目标,))#没有观测的失效

            try:#建立监视
                拆除监视=自身._上下文.fs.监视(目标,变更回调,融合)#返回关闭函数
                if 跟随者.错误 is not None:#建立期间已经失败
                    raise 跟随者.错误#走下面的包装
            except BaseException as 错误:#不能监视
                if 已中止(融合) and 跟随者.错误 is None:#纯粹是取消
                    return#不包成不支持
                失败=跟随者.错误 if 跟随者.错误 is not None else 错误#优先监视自己的错误
                raise 远程错误('workspace-file/watch-unsupported',str(失败),{'path':路径})#不能监视
            跟随者.解决初始化(拆除监视)#关闭时可以卸监视
            if 已中止(融合):#刚建好就取消
                return#卸掉
            yield {'kind':'ready'}#宿主监视已经活动
            for 观察 in 跟随者.读取():#排队和后来的失效
                被观察=观察[0]#目标
                if 被观察['targetKey']!=目标['targetKey']:#不是这一目标
                    continue#丢掉
                信息=状态()#失效后再读当前元数据
                if 已中止(融合):#读的期间取消
                    return#结束
                绝对路径=自身._上下文.fs.进程路径(目标)#执行世界路径
                if 信息 is not None:#还在
                    变更={'absolutePath':绝对路径,'version':信息['version']}#当前版本
                else:#没了
                    变更={'absolutePath':绝对路径,'absent':True}#确认缺失
                yield {'kind':'change','change':变更}#一帧
        finally:#无论哪条路退出都卸监视
            跟随者.解决初始化(拆除监视)#还没建成就用空关闭函数
            跟随者.等待关闭()#等卸完，失败则抛出
