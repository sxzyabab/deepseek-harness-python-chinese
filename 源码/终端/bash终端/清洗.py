"""面向第一版按行发布的流式终端控制清洗器。"""

提示符标记前缀='133;D;'#提示符OSC前缀
受控提示符='dsh> '#受控提示符文本
def 字节长(文本):#UTF-8字节长度
    """对齐 Node Buffer.byteLength 的 UTF-8 字节数。"""
    return len(文本.encode('utf-8'))#UTF-8字节数

def 归一化终端文本(文本):#为按行渲染归一化CRLF与单独回车
    """为按行渲染归一化 CRLF 与单独回车；去掉 BEL 后的按行文本。"""
    return 文本.replace('\r\n','\n').replace('\r','\n').replace('\x07','')#CRLF与CR变LF并去掉BEL

class 终端清洗器:#终端清洗器
    """去掉 CSI/OSC/短转义序列，同时保留跨分片未完成序列。完整终端仿真有意推迟；普通行输出与私有提示符标记才是受支持的约定。"""
    def __init__(自身,最大挂起字节):#挂起缓冲字节上限
        """挂起缓冲字节上限。"""
        自身.挂起=''#未完成的待处理缓冲
        自身.丢弃模式=None#超限后的丢弃模式：osc/csi/None
        自身.丢弃OSC半截转义=False#OSC是否正等ST的第二字节
        自身.挂起回车=False#是否有挂起的回车
        自身.跟踪提示符尾巴=False#是否正在收集提示符尾巴
        自身.最大挂起字节=最大挂起字节#字节上限

    def 推入(自身,分片):#推入一块已解码数据
        """消费一块已解码的终端数据；返回可打印文本，以及私有提示符标记是否完成。"""
        自身.挂起+=自身.丢掉前缀(分片)#先丢掉超限前缀再接到缓冲
        正文=''#可打印正文
        提示符=False#是否见到提示符标记
        带尾巴=自身.跟踪提示符尾巴#本分片是否带尾巴
        提示符尾巴=''#提示符后文本
        下标=0#扫描位置
        def 追加正文(值):#追加可打印文本
            """追加可打印文本，跟踪尾巴时同步追加。"""
            nonlocal 正文,提示符尾巴#写入外层
            正文+=值#写入正文
            if 自身.跟踪提示符尾巴:#跟踪尾巴
                提示符尾巴+=值#同步追加
        while 下标<len(自身.挂起):#扫描缓冲
            转义=自身.挂起.find('\x1b',下标)#下一转义
            if 转义<0:#没有转义
                追加正文(自身.挂起[下标:])#余下全是正文
                下标=len(自身.挂起)#扫完
                break#离开循环
            追加正文(自身.挂起[下标:转义])#转义前的正文
            if 转义+1>=len(自身.挂起):#转义被截断
                下标=转义#留下未完成转义
                break#等下一块
            种类=自身.挂起[转义+1]#转义第二字节
            if 种类==']':#OSC
                响铃=自身.挂起.find('\x07',转义+2)#BEL终止
                串终止=自身.挂起.find('\x1b\\',转义+2)#ST终止
                结束=-1#序列结束位置
                if 响铃>=0 and 串终止>=0:#两种终止都有
                    结束=min(响铃+1,串终止+2)#取更早的终止
                elif 响铃>=0:#只有BEL
                    结束=响铃+1#只有BEL
                elif 串终止>=0:#只有ST
                    结束=串终止+2#只有ST
                if 结束<0:#终止还没到
                    下标=转义#留下未完成OSC
                    break#等下一块
                终止字节=1 if 自身.挂起[结束-1]=='\x07' else 2#终止符长度
                内容=自身.挂起[转义+2:结束-终止字节]#OSC内容
                if 内容.startswith(提示符标记前缀):#私有提示符标记
                    提示符=True#本分片含提示符
                    自身.跟踪提示符尾巴=True#开始收集尾巴
                    带尾巴=True#返回尾巴
                    提示符尾巴=''#从标记后重计
                下标=结束#跳过该OSC
                continue#继续扫描
            if 种类=='[':#CSI
                结束=转义+2#参数扫描位置
                while 结束<len(自身.挂起):#找最终字节
                    码=ord(自身.挂起[结束])#当前字节
                    if 码>=0x40 and 码<=0x7e:#CSI最终字节
                        break#找到
                    结束+=1#继续
                if 结束>=len(自身.挂起):#CSI被截断
                    下标=转义#留下未完成CSI
                    break#等下一块
                下标=结束+1#跳过该CSI
                continue#继续扫描
            #两字节转义族（保存/恢复光标等）
            下标=转义+2#跳过短转义
        自身.挂起=自身.挂起[下标:]#留下未完成后缀
        自身.强制挂起上限()#超限则丢弃并进入丢弃模式
        结果={'text':自身.归一化文本(正文),'prompt':提示符}#本分片结果
        if 带尾巴:#需要时带上尾巴
            结果['promptTail']=提示符尾巴#提示符后文本
        return 结果#返回结束

    def 冲掉(自身):#PTY退出时冲掉尾部可打印碎片
        """PTY 退出时冲掉尾部可打印碎片；未完成转义丢弃。"""
        正文='' if 自身.挂起.startswith('\x1b') else 自身.挂起#未完成转义丢掉
        自身.挂起=''#清空缓冲
        自身.丢弃模式=None#退出丢弃模式
        自身.丢弃OSC半截转义=False#清除OSC半截状态
        自身.跟踪提示符尾巴=False#停止收集尾巴
        归一=自身.归一化文本(正文)#归一化
        if not 自身.挂起回车:#没有挂起回车
            return 归一#直接返回
        自身.挂起回车=False#清掉挂起回车
        return 归一+'\n'#回车收成换行

    def 归一化文本(自身,文本):#归一化一块文本
        """接上挂起回车后做 CRLF/BEL 处理。"""
        完整=('\r'+文本) if 自身.挂起回车 else 文本#接上挂起的回车
        自身.挂起回车=False#先清掉
        if 完整.endswith('\r'):#以回车结尾
            完整=完整[:-1]#去掉末尾回车
            自身.挂起回车=True#留到下一块
        return 归一化终端文本(完整)#CRLF与BEL处理

    def 强制挂起上限(自身):#强制挂起上限
        """超限则按序列种类进入丢弃模式并清空缓冲。"""
        if 字节长(自身.挂起)<=自身.最大挂起字节:#未超限
            return#结束
        自身.丢弃模式='osc' if len(自身.挂起)>1 and 自身.挂起[1]==']' else 'csi'#按序列种类丢弃
        自身.挂起=''#丢掉超限缓冲

    def 丢掉前缀(自身,分片):#丢掉跨分片的未完成控制序列
        """丢掉跨分片的未完成控制序列，返回其后正文。"""
        if 自身.丢弃模式 is None:#不在丢弃模式
            return 分片#原样
        if 自身.丢弃模式=='csi':#丢CSI直到最终字节
            下标=0#逐字节
            while 下标<len(分片):#逐字节
                码=ord(分片[下标])#当前字节
                if 码>=0x40 and 码<=0x7e:#CSI最终字节
                    自身.丢弃模式=None#结束丢弃
                    return 分片[下标+1:]#返回其后正文
                下标+=1#继续
            return ''#整块仍在CSI里
        下标=0#OSC扫描位置
        if 自身.丢弃OSC半截转义:#上一块以ESC结尾
            自身.丢弃OSC半截转义=False#清掉半截ESC
            if 分片.startswith('\\'):#ST第二字节
                自身.丢弃模式=None#结束丢弃
                return 分片[1:]#返回其后正文
        while 下标<len(分片):#找OSC终止
            if 分片[下标]=='\x07':#BEL
                自身.丢弃模式=None#结束丢弃
                return 分片[下标+1:]#返回其后正文
            if 分片[下标]=='\x1b':#可能的ST
                if 下标+1<len(分片) and 分片[下标+1]=='\\':#完整ST
                    自身.丢弃模式=None#结束丢弃
                    return 分片[下标+2:]#返回其后正文
                if 下标+1==len(分片):#ESC落在块尾
                    自身.丢弃OSC半截转义=True#记下半截ESC
            下标+=1#继续
        return ''#整块仍在OSC里
