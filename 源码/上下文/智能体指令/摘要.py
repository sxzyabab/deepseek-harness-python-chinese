"""工作区指令去重所用的内容身份。"""
import hashlib#SHA-1哈希

def 指令内容摘要(内容):#计算指令内容的SHA-1摘要
    """计算指令加载与会话状态共用的内容身份。返回小写十六进制 SHA-1 摘要。"""
    return hashlib.sha1(内容.encode('utf-8')).hexdigest()#对原文做SHA-1并输出十六进制

def 去空白指令摘要(内容):#计算去空白后的指令摘要
    """计算按目录去重所用的空白不敏感身份。哈希前去掉首尾空白，因此仅外围空白不同的符号链接或字节拷贝兄弟仍折叠为同一份渲染文件。"""
    return 指令内容摘要(内容.strip())#先去首尾空白再做内容SHA-1
