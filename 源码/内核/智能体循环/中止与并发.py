from threading import Event as 事件#取消通道与已放弃标志
from ...基础设施.js特性 import PromiseEX as 期约#中文别名的期约
from ...基础设施.通用工具 import 启动守护线程
from .异常 import 循环错误,中止错误

class 中止信号(事件):
    '取消通道。Event 本身就是信号'
    def __init__(自身):
        '创建未中止的通道'
        事件.__init__(自身)#未置位
        自身.原因=None#跨包读取的中止原因

    def 等待(自身):
        '阻塞到中止'
        自身.wait()#阻塞

class 中止控制器:
    '发出中止的控制器'
    def __init__(自身):
        '创建配套信号'
        自身.信号=中止信号()#本控制器的信号

    def 中止(自身,原因=None):
        '中止配套信号，只生效一次'
        if 自身.信号.is_set():#已经中止
            return#只生效一次
        自身.信号.原因=原因#记下原因
        自身.信号.set()#置位

def 已中止(信号):
    '信号是否已中止。无信号视为未中止'
    if 信号 is None:#无信号
        return False#未中止
    return 信号.is_set()#Event 已置位

def 若已中止则抛出(信号):
    '已中止则抛出承载原因的异常'
    if not 已中止(信号):#无信号或仍活着
        return#仍活着
    if 信号.原因 is not None:#有承载异常
        raise 信号.原因#抛出
    raise 中止错误()#默认中止

def 合成信号(*信号参数):
    '最先中止的那路胜出，返回融合信号'
    融合=中止控制器()#融合控制器
    def 转发(源):
        '源中止后把原因交给融合'
        if not 已中止(源):#尚未中止
            源.等待()#阻塞到这一路
        融合.中止(源.原因)#转发原因
    for 信号 in 信号参数:#先看已经中止的
        if 信号 is None:#无信号
            continue#跳过
        if 已中止(信号):#已中止
            融合.中止(信号.原因)#立刻胜出
            return 融合.信号#已中止的融合信号
        启动守护线程(转发,信号)#听这一路
    return 融合.信号#融合信号

def 包装中止错误(标识,原因):
    '把非异常原因收成创建中止错误'
    if isinstance(原因,BaseException):#原因本身已是异常
        return 原因#原样交回
    中止异常=循环错误(f'智能体 "{标识}" 创建已中止')#非异常原因包成循环错误
    中止异常.原因=原因#原因挂在异常上供调用方读取
    return 中止异常#交回包装后的错误

def 启动可中止操作(操作,信号,标识,回收已放弃结果=None):
    """在线程里跑同步操作，与中止信号竞速，返回期约。
    中止先到时以中止错误拒绝，操作稍后才产出的值交给回收函数"""
    结果=期约()#本次操作的结算点
    if 已中止(信号):#调用时就已中止则不再起线程
        结果.拒绝(包装中止错误(标识,信号.原因))#直接以中止错误拒绝
        return 结果#交回已拒绝的期约
    已放弃=事件()#中止先到后置位，之后操作的产出不再交给调用方
    已结算=事件()#操作线程结束后置位，让监视线程退出
    def 执行操作():
        '在工作线程里执行操作，按是否已放弃决定结算或回收'
        try:
            值=操作()#同步执行操作
        except BaseException as 错误:#操作失败，线程入口把错误收进期约
            if not 已放弃.is_set():#调用方还在等才拒绝
                结果.拒绝(错误)#以操作的错误拒绝
            已结算.set()#通知监视线程退出
            return
        if 已放弃.is_set():#中止先到，值已无人等待
            已结算.set()#通知监视线程退出
            if 回收已放弃结果 is not None:#调用方给了回收函数
                回收已放弃结果(值)#让回收函数拆除这份迟到的值
            return
        结果.解决(值)#正常结算
        已结算.set()#通知监视线程退出
    def 监视中止():
        '轮询中止信号，中止先到则以中止错误拒绝'
        while not 已结算.is_set():#操作未结束就继续监视
            if 已中止(信号):#中止先到
                已放弃.set()#标记调用方已走
                结果.拒绝(包装中止错误(标识,信号.原因))#以中止错误拒绝
                return
            已结算.wait(0.05)#每 50 毫秒看一次信号，操作结束时提前醒来
    启动守护线程(执行操作)#操作线程
    启动守护线程(监视中止)#监视线程
    return 结果#调用方对期约链接 然后 与 捕获
