"""进程本地的助手尝试分帧与耐久流累积。

对齐上游 `agent-loop/src/assistant-stream.ts`。公开面仅中文名；事件名与帧 type 保持上游 wire。
无英文别名。
"""
import time#墙钟毫秒
from ...模型后端.llm import 助手流累积器,块组装器,尝试标识#流紧凑、组装与尝试 id

__all__=('助手流尝试',)#仅中文公开名

class 助手流尝试:#助手流尝试
    """把一次模型尝试折成一条紧凑流外加有序瞬态帧。"""
    def __init__(自身,会话号,尝试号,下一修订,轮次,步骤,发出):#构造一次尝试
        """铸造尝试身份并记下修订分配器、回合、步骤与帧发布器。

        @param 会话号: 仅嵌入 Agent 生命周期本地尝试 id 的身份。
        @param 尝试号: 附着会话本地的尝试计数。
        @param 下一修订: 分配下一发出帧修订号。
        @param 轮次: 拥有该请求的耐久回合。
        @param 步骤: 拥有该请求的耐久步骤。
        @param 发出: Agent 作用域通知发布器。
        """
        自身._累积器=助手流累积器()#紧凑累积
        自身._组装器=块组装器()#块组装
        自身._下标=0#已发 chunk 下标
        自身._终端=False#是否已发终端帧
        自身._下一修订=下一修订#修订分配器
        自身.轮次=轮次#回合
        自身.步骤=步骤#步骤
        自身._发出=发出#帧发布
        自身.尝试标识=尝试标识(str(会话号)+':'+str(尝试号))#铸造尝试 id

    @property
    def 已结束(自身):#是否已结束
        """这次已开始的尝试是否已发出终端帧。"""
        return 自身._终端#是否已终端

    def 开始(自身):#发布 start 帧
        """在首个送达块之前发布开场标记。"""
        自身._发出({#发出开场
            'type':'start',#开场
            'attemptId':自身.尝试标识,#尝试 id
            'revision':自身._下一修订(),#修订
            'turn':自身.轮次,#回合
            'step':自身.步骤,#步骤
        })#结束 emit

    def 推入(自身,块):#推入流块
        """每个块快照一次，再喂给耐久紧凑、组装与实时发布。"""
        带时=自身._累积器.推入({'time':int(time.time()*1000),'chunk':块})#打时间并紧凑
        自身._组装器.推入(带时['chunk'])#组装块
        下标=自身._下标#当前下标
        自身._下标=下标+1#推进
        自身._发出({#发出 chunk 帧
            'type':'chunk',#块帧
            'attemptId':自身.尝试标识,#尝试 id
            'revision':自身._下一修订(),#修订
            'index':下标,#块下标
            'time':带时['time'],#时间
            'chunk':带时['chunk'],#块载荷
        })#结束 emit

    def 落定(自身,事件类型,追加):#终端结算
        """在匹配的耐久事件提交后发布终端结算。

        @param 事件类型: 耐久结算类型（assistant/message 或 assistant/attempt）。
        @param 追加: 同步耐久追加，返回已提交序号。
        """
        try:#追加可能失败
            序号=追加()#提交耐久事件
        except BaseException:#追加失败
            自身.放弃()#先发放弃帧
            raise#再上抛
        自身._终端=True#标记已终端
        自身._发出({#发出 end 帧
            'type':'end',#结束
            'attemptId':自身.尝试标识,#尝试 id
            'revision':自身._下一修订(),#修订
            'index':自身._下标,#当前块计数
            'outcome':{'kind':'committed','eventType':事件类型,'seq':序号},#已提交结局
        })#结束 emit

    def 放弃(自身):#放弃尝试
        """无法提交耐久尝试事件时发布放弃。"""
        自身._终端=True#标记已终端
        自身._发出({#发出放弃 end
            'type':'end',#结束
            'attemptId':自身.尝试标识,#尝试 id
            'revision':自身._下一修订(),#修订
            'index':自身._下标,#当前块计数
            'outcome':{'kind':'abandoned'},#放弃结局
        })#结束 emit

    @property
    def 流(自身):#紧凑流
        """最终耐久事件用的精确紧凑流。"""
        return list(自身._累积器.快照())#快照拷贝

    def 块列表(自身):#完成块
        """同一批块得到的规范完成消息块。"""
        return 自身._组装器.块列表()#组装结果

    def 中断块列表(自身):#打断前缀
        """取消打断尝试时的安全可见前缀。"""
        return 自身._组装器.中断块列表()#安全前缀

    @property
    def 用量(自身):#用量
        """流中适配器最近报告的用量。"""
        return 自身._组装器.用量#组装器用量

    @property
    def 结束(自身):#结束原因
        """终端原因；流省略时默认 stop。"""
        return 自身._组装器.结束#组装器结束原因

    @property
    def 回放状态(自身):#回放状态
        """终端 finish 记录携带的重放状态。"""
        return 自身._组装器.回放状态#组装器重放
