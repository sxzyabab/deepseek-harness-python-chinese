"""仓库测试用的规范工具定义夹具。对齐上游 `tools/src/testing.ts`。公开面仅中文名。"""
from .模式 import 定义工具#导入工具定义器

__all__=('定义内容工具夹具',)#仅中文公开名

内容值模式={'type':'array','items':{'type':'json'}}#内容数组输出模式

def 定义内容工具夹具(选项):
    """定义故意把内容块当作规范 JSON 值的测试夹具。产品工具必须改声明领域自有 DTO。"""
    用户执行=选项['execute']#抽出执行体
    定义选项=dict(选项)#其余夹具字段
    def 渲染(_参数,值):
        """规范值即内容块。"""
        return 值#内容数组原样
    def 执行包装(参数,执行上下文):
        """包装执行：内容块当作 JSON 数组。"""
        return 用户执行(参数,执行上下文)#交给夹具执行体
    定义选项['output']={
        'schema':内容值模式,#JSON 数组模式
        'render':渲染,#规范值即内容块
    }#输出约定
    定义选项['execute']=执行包装#执行包装
    return 定义工具(定义选项)#交给正式定义器
