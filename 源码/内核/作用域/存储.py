class 插入序表:#插入有序实时映射
    """插入有序映射，迭代器在一代非空表内实时；排空后换新表以脱离旧迭代器。

    对齐上游 JS Map 的插入序与删空后换新代表行为；Python dict 虽保序，但删键不留空洞、重插不挪到末尾，故自建。
    """
    def __init__(自身):#建立空表
        """建立空表。"""
        自身._键=[]#插入序键，含已删空洞
        自身._值={}#现存键到值

    def 设(自身,键,值):#写入键值
        """写入键值；重插已删键时放到末尾。"""
        if 键 not in 自身._值:#新槽或重插
            自身._键.append(键)#新槽或重插到末尾
        自身._值[键]=值#写入

    def 删(自身,键):#删掉现存条目
        """删掉现存条目并留下键空洞，使进行中的迭代器不被后续重插打乱。"""
        自身._值.pop(键,None)#留下键空洞

    def 获取(自身,键):#按键读取
        """按键读取，缺失为 None。"""
        return 自身._值.get(键)#缺则为 None

    def 有(自身,键):#键是否仍在表中
        """键是否仍在表中。"""
        return 键 in 自身._值#是否现存

    def 大小(自身):#现存条目数
        """现存条目数。"""
        return len(自身._值)#现存条数

    def 诸键(自身):#实时迭代键
        """按插入序实时迭代现存键。"""
        下标=0#实时游标
        while 下标<len(自身._键):#尚未走完
            键=自身._键[下标]#当前槽
            下标+=1#前进
            if 键 in 自身._值:#现存
                yield 键#现存则产出

    def 诸条目(自身):#实时迭代条目
        """按插入序实时迭代现存条目。"""
        下标=0#实时游标
        while 下标<len(自身._键):#尚未走完
            键=自身._键[下标]#当前槽
            下标+=1#前进
            if 键 in 自身._值:#现存
                yield (键,自身._值[键])#现存则产出

    def 诸值(自身):#实时迭代值
        """按插入序实时迭代现存值。"""
        下标=0#实时游标
        while 下标<len(自身._键):#尚未走完
            键=自身._键[下标]#当前槽
            下标+=1#前进
            if 键 in 自身._值:#现存
                yield 自身._值[键]#现存则产出

class 身份表:#按身份存取的强映射
    """按对象身份存取的强引用映射，对应 JS Map<object, V>；精确作用域层不能弱引用，否则无人持键时层会丢。"""
    def __init__(自身):#建立空表
        """建立空表。"""
        自身._表={}#标识到(键,值)

    def 设(自身,键,值):#按身份写入
        """按身份写入。"""
        自身._表[id(键)]=(键,值)#强引用键与值

    def 取(自身,键):#按身份读取
        """按身份读取，缺失为 None。"""
        项=自身._表.get(id(键))#按标识查
        if 项 is None:#没有
            return None#没有
        已有,值=项#拆开
        if 已有 is 键:#仍是原对象
            return 值#仍是原对象
        return None#标识复用

    def 删(自身,键):#按身份删除
        """按身份删除。"""
        项=自身._表.get(id(键))#按标识查
        if 项 is not None and 项[0] is 键:#仍是原对象
            del 自身._表[id(键)]#删掉本条

class 具名条目:#插入有序具名表
    """插入有序的具名条目，重复诊断由调用方拥有。

    值是借用的。迭代器在一代非空表内是实时的；把表排空会让它们与更后的插入脱钩。每次成功插入返回该精确条目的幂等撤销。
    """
    def __init__(自身,重复错误):#保存重复名诊断
        """保存重复名诊断。"""
        自身.重复错误=重复错误#重复名诊断工厂 (名) → Error
        自身.数据=插入序表()#名到值

    def 插入(自身,名,值):#插入唯一名
        """插入一个唯一名，返回只撤销本次插入的幂等撤销器。"""
        数据=自身.数据#当前代表
        if 数据.有(名):#重复
            raise 自身.重复错误(名)#重复则抛
        数据.设(名,值)#写入
        仍有效=True#撤销是否仍有效
        def 撤销():#幂等撤销本次插入
            """幂等撤销本次插入。"""
            nonlocal 仍有效#修改外层
            if not 仍有效:#已撤销
                return#已撤销
            仍有效=False#标为失效
            数据.删(名)#删掉本条
            if 数据.大小()==0 and 自身.数据 is 数据:#本代已空
                自身.数据=插入序表()#排空则换新表以脱离旧迭代器
        return 撤销#撤销器

    def 获取(自身,名):#按名读取
        """读一个具名值，缺失为 None。"""
        return 自身.数据.获取(名)#查表

    def 含有(自身,名):#名是否在表中
        """测试一个名是否在表中。"""
        return 自身.数据.有(名)#查表

    def 诸键(自身):#迭代名
        """按插入序迭代实时名。"""
        return 自身.数据.诸键()#原生键迭代

    def 诸条目(自身):#迭代条目
        """按插入序迭代实时条目。"""
        return 自身.数据.诸条目()#原生条目迭代

    def 诸值(自身):#迭代值
        """按插入序迭代实时值。"""
        return 自身.数据.诸值()#原生值迭代

    def 是否空(自身):#表是否为空
        """测试本表是否没有条目。"""
        return 自身.数据.大小()==0#大小为零

class 匿名条目:#插入有序匿名表
    """插入有序的匿名条目，注册身份彼此独立。

    相等值仍是分开的注册。值是借用的，迭代器在一代非空表内是实时的；把表排空会让它们与更后的追加脱钩。
    """
    def __init__(自身):#建立空表
        """建立空表。"""
        自身.数据=插入序表()#独立身份键到值

    def 追加(自身,值):#追加独立值
        """追加一个独立拥有的值，返回本次精确追加的幂等撤销器。"""
        数据=自身.数据#当前代表
        键=object()#独立身份，对齐上游 Symbol()
        数据.设(键,值)#写入
        仍有效=True#撤销是否仍有效
        def 撤销():#幂等撤销本次追加
            """幂等撤销本次追加。"""
            nonlocal 仍有效#修改外层
            if not 仍有效:#已撤销
                return#已撤销
            仍有效=False#标为失效
            数据.删(键)#删掉本条
            if 数据.大小()==0 and 自身.数据 is 数据:#本代已空
                自身.数据=插入序表()#排空则换新表
        return 撤销#撤销器

    def 诸值(自身):#迭代值
        """按插入序迭代实时值。"""
        return 自身.数据.诸值()#原生值迭代

    def 是否空(自身):#表是否为空
        """测试本表是否没有条目。"""
        return 自身.数据.大小()==0#大小为零

class 作用域层集:#全局层与精确作用域层
    """拥有一个注册表的全局层与精确作用域层。

    读取从不创建作用域层。注册从所给 Cordis 上下文同时派生可见性与 effect 所有权，在通知前收集撤销，并只回收完全空的聚合层。
    层须提供 `是否空()`；调用方在建层工厂里放入具名/匿名表。
    """
    def __init__(自身,建层,变更时):#急切构造全局层
        """急切构造全局层。"""
        自身.建层=建层#建层工厂 (作用域键|None) → 层
        自身.变更时=变更时#变更通知
        自身.全局=建层(None)#全局层无键
        自身.作用域层=身份表()#精确作用域覆盖

    def 窥视(自身,作用域):#读已有精确覆盖
        """读一份已有的精确作用域覆盖，不创建、不看链。

        故意对链盲目：寻址一个作用域自己的贡献（其限制、其守卫）的调用方不得静默捡到祖先的——继承才是重点时用链上层。
        """
        if 作用域 is None:#无键
            return None#无键则无覆盖
        return 自身.作用域层.取(作用域)#查表

    def 链上层(自身,作用域):#父链上已有层
        """沿作用域父链的已有覆盖，最远祖先在前、精确作用域在后，因此按顺序叠层时最近作用域说了算。"""
        from . import 获取作用域链#读父链（延迟导入避免环）
        结果=[]#结果
        for 键 in reversed(获取作用域链(作用域)):#最远祖先在前
            层=自身.作用域层.取(键)#该键的层
            if 层 is not None:#有层
                结果.append(层)#有则接入
        return 结果#返回层

    def 合并(自身,作用域,挑选):#全局再叠链阴影
        """物化全局具名条目，再跟上作用域链阴影，最近作用域的条目赢得一个名。"""
        合并结果={}#先放全局
        for 名,值 in 挑选(自身.全局).诸条目():#全局条目
            合并结果[名]=值#全局条目
        for 层 in 自身.链上层(作用域):#再叠链
            for 名,值 in 挑选(层).诸条目():#本层条目
                合并结果[名]=值#近者覆盖
        return 合并结果#有效映射

    def 副作用(自身,上下文对象,动作,选项):#挂上 effect
        """把一次同步层变更接到其注册上下文，返回 ctx.effect() 的精确拆除器。

        选项：`标签`（必填，Cordis effect 诊断名）、`通知`（可选，默认 True；守卫类变更可关）。
        """
        from . import 获取作用域#读标签（延迟导入避免环）
        作用域=获取作用域(上下文对象)#调用作用域
        通知=True#默认通知
        if '通知' in 选项:#显式通知
            通知=选项['通知']#显式通知
        标签=选项['标签']#effect 标签
        def 执行体():#生成器副作用
            """生成器副作用：先变更再登记拆除。"""
            新建=False#是否本调用新建
            if 作用域 is None:#全局
                层=自身.全局#用全局层
            else:#作用域
                已有=自身.作用域层.取(作用域)#已有层
                if 已有 is None:#没有
                    层=自身.建层(作用域)#新建
                    自身.作用域层.设(作用域,层)#挂上
                    新建=True#记为新建
                else:#已有
                    层=已有#复用
            try:#执行变更
                撤销=动作(层)#拿到撤销
            except Exception:#变更失败
                if 作用域 is not None and 新建 and 层.是否空():#新建且仍空
                    自身.作用域层.删(作用域)#新建且仍空则收回
                raise#原样抛出
            def 拆除回调():#撤销变更
                """撤销变更并在层空时收回。"""
                撤销()#撤销变更
                if 作用域 is not None and 层.是否空():#层空
                    自身.作用域层.删(作用域)#层空则收回
                if 通知:#需要通知
                    自身.变更时()#通知
            yield 拆除回调#拆除
            if 通知:#需要通知
                自身.变更时()#注册成功也通知
        return 上下文对象.effect(执行体,标签)#绑定标签
