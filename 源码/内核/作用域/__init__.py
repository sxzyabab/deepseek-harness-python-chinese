class 作用域父绑定:#改接父链接的特权句柄
    """移动一个作用域键父链接的特权句柄。仅原绑定者持有；空白会话重组约定由持有者遵守。"""
    def __init__(自身,键):#记下被绑定的键
        """记下被绑定的键。"""
        自身._键=键#绑定键

    def 改接(自身,父):#改接到新父
        """把绑定键改接到另一个父，循环检查与首次绑定相同。"""
        链接作用域父(自身._键,父)#同样带循环检查

class 作用域:#已铸造的注册作用域
    """已铸造的注册作用域及其静止拆除边界。"""
    def __init__(自身,上下文对象,原始拆除,拆除):#保存上下文与拆除边界
        """保存上下文与拆除边界。"""
        自身.上下文=上下文对象#带标签的作用域上下文；经此做出的注册归本光纤
        自身.原始拆除=原始拆除#精确 Cordis disposer，嵌进有序组合 effect 时用
        自身.拆除=拆除#共用幂等完全停稳边界；竞态调用等待同一次 teardown

def 链接作用域父(键,父):#带循环检查的写入
    """绑定与每次改接共享的、带循环检查的写入。成环则拒绝，因为每个链消费方都走到根。"""
    游标=父#沿父链走
    while 游标 is not None:#尚未到根
        if 游标 is 键:#成环
            raise Exception('dsh-scope: scope parent link would form a cycle')#成环则拒绝
        游标=作用域父表.取(游标)#上一父
    作用域父表.设(键,父)#记下父

def 绑定作用域父(键,父):#只绑一次
    """把父绑定为键的包围作用域，只绑一次，返回唯一可改接该键的绑定。

    已有父的键会抛错：没有开放的改接路径，因此除原绑定者外谁都不能移动作用域祖先。
    """
    if 作用域父表.有(键):#已有父
        raise Exception('dsh-scope: scope key is already bound to a parent; re-linking requires the binding returned by the original bind')#必须用原绑定改接
    链接作用域父(键,父)#写入链接
    return 作用域父绑定(键)#返回绑定

def 获取作用域父(键):#读包围作用域
    """读一个键的包围作用域，根作用域为 None。"""
    return 作用域父表.取(键)#查表

def 获取作用域链(键):#走到根
    """从某键到其根祖先的链，最近者在前；键为 None 时为空链。"""
    链=[]#链
    游标=键#起始
    while 游标 is not None:#尚未到根
        链.append(游标)#沿父上溯
        游标=作用域父表.取(游标)#上一父
    return 链#返回链

def 等到光纤静止(光纤对象):#等到拆除惯性结束
    """即使原始拆除器已被领取，也跟随 Cordis 光纤走完拆除与 inertia。"""
    结果=光纤对象.dispose()#发起拆除
    if hasattr(结果,'等待'):#拆除返回承诺
        结果.等待()#等到拆除承诺
    while 光纤对象.inertia is not None:#仍有惯性
        惯性=光纤对象.inertia#当前惯性
        if hasattr(惯性,'等待'):#惯性可等待
            惯性.等待()#等到惯性结束
        else:#非承诺
            break#非承诺则停

