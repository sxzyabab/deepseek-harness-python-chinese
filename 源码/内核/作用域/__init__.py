class 弱身份表:#按身份存取的弱键表
    """按对象身份存取，键可被回收，对应 JS WeakMap。键死则条目清掉，标识复用不会误命中。"""
    def __init__(自身):#建立空表
        """建立空表。"""
        自身._表={}#id(键) → (弱引用, 值)

    def 设(自身,键,值):#按身份写入
        """按身份写入；键被回收时自动摘掉本条。"""
        标识=id(键)#对象标识（仅作槽位，命中仍靠 is）
        def 清理(引用):#键被回收时摘掉条目
            """键被回收时摘掉条目；仅当槽里仍是本条弱引用才删，避免竞态误删。"""
            当前=自身._表.get(标识)#仍登记的项
            if 当前 is not None and 当前[0] is 引用:#仍是本条弱引用
                自身._表.pop(标识,None)#回收条目
        自身._表[标识]=(weakref.ref(键,清理),值)#写入弱引用与值

    def 取(自身,键):#按身份读取
        """按身份读取，缺失或键已死/标识复用为 None。"""
        项=自身._表.get(id(键))#按标识查
        if 项 is None:#没有
            return None#没有
        引用,值=项#拆开
        if 引用() is 键:#仍是原对象
            return 值#仍是原对象
        return None#标识复用或已死

    def 有(自身,键):#是否登记过该键
        """是否仍登记着该活键。"""
        项=自身._表.get(id(键))#按标识查
        if 项 is None:#没有
            return False#没有
        return 项[0]() is 键#仍是原对象

