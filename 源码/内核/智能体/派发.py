"""Agent 作用域的派发与提示词组装辅助。

对齐上游 `agent/src/dispatch.ts`。派发器字典键为 `发出`／`串行`／`瀑布`。
"""
from ..作用域 import 作用域目标#作用域载体构造
from ...依赖.工具 import 获取内部数据#读事件总线内部成员

__all__=('智能体事件派发','智能体载体','智能体事件','发出智能体事件','为组装构建上下文')#仅中文公开名

class 智能体事件派发:
    """把 Agent 主体接到其作用域载体的派发器。键：发出／串行／瀑布。"""
    def 发出(自身,名称,载荷):
        """在 Agent 作用域内发即忘通知。"""
        raise NotImplementedError('智能体事件派发.发出')#由智能体事件构造

    def 串行(自身,名称,载荷):
        """在 Agent 作用域内按序等待派发。"""
        raise NotImplementedError('智能体事件派发.串行')#由智能体事件构造

    def 瀑布(自身,名称,载荷,*剩余):
        """在 Agent 作用域内做环绕中间件派发。"""
        raise NotImplementedError('智能体事件派发.瀑布')#由智能体事件构造

def 智能体载体(智能体):
    """为一个 Agent 主体构建融合作用域载体。"""
    return 作用域目标(智能体,智能体)#以 Agent 自身为键

def 智能体事件(上下文对象,智能体,载体=None):
    """构建把 Agent 主体接到其作用域载体的派发器。返回键仅中文的字典。"""
    if 载体 is None:
        载体=智能体载体(智能体)#缺省当场建载体
    def 融合(载荷):
        """注入主体，调用方载荷盖不过 agent。"""
        结果=dict(载荷)#展开载荷
        结果['agent']=智能体#注入主体
        return 结果#融合载荷
    def 发出(名称,载荷):
        """在 Agent 作用域内发即忘通知。"""
        参数=[载体,名称,融合(载荷)]#载体、事件名、融合载荷
        事件总线=获取内部数据(上下文对象,'属性链')['事件']#事件总线，不经壳
        for 回调 in 获取内部数据(事件总线,'解析监听器')(事件总线,'emit',参数):#逐个监听器
            try:
                回调(*参数)#监听器已是同步
            except Exception as 错误:
                上下文对象.日志.警告('agent event "'+名称+'" listener threw: '+str(错误))#记抛错
    def 串行(名称,载荷):
        """在 Agent 作用域内按序等待派发。"""
        return 上下文对象.广播(载体,名称,融合(载荷))#经载体按序广播
    def 瀑布(名称,载荷,*剩余):
        """在 Agent 作用域内做环绕中间件派发。"""
        return 上下文对象.链式拦截(载体,名称,融合(载荷),*剩余)#经载体瀑布派发
    return {'发出':发出,'串行':串行,'瀑布':瀑布}#公开键仅中文

def 发出智能体事件(上下文对象,智能体,名称,载荷):
    """发出一条受控 Agent 通知，不分配常驻派发器。"""
    智能体事件(上下文对象,智能体)['发出'](名称,载荷)#临时派发器发即忘

def 为组装构建上下文(智能体,信号=None):
    """构建把 Agent 与作用域一起设好的提示词组装上下文。"""
    结果={'agent':智能体,'scope':智能体}#Agent 与作用域
    if 信号 is not None:
        结果['signal']=信号#轮次信号
    return 结果#组装上下文
