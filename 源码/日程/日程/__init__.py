def 取字段(对象,键,缺省=None):#从映射或对象读字段
    """从映射或对象读字段。"""
    if 对象 is None:#空对象
        return 缺省#缺席
    if isinstance(对象,dict):#映射
        if 键 in 对象:#自有键
            return 对象[键]#映射键
        return 缺省#缺席
    return getattr(对象,键,缺省)#对象属性

def 解开(值):#承诺则等待否则原样
    """承诺则等待，否则原样返回。"""
    if 是否thenable(值):#可等待
        return 值.等待()#等待承诺
    return 值#同步值

def 应用(上下文):#只为在本插件加载后发布的根智能体安装日程
    """只为在本插件加载后发布的根智能体安装日程。"""
    运行时们={}#根智能体到拆除回调
    停止中=[False]#是否正在停止接受新所有者
    def 装寿命():#注册生命周期副作用
        """注册生命周期副作用。"""
        def 智能体已创建(载荷,*其余):#根智能体创建
            """根智能体创建时安装日程。"""
            智能体=取字段(载荷,'agent')#新智能体
            if 停止中[0] or 智能体 in 运行时们:#停止中或已安装
                return#跳过
            if 智能体 not in 上下文.agents.roots():#非根
                return#跳过
            运行时=日程运行时(上下文,智能体)#为该根创建运行时
            def 装所有者():#挂到智能体 fiber
                """挂到智能体 fiber。"""
                def 变更后驱():#工具变更后驱使
                    """工具变更后驱使。"""
                    运行时.请求驱动()#请求驱动
                卸工具=登记日程工具(上下文,智能体.ctx,智能体,变更后驱)#注册工具并在变更后驱使
                def 状态时(载荷2,*其余2):#空闲时驱使
                    """空闲时驱使。"""
                    if 取字段(载荷2,'status')=='idle':#空闲
                        事件们=取字段(取字段(智能体,'session'),'events')#事件流
                        if any(取字段(事件,'type')=='schedule/change' for 事件 in 事件们):#有日程
                            运行时.请求驱动()#请求驱动
                停状态=智能体.ctx.on('agent/status',状态时)#status 监听
                运行时.启动()#启动运行时
                def 拆所有者():#拆除该所有者
                    """拆除该所有者。"""
                    停状态()#停状态监听
                    卸工具()#卸工具
                    try:#等待运行时停稳
                        运行时.拆除()#拆除运行时
                    finally:#无论成败都摘映射
                        if 运行时们.get(智能体) is 拆所有者回调:#仍是当前回调才删除
                            del 运行时们[智能体]#删除
                return 拆所有者#拆除回调
            拆所有者回调=智能体.ctx.effect(装所有者,'schedule.runtime()')#fiber 标签
            运行时们[智能体]=拆所有者回调#记下所有者拆除
        停创建=上下文.on('agent/created',智能体已创建)#agent/created
        def 拆寿命():#插件拆除
            """插件拆除。"""
            停止中[0]=True#不再接受新根
            停创建()#停创建监听
            拆除们=list(运行时们.values())#拷贝拆除回调
            运行时们.clear()#清空映射
            for 拆除 in 拆除们:#并行等全部所有者停稳（线程内同步）
                try:#调用拆除
                    解开(拆除())#可等待则等
                except Exception:#单个失败不挡其余
                    pass#吞掉：allSettled 语义
        return 拆寿命#拆除结束
    上下文.effect(装寿命,'schedule.lifecycle()')#生命周期标签

