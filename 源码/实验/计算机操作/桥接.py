'把保留的应用程序对象接到调用程序当前记了日志的工具绑定上'
from .类型 import 观察汇聚端
from .接口 import 创建计算机操作接口

__all__=['连接计算机操作']

def 连接计算机操作(获取工具,收到文本=None):
    '外部程序每次操作都重新取当前的 tools.cua 绑定。拒绝原样传出，不重试'
    def 派发(操作):
        '取当前绑定并调用一次'
        return 获取工具()(操作)#当前执行的绑定
    def 文本(值):
        '可选文本交给调用方的执行环境'
        if 收到文本 is not None:#调用方要文本
            return 收到文本(值)#交给它
        return None#没有接收者
    def 图像(_截图):
        '标准 tools.cua 结果已经带上截图附件'
        return None#不再发一次
    return 创建计算机操作接口(派发,观察汇聚端(文本,图像))#对象接口
