'实时折叠时保住看见的那一行，空出来的视口留在全部数据行后面'

检查器行高=30#表头和数据行的固定高度，单位是 CSS 像素

class 检查器表格布局:
    '可见数据行、折叠后的滚动位置，以及为了不跳动而留下的底部空白'
    def __init__(自身,层级,先前=None,视口=None,锚=None):
        '先前只在不是手动展开时传入。锚是刚点的那一行在视口里的位置'
        if 视口 is None:#没量过
            视口={'offset':0,'height':0}#零视口
        自身.层级=层级#当前可见层级
        自身.行下标={}#键到当前行号
        for 行号,行 in enumerate(层级.行):#可见行
            自身.行下标[行['key']]=行号#记下
        自身.项=[]#虚拟项，不含表头和尾部空白
        for 行号,行 in enumerate(层级.行):#每一可见行
            自身.项.append({'key':行['key'],'rowIndex':行号,'row':行,'size':检查器行高})#固定行高
        自身.保留折叠=False#这次是不是实时合上导致变短
        if 先前 is not None and len(层级.行)<len(先前.层级.行):#可见行变少
            for 行 in 层级.行:#找从开到合的块
                if 行.get('disclosure')!='closed':#不是合上
                    continue#下一行
                旧号=先前.行下标.get(行['key'],-1)#上一份里的位置
                if 旧号<0 or 旧号>=len(先前.层级.行):#上一份没有
                    continue#下一行
                if 先前.层级.行[旧号].get('disclosure')=='open':#上一份是开的
                    自身.保留折叠=True#这次要保住锚
                    break#找到一个就够
        锚号=None if 锚 is None else 自身.行下标.get(锚['key'])#被点的行还在不在
        if 锚 is not None and 锚号 is not None:#点的那一行还在
            自身.滚动偏移=max(0,(锚号+1)*检查器行高-锚['top'])#让它停在原来的视口位置
        elif 自身.保留折叠 and 先前 is not None:#实时合上
            自身.滚动偏移=自身.锚偏移(先前,视口['offset'])#按上一份视口推
        else:#不用改滚动
            自身.滚动偏移=None#交给跟随最新或用户滚动
        自然=(len(自身.项)+1)*检查器行高#表头加数据行
        if 自身.滚动偏移 is None:#没有锚
            最小=0 if 先前 is None else 先前.最小范围#沿用上一份最小高度
        else:#有新的滚动位置
            先前最小=0 if 先前 is None else 先前.最小范围#上一份
            最小=max(自身.滚动偏移+视口['height'],先前最小+自身.滚动偏移-视口['offset'])#盖住视口
        if 最小>自然:#自然高度不够
            自身.最小范围=最小#记住，避免下次跳动
        else:#自然高度够了
            自身.最小范围=0#不再留最小高度
        自身.底边距=max(0,自身.最小范围-自然)#多出来的空白放在数据后面

    def 粘性下标(自身,项下标):
        '表头之下要钉住的祖先下标'
        return 自身.层级.粘性下标(项下标)#层级已经算过

    def 偏移处粘性下标(自身,偏移):
        '当前滚动位置上，从外到内还钉着的祖先'
        结果=[]#已经占用的粘性层
        if len(自身.项)==0:#没有数据行
            return 结果#空
        首=max(0,int(偏移/检查器行高))#滚动落到的第一行
        while len(结果)<len(自身.项):#不会超过行数
            候选=min(len(自身.项)-1,首+len(结果))#跳过已经钉住的层
            祖先=自身.粘性下标(候选)#这一行的祖先
            if len(结果)>=len(祖先):#没有下一层
                break#停
            下一=祖先[len(结果)]#这一层的新祖先
            一致=True#前面的层必须相同
            for 层,已有 in enumerate(结果):#已钉住的层
                if 层>=len(祖先) or 祖先[层]!=已有:#换了一支
                    一致=False#不能再加
                    break#停
            if not 一致:#分支变了
                break#停
            结果.append(下一)#钉住这一层
        return 结果#外层在前

    def 锚偏移(自身,先前,偏移):
        '合上之后，尽量还停在原来看见的那一行或它的祖先'
        if len(先前.项)==0:#上一份是空的
            return 0#回到顶
        首=max(0,min(len(先前.项)-1,int(偏移/检查器行高)))#上一份视口第一行
        粘性=先前.偏移处粘性下标(偏移)#当时钉住的层数
        下标=min(len(先前.项)-1,首+len(粘性))#第一行再跳过粘性层
        行=先前.项[下标]['row']#当时看见的行
        留下=自身.行下标.get(行['key'])#这一份还在不在
        if 留下 is not None:#行还在
            return max(0,偏移+(留下-下标)*检查器行高)#按行差平移
        祖先=先前.粘性下标(下标)#从近到远的祖先下标，函数返回的是外层在前
        层=len(祖先)-1#从最近的祖先开始
        while 层>=0:#还有祖先
            父=先前.项[祖先[层]]['row']#祖先行
            下一=自身.行下标.get(父['key'])#祖先还在
            if 下一 is not None:#找到还能看见的祖先
                return max(0,(下一-层)*检查器行高)#对齐到那一层
            层=层-1#再外一层
        return 0#都没了就回到顶
