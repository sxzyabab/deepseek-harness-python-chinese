"""命令表共享的参数拆分：短标志（捆绑或分离）、长标志、`--`，以及其后的操作数。

对齐上游 `webworker-runtime/src/shell/programs/options.ts`。公开面仅中文名。
"""
__all__=['解析选项','数值选项','拆成行']#仅中文公开名

def 拆长标志(文本):#拆长标志
    """拆分 `name=value`；无 `=` 的长标志无值。"""
    分隔=文本.find('=')#等号位置
    return (文本,None) if 分隔<0 else (文本[:分隔],文本[分隔+1:])#无等号或拆分

def 解析选项(argv,带值=None):#拆分程序参数
    """拆分一个程序的参数。"""
    if 带值 is None:#默认无带值短字母
        带值=set()#空集合
    标志=set()#标志集合
    值们={}#带值标志
    操作数=[]#操作数缓冲
    其余=list(argv[1:])#去掉程序名
    字面=False#是否已遇--
    索引=0#扫描游标
    while 索引<len(其余):#逐参扫描
        参数=其余[索引]#当前参数
        if 字面 or 参数=='-' or not 参数.startswith('-'):#字面或非标志
            操作数.append(参数)#记入操作数
            索引+=1#下一参数
            continue#继续
        if 参数=='--':#字面分隔符
            字面=True#其后全作字面
            索引+=1#下一参数
            continue#继续
        if 参数.startswith('--'):#长标志
            名,值=拆长标志(参数[2:])#拆name=value
            标志.add(名)#记录标志名
            if 值 is not None:#有值则记下
                值们[名]=值#记下
            索引+=1#下一参数
            continue#继续
        游标=1#捆绑短字母起点
        while 游标<len(参数):#捆绑短字母
            字母=参数[游标]#当前短字母
            标志.add(字母)#记录短标志
            if 字母 not in 带值:#无值则继续
                游标+=1#下一字母
                continue#继续
            内联=参数[游标+1:]#同行内联值
            if 内联!='':#有内联值
                值们[字母]=内联#记下内联
            else:#需下一参数
                索引+=1#消费下一参
                值们[字母]=其余[索引] if 索引<len(其余) else ''#记下或空串
            break#带值字母截断捆绑
        索引+=1#下一参数
    return {'flags':标志,'values':值们,'operands':操作数}#返回解析结果

def 数值选项(选项,标志名,回退):#读数值标志
    """读取数值标志值。"""
    原始=选项['values'].get(标志名)#原始字符串
    if 原始 is None:#缺失则回退
        return 回退#回退
    try:#解析整数
        已解析=int(原始,10)#解析
    except ValueError:#非法
        return 回退#回退
    return 已解析#合法数字

def 拆成行(文本):#拆成行
    """将文本拆成行，供面向行的工具使用。"""
    if 文本=='':#空文本无行
        return []#无行
    行们=文本.split('\n')#按换行切分
    if 行们[-1]=='':#末尾空行
        行们.pop()#去掉
    return 行们#返回行列表
