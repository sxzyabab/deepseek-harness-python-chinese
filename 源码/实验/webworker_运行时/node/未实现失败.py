"""结构性未实现桩：被替换的模块必须暴露导入方命名的每一个符号
（缺失的 CommonJS 符号在调用时退化为 `undefined`，
而不是在链接期失败），且每一个符号在最终被调用时
都必须准确报告不可用的内容。

对齐上游 `webworker-runtime/src/node/notImplementedFail.ts`。公开面仅中文名。
"""
__all__=['未实现失败','不可用错误']#仅中文公开名

def 未实现失败(模块,符号):#构造抛错替身
    """构造一个抛错函数，错误信息包含模块名与符号名。拒绝信息在向上传播前
    也会写入控制台：调用方常在远离根因处吞掉这些错误，
    调试 Worker 会话时，控制台那一行才是定位失败点的依据。

    Face 是本桩所替代的 Node 声明，使被替换模块发布导入方编译所依赖的类型。
    不论该声明如何，值始终是一个抛错函数：调用方在任何已声明参数、返回值
    或 `new` 结果存在之前就会碰到抛错。
    使用函数表达式而非箭头，因为替代类的桩在 `new` 下也必须拒绝，
    而箭头没有可到达的构造行为。
    """
    def 拒绝(*位置参数,**关键字参数):#返回拒绝函数
        """调用即抛不可用错误。"""
        raise 不可用错误(模块,符号)#抛出不可用错误
    return 拒绝#交回替身

def 不可用错误(模块,符号):#构造拒绝错误
    """构造拒绝错误并先写入控制台，供无法做成普通抛错函数的桩使用
    （构造器、结构性假对象上的方法）。
    """
    消息=f'web-preview: {模块}.{符号} is not available in the worker host'#拼诊断文案
    print(消息)#先写控制台（对齐 console.error）
    return Exception(消息)#返回错误实例
