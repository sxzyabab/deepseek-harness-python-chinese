'按动作登记卡片正文。框架给没有正文的动作只留暂不需要'
__all__=['操作卡片注册表']


class 正文来源:
    '注册表当前正文表。快照引用在每次登记后更换'
    def __init__(自身,注册表):
        '记下所属注册表'
        自身.注册表=注册表

    def getSnapshot(自身):
        '当前动作到正文的映射'
        return 自身.注册表.正文表

    def subscribe(自身,监听):
        '登记变更回调，返回退订'
        自身.注册表.监听.add(监听)

        def 退订():
            '卸下这一次监听'
            自身.注册表.监听.discard(监听)

        return 退订


class 操作卡片注册表:
    '卡片正文按 action 存放。登记寿命跟贡献插件的副作用走'
    def __init__(自身,上下文):
        '正文表从空开始'
        自身.上下文=上下文
        自身.正文表={}
        自身.监听=set()
        自身.来源=正文来源(自身)
        自身.source=自身.来源

    def 发布(自身,正文表):
        '换上新表并通知监听'
        自身.正文表=正文表
        for 监听 in list(自身.监听):
            监听()

    def 登记(自身,描述):
        '登记一种动作的正文。同一动作再登记就失败'
        动作=描述['action']
        命名空间=描述['locale']
        正文类=描述['Body']

        def 画出(份额,译):
            '把框架份额和这一正文的翻译交给正文'
            属性=dict(份额)
            属性['t']=译
            if isinstance(正文类,type):
                return 正文类(属性)
            return 正文类(属性)

        正文={'locale':命名空间,'render':画出}

        def 挂上():
            '占用这个动作，卸下时删掉'
            if 动作 in 自身.正文表:
                raise Exception('action-cards: a body for "'+动作+'" is already registered')
            下一=dict(自身.正文表)
            下一[动作]=正文
            自身.发布(下一)

            def 卸下():
                '从当前表删掉这一动作'
                再下一=dict(自身.正文表)
                再下一.pop(动作,None)
                自身.发布(再下一)

            return 卸下

        拆除=自身.上下文.副作用(挂上,'action-cards: body '+动作)

        def 退订():
            '调用方在自己的副作用里持有这个拆除器'
            拆除()

        return 退订

    register=登记
