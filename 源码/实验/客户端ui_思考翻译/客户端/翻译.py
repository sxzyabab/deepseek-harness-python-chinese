'一个展开区里按段落顺序翻译'
import re#段落分隔
from ....客户端.连接.rpc import 中止控制器#这一展开区的取消

__all__=['思考翻译']


class 思考翻译:
    '一个展开区的取消、请求顺序和过期结果'
    def __init__(自身,选择,最大字符,翻译,发布):
        '记下提供方、语言、上限和发布回调'
        自身.选择=选择#provider 与 targetLanguage
        自身.最大字符=最大字符#单次 UTF-16 上限
        自身.翻译=翻译#一次远程请求
        自身.发布=发布#交给界面的状态
        自身.控制器=中止控制器()#本展开区的取消
        自身.缓存={}#原文到译文
        自身.片段表=[]#当前拆分
        自身.待定=False#有请求在途
        自身.失败=False#最近一次失败

    def 更新(自身,文本,进行中):
        '采用当前原文，并排上新完成的片段'
        def 码元长(片段):
            '按 UTF-16 码元计长度'
            return len(片段.encode('utf-16-le'))//2

        def 按码元切(片段,起,止=None):
            '按 UTF-16 码元切片，不拆开代理对'
            原始=片段.encode('utf-16-le')#码元字节
            if 止 is None:
                止=len(原始)//2#切到末尾
            return 原始[起*2:止*2].decode('utf-16-le')#回到字符

        分隔=re.compile(r'\r?\n(?:[\t ]*\r?\n)+')#空行，空白行也算
        起点=0#下一段的字符起点
        结果=[]#拆出来的片段
        while True:
            匹配=分隔.search(文本,起点)#下一段落分隔
            if 匹配 is None:
                段尾=len(文本)#没有分隔就到末尾
            else:
                段尾=匹配.start()#分隔之前
            剩余=文本[起点:段尾]#这一段正文
            while 码元长(剩余)>自身.最大字符:
                切点=自身.最大字符#先按上限切
                if 切点>=1:
                    原始=剩余.encode('utf-16-le')#看切点前一个码元
                    单元=int.from_bytes(原始[(切点-1)*2:切点*2],'little')#码元
                    if 0xD800<=单元<=0xDBFF:
                        切点=切点-1#不拆开代理对
                前段=按码元切(剩余,0,切点)#切点之前
                空白=re.search(r'\s+\S*$',前段)#靠后的空白
                if 空白 is not None:
                    空白位=len(前段[:空白.start()].encode('utf-16-le'))//2#码元下标
                    if 空白位>0:
                        切点=空白位#改在空白处切
                来源=按码元切(剩余,0,切点)#这一刀的正文
                剩余=按码元切(剩余,切点)#剩下的
                前导=re.match(r'^\s+',剩余)#紧挨着的空白归后缀
                if 前导 is None:
                    后缀=''#没有前导空白
                else:
                    后缀=前导.group(0)#原样保留
                剩余=剩余[len(后缀):]#正文去掉这段空白
                结果.append({'文本':来源,'后缀':后缀,'完成':True})#超长段已完成
            if 匹配 is None:
                段后缀=''#最后一段没有分隔
            else:
                段后缀=匹配.group(0)#段落之间的空白
            结果.append({
                '文本':剩余,
                '后缀':段后缀,
                '完成':匹配 is not None or not 进行中,#还在增长的尾段先不译
            })
            if 匹配 is None:
                break#没有下一段
            起点=匹配.end()#下一段从分隔之后开始
        自身.片段表=结果#换上这一版
        自身.发出()#先按缓存拼一版
        自身.运行()#再译新完成的

    def 重试(自身):
        '失败后重试尚未翻译的片段'
        自身.失败=False#清掉失败
        自身.运行()#继续未缓存的

    def 拆除(自身):
        '中止本展开区的请求，之后不再发布'
        自身.控制器.abort()#取消在途

    def 已拆除(自身):
        '控制器已中止'
        return 自身.控制器.signal.aborted#已取消

    def 下一段(自身):
        '下一个已完成、非空白、尚未缓存的片段'
        for 片段 in 自身.片段表:
            if 片段['完成'] and 片段['文本'].strip()!='' and 片段['文本'] not in 自身.缓存:
                return 片段#这一段还没译
        return None#都译完了或还没完成

    def 发出(自身):
        '已完成片段用缓存译文，未完成片段保留原文'
        if 自身.已拆除():
            return#拆除后不再发布
        段=[]#拼出来的展示
        for 片段 in 自身.片段表:
            if 片段['完成'] and 片段['文本'] in 自身.缓存:
                内容=自身.缓存[片段['文本']]#用译文
            else:
                内容=片段['文本']#还用原文
            段.append(内容+片段['后缀'])#后缀原样接上
        自身.发布({'文本':''.join(段),'待定':自身.待定,'失败':自身.失败})#交给界面

    def 运行(自身):
        '串行翻译已完成且未缓存的片段'
        if 自身.待定 or 自身.失败 or 自身.已拆除():
            return#已经在译、失败待重试，或已拆除
        下一段=自身.下一段()#第一段
        if 下一段 is None:
            return#没有可译的
        自身.待定=True#开始在途
        自身.发出()#先标成正在翻译
        try:
            while 下一段 is not None:
                译文=自身.翻译({
                    'provider':自身.选择['provider'],#已选提供方
                    'targetLanguage':自身.选择['targetLanguage'],#已解析的目标语言
                    'text':下一段['文本'],#这一段原文
                },自身.控制器.signal)#带上本展开区的取消
                if 自身.已拆除():
                    return#结果作废
                自身.缓存[下一段['文本']]=译文#留下译文
                自身.发出()#这一段换成译文
                下一段=自身.下一段()#下一段
        except Exception:
            if not 自身.已拆除():
                自身.失败=True#留下失败，等重试
        finally:
            自身.待定=False#在途结束
            自身.发出()#发布最终状态
