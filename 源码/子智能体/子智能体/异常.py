class 子智能体深度错误(Exception):
    '启动子体会超过所请求深度上限时抛出'
    def __init__(自身,尝试深度,最大深度):
        '记下尝试深度与上限；消费方只读中文属性'
        Exception.__init__(自身,'子智能体深度 '+str(尝试深度)+' 超过 maxDepth '+str(最大深度))#文案含两个数
        自身.尝试深度=尝试深度#已算出的子深度
        自身.最大深度=最大深度#调用方给出的绝对上限

