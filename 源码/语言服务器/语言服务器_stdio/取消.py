def 中止错误(信号):
    '把中止信号转成可抛出的错误，并保留超时分类'
    超时=取超时(信号)#尝试取出超时分类
    if 超时 is not None:#有超时原因则原样返回
        return 超时#超时原因
    return 语言服务器错误('语言服务器查询已中止','LSP_ABORTED')#通用中止

def 可中止等待(工作,信号=None):
    '返回期约：工作先结算就跟随工作，信号先中止就以分类后的中止原因拒绝；底层工作仍保留自己的处理，并继续到其所有者定义的静止边界。工作是期约'
    if 信号 is None:#无信号则原样返回工作
        return 工作#工作期约
    if 已中止(信号):#已中止则立刻拒绝
        已拒绝=期约()#拒绝结果
        已拒绝.拒绝(中止错误(信号))#分类中止
        return 已拒绝#已落定
    取消=期约()#信号中止时拒绝
    def 转发中止():
        '信号中止时拒绝取消期约'
        等待中止(信号)#阻塞到中止
        取消.拒绝(中止错误(信号))#用分类中止拒绝
    启动守护线程(转发中止)#转发中止
    return 期约.竞速([工作,取消])#工作与中止谁先到谁决定
