class 策略调度标记:#已安装策略的进程级路由句柄
    """已安装策略的进程级路由句柄。

    Node 侧对应 undici 全局 Agent（factory 内按源站建 ProxyAgent 或 Pool）。
    Python 无 undici Agent / Pool / ProxyAgent；本对象只证明策略已安装并可查询路由，
    关闭时仅作拆除标记（无真实连接池可关，已派发请求语义上仍可完成）。
    """
    def __init__(自身,策略):#绑到已安装策略
        """记下按之路由的策略。"""
        自身.策略=策略#当前策略
        自身._已关闭=False#是否已关闭

    def 关闭(自身):#拆除时调用
        """标记关闭；无真实连接池。"""
        自身._已关闭=True#记下关闭

#代理路由：{'经代理':True,'代理':str,'调度器':策略调度标记} 或 {'经代理':False}
代理路由=dict#名义类型
直连路由={'经代理':False}#不经任何代理发送的路由，因无每请求状态而共享

def 按网址取代理路由(网址):#按网址取路由
    """决定如何发送一次请求，并交回该决定假定的传输标记。

    网址为 urllib.parse 解析结果。未安装则直连；经代理臂携带已按本策略路由的调度标记。
    """
    策略=活动策略#活动策略
    调度器=已安装调度标记#已装调度标记
    if 策略 is None or 调度器 is None:#未安装则直连
        return 直连路由#直连
    代理=按网址取代理(策略,网址)#选代理
    if 代理 is None:#直连
        return 直连路由#直连
    return {'经代理':True,'代理':代理,'调度器':调度器}#经代理

def 快照代理环境():#快照代理环境
    """读取本包发布的每个代理名，以 os.environ 当前所持为准。"""
    快照={}#快照
    for 名称们 in 策略环境名.values():#每组名
        for 名称 in 名称们:#逐名
            快照[名称]=os.environ.get(名称)#读当前；缺席为 None
    return 快照#返回

def 写入代理环境(各值):#写代理环境
    """把每个代理名设为各值所持值，值为 None 的名则删除。返回把每个名恢复到本调用前状态的函数。"""
    #写任何一个之前快照每个名。Windows 大小写不敏感折叠环境名，因此写小写后再读大写会读回刚写的值。
    先前=快照代理环境()#写前快照
    for 名称 in 先前:#逐名
        值=各值.get(名称)#目标值
        if 值 is None:#删除
            os.environ.pop(名称,None)#删除
        else:#写入
            os.environ[名称]=值#写入
    def 恢复():#恢复器
        """把每个名恢复到写入前状态。"""
        for 名称,值 in 先前.items():#逐名恢复
            if 值 is None:#删除
                os.environ.pop(名称,None)#删除
            else:#写回
                os.environ[名称]=值#写回
    return 恢复#结束恢复器

def 应用策略环境(策略):#发布策略环境
    """经代理环境变量发布策略，供读环境而非策略对象的消费者看到唯一已解析答案。

    全局调度标记不读这些；它按策略路由。返回恢复本调用改过的每个名的函数。
    """
    global 继承代理环境#最外层继承指针
    先前继承=继承代理环境#先前继承
    if 先前继承 is None:#最外层快照
        继承代理环境=快照代理环境()#记下用户环境
    待发布={}#待写值
    for 字段,名称们 in 策略环境名.items():#按字段
        值=策略.get(字段) if 字段!='绕过代理' else 策略['绕过代理']#策略值
        for 名称 in 名称们:#写每个名
            待发布[名称]=值#写入映射
    恢复环境=写入代理环境(待发布)#写入并得恢复器
    def 恢复():#恢复
        """恢复环境与继承指针。"""
        global 继承代理环境#继承指针
        恢复环境()#恢复环境
        继承代理环境=先前继承#恢复继承指针
    return 恢复#结束恢复

def 创建策略调度标记(策略):#创建策略调度标记
    """为一份策略构建进程级调度标记。

    Node 侧会 new Agent({ factory(origin) { ProxyAgent | Pool } })，factory 内调 proxyForUrl。
    Python 无 undici Agent / Pool / ProxyAgent；路由仍经按网址取代理，与查询面同一匹配器。
    """
    return 策略调度标记(策略)#可安装的策略状态

def 安装全局代理(策略):#安装全局代理
    """经策略路由本进程出站 HTTP。

    Node 侧替换 undici 全局 dispatcher。Python 侧记录活动策略、可选发布环境，并安装策略调度标记。
    不代理任何东西的策略安装直连状态且按叠装规则处理环境。返回拆除器。
    """
    global 活动策略,已安装调度标记#进程级状态
    先前策略=活动策略#先前策略
    if 策略['来源']=='none':#直连策略
        #叠在已安装策略上的直连策略必须真正停止代理。只记录策略会留下先前标记——且 mode off 会成静默空操作。
        if 先前策略 is None:#无已装
            活动策略=策略#记下直连策略
            def 拆除空():#拆除
                """恢复空策略。"""
                global 活动策略#活动策略
                活动策略=先前策略#恢复空
            return 拆除空#结束拆除
        先前已装=已安装调度标记#先前调度标记
        #下层安装把规范化策略发布进环境；无活动策略则恢复用户自己的值。
        恢复环境=写入代理环境(继承代理环境) if 继承代理环境 is not None else None#恢复用户环境
        #Node 侧此处 setGlobalDispatcher(new Agent())；Python 无对等全局 dispatcher，仅清安装标记。
        活动策略=策略#记下策略
        已安装调度标记=None#清安装标记
        def 拆除直连覆盖():#拆除直连覆盖
            """恢复先前策略、标记与环境。"""
            global 活动策略,已安装调度标记#进程级状态
            活动策略=先前策略#恢复策略
            已安装调度标记=先前已装#恢复安装标记
            if 恢复环境 is not None:#有环境可还原
                恢复环境()#恢复环境
        return 拆除直连覆盖#结束拆除
    恢复环境=应用策略环境(策略)#发布策略环境
    先前已装=已安装调度标记#先前安装
    标记=创建策略调度标记(策略)#创建策略调度标记（非 undici Agent）
    活动策略=策略#记下策略
    已安装调度标记=标记#记下安装
    def 拆除代理():#拆除代理
        """恢复先前全局状态并关闭调度标记。"""
        global 活动策略,已安装调度标记#进程级状态
        活动策略=先前策略#恢复策略
        已安装调度标记=先前已装#恢复安装标记
        恢复环境()#恢复环境
        标记.关闭()#关闭标记（无真实连接池）
    return 拆除代理#结束拆除

def 子进程代理环境():#子进程代理环境
    """派生子进程需要的代理环境。

    子进程继承父环境，而本进程已重写为自身已解析策略。用户导出的代理名恢复为其所写；
    未命名方案携带已解析值。旁路列表始终是已解析的。含本包拒绝过的值时扣下 NODE_USE_ENV_PROXY。
    """
    策略=活动策略#活动策略
    继承=继承代理环境#继承环境
    if 策略 is None or 策略['来源']=='none' or 继承 is None:#无代理
        return {}#空对象
    覆盖={'NODE_USE_ENV_PROXY':'1'}#默认开标志（环境变量名保留英文）
    for 字段,名称们 in 策略环境名.items():#按字段
        已解析=策略.get(字段) if 字段!='绕过代理' else 策略['绕过代理']#已解析值
        #任一大小写命名方案即认领该方案：子得到用户所写、所写大小写。
        已命名=字段!='绕过代理' and any(继承.get(名称) is not None for 名称 in 名称们)#用户是否命名
        for 名称 in 名称们:#写覆盖
            覆盖[名称]=继承.get(名称) if 已命名 else 已解析#写覆盖
    节点解析名=策略环境名['http代理']+策略环境名['https代理']#Node 解析的名
    if any(覆盖.get(名称) is not None and not 是否受支持代理网址(覆盖[名称]) for 名称 in 节点解析名):#含拒绝方案
        覆盖.pop('NODE_USE_ENV_PROXY',None)#扣下标志
    return 覆盖#返回覆盖

def 从环境安装代理(环境,报告):#从环境安装代理
    """从环境解析本进程代理策略并安装。

    解析、报告与安装是一次操作。环境提供但本包不能用的值报告并跳过而非抛出。
    返回恢复先前策略与环境的拆除器。
    """
    结果=解析代理策略(环境)#解析策略
    for 诊断 in 结果['诊断']:#按考虑顺序
        报告(诊断['消息'])#报告诊断
    return 安装全局代理(结果['策略'])#安装

def 清空代理环境():#清空代理环境
    """从派生子进程移除每个代理名的环境覆盖。None 表示删除继承名。"""
    return {名称:None for 名称 in 代理环境名}#全 None
