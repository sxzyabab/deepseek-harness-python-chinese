"""不可变的启动时环境快照，记录每一项值由哪一层提供。Harness 消费方经它解析，而不是扁平的进程环境；启动器仍可为配置表达式和第三方库物化已接受的值。"""
import os#平台判定与进程环境
__all__=[#仅中文公开名
    '来源_进程','来源_项目环境','来源_用户环境','来源顺序','启动环境键',
    '启动环境来源','启动环境条目','启动环境层输入','查找键','启动环境快照',
    '创建启动环境快照','取启动环境',
]#公开面结束

来源_进程='process'#本进程继承的环境；英文取值 process
来源_项目环境='project-env'#调用目录的.env；英文取值 project-env
来源_用户环境='user-env'#Harness主目录的.env；英文取值 user-env
来源顺序=(来源_进程,来源_项目环境,来源_用户环境)#层顺序，最受信任的在前
启动环境键='launchEnvironment'#启动器填入本次运行快照的上下文槽键名
启动环境来源=str#来源层名义类型：process|project-env|user-env
启动环境条目=dict#条目名义类型：value/source，文件层可有 path
启动环境层输入=dict#层输入名义类型：source/values，文件层可有 path

def 查找键(名称):#平台相关的查找键
    """一个变量名解析所用的映射键。Windows 对环境名大小写不敏感；其余平台敏感。"""
    if os.name=='nt':#Windows折叠大小写
        return 名称.upper()#折叠后的键
    return 名称#POSIX精确匹配

class 启动环境快照:#一次启动的冻结环境
    """一次启动的冻结环境。经创建启动环境快照构造；之后无人改动，因此后来的切目录、工作区切换或恢复会话看到的是启动时消费方解析到的同一批值。"""
    def __init__(自身,按来源):#收下按来源层收纳的拷贝
        """收下按来源层收纳的不可变拷贝。"""
        自身._按来源=按来源#来源层到路径与变量表的映射

    def 从中取(自身,名称,来源们):#只从允许层按信任顺序解析
        """只从来源们解析一个名字，仍保留规范信任顺序；省略的层不可达。返回第一个匹配条目，或 None。"""
        键=查找键(名称)#平台查找键
        for 来源 in 来源顺序:#规范顺序遍历
            if 来源 not in 来源们:#调用方未允许该层
                continue#跳过
            层=自身._按来源.get(来源)#取出该层拷贝
            if 层 is None:#没有该层
                continue#跳过
            值=层['values'].get(键)#按折叠键取值
            if 值 is None:#本层没有该名
                continue#跳过
            条目={'value':值,'source':来源}#胜出条目
            路径=层.get('path')#文件层路径
            if 路径 is not None:#有路径才带上
                条目['path']=路径#文件绝对路径
            return 条目#胜出
        return None#没有任何允许层提供

    def 取(自身,名称):#按最受信任优先跨每一层解析
        """按最受信任优先，跨每一层解析一个名字。返回胜出的条目；没有任何层提供时为 None。"""
        return 自身.从中取(名称,来源顺序)#全层解析

def 创建启动环境快照(各层):#从各层内容构建快照
    """从各层内容构建快照。各层任意顺序；结果按规范信任顺序搜索它们。返回不可变快照。"""
    #拷贝每一层，使之后的改动无法影响快照。Windows上折叠名字以免大小写变体拆开优先级；POSIX保持精确匹配。
    按来源={}#按来源层收纳拷贝
    for 层 in 各层:#逐层拷贝进映射
        变量表={}#本层折叠后的变量表
        for 名称,值 in 层['values'].items():#按平台键折叠后拷贝
            变量表[查找键(名称)]=值#写入折叠键
        拷贝={'values':变量表}#一层拷贝
        if 层.get('path') is not None:#有路径才带上
            拷贝['path']=层['path']#文件层绝对路径
        按来源[层['source']]=拷贝#后写的同层覆盖先写的
    return 启动环境快照(按来源)#冻结快照对象

def 取启动环境(上下文对象):#读取或回退本次启动快照
    """返回启动器快照；宿主未提供时把继承环境当作唯一层。"""
    取方法=getattr(上下文对象,'取',None)#中文宽松读取（Cordis 反射混入）
    if callable(取方法):#有中文取
        已有=取方法(启动环境键,False)#启动器填入的快照，宽松读取
    else:#试英文 get
        取英=getattr(上下文对象,'get',None)#英文 get（Cordis 反射混入）
        if callable(取英):#有英文 get
            已有=取英(启动环境键,False)#宽松读取
        else:#无反射取则直接属性
            已有=getattr(上下文对象,启动环境键,None)#可选启动环境属性
    if 已有 is not None:#宿主已提供
        return 已有#用启动器快照
    return 创建启动环境快照([{'source':来源_进程,'values':dict(os.environ)}])#无快照则只用进程环境
