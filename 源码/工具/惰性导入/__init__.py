__all__=['创建惰性导入']#仅中文公开名

def 创建惰性导入(规格名,父网址):#按调用方解析并只缓存成功结果
    """按调用方相对解析创建成功结果缓存。失败的加载不缓存。父网址对应调用方 import.meta.url。"""
    已加载=False#尚未成功加载
    值=None#缓存槽
    def 加载():#首次使用才导入
        """首次成功后复用同一模块值。"""
        nonlocal 已加载,值#改外层缓存
        if not 已加载:#尚未成功
            值=__import__(规格名)#按规格名导入
            已加载=True#只缓存成功
        return 值#模块值
    return 加载#零参加载器
