"""零依赖环形双端队列：跨异步工作仍保留条目的队列。"""
__all__=['双端队列']#仅中文公开名

最小容量=16#初始与收缩下限

class 双端队列:#环形双端队列
    """摊还常数时间的插入与删除。移除项会立刻清空引用，稀疏存储在活条目数降到容量四分之一以下时收缩。"""
    def __init__(自身):#构造空队列
        """构造空队列。"""
        自身._缓冲=[None]*最小容量#环形缓冲
        自身._头=0#头下标
        自身._计数=0#活条目数
    @property#只读
    def 大小(自身):#可移除条目数
        """可移除条目数。"""
        return 自身._计数#活条目数
    def 尾推(自身,值):#尾后追加
        """在当前尾后追加一条。"""
        自身._确保容量()#必要时扩容
        尾=自身._头+自身._计数#尾位置
        自身._缓冲[尾 if 尾<len(自身._缓冲) else 尾-len(自身._缓冲)]=值#写入
        自身._计数+=1#计数加一
    def 头推(自身,值):#头前插入
        """在当前头前插入一条。"""
        自身._确保容量()#必要时扩容
        自身._头=0 if 自身._头==0 else 自身._头-1#头前移
        自身._缓冲[自身._头]=值#写入
        自身._计数+=1#计数加一
    def 头弹(自身):#移除头并清引用
        """移除头并清引用。空队列返回 None。"""
        if 自身._计数==0:#空队列
            return None#无条目
        值=自身._缓冲[自身._头]#读出
        自身._缓冲[自身._头]=None#清引用
        自身._头+=1#头后移
        if 自身._头==len(自身._缓冲):#绕回
            自身._头=0#归零
        自身._计数-=1#计数减一
        自身._收缩()#必要时缩容
        return 值#被移除项
    def 清空(自身):#丢弃全部条目
        """丢弃全部条目并释放当前后备存储。"""
        自身._缓冲=[None]*最小容量#重置缓冲
        自身._头=0#头归零
        自身._计数=0#计数归零
    def _确保容量(自身):#必要时翻倍
        """活条目将满时翻倍容量。"""
        if 自身._计数<len(自身._缓冲):#仍有空位
            return#不用扩
        自身._调整大小(len(自身._缓冲)*2)#翻倍
    def _收缩(自身):#必要时减半
        """活条目降到四分之一以下时收缩。"""
        if 自身._计数==0:#已空
            自身._头=0#头归零
            return#停
        if len(自身._缓冲)>最小容量 and 自身._计数<=len(自身._缓冲)//4:#可收缩
            自身._调整大小(max(最小容量,len(自身._缓冲)//2))#减半但不低于下限
    def _调整大小(自身,容量):#重排成连续段
        """把活条目搬到新缓冲并从头连续排列。"""
        下一=[None]*容量#新缓冲
        源=自身._头#当前头
        for 下标 in range(自身._计数):#逐条复制
            下一[下标]=自身._缓冲[源]#复制
            源+=1#前进
            if 源==len(自身._缓冲):#绕回
                源=0#归零
        自身._缓冲=下一#替换
        自身._头=0#头归零
