定时器延迟上限毫秒=2147483647#Node调度延迟时不会钳成一毫秒的最大延迟

class 超时原因(Exception):#能力拥有的超时中止原因
    """内部中止原因，携带能力拥有的码与已到截止。提供方在返回调用方之前经取超时翻译。"""
    def __init__(自身,码,超时毫秒):#记下超时码与截止毫秒
        """记下能力拥有的超时码与已到截止毫秒。"""
        super().__init__(码+' after '+str(超时毫秒)+'ms')#拼出英文诊断文案，字面量不翻译
        自身.name='TimeoutReason'#固定错误名为TimeoutReason
        自身.code=码#能力拥有的超时码
        自身.timeoutMs=超时毫秒#已到截止毫秒

class 中止信号:#对应AbortSignal，只通知不自己停工作
    """对应 AbortSignal：已中止后暴露原因，等待可阻塞到中止。"""
    def __init__(自身,事件对象,取原因):#绑到共享事件与原因读取
        """绑到共享事件与原因读取。"""
        自身._事件=事件对象#中止事件
        自身._取原因=取原因#读取原因
    @property#只读属性
    def 已中止(自身):#是否已经中止
        """是否已经中止。"""
        return 自身._事件.is_set()#事件已置位
    @property#只读属性
    def 原因(自身):#中止原因
        """中止原因。"""
        return 自身._取原因()#当前原因
    def 等待(自身):#阻塞直到中止
        """阻塞直到中止。"""
        自身._事件.wait()#等待事件

class 中止控制器:#对应AbortController
    """对应 AbortController：一对控制器与信号。"""
    def __init__(自身):#创建一对控制器与信号
        """创建一对控制器与信号。"""
        自身._事件=threading.Event()#中止事件
        自身._原因=None#中止原因
        自身.信号=中止信号(自身._事件,自身._读原因)#对外信号
    def _读原因(自身):#读取当前中止原因
        """读取当前中止原因。"""
        return 自身._原因#原因
    def 中止(自身,原因=None):#发出中止；重复调用忽略
        """发出中止；重复调用忽略。"""
        if 自身._事件.is_set():#已中止
            return#忽略
        自身._原因=原因#记下原因
        自身._事件.set()#置位

def 取已中止(信号):#读已中止事实
    """从中文或英文字段读已中止事实。"""
    if hasattr(信号,'已中止'):#中文属性
        return bool(信号.已中止)#中文
    return bool(getattr(信号,'aborted',False))#英文或缺席

def 取原因值(信号):#读中止原因
    """从中文或英文字段读中止原因。"""
    if hasattr(信号,'原因'):#中文属性
        return 信号.原因#中文
    return getattr(信号,'reason',None)#英文或缺席

def 等待中止(信号):#阻塞到信号中止
    """阻塞到信号中止；优先走等待方法。"""
    等待=getattr(信号,'等待',None)#中文等待
    if callable(等待):#有等待
        等待()#阻塞
        return#结束
    等待英=getattr(信号,'wait',None)#英文等待
    if callable(等待英):#有英文等待
        等待英()#阻塞
        return#结束
    while not 取已中止(信号):#无等待则轮询
        threading.Event().wait(0.01)#短暂让出

def 合成信号(*信号们):#对应AbortSignal.any
    """对应 AbortSignal.any：先中止的一路获胜并把原因转到合成信号。"""
    控制器=中止控制器()#合成控制器
    for 源 in 信号们:#逐路检查
        if 取已中止(源):#已中止则立刻合成
            控制器.中止(取原因值(源))#转发原因
            return 控制器.信号#合成信号
    def 转发(源):#源中止后转发
        """源中止后转发到合成控制器。"""
        等待中止(源)#阻塞到源中止
        控制器.中止(取原因值(源))#转发原因
    for 源 in 信号们:#监视每一路
        threading.Thread(target=转发,args=(源,),daemon=True).start()#后台监视
    return 控制器.信号#融合信号

def 断言定时器延迟(超时毫秒,名称):#校验定时器延迟合法
    """校验定时器延迟为正有限且不超过上限。"""
    if (isinstance(超时毫秒,bool) or not isinstance(超时毫秒,(int,float)) or#布尔或非数
            not math.isfinite(超时毫秒) or 超时毫秒<=0 or 超时毫秒>定时器延迟上限毫秒):#非正、非有限或超上限
        raise Exception(名称+' must be a positive finite number no greater than '+str(定时器延迟上限毫秒))#字段名进入抛出文案

def 夹取超时(请求,默认,上限,名称='timeoutMs'):#把可选提示钳到后端默认与上限之间
    """校验调用方可选的超时提示，使用后端默认值，再封顶。提供的值必须为正且有限；零不是公开的禁用超时哨兵。返回 min(请求 ?? 默认, 上限)。"""
    if 请求 is not None and (isinstance(请求,bool) or not isinstance(请求,(int,float)) or not math.isfinite(请求) or 请求<=0):#提供了但非法
        raise Exception(名称+' must be a positive finite number')#必须是正有限数
    return min(默认 if 请求 is None else 请求,上限)#缺席用默认，再与上限取小

class 截止句柄:#融合后的截止句柄
    """截止信号加上清除其定时器的清理（只释放一次）。"""
    def __init__(自身,信号,清理):#记下信号与清理
        """记下融合信号与定时器清理。"""
        自身.signal=信号#英文字段，供取字段读
        自身.信号=信号#中文字段
        自身._清理=清理#清理函数
        自身._已释放=False#是否已释放
    def 释放(自身):#清除定时器
        """清除定时器。调用一次即安全。"""
        if 自身._已释放:#已释放
            return#只释放一次
        自身._已释放=True#标记已释放
        自身._清理()#清掉定时器

def 截止(上游,超时毫秒,码):#融合上游取消与可识别超时
    """把上游取消与可识别超时融合。超时毫秒<=0 是内部无定时器哨兵；返回的释放清除已武装定时器。信号只通知，因此调用方必须自己停下工作。"""
    if 超时毫秒<=0:#无超时（后台工作）
        信号=上游 if 上游 is not None else 中止控制器().信号#只转发上游；没有上游时用永不中止的信号
        return 截止句柄(信号,lambda: None)#无定时器可清
    断言定时器延迟(超时毫秒,'deadline timeoutMs')#校验截止延迟可调度
    控制器=中止控制器()#本截止专用控制器
    def 到期():#到期用超时原因中止
        """到期用超时原因中止。"""
        控制器.中止(超时原因(码,超时毫秒))#带能力码中止
    定时器=threading.Timer(超时毫秒/1000.0,到期)#按毫秒调度
    定时器.daemon=True#守护线程
    定时器.start()#武装定时器
    if 上游 is not None:#有上游则融合
        信号=合成信号(上游,控制器.信号)#AbortSignal.any采用最先中止那路的原因
    else:#无上游
        信号=控制器.信号#只用定时器
    return 截止句柄(信号,定时器.cancel)#释放已武装定时器

class 空闲看门狗句柄:#可再武装的空闲看门狗
    """围绕一次未完成迭代器需求的可再武装超时。"""
    def __init__(自身,信号,超时毫秒,码):#记下稳定信号与空闲参数
        """记下整次调用稳定的融合信号与空闲参数。"""
        自身.signal=信号#英文稳定信号
        自身.信号=信号#中文稳定信号
        自身._超时毫秒=超时毫秒#空闲间隔毫秒
        自身._码=码#超时原因上的能力码
        自身._定时器=None#当前武装的定时器
        自身._未完成=False#是否已有未完成的下一步
        自身._已释放=False#是否已释放
        自身._中止源=None#本看门狗专用中止源，供到期写入
    def _绑中止源(自身,中止源):#绑上看门狗专用中止源
        """绑上看门狗专用中止源，供到期写入。"""
        自身._中止源=中止源#记下
    def _武装(自身):#（再）武装空闲定时器
        """（再）武装空闲定时器。"""
        if 自身._定时器 is not None:#已有旧定时器
            自身._定时器.cancel()#先清掉旧定时器
        def 到期():#到期中止
            """用能力码中止。"""
            自身._中止源.中止(超时原因(自身._码,自身._超时毫秒))#用能力码中止
        自身._定时器=threading.Timer(自身._超时毫秒/1000.0,到期)#按空闲间隔调度
        自身._定时器.daemon=True#守护线程
        自身._定时器.start()#开始计时
    def 下一步(自身,迭代器):#武装期间取下一个值
        """在空闲定时器已武装时等待一次迭代器需求，返回 {done,value}。"""
        if 自身._已释放:#已释放不能再取
            raise Exception('idleWatchdog is disposed')#已释放
        if 自身._未完成:#禁止重叠下一步
            raise Exception('idleWatchdog next is already outstanding')#已有未完成需求
        自身._未完成=True#标记需求未完成
        自身._武装()#开始空闲计时
        try:#等待迭代器进展
            try:#取下一个值
                值=next(迭代器)#交回下一个值
                return {'done':False,'value':值}#未结束
            except StopIteration as 结束:#迭代结束
                return {'done':True,'value':结束.value}#结束结果
        finally:#无论成败都拆掉本次计时
            if 自身._定时器 is not None:#有定时器
                自身._定时器.cancel()#清除本次武装
            自身._定时器=None#标记无定时器
            自身._未完成=False#允许下一次下一步
    def 脉冲(自身):#无值的传输活动后重置计时
        """在没有迭代器值的传输活动后，为未完成需求再武装；否则为空操作。"""
        if 自身._已释放 or not 自身._未完成:#已释放或无未完成需求则忽略
            return#空操作
        自身._武装()#重新武装空闲定时器
    def 释放(自身):#释放看门狗
        """清除已武装定时器；拥有流退出时调用一次即安全。"""
        if 自身._已释放:#只释放一次
            return#已释放
        自身._已释放=True#标记已释放
        if 自身._定时器 is not None:#有残留定时器
            自身._定时器.cancel()#清掉残留定时器
        自身._定时器=None#丢掉句柄

def 空闲看门狗(上游,超时毫秒,码):#为空闲迭代器需求武装看门狗
    """为迭代器创建可再武装的空闲看门狗。定时器只在下一步未完成时存在，因此消费方思考时间不算提供方空闲。返回的信号整次调用稳定且只通知；迭代器必须观察它才能终止工作。"""
    断言定时器延迟(超时毫秒,'idleWatchdog timeoutMs')#校验空闲间隔可调度
    超时控制器=中止控制器()#看门狗专用控制器
    if 上游 is None:#无上游则只用看门狗信号
        信号=超时控制器.信号#单独看门狗信号
    else:#与上游融合
        信号=合成信号(上游,超时控制器.信号)#与上游融合
    句柄=空闲看门狗句柄(信号,超时毫秒,码)#看门狗实例
    句柄._绑中止源(超时控制器)#绑上到期写入源
    return 句柄#可再武装看门狗

def 取超时(载体,码=None):#从载体取出匹配的超时原因
    """从带 reason/原因 的对象恢复超时原因。提供码可把本截止与嵌套上游截止区分开；外码走普通取消路径。"""
    if isinstance(载体,dict):#裸reason载体
        原因=载体.get('reason')#英文键
        if 原因 is None:#缺席再试中文键
            原因=载体.get('原因')#中文键
    else:#信号或对象载体
        原因=取原因值(载体)#中文或英文属性
    if not isinstance(原因,超时原因):#不是本库超时原因
        return None#未匹配
    if 码 is None or 原因.code==码:#无码要求或码精确匹配
        return 原因#匹配的超时原因
    return None#码不匹配
