"""轻依赖的**截留**库：给必须限制回传上下文量的工具，产出有上界的面向模型输出。调用方把条目或文本块喂进有界对象，再拿到截留内容与精确省略元数据（`保留条目` / `保留文本`）。

本库只拥有机械问题「留下了什么、省略了什么」。工具自己的代码仍拥有业务语义：文件分组、行号、退出码、提供方错误状态、按行预览截断、溢出文件，以及面向模型的文案。特别地，`保留文本['truncated']`/`保留条目['truncated']` 表示「截留器因预算省略了本来可用的内容」——不是「上游不完整」。权限失败、跳过的二进制、提供方部分失败、不可读候选留在工具域字段里，绝不折进 `truncated`。

这刻意是库而不是 cordis 服务或插件：不取 `ctx`、不注册、不发事件。两套截留器是仅有的有状态部件，状态按实例（一次累积），从不跨调用。工具包需要有界输出时直接导入。

两套截留器的资源模型不同，因此用两个名字而不是一个泛型收集器：
- `条目保留器` 约束有序逻辑单元（路径、grep 命中、搜索来源）。v1 只有 `head` 截留。
- `文本保留器` 约束面向字节的文本流（bash 标准输出/标准错误、web 正文）。`head` / `tail` / `headTail`，在 `收尾` 处保住 UTF-8 边界。
"""
