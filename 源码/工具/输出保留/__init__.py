def 取策略字段(策略,键):#从映射或对象读策略字段
    """从映射或对象读策略字段（对齐 TS 属性访问）。"""
    if isinstance(策略,dict):#映射策略
        return 策略[键]#映射键
    return getattr(策略,键)#对象属性

def 是否非负整数(值):#对齐 Number.isInteger 且非负
    """非负整数（排除布尔）；浮点整值也接受以便对齐 JS Number.isInteger。"""
    if isinstance(值,bool):#布尔不是数字
        return False#布尔不是整数
    if isinstance(值,int):#整型
        return 值>=0#非负即可
    if isinstance(值,float):#浮点
        return 值.is_integer() and 值>=0#整值且非负
    return False#其它类型

def 断言预算(值,名):#校验预算字段是非负整数
    """断言预算字段是非负整数（截留器请求约定）。"""
    if not 是否非负整数(值):#非整或为负
        raise Exception(名+' must be a non-negative integer')#字段名进入抛出文案，字面量不翻译
    return int(值)#收窄为整型

class 条目保留器:#有序单元截留器
    """约束有序逻辑单元流，留下前 `maxItems` 个（条目保留策略的 `head`）。`推入()` 按单元报告是否留下，以及截留结果现在是否已截断。

分组、排序、路径映射、按单元预览截断，以及任何 `incomplete` 状态都留在截留器**外面**：它只计数和留下，别无其他。调用方推入已准备好的逻辑单元，在 `收尾` 之后自己对留下的子集分组/排序。
    """
    def __init__(自身,策略):#按头策略构造
        """按头策略构造：`maxItems`（非负整数）。"""
        自身.最大条目=断言预算(取策略字段(策略,'maxItems'),'maxItems')#记下留下上限
        自身.条目=[]#已留下的单元
        自身.已见=0#观察过的单元数
        自身.省略计数=0#因预算丢掉的单元数

    def 推入(自身,条目):#推入一个逻辑单元
        """提供一个单元。截留器未满 `maxItems` 时留下；否则丢掉并计入省略。调用方继续推入全部观察过的单元，因此最终省略量计数精确。

        @param 条目 已准备好的逻辑单元（路径、扁平命中、来源）。
        @returns 本次推入的推入判定。
        """
        自身.已见+=1#观察计数加一
        if len(自身.条目)<自身.最大条目:#尚未顶满上限
            #只有未满上限、尚未省略时才到这里（条目只增、上限固定），因此还没丢掉任何东西：truncated恒为false。
            自身.条目.append(条目)#收下本单元
            return {'kept':True,'truncated':False}#全部留下且尚未截断
        自身.省略计数+=1#计入一次省略
        return {'kept':False,'truncated':True}#已满则丢掉

    def 收尾(自身):#产出条目截留快照
        """收尾并报告留下了什么、省略了什么。

        @returns 保留条目快照（下游可安全分组/排序）。
        """
        已截断=自身.省略计数>0#是否省略过任何单元
        return {#条目快照
            'items':list(自身.条目),#留下的单元
            'truncated':已截断,#是否因预算截断
            'seen':自身.已见,#观察过的单元数
            'kept':len(自身.条目),#留下的单元数
            'omitted':({'kind':'exact','count':自身.省略计数} if 已截断 else {'kind':'none'}),#按是否截断选择省略形态
        }#快照结束

def 裁掉尾部半截UTF8(字节):#裁掉前缀切点处的半截UTF-8
    """丢掉尾部不完整的 UTF-8 序列，使前缀切割从不在边界处发出替换字符。从续字节（`10xxxxxx`）往回走到引导字节；若其后字节数少于引导字节声明的长度，则序列不完整，予以裁掉。完整尾巴，或长/短到不可能是合法引导的一段，原样返回（真正畸形的内部留给解码器替换）。"""
    索引=len(字节)-1#从最后一个字节往回走
    #续字节是0b10xxxxxx；最多回扫3个（最长序列为4）。循环守卫已做下标检查，因此读取都在范围内。
    while 索引>=0 and (字节[索引]&0xc0)==0x80 and len(字节)-索引<=3:#跳过续字节找到引导或停下
        索引-=1#继续往回
    if 索引<0:#整段都是续字节，无法裁出合法引导
        return 字节#原样返回
    引导=字节[索引]#候选引导字节
    期望=1 if 引导<0x80 else 2 if 引导<0xe0 else 3 if 引导<0xf0 else 4 if 引导<0xf8 else 0#引导字节声明的序列长度；0表示不是引导
    #expected为0 → 不是引导字节（散落的续字节/非法）：原样留下。
    if 期望==0:#非法引导则不裁
        return 字节#原样
    return 字节[:索引] if len(字节)-索引<期望 else 字节#序列未写完则裁到引导前，否则原样

def 裁掉前导续字节UTF8(字节):#裁掉后缀切点处的前导续字节
    """丢掉前导续字节（`10xxxxxx`），使后缀切割从引导/ASCII 字节开始，而不是码点中间。"""
    索引=0#从首字节往前走
    #i < length守卫读取。
    while 索引<len(字节) and (字节[索引]&0xc0)==0x80:#跳过前导续字节
        索引+=1#前移
    return 字节[索引:]#从第一个非续字节起留下

def 拼接(块们):#拼接字节块
    """把各块拼成一块连续缓冲区（长度恰好是它们的总和）。"""
    return b''.join(块们)#连续缓冲区

def 解码UTF8(字节):#utf-8解码，非致命：内部畸形字节→U+FFFD
    """对齐 TextDecoder：畸形字节替换为 U+FFFD。"""
    return 字节.decode('utf-8',errors='replace')#非致命解码

def 编码UTF8(文本):#UTF-8编码器，把字符串块变成字节
    """对齐 TextEncoder.encode。"""
    return 文本.encode('utf-8')#编成UTF-8字节

class 文本保留器:#面向字节的文本截留器
    """约束面向字节的文本流，留下前缀、后缀或两端（文本保留策略）。三种策略共用一套前缀/后缀累加器：`head` 只有前缀，`tail` 只有后缀，`headTail` 两端都有。

按字节而不是字符：上限和 `omittedBytes` 都是字节计数，面向进程/正文安全。跨码点的块会处理——`收尾` 在每次切割处裁掉半截码点，使返回文本从不在边界引入替换字符。截留器内存最多持有 `prefixCap + tailBytes + 一块`（滑出窗口的旧后缀块会丢掉），因此大流不会无界累积。
    """
    def __init__(自身,策略):#按文本策略构造
        """按文本策略构造；字节预算必须是非负整数。"""
        种类=取策略字段(策略,'kind')#策略判别标签
        if 种类=='head':#只留前缀
            自身.前缀上限=断言预算(取策略字段(策略,'maxBytes'),'maxBytes')#前缀上限取maxBytes
            自身.后缀上限=0#不留后缀
        elif 种类=='tail':#只留后缀
            自身.前缀上限=0#不留前缀
            自身.后缀上限=断言预算(取策略字段(策略,'maxBytes'),'maxBytes')#后缀上限取maxBytes
        elif 种类=='headTail':#两端都留
            自身.前缀上限=断言预算(取策略字段(策略,'headBytes'),'headBytes')#前缀上限
            自身.后缀上限=断言预算(取策略字段(策略,'tailBytes'),'tailBytes')#后缀上限
        else:#未知策略
            raise Exception('unknown TextRetentionStrategy kind: '+str(种类))#非法策略
        自身.前缀块=[]#已留下的前缀块
        自身.前缀已持=0#前缀已持有字节数
        自身.后缀块=[]#滚动后缀窗口里的块
        自身.后缀已持=0#后缀窗口已持有字节数
        自身.总量=0#观察过的总字节

    def 省略于(自身,总量):#按总量计算省略字节
        """已观察到 `总量` 字节时省略的字节：`总量 − 留下前缀 − 留下后缀`。"""
        前缀长=min(总量,自身.前缀上限)#实际能留的前缀
        后缀长=min(总量-前缀长,自身.后缀上限)#前缀之外还能留的后缀
        return 总量-前缀长-后缀长#其余即为省略

    def 推入(自身,块):#推入一块文本
        """提供一块（字节，或按 UTF-8 编码的字符串）。前缀字节填到前缀上限后停止；后缀字节滚动，只留下最后 `suffixCap` 字节。`kept` 仅在本块没有任何字节被丢掉时为 `true`。

        @param 块 流的下一段字节（`bytes`/`bytearray`/`memoryview` 或 UTF-8 `str`）。
        @returns 本次推入的推入判定。
        """
        if isinstance(块,str):#字符串先编成UTF-8字节
            字节=编码UTF8(块)#编码
        elif isinstance(块,(bytearray,memoryview)):#可变或视图
            字节=bytes(块)#收成不可变字节
        else:#已是bytes或兼容缓冲
            字节=块#原样当作字节序列
        之前=自身.总量#推入前已观察的总字节
        自身.总量+=len(字节)#累加本块字节

        #前缀：只取到上限为止；本块其余部分「不进前缀」。
        空位=自身.前缀上限-自身.前缀已持#前缀还剩多少空位
        取量=max(0,min(空位,len(字节)))#本块实际写入前缀的字节
        if 取量>0:#还有前缀空位
            自身.前缀块.append(字节[:取量])#收下前缀切片
            自身.前缀已持+=取量#前缀持有量加上本切片
        #前缀收取结束

        #后缀：整块追加，再丢掉已完全滑出最后suffixCap字节的整块前导块（内存有界）。
        if 自身.后缀上限>0:#需要后缀窗口
            自身.后缀块.append(字节)#整块进入后缀窗口
            自身.后缀已持+=len(字节)#后缀持有量加上本块
            头块=自身.后缀块[0] if 自身.后缀块 else None#窗口最前一块
            while 头块 is not None and 自身.后缀已持-len(头块)>=自身.后缀上限:#整块都已滑出窗口
                自身.后缀块.pop(0)#丢掉最前一块
                自身.后缀已持-=len(头块)#持有量减去丢掉的块
                头块=自身.后缀块[0] if 自身.后缀块 else None#看新的最前一块
            #整块滑出循环结束
            #最前一块仍可能含超出最后suffixCap的前导字节——循环上面会把大于窗口的单块整块留下（丢掉唯一一块会让持有量<上限）。裁掉那些前导字节，使累加器（以及收尾的拼接）以suffixCap为界，而不是再分配/拷贝整块；收尾永远只读最后suffixLen≤suffixCap字节，因此这里丢掉的不会是它要返回的。（循环不变量suffixHeld-head.length<suffixCap保证head.length>excess，因此切片非空。）
            if 头块 is not None and 自身.后缀已持>自身.后缀上限:#最前一块仍有超出窗口的前导
                超出=自身.后缀已持-自身.后缀上限#超出窗口的前导字节数
                自身.后缀块[0]=头块[超出:]#裁掉前导，只留窗口内
                自身.后缀已持-=超出#持有量收到上限
            #单块前导裁剪结束
        #后缀窗口结束

        #丢掉的=任何一侧都留不住的字节。用与收尾相同的省略于算累计省略，使推入与收尾永不分歧；单次推入只需知道本块是否把总量推过两端上限所能持有的量。
        本块丢掉=自身.省略于(自身.总量)>自身.省略于(之前)#本块是否新增了省略
        return {#本块判定
            'kept':not 本块丢掉,#本块没有任何字节被丢掉才算留下
            'truncated':自身.省略于(自身.总量)>0,#累计是否已因预算省略
        }#判定结束

    def 收尾(自身):#产出文本截留快照
        """收尾：解码留下的前缀和后缀（各自在切割处裁到 UTF-8 边界）并报告精确省略字节数。

        @returns 保留文本快照（可安全交给格式化器）。
        """
        前缀长=min(自身.总量,自身.前缀上限)#实际前缀字节
        后缀长=min(自身.总量-前缀长,自身.后缀上限)#实际后缀字节

        前缀=拼接(自身.前缀块)#恰好前缀长字节（前缀已持 === 前缀长）
        后缀全=拼接(自身.后缀块)#后缀窗口连续缓冲
        后缀=后缀全[自身.后缀已持-后缀长:] if 后缀长>0 else b''#取出最后后缀长字节

        #预算未省略时，前缀和后缀是同一条流的相邻切片（前缀长+后缀长===总量），因此头|尾分割是人为的：一个码点可能跨过它。把连续整体当作一块解码——若在这里分别裁或分别解码两半，会破坏跨边界码点，尽管并未丢掉内容。只有真正出现省略缺口时，两侧才是真正的切割：各自裁到UTF-8边界再分别解码，使码点从不跨缺口拼回去。
        预算省略=自身.省略于(自身.总量)#按预算算出的省略字节
        if 预算省略>0:#有省略缺口才各自裁边界
            留下前缀=裁掉尾部半截UTF8(前缀)#前缀去尾部半截
            留下后缀=裁掉前导续字节UTF8(后缀)#后缀去前导续字节
            文本=解码UTF8(留下前缀)+解码UTF8(留下后缀)#缺口两侧各自解码
        else:#无缺口则保持相邻原样
            留下前缀=前缀#原样前缀
            留下后缀=后缀#原样后缀
            文本=解码UTF8(拼接([前缀,后缀]))#无缺口则拼成一块再解码

        #按实际返回的字节报告省略，而不是裁边界前的预算：边界裁剪也会丢掉半截码点字节，若只按预算计数会高估留下的文本（据此拼出的「省略了N字节」通知会是谎言）。
        省略=自身.总量-len(留下前缀)-len(留下后缀)#相对实际返回文本的省略字节
        已截断=省略>0#是否省略过任何字节

        return {#文本快照
            'text':文本,#留下的文本
            'truncated':已截断,#是否因预算或边界裁剪而省略
            'omittedBytes':({'kind':'exact','count':省略} if 已截断 else {'kind':'none'}),#按是否省略选择形态
        }#快照结束

def 描述省略(省略,单位):#把省略量写成标准子句
    """针对一个省略量值的标准化、避免假精度的措辞——本库拥有的「可以标准化省略措辞」那一半。`exact` 打印计数（`Omitted 3 items`）；`unknown` 不打印计数，因为调用方没给。`none` 是空字符串。

    @param 省略 截留结果里的省略元数据。
    @param 单位 省略量所用名词（`items`、`bytes`、`chars`、`lines`）。
    @returns 中性子句（无尾空格）；未省略时为 `''`。
    """
    种类=省略['kind'] if isinstance(省略,dict) else getattr(省略,'kind')#省略形态
    if 种类=='none':#未省略
        return ''#空子句
    if 种类=='exact':#有精确计数
        计数=省略['count'] if isinstance(省略,dict) else getattr(省略,'count')#精确计数
        return 'Omitted '+str(计数)+' '+单位+'.'#英文标准子句，字面量不翻译
    if 种类=='unknown':#省略但无计数
        return 'More '+单位+' were omitted.'#不带数字的英文子句，字面量不翻译
    raise Exception('unknown Omitted kind: '+str(种类))#非法形态

def 格式化保留通知(通知,恢复):#拼出截留页脚行
    """把保留通知收成一行页脚：本库拥有的标准化省略子句（`描述省略`）后面接工具自己的恢复指引。本库从不拥有恢复措辞——只有工具知道动作（「收窄模式」、「抓取更具体的 URL」、「读溢出文件」）——因此 `恢复` 提供它们，并收到完整通知以便据此措辞（`kept`、`limit`、`omitted`，……）。任一半都可以空；两半用单个空格拼接。

    @param 通知 中性截留结果。
    @param 恢复 工具提供的指引构造器；收到通知，返回一句话（或 `''`）。
    @returns 拼好的页脚行。
    """
    省略=通知['omitted'] if isinstance(通知,dict) else getattr(通知,'omitted')#省略量
    单位=通知['unit'] if isinstance(通知,dict) else getattr(通知,'unit')#单位名词
