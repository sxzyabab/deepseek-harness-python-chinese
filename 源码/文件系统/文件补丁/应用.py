'把已解析的 hunk 应用到 LF 文本。不改输入，失败不抛异常'
def 是空白(字符):
    'Unicode White_Space。不含 BOM'
    return 字符.isspace()

def 去空白(文本,去开头):
    '按需要去掉开头空白，始终去掉结尾空白'
    起=0#扫描起点
    止=len(文本)#扫描终点
    if 去开头:#也去开头
        while 起<止 and 是空白(文本[起]):
            起=起+1
    while 止>起 and 是空白(文本[止-1]):#去结尾
        止=止-1
    return 文本[起:止]

def 规范标点(文本):
    '去首尾空白后，把若干 Unicode 标点换成 ASCII'
    文本=去空白(文本,True)#先裁空白
    结果=[]#逐字符替换
    for 字符 in 文本:
        码=ord(字符)
        if 0x2010<=码<=0x2015 or 码==0x2212:#各种横线
            结果.append('-')
        elif 0x2018<=码<=0x201B:#单引号
            结果.append("'")
        elif 0x201C<=码<=0x201F:#双引号
            结果.append('"')
        elif 码==0x00A0 or 0x2002<=码<=0x200A or 码 in (0x202F,0x205F,0x3000):#各种空格
            结果.append(' ')
        else:
            结果.append(字符)#原样
    return ''.join(结果)

def 寻找序列(行表,模式,起点,文件结束):
    """四级匹配里返回第一个命中的行下标。
    空模式命中起点。模式比原文长则没有。
    文件结束时只看尾部那一个候选，即使它在游标之前"""
    if len(模式)==0:#空模式
        return 起点
    if len(模式)>len(行表):#放不下
        return None
    最后=len(行表)-len(模式)#最后一个可开始的下标
    第一=最后 if 文件结束 else 起点#EOF 只搜尾部
    遍次=(
        lambda 值:值,#精确
        lambda 值:去空白(值,False),#去尾空白
        lambda 值:去空白(值,True),#去首尾空白
        规范标点,#再映射标点
    )
    for 规范 in 遍次:#一级走完所有位置才进下一级
        期望=[规范(行) for 行 in 模式]#这一级的模式
        下标=第一
        while 下标<=最后:#候选起点
            偏移=0
            命中=True
            while 偏移<len(期望):#逐行比
                if 规范(行表[下标+偏移])!=期望[偏移]:
                    命中=False
                    break
                偏移=偏移+1
            if 命中:#这一级命中
                return 下标
            下标=下标+1
    return None#四级都没有

def 应用修改块(原文,修改块表):
    """把有序 hunk 应用到调用方已按 LF 规范化的文本。
    全部搜索都对着原文。失败返回 {'成功':False,'失败':...}，不含半截文本。
    非空成功结果以 LF 结尾"""
    原行=原文.split('\n')#按 LF 切，CR 是普通字符
    if len(原行)>0 and 原行[-1]=='':#丢掉切分产生的末尾空元素
        原行.pop()
    替换表=[]#先收集，再按起点应用
    行下标=0#顺序搜索游标
    for 修改块 in 修改块表:
        if '上下文' in 修改块:#先找锚点
            模式=[修改块['上下文']]
            找到=寻找序列(原行,模式,行下标,False)#锚点不走 EOF
            if 找到 is None:
                return {'成功':False,'失败':{
                    '修改块行号':修改块['行号'],'阶段':'context',
                    '搜索起点':行下标,'模式':模式,
                }}
            行下标=找到+1#从锚点下一行继续
        if len(修改块['旧行'])==0:#纯插入
            if len(原行)>0 and 原行[-1]=='':#末尾已有空源行
                插入点=len(原行)-1#插在它前面
            else:
                插入点=len(原行)#插在末尾
            替换表.append({'起点':插入点,'旧长':0,'新行':修改块['新行']})
            continue#插入不推进游标
        模式=list(修改块['旧行'])#可丢掉末尾空行再试
        新行=list(修改块['新行'])
        找到=寻找序列(原行,模式,行下标,修改块['文件结束'])
        if 找到 is None and len(模式)>0 and 模式[-1]=='':#末行是空哨兵
            模式=模式[:-1]
            if len(新行)>0 and 新行[-1]=='':
                新行=新行[:-1]
            找到=寻找序列(原行,模式,行下标,修改块['文件结束'])
        if 找到 is None:#仍没有
            return {'成功':False,'失败':{
                '修改块行号':修改块['行号'],'阶段':'oldLines',
                '搜索起点':行下标,'模式':list(修改块['旧行']),#报告原始模式
            }}
        替换表.append({'起点':找到,'旧长':len(模式),'新行':新行})
        行下标=找到+len(模式)#游标推到匹配末尾
    替换表.sort(key=lambda 项:项['起点'])#起点相同时保持补丁顺序
    行=原行
    for 替换 in reversed(替换表):#从后往前，前面的下标不变
        行=行[:替换['起点']]+list(替换['新行'])+行[替换['起点']+替换['旧长']:]
    if len(行)==0 or 行[-1]!='':#非空结果补一个空元素，连接后以 LF 结尾
        行.append('')
    return {'成功':True,'之后':'\n'.join(行)}
