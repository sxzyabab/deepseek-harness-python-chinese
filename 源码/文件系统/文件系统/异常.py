from ...模型后端.llm.异常 import 装备错误#从LLM包导入HarnessError基类

class 文件系统错误(装备错误):#文件系统带类型错误
    """带类型的文件系统错误。
    扩展装备错误，因此携带稳定错误码并链接 cause。
    dsh-fs 拥有此词汇，使后端与策略层抛出同一套错误码，而不是各自发明消息字符串。
    工具注册表在 isError 结果上暴露 {name, code}，以便重试/权限/UI 层无需解析消息即可分支
    """
    def __init__(自身,消息,码,选项=None):#构造文件系统错误
        """构造文件系统错误。
        记下稳定 code，并把 cause 链到本错误
        """
        装备错误.__init__(自身,消息,码,选项)#交给装备错误保存消息、错误码与cause
        自身.code=码#再写下本类的错误码字段
        自身.name='FsError'
