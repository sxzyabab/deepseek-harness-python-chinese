"""仅事件的文件系统观察策略：弱映射记录存在/缺失观察，意图监听器推导写/编辑守卫；未加载时工具保持无条件变更。"""
from weakref import WeakKeyDictionary as 弱键字典#所有者到目标观察的弱映射
from ..文件系统 import 文件系统错误#文件系统带类型错误

名称='fs-observation-policy'#Cordis 插件名

__all__=['名称','观察态门','应用']#仅中文公开名；Cordis 槽英文别名不入表

class 观察态门:#按所有者记录观察并推导写/编辑意图
    """每上下文的已观察文件状态，以及其上的三个 fs/* 决策。每次应用创建一个实例，以便拆除时丢掉全部状态供 HMR。"""
    def __init__(自身):#初始化空观察弱映射
        """初始化已观察文件状态。"""
        自身.已观察=弱键字典()#所有者到目标键到观察的弱映射

    def 所有者(自身,行动者):#从行动者推导观察态所有者
        """从不透明事件行动者推导观察态所有者——通常是活动的智能体会话。无法推导所有者时为 None（例如没有智能体的直接工具调用）；此类调用可自由读，但不能满足写/编辑的先前观察策略。行动者是跨包 dict。"""
        if 行动者 is None or 'agent' not in 行动者:#无行动者或无智能体键
            return None#无法推导所有者
        智能体=行动者['agent']#可选的智能体承载
        if 智能体 is None or 'session' not in 智能体:#智能体缺席或无会话键
            return None#无法推导所有者
        return 智能体['session']#有智能体会话则以其为所有者

    def 读取(自身,所有者对象,目标键):#读取某所有者对某目标的观察
        """读取某所有者对某目标的观察；没有所有者表或没有该键则为 None。"""
        if 所有者对象 not in 自身.已观察:#尚无该所有者的目标表
            return None#未见过
        目标表=自身.已观察[所有者对象]#取出该所有者的目标表
        if 目标键 not in 目标表:#没有该键
            return None#未见过
        return 目标表[目标键]#已记录的观察

    def 写入(自身,所有者对象,目标键,观察):#写入某所有者对某目标的观察
        """写入某所有者对某目标的观察。"""
        if 所有者对象 not in 自身.已观察:#尚无目标表则新建
            自身.已观察[所有者对象]={}#新建目标键到观察的映射
        自身.已观察[所有者对象][目标键]=观察#记录此次观察

    def 清空(自身):#丢掉全部已记录状态
        """丢掉全部已记录状态（HMR 安全 / 拆除）。"""
        自身.已观察=弱键字典()#换成新的空弱映射

    def 写意图(自身,目标,行动者):#按先前观察推导写意图
        """决定写意图：未见过或确认缺失 ⇒ createIfAbsent；确认存在 ⇒ 按观察到的版本 replaceIfVersion。目标与观察均为 dict。"""
        所有者对象=自身.所有者(行动者)#推导观察所有者
        先前=自身.读取(所有者对象,目标['targetKey']) if 所有者对象 is not None else None#有所有者才取先前观察
        if 先前 is not None and 先前['kind']=='present':#先前确认为存在
            return {'kind':'replaceIfVersion','version':先前['version']}#按观察版本做替换
        return {'kind':'createIfAbsent'}#否则只允许创建

    def 编辑意图(自身,目标,行动者):#按先前观察推导编辑版本守卫
        """决定编辑版本守卫：未见过以 FS_NOT_OBSERVED 拒绝，确认缺失以 FS_NOT_FOUND 拒绝，存在则把观察到的版本作为 CAS 基准。目标与观察均为 dict。"""
        所有者对象=自身.所有者(行动者)#推导观察所有者
        先前=自身.读取(所有者对象,目标['targetKey']) if 所有者对象 is not None else None#有所有者才取先前观察
        if 所有者对象 is None or 先前 is None:#没有所有者或未见过该目标
            raise 文件系统错误('edit requires reading "'+目标['displayPath']+'" first','FS_NOT_OBSERVED')#编辑前必须先读
        if 先前['kind']=='absent':#先前确认缺失
            raise 文件系统错误('cannot edit "'+目标['displayPath']+'": not found','FS_NOT_FOUND')#不能编辑不存在的文件
        return {'version':先前['version']}#用观察到的版本做 CAS

    def 观察(自身,目标,观察载荷,行动者):#记录权威观察
        """为此所有者与目标记录一次权威的存在或缺失观察。目标是 dict。"""
        所有者对象=自身.所有者(行动者)#推导观察所有者
        if 所有者对象 is not None:#有所有者才写入观察
            自身.写入(所有者对象,目标['targetKey'],观察载荷)#写入观察

def 应用(上下文):#安装观察策略监听器
    """注册三个 fs/* 监听器。无 inject——本插件不读服务；只在自己的弱键字典上操作。瀑布未绑定（工具派发时没有 this），因此监听器接收原始 (目标, 行动者, next) 参数。"""
    门=观察态门()#为此上下文创建观察门
    def 拆除工厂():#注册拆除副作用
        """拆除时丢掉全部已记录状态，使重载插件从干净状态开始（HMR 安全）。弱键字典本身会被 GC，但替换它让释放对测试可观察且立即发生。"""
        def 清理():#清空观察状态
            """清空观察状态。"""
            门.清空()#换成新的空弱映射
        return 清理#拆除器
    上下文.副作用(拆除工厂,'fs-observation-policy observed-state teardown')#副作用说明标签
    def 写意图监听(目标,行动者,*其余):#写意图单槽决策——不要调用 next()
        """占用写意图单决策槽；同步返回意图 dict。"""
        return 门.写意图(目标,行动者)#按先前观察推导
    上下文.监听('fs/write-intent',写意图监听)#写意图单槽决策
    def 编辑意图监听(目标,行动者,*其余):#编辑意图单槽决策——不要调用 next()
        """占用编辑意图单决策槽；同步返回守卫 dict，抛错直接上抛。"""
        return 门.编辑意图(目标,行动者)#按先前观察推导
    上下文.监听('fs/edit-intent',编辑意图监听)#编辑意图单槽决策
    def 观察监听(目标,观察载荷,行动者,*其余):#记录观察；必须保持同步且不抛错
        """fs/observed 必须保持同步且不抛错：emit 不等待承诺，且成功变更已经提交。弱键字典写入对存在与缺失都满足该约定。"""
        门.观察(目标,观察载荷,行动者)#写入观察门
    上下文.监听('fs/observed',观察监听)#fs/observed 监听结束

name=名称#Cordis 插件名
apply=应用#Cordis 插件入口
default=应用#框架槽
