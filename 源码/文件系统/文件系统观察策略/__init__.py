"""仅事件的文件系统观察策略；不注册服务。弱引用的所有者/目标映射记录每一次权威存在/缺失观察，单槽意图监听器从该状态推导守卫，提供方执行原子新鲜度/不覆盖检查。没有此插件时，工具保留裸提供方的无条件变更行为。组合规则见包 README。"""
