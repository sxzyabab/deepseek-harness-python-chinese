def 擦洗父环境():#去掉凭证形态名字和全部 DSH_* 名字后的环境父环境
    """去掉凭证形态名字和全部 DSH_* 名字后的环境父环境——每个 harness 子进程起步的规范基座。

    PATH、HOME、locale 和代理变量会留下；harness 身份从不隐式泄漏。
    有意转发的凭证或当前 DSH_* 事实走规格的显式 env，在这次擦洗之后合并。
    两次擦洗都大小写不敏感。导出为普通函数，让无法走服务的启动器共用同一份擦洗定义。
    """
    环境={}#新环境对象
    for 键,值 in os.environ.items():#遍历父环境
        if 值 is not None and 敏感环境模式.search(键) is None and not 键.upper().startswith(托管环境前缀):#非凭证且非 DSH_ 才保留
            环境[键]=值#写入擦洗后的环境
    for 名,代理值 in 子进程代理环境().items():#叠上子进程代理环境
        if 代理值 is None:#用户从未设置则删
            if 名 in 环境:#有名
                del 环境[名]#去掉
        else:#有值
            环境[名]=代理值#还原用户导出
    return 环境#返回擦洗后的环境

