class 任务注册表(服务):#抽象后台任务注册表
    """抽象后台任务注册表。子类化、实现抽象方法，并把子类当插件加载——它注册为 ctx.jobs（每个上下文一个实现；加载第二个会抛错，这是 cordis 标准的重复服务行为）。

    实现必须遵守这些语义：
    - 注册比生产者和控制器 fiber 活得更久。所有者和服务拆除会取消在线工作并等待合规生产者；抛错的拆除取消只强制失败记录。拆除取消也把记录标为已报告，因为因其所有者正在被销毁的记录已经没有读者。
    - 有主任务的访问按其所有者会话 id 围栏。id 可预测，因此边界是授权而不是保密。
    - 结算先到先得：一条终态记录、已释放等待者，以及一轮被包含的监听器通知，即使面对迟到的生产者结局。完成最后宣布，在记录已提交且该结算的每一个其他观察者都已看到之后，因为报告器可能同步打开模型回合。
    - 启动 在没有已挂接任务控制器服务该 spec 的所有者时拒绝工作，因此生产者不能启动所有者无法收集或停止的工作。一个注册表服务进程内的每个组合，因此这个问题——以及完成监听器投递——是相对所有者的而不是全进程的：从未作用域上下文做出的注册服务每个所有者，在智能体组合作用域下做出的注册恰好服务在其下组合的智能体。
    """
    def __init__(自身,上下文对象):#构造服务
        """登记为 ctx.jobs。直接实例化抽象类会在加载时大声失败。"""
        if type(自身) is 任务注册表:#直接实例化抽象类
            raise Exception('@deepseek-ai/dsh-jobs is the abstract job registry seam; load an implementation such as @deepseek-ai/dsh-jobs-local instead')#必须加载实现
        super().__init__(上下文对象,'jobs')#以jobs键注册

    def 启动(自身,规格):#启动并原子注册
        """在启动并原子注册工作前预检访问、校验、所有者清理和实现拥有的准入。任何预检拒绝都不留下任务 id 或执行资源。抛错的启动器什么也不注册；它返回后，注册不能失败。结算记录结局、通知监听器并释放等待者。返回注册表签发的 `<kind>-N` id。"""
        raise NotImplementedError('JobRegistry.start')#子类必须实现

    def 列出(自身,调用方=None):#列出可见任务
        """按注册顺序列出调用方拥有的和无主任务，不暴露另一会话的标签。非智能体调用方只看见无主任务。返回新鲜快照。"""
        raise NotImplementedError('JobRegistry.list')#子类必须实现

    def 获取(自身,标识,调用方=None):#取非消费快照
        """返回非消费快照，不改变其读游标或通知状态。未知或外会话任务抛错。"""
        raise NotImplementedError('JobRegistry.get')#子类必须实现

    def 读取(自身,标识,调用方=None):#读取输出增量或终态
        """读取下一段流增量，或结算后的幂等最终输出。终态读取把任务标为已报告。未知或外会话任务抛错。返回输出文本和读后快照。"""
        raise NotImplementedError('JobRegistry.read')#子类必须实现

    def 终止(自身,标识,调用方=None,原因=None):#请求取消
        """请求取消，然后把任务标为 stopping 和已报告。生产者抛错会传播且不改任务状态。未知或外会话任务抛错。在线工作为 requested，否则 already-finished。"""
        raise NotImplementedError('JobRegistry.kill')#子类必须实现

    def 等待(自身,标识,超时毫秒,调用方=None,信号=None):#等待结算或超时
        """等待结算或超时，不取消任务。调用方中止仅在任务在线时拒绝；结算后终态快照胜出，因此为此等待者抑制的通知仍会投递。非法、未知或外会话输入抛错。返回结算或超时时的快照。"""
        raise NotImplementedError('JobRegistry.wait')#子类必须实现

    def 任务完成时(自身,监听器):#注册完成监听
        """注册一个作用域绑定的完成监听器。它收到其注册上下文作用域覆盖的所有者的结算；每个监听器被包含；返回的 Promise 被观察但不被等待。服务拆除后没有监听器再跑。返回注销该监听器的 disposer。"""
        raise NotImplementedError('JobRegistry.onJobDone')#子类必须实现

    def 任务变化时(自身,监听器):#注册列表变化监听
        """注册一个作用域绑定的可见集合变化观察者。它在每次改变该所有者 list 返回内容的提交之后开火——注册、每一次 stopping 转移（包括拆除在等待慢生产者之前执行的那一次）、结算、所有者拆除移除，以及服务拆除提交的清空——因此观察者重读而不是累积增量。

        投递在与 任务完成时 相同的条款上相对所有者：从未作用域上下文注册的观察者——宿主组合自己的载体——看见每个所有者，而在智能体组合作用域下注册的恰好看见在其下组合的智能体。

        这不是 任务完成时 的超集：那个在先到先得语义下投递终态记录，任务控制器把它耦到通知投递，而这个不携带投递含义也不把任何东西标为已报告。监听器被包含且从不被等待。返回注销该监听器的 disposer。
        """
        raise NotImplementedError('JobRegistry.onJobsChanged')#子类必须实现

    def 挂接控制器(自身,名称):#挂接任务控制器
        """挂接一个能读取和停止任务的作用域绑定控制器。它服务其注册上下文作用域覆盖的所有者，启动 拒绝没有已挂接控制器服务的所有者。诊断标签；重复名称保持独立。返回拆下此控制器的 disposer。"""
        raise NotImplementedError('JobRegistry.attachController')#子类必须实现

默认=任务注册表#默认导出
default=任务注册表#Cordis默认导出
