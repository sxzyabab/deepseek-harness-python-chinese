"""把紧凑游程展开为保留事件的迁移输出上下文。"""

class 会话格式事件收集器:#事件收集器
    """按源顺序保留已落定事件。"""
    def __init__(自身):#构造
        """初始化空保留列表。"""
        自身.values=[]#保留事件

    def emitEvent(自身,事件):#发出事件
        """保留一条已落定事件。"""
        自身.values.append(事件)#推入

    def emitRun(自身,游程):#发出游程
        """把一个紧凑游程直接展开为保留事件。"""
        for 事件 in 游程.expand():#展开
            自身.values.append(事件)#推入
