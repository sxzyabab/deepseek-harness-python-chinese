"""词汇感知格式恢复后使用的已安装当代会话校验。"""
from ...内核.会话 import (#从会话包导入
    会话格式版本,#会话格式版本
    会话,#会话类
    会话标识,#会话id
)#从会话包导入

def 取字段(对象,键):#读取字段
    """读取映射或对象上的字段。"""
    if isinstance(对象,dict):#映射
        return 对象[键]#映射键
    return getattr(对象,键)#对象属性

def 校验已安装当代会话头(头):#校验已安装当代头
    """经已安装会话包校验当代逻辑元数据。

    参数:
        头: 分离的当代逻辑头。
    返回:
        校验成功后无返回。
    """
    if 取字段(头,'version')!=会话格式版本:#版本不符
        raise Exception(#错误
            'installed Session format is v'+str(会话格式版本)+', got v'+str(取字段(头,'version')),#消息
        )#Exception结束
    会话.从恢复(#从恢复构造以校验
        会话标识(取字段(头,'id')),#会话id
        [],#无事件
        头,#头
    )#从恢复结束

def 校验已安装当代会话产物(产物):#校验已安装当代产物
    """经已安装会话包校验当代头、事件信封、消息、表面操作与种子切口。

    参数:
        产物: 词汇恢复后的当代逻辑产物。
    返回:
        校验成功后无返回。
    """
    产物头=取字段(产物,'header')#产物头
    if 取字段(产物头,'version')!=会话格式版本:#版本不符
        raise Exception(#错误
            'installed Session format is v'+str(会话格式版本)+', got v'+str(取字段(产物头,'version')),#消息
        )#Exception结束
    会话.从恢复(#从恢复构造以校验
        会话标识(取字段(产物头,'id')),#会话id
        取字段(产物,'events'),#事件
        产物头,#头
    )#从恢复结束
