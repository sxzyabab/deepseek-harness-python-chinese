__all__=('节点ptc错误',)#仅中文公开名

class 节点ptc错误(Exception):#本包异常基类
    'Node PTC 运行时失败'
    def __init__(自身,消息):#记下英文消息
        '用原样英文消息构造'
        super().__init__(消息)#英文消息

def 制作绑定调用错误(类名,成员属性,定义字段):#按命名空间物化拒绝类
    '物化一次绑定调用的拒绝类；类名与成员属性由调用方闭合'
    class 绑定调用错误(节点ptc错误):#该类
        '一次绑定调用的拒绝'
        def __init__(自身,成员名,消息):#记下
            '用英文消息与成员名构造'
            节点ptc错误.__init__(自身,消息)#消息
            定义字段(自身,'name',类名)#错误名
            定义字段(自身,成员属性,成员名)#成员
    绑定调用错误.__name__=类名#类名
    return 绑定调用错误#构造器
