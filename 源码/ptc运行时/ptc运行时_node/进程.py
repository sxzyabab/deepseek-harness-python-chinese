'继承控制通道上的 Node 子进程执行；此处不跑 Harness 服务'
from ...基础设施.js特性 import PromiseEX as 期约#期约
from .通道 import json通道#分帧
from .引导 import 运行程序#程序求值
from .环境 import 启动环境名#启动环境白名单
from .异常 import 节点ptc错误#本包异常

__all__=['运行节点主程序']#仅中文公开名

def 运行节点主程序(流,最大消息字节,进程状态):#握手后跑一个宿主程序
    """在继承、已接管的控制端点上跑一个宿主程序。
    流是已接管的双工端。
    最大消息字节是宿主校验过的帧与排队写入上限。
    进程状态含 env、stdout、stderr、exitCode。
    返回期约：控制输出刷完且观察到宿主关闭后解决；传输失败则关通道
    """
    if type(最大消息字节) is bool or type(最大消息字节) is not int or 最大消息字节<=0 or 最大消息字节>0xffffffff:#非法上限
        raise 节点ptc错误('invalid control message limit')#拒绝
    for 键 in list(进程状态.env.keys()):#清掉非启动名
        if 键.upper() not in 启动环境名:#不在白名单
            del 进程状态.env[键]#删除
    进程状态.env=type(进程状态.env)()#换成空环境对象
    引导完成=期约()#boot 数据
    监听器表=[]#回复监听
    已启动=[False]#是否已收到 boot
    已失败=[False]#传输或协议失败
    已发终态=[False]#是否已发 done
    宿主已关=期约()#宿主关闭
    收尾结果=期约()#主程序回执
    def 记下宿主关闭():#流关闭或传输失败
        '宿主关闭只解决一次'
        if 宿主已关.状态=='pending':#尚未解决
            宿主已关.解决()#关闭
    def 解决引导(引导数据):#收到 boot
        'boot 只解决一次'
        if 引导完成.状态=='pending':#尚未解决
            引导完成.解决(引导数据)#引导数据
    def 拒绝引导(错误):#boot 失败
        'boot 只拒绝一次'
        if 引导完成.状态=='pending':#尚未结算
            引导完成.拒绝(错误)#拒绝
    def 接收(原始,字节):#一帧
        '分派 boot 或回复'
        if not 已启动[0]:#首帧必须是 boot
            已启动[0]=True#已启动
            if type(原始) is not dict or 原始.get('type')!='boot':#不是 boot
                拒绝引导(节点ptc错误('expected program boot frame'))#拒绝
                return
            解决引导(原始['data'])#引导数据
            return
        if 已发终态[0]:#终态后忽略回复
            return#忽略
        for 监听器 in 监听器表:#逐个
            监听器(原始)#回复
        _=字节#帧长由通道计量
    def 失败(错误,种类):#通道失败
        '协议失败始终结算；传输失败在终态前结算'
        if (not 已发终态[0]) or 种类=='protocol':#需失败
            已失败[0]=True#标记
            拒绝引导(错误)#拒绝 boot
            通道.关闭()#关
            进程状态.exitCode=1#失败码
        记下宿主关闭()#关闭
    通道=json通道(流,最大消息字节,接收,失败)#分帧
    进程状态.控制读线程=通道.读线程#子进程入口等到读线程结束再取退出码
    未完成=set()#发送期约
    def 发送(消息):#程序到宿主
        '终态后不再发送；done 标记终态。传输失败吞掉并解决本次回执'
        if 已发终态[0]:#已终态
            return#忽略
        if 消息['type']=='done':#终态帧
            已发终态[0]=True#标记
        回执=期约()#本次发送
        未完成.add(回执)#登记
        def 发送成功(忽略=None):#写出已解决
            '摘掉本次回执。忽略是写出回执的值'
            未完成.discard(回执)#摘掉
            if 回执.状态=='pending':#尚未解决
                回执.解决()#成功
        def 发送失败(错误):#写出被拒绝
            '吞掉传输失败并摘掉本次回执。错误已反映到退出码'
            已失败[0]=True#标记
            通道.关闭()#关
            进程状态.exitCode=1#失败码
            记下宿主关闭()#关闭
            未完成.discard(回执)#摘掉
            if 回执.状态=='pending':#尚未解决
                回执.解决()#发送路径吞错
        try:#提交一帧
            写出=通道.发送(消息)#一帧期约
        except (节点ptc错误,OSError,ValueError,TypeError) as 错误:#编码失败
            发送失败(错误)#吞掉
            return#已结算
        写出.然后(发送成功,发送失败)#接上回执
    class 引导端口:#程序端口
        '程序消息与宿主回复'
        def 发消息(自身,消息):#发出
            '发出一帧'
            发送(消息)#发送
        def 监听(自身,事件,监听器):#挂回复
            '挂一条回复监听'
            监听器表.append(监听器)#登记
    def 收尾(忽略=None):#关通道并解决主程序
        '与原来的 finally 一样收口。忽略是前一段的值'
        if 已失败[0]:#失败
            进程状态.exitCode=1#失败码
        if 收尾结果.状态=='pending':#尚未解决
            收尾结果.解决()#主程序结束
        通道.关闭()#关。读线程随后退出，入口再取退出码
    def 收尾失败(错误):#链上失败也收口
        '传输或程序失败后收口，主程序期约仍解决'
        已失败[0]=True#标记
        收尾()#关通道
    def 等宿主(忽略=None):#排空之后等宿主关闭
        '宿主关闭后收口。忽略是排空值'
        宿主已关.然后(收尾,收尾失败)#等宿主
    def 等排空(忽略=None):#发送都结束后排空
        '排空后等宿主。忽略是上一轮发送'
        通道.排空().然后(等宿主,收尾失败)#排空写入
    def 再等发送(忽略=None):#未完成发送可能在等待期间增加
        '有未完成发送就全部等完，再排空。忽略是上一轮汇合值'
        if len(未完成)>0:#还有发送
            期约.全部(list(未完成)).然后(再等发送,收尾失败)#等这一批
            return#下一次再看
        等排空()#没有未完成发送
    def 程序已结束(忽略=None):#程序已发出终态
        '转去等发送。忽略是程序期约的值'
        再等发送()#等发送
    def 已有引导(引导数据):#boot 已到
        '跑程序，结束后等发送'
        运行程序(引导端口(),引导数据,{'stdout':进程状态.stdout,'stderr':进程状态.stderr}).然后(程序已结束,收尾失败)#求值
    def 就绪已写(忽略=None):#ready 已写出
        '等 boot。忽略是 ready 回执'
        引导完成.然后(已有引导,收尾失败)#boot
    def 就绪失败(错误):#ready 失败
        '就绪帧失败则收口'
        收尾失败(错误)#收口
    try:#提交就绪
        就绪写出=通道.发送({'type':'ready'})#就绪期约
    except (节点ptc错误,OSError,ValueError,TypeError) as 错误:#编码失败
        收尾失败(错误)#收口
        return 收尾结果#主程序回执
    就绪写出.然后(就绪已写,就绪失败)#等就绪写出
    return 收尾结果#主程序回执
