"""一次运行的外层输出账本；绑定值永不进入。"""
from .输出json import json字符串字节上限,json值字节上限,截断json字符串字节#字节计量
from .协议 import 节点ptc错误#本包异常

__all__=['输出账本']#仅中文公开名

class 输出账本:#一次运行的合计外层输出账本
    """一次运行的合计外层输出账本；绑定值永不进入。"""
    def __init__(自身,最大字节):#记下硬顶
        """记下合计字节硬顶。空日志数组 JSON 为 [] 占 2 字节。"""
        自身._最大字节=最大字节#硬顶
        自身._字节=2#[] 的 JSON
        自身._条数=0#已接纳条数

    def 接纳(自身,文本,槽):#接纳一条精确日志
        """接纳一条精确日志，或报告已越过硬顶。文本是日志。槽是已接纳列表。"""
        分隔=1 if 自身._条数>0 else 0#非首条逗号
        串字节=json字符串字节上限(文本,自身._最大字节-自身._字节-分隔)#本条预算
        if 串字节 is None:#越界
            return False#拒绝
        自身._字节+=串字节+分隔#入账
        自身._条数+=1#加一条
        槽.append(文本)#写入槽
        return True#接纳

    def 成功(自身,日志,值=None):#成功完成
        """按合计上限结算一次缺席或 JSON 完成。日志是已接纳列表。值为完成值。"""
        if 值 is not None and json值字节上限(值,自身._最大字节-自身._字节) is None:#完成值放不下
            return 自身.超限(日志)#改报超限
        结果={'logs':日志}#日志
        if 值 is not None:#有完成值
            结果['value']=值#写入
        return 结果#成功结果

    def 失败(自身,日志,错误):#失败诊断
        """结算失败诊断；合计字节越顶时输出上限优先。日志是已接纳列表。错误是 dict。"""
        if json字符串字节上限(错误['message'],自身._最大字节-自身._字节) is None:#诊断放不下
            return 自身.超限(日志)#改报超限
        return {'logs':日志,'error':错误}#失败结果

    def 超限(自身,日志):#显式输出上限失败
        """构造显式 output-limit 失败，并保留能放下的日志前缀。"""
        全文='outer output exceeded '+str(自身._最大字节)+' bytes'#固定诊断
        消息字节=len(全文)+2#ASCII 加引号
        保留=[]#能放下的前缀
        保留字节=2#[]
        日志预算=自身._最大字节-消息字节#留给日志
        for 文本 in 日志:#逐条
            分隔=1 if len(保留)>0 else 0#逗号
            可用=日志预算-保留字节-分隔#本条可用
            串字节=json字符串字节上限(文本,可用)#整条？
            if 串字节 is not None:#整条放下
                保留.append(文本)#收下
                保留字节+=串字节+分隔#入账
                continue#下一条
            前缀=截断json字符串字节(文本,可用)#截前缀
            if len(前缀)>0:#有前缀
                前缀字节=json字符串字节上限(前缀,可用)#前缀字节
                if 前缀字节 is None:#截断保证可放入
                    raise 节点ptc错误('output ledger produced an oversized log prefix')#账本自相矛盾
                保留.append(前缀)#收下前缀
                保留字节+=前缀字节+分隔#入账
            break#截断后停止
        可用消息=自身._最大字节-保留字节#留给消息
        消息=截断json字符串字节(全文,可用消息)#必要时截消息
        return {'logs':保留,'error':{'kind':'output-limit','message':消息}}#超限结果
