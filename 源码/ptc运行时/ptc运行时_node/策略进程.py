'已提交的会话文件政策变更之后，使 Node PTC 进程失效'
from ...基础设施.js特性 import PromiseEX as 期约#期约

__all__=['策略进程']#仅中文公开名

class 策略进程:#异步清理，不挡住权限写入
    '跟踪已接纳的调用或保留进程，直到所有者确认清理完成'
    def __init__(自身,上下文):#挂上政策变更与拆除
        '即使之后没有程序再跑，政策变更也开始清理'
        自身.上下文=上下文#宿主
        自身.进程集=set()#仍在跟踪的进程
        def 会话事件(会话,事件):#session/event
            '模式变了就标记失效并开始释放；释放失败只记日志'
            if 事件['type']!='sandbox/mode':#不是文件政策
                return#忽略
            for 进程 in list(自身.进程集):#快照，释放会改集合
                if 进程['sessionId']!=会话.id or 进程['mode']==事件['data']['mode']:#别的会话或模式没变
                    continue#跳过
                进程['invalidated']=True#失效
                def 释放失败(错误,进程项=进程):#这次释放失败
                    '失败留在日志里，进程仍可再试'
                    _=进程项#按登记时的进程闭合
                    上下文.日志.警告(错误)#不打断事件
                自身._释放(进程).捕获(释放失败)#不等待
        上下文.监听('session/event',会话事件,{'全局':True})#全局监听
        def 登记清理():#纤程拆除
            '等已跟踪进程的清理结束'
            def 拆除():#拆除器
                '返回落定期约'
                return 自身.落定(list(自身.进程集))#快照
            return 拆除#拆除器
        上下文.副作用(登记清理,'Node PTC policy cleanup')#登记

    def 登记(自身,政策,释放):#跟踪到所有者确认清理
        """跟踪一次已接纳的调用或保留进程。
        政策是已解析的进程政策，会话身份可缺席。
        释放是可重复的取消，并返回等待清理的期约。
        返回成功清理后的摘除函数；没有会话身份时摘除是空操作
        """
        if 'sessionId' not in 政策 or 政策['sessionId'] is None:#没有会话
            def 空摘除():#不进入失效表
                '没有会话身份的进程不跟踪'
                return None#无清理
            return 空摘除#空操作
        会话服务=自身.上下文.获取服务('sessions')#会话表
        会话=None#缺席
        if 会话服务 is not None:#有会话服务
            会话=会话服务.获取(政策['sessionId'])#按 id
        if 会话 is None:#会话已经不在
            模式=政策['mode']#用进程自己的模式
        else:#用该会话当前解析出的模式
            模式=自身.上下文.sandboxPolicy.解析({'session':会话})['mode']#当前模式
        进程={'sessionId':政策['sessionId'],'mode':模式,'release':释放,'invalidated':False}#一条跟踪
        自身.进程集.add(进程)#记下
        def 摘除():#清理成功后的回调也会删
            '从跟踪表去掉；重复调用无害'
            自身.进程集.discard(进程)#去掉
        return 摘除#摘除

    def 等待(自身,会话标识):#再接纳程序前等待失效进程
        """等待这个会话上已失效的进程。
        失败会拒绝，并且可以再试
        """
        待等=[]#已失效
        for 进程 in list(自身.进程集):#快照
            if 进程['sessionId']==会话标识 and 进程['invalidated']:#这个会话且已失效
                待等.append(进程)#等它
        return 自身.落定(待等)#全部落定

    def _释放(自身,进程):#幂等
        '清理期约在失败时删掉，调用方可以再试'
        if 'cleanup' in 进程:#已经在清理
            return 进程['cleanup']#同一条
        def 成功(忽略=None):#清理完成
            '从跟踪表去掉'
            自身.进程集.discard(进程)#去掉
            return 忽略#原值
        def 失败(错误):#清理失败
            '删掉清理槽，让下一次再试，并继续拒绝'
            进程.pop('cleanup',None)#可再试
            拒绝=期约()#拒绝回执
            拒绝.拒绝(错误)#原错误
            return 拒绝#继续拒绝
        进程['cleanup']=进程['release']().然后(成功,失败)#占槽
        return 进程['cleanup']#同一条

    def 落定(自身,进程列表):#等这一批释放
        '按输入顺序抛出第一个失败'
        回执=期约()#调用方
        if len(进程列表)==0:#没有要等的
            回执.解决()#完成
            return 回执#已完成
        结果=[None]*len(进程列表)#按输入顺序
        剩余=[len(进程列表)]#还没结算的个数
        def 记下(下标,状态,值):#一条结算
            '全部结算后按顺序找第一个拒绝'
            结果[下标]=(状态,值)#记下
            剩余[0]-=1#减一
            if 剩余[0]!=0:#还没齐
                return#等
            for 状态项,值项 in 结果:#输入顺序
                if 状态项=='rejected':#第一个失败
                    回执.拒绝(值项)#拒绝
                    return#结束
            回执.解决()#都成功
        下标=0#输入顺序
        for 进程 in 进程列表:#逐个
            def 成功(值=None,序号=下标):#这条成功
                '记成功'
                记下(序号,'fulfilled',值)#成功
            def 失败(错误,序号=下标):#这条失败
                '记失败'
                记下(序号,'rejected',错误)#失败
            自身._释放(进程).然后(成功,失败)#不等顺序完成
            下标+=1#下一个
        return 回执#全部落定后解决或拒绝
