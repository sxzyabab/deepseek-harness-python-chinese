"""有界进程通道上的 JSON 消息词汇。宿主校验每一帧，因为模型代码可直接写继承描述符。"""
__all__=[#仅中文公开名
    '节点ptc错误','程序引导数据字段','调用消息字段','日志消息字段',
    '输出上限消息字段','完成消息字段','回复消息字段',
]#公开面结束

class 节点ptc错误(Exception):#本包异常基类
    """Node PTC 运行时失败。"""
    def __init__(自身,消息):#记下英文消息
        """用原样英文消息构造。"""
        super().__init__(消息)#英文消息

程序引导数据字段=('code','namespaces','maxOutputBytes')#就绪握手后宿主交给程序的引导
调用消息字段=('type','id','global','name','args')#程序→宿主：一次桥接绑定调用
日志消息字段=('type','text')#程序→宿主：捕获文本，急切流出
输出上限消息字段=('type',)#程序→宿主：程序侧计量触顶
完成消息字段=('type','value','error')#程序→宿主：程序已结算
回复消息字段=('type','id','ok','value','message')#宿主→程序：一次调用的回答
