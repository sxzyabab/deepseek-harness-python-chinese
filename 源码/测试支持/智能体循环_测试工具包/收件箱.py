from ...内核.智能体.类型 import 下一轮,下一步#两条待处理列表名

__all__=['创建收件箱桩','不支持的收件箱']#仅中文公开名

def 创建收件箱桩():#创建收件箱桩
    """为只演练公开队列操作的测试创建可变内存收件箱桩。

    持久事件、投影校验与实时收件箱通知需要由智能体循环测试工具架创建的真实智能体。
    """
    待处理={下一轮:[],下一步:[]}#待处理表

    def 定位(消息身份):#定位消息
        """在两条队列中定位身份。"""
        for 目标 in (下一轮,下一步):#扫两队列
            下标=0#索引
            for 消息 in 待处理[目标]:#找索引
                if 消息['id']==消息身份:#命中
                    return {'target':目标,'index':下标}#命中
                下标+=1#前进
        return None#未找到

    class 收件箱桩:#收件箱实现
        """由两个进程本地数组支撑的收件箱。"""

        @property#下一轮
        def 下一轮队列(自身):#下一轮只读
            """下一轮待处理。"""
            return 待处理[下一轮]#下一轮

        @property#下一步
        def 下一步队列(自身):#下一步只读
            """下一步待处理。"""
            return 待处理[下一步]#下一步

        def 清空(自身):#清空
            """清空两队列。"""
            del 待处理[下一步][:]#清下一步
            del 待处理[下一轮][:]#清下一轮

        def 追加(自身,目标,消息):#追加
            """尾插。"""
            待处理[目标].append(消息)#推入尾

        def 前置(自身,目标,消息):#前置
            """头插。"""
            待处理[目标].insert(0,消息)#推入头

        def 替换(自身,消息身份,消息):#替换
            """就地替换。"""
            位置=定位(消息身份)#定位
            if 位置 is None:#未找到
                return False#未找到
            待处理[位置['target']][位置['index']:位置['index']+1]=[消息]#就地替换
            return True#成功

        def 移除(自身,消息身份):#移除
            """删除。"""
            位置=定位(消息身份)#定位
            if 位置 is None:#未找到
                return False#未找到
            del 待处理[位置['target']][位置['index']]#删除
            return True#成功

        def 拼接(自身,目标,起点,删除数,插入):#拼接
            """委托 list.splice 语义。"""
            列表=待处理[目标]#目标列表
            移除=列表[起点:起点+删除数]#被移除
            列表[起点:起点+删除数]=list(插入)#写入
            return 移除#返回移除

    return 收件箱桩()#返回实现

