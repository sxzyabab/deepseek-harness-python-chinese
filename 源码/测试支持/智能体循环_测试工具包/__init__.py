def 挂载智能体循环测试依赖(上下文,选项=None):#挂载智能体循环测试依赖
    """为 AgentLoop 测试挂载标准先决服务。

    故意不挂载 AgentLoop、也不注册适配器，使测试保留加载顺序与待测拓扑的控制权。
    上下文拥有每一个已挂载服务并负责释放。
    固定顺序：LLM、会话、会话投影注册表、系统提示词、工具、智能体注册表。
    """
    if 选项 is None:#缺省选项
        选项={}#空映射
    系统配置=选项.get('systemPrompt')#系统提示词配置
    工具配置=选项.get('tools')#工具配置
    上下文.启动插件(语言模型运行时)#挂载LLM运行时
    上下文.启动插件(会话存储)#挂载会话存储
    上下文.启动插件(会话投影注册表)#挂载会话投影注册表
    上下文.启动插件(系统提示词,{} if 系统配置 is None else 系统配置)#挂载系统提示词
    上下文.启动插件(工具运行时,{} if 工具配置 is None else 工具配置)#挂载工具运行时
    上下文.启动插件(智能体注册表)#挂载智能体注册表

def 挂载智能体循环测试架(上下文):#挂载测试架
    """挂载生产 AgentLoop 并暴露其狭窄的测试驱动操作。

    调用本助手前先挂载 挂载智能体循环测试依赖 与任何对加载顺序敏感的消费方。
    上下文拥有循环与工具架返回的每个智能体。
    """
    上下文.启动插件(智能体循环,{'agents':[]})#挂载空智能体循环

    def 创建(标识,选项=None,元=None):#创建智能体
        """创建由工具架上下文拥有的生产智能体与新会话。"""
        if 选项 is None:#缺省
            选项={}#空
        if 元 is None:#缺省
            元={}#空
        return 上下文.agentLoop.创建(标识,选项,元)#创建

    def 领取(智能体,目标,轮次):#认领收件箱
        """经生产循环驱动的认领操作接纳待处理消息。"""
        return 智能体.inbox.领取(目标,轮次)#认领

    return {'create':创建,'claim':领取,'创建':创建,'领取':领取}#驱动（中英键）

def 应用(上下文对象,选项=None):#Cordis入口
    """挂载先决服务（测试工具包通常由 harness 直接调用挂载函数）。"""
    挂载智能体循环测试依赖(上下文对象,选项)#委托挂载

apply=应用#入口
