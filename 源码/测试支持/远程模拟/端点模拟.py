class 远程模拟:
    """端点具名的 Remote mock。分发 / 打开是核心；rpc 是同一核心的 Connection 载体面。"""

    def __init__(自身):
        """组装默认表、间谍、日志与载体面。"""
        自身.一元默认={}#一元默认
        自身.脚本表={}#流脚本
        自身._活流=[]#活流
        自身._打开等待表=[]#打开等待
        自身._锁=threading.Lock()#活流锁
        自身.日志库=调用日志库()#日志库
        自身._一元间谍表={}#一元间谍
        自身._流间谍表={}#流间谍
        def 选取(端点):
            """按已配置模式选取端点间谍。"""
            if 自身.取模式(端点)=='stream':#流
                return 自身._流间谍(端点)#流间谍
            return 自身._一元间谍(端点)#一元间谍
        自身._代理=创建远程代理(选取)#惰性代理
        自身.远程=自身._代理#远程代理
        自身.日志=自身.日志库#日志
        自身.活流=活流控制(自身)#活流控制
        自身.rpc=连接载体面(自身._载体调用,自身._载体打开)#框架槽

    @classmethod
    def 创建(类,选项=None):
        """创建 mock：`$events` 流用一条就绪帧应答打开并保持打开。"""
        if 选项 is None:#缺省
            选项={}#空选项
        模拟=类()#新建
        if '主机' in 选项 and 选项['主机'] is not None:#有 Host 事实
            主机=选项['主机']#Host 事实
        else:#默认
            主机={'home':'/home/mock'}#默认 home
        世代=[0]#代次
        def 就绪脚本(_参数,流):
            """推入一条 ready 帧并保持打开。"""
            世代[0]+=1#递增
            流.推入({'type':'ready','clientId':f'mock-client-{str(世代[0])}','host':主机})#就绪帧
        return 模拟.登记流(事件端点,就绪脚本)#登记 $events

    def 登记一元(自身,端点,规则):
        """设置端点的默认应答或位置处理函数，不改其原生间谍覆盖。"""
        自身.一元默认[端点]=规则#写入默认
        return 自身#链式

    def 登记流(自身,端点,脚本=None):
        """把端点声明为流；若提供脚本则替换默认脚本。"""
        if 脚本 is not None or 端点 not in 自身.脚本表:#写入或首次声明
            自身.脚本表[端点]=脚本#写入
        return 自身#链式

    def 装载(自身,表):
        """登记端点默认，不改原生间谍覆盖。"""
        if 'unary' in 表 and 表['unary'] is not None:#有一元
            for 端点,规则 in 表['unary'].items():#逐条
                自身.登记一元(端点,规则)#登记
        if 'streams' in 表 and 表['streams'] is not None:#有流声明
            for 端点 in 表['streams']:#逐条
                自身.登记流(端点)#声明
        if 'stream' in 表 and 表['stream'] is not None:#有流脚本
            for 端点,脚本 in 表['stream'].items():#逐条
                自身.登记流(端点,脚本)#登记
        return 自身#链式

    def 取模式(自身,端点):
        """端点是已声明流还是有一元规则；未登记则为 None。"""
        if 端点 in 自身.脚本表:#流
            return 'stream'#流
        if 端点 in 自身.一元默认:#一元
            return 'unary'#一元
        return None#未登记

    def 端点列表(自身):
        """已登记端点与已访问代理方法，已排序。"""
        名称集=set(自身.脚本表.keys())#从脚本开始
        for 端点 in 自身.一元默认:#加一元
            名称集.add(端点)#加入
        for 命名空间,方法空间 in 自身._代理.items():#已访问命名空间
            for 方法名 in 方法空间.keys():#已访问方法
                名称集.add(f'{命名空间}/{方法名}')#加端点
        return sorted(名称集)#排序

    def 分发(自身,端点,参数):
        """用已登记规则的值原样应答一次一元调用。"""
        try:#调用间谍
            应答=自身._一元间谍(端点)(*参数)#默认或覆盖
        except 远程模拟错误 as 错误:#本包错误
            if 错误.种类=='missing-unary':#漏配
                raise 错误#原样抛
            记录=自身.日志库.记调用(端点,参数)#记调用
            记录.状态='failed'#失败状态
            记录.结果=错误#记下错误
            raise 错误#再抛
        except BaseException as 错误:#其他抛错
            包装=转错误(错误)#转错误
            记录=自身.日志库.记调用(端点,参数)#记调用
            记录.状态='failed'#失败状态
            记录.结果=包装#记下错误
            raise 包装#再抛
        记录=自身.日志库.记调用(端点,参数)#记调用
        记录.结果=应答#落定结果
        记录.状态='answered'#已应答
        return 记录.结果#返回

    def 打开(自身,端点,参数,信号=None):
        """经端点的原生间谍打开；默认把已登记脚本跑成受控流。"""
        return 自身._流间谍(端点)(*参数,信号=信号)#经流间谍

    def 断言无漏配(自身):
        """任何请求没找到规则时抛错，点名这些端点与已登记端点。"""
        漏配=自身.日志库.漏配列表()#漏配
        if len(漏配)==0:#无漏配
            return
        行表=[]#行
        for 条目 in 漏配:#逐条
            行表.append(f'  {条目.端点} ({条目.模式})')#行
        raise 远程模拟错误(f"remote-mock: {str(len(漏配))} unmatched request(s):\n"+'\n'.join(行表)+f"\nregistered: {', '.join(自身.端点列表())}")#抛错

    def _一元间谍(自身,端点):
        """端点的一元间谍；初始实现读取当前默认。"""
        if 端点 in 自身._一元间谍表:#已缓存
            return 自身._一元间谍表[端点]#返回
        def 默认(*位置参数,**关键字参数):
            """读当前一元默认。"""
            return 自身._一元应答(端点,位置参数)#当前默认
        间谍=间谍函数(默认)#新建
        自身._一元间谍表[端点]=间谍#缓存
        return 间谍#返回

    def _一元应答(自身,端点,参数):
        """按已登记规则计算一元应答。"""
        if 端点 not in 自身.一元默认:#无规则
            自身.日志库.记漏配(端点,'unary')#记漏配
            raise 远程模拟错误(自身._无规则文案(端点),'missing-unary')#抛缺失
        规则=自身.一元默认[端点]#取规则
        if 是规则函数(规则):#处理函数
            return 规则(*参数)#计算
        return 规则#原值

    def _流间谍(自身,端点):
        """端点的流间谍；初始实现打开已登记脚本。"""
        if 端点 in 自身._流间谍表:#已缓存
            return 自身._流间谍表[端点]#返回
        def 默认(*位置参数,信号=None):
            """剥出取消信号后打开脚本。"""
            if 信号 is None:#未给信号
                信号=中止控制器().信号#新建
            return 自身._打开脚本(端点,位置参数,信号)#打开脚本
        间谍=间谍函数(默认)#新建
        自身._流间谍表[端点]=间谍#缓存
        return 间谍#返回

    def _打开脚本(自身,端点,参数,信号):
        """按已登记脚本打开受控流。"""
        脚本=自身.脚本表[端点] if 端点 in 自身.脚本表 else None#取脚本
        if 脚本 is None:#无脚本
            自身.日志库.记漏配(端点,'stream')#记漏配
            raise 远程模拟错误(自身._无规则文案(端点))#抛错
        流=模拟流(自身.日志库.记流(端点,参数),信号)#建受控流
        with 自身._锁:#串行
            自身._活流.append(流)#记入活流
            自身._唤醒已打开(端点)#唤醒打开等待
        流.执行脚本(脚本,参数)#执行脚本
        return 流#返回流

    def _无规则文案(自身,端点):
        """无规则诊断文案。"""
        return f"remote-mock: {端点} 没有规则；已登记：{', '.join(自身.端点列表())}"#诊断

    def _匹配(自身,端点,条件):
        """端点上仍打开或仍持有未拉项的流；其余忘掉。"""
        with 自身._锁:#串行
            留下=[]#仍活
            for 流 in 自身._活流:#扫描
                if 流.记录.状态=='open' or 流.排队数>0:#仍相关
                    留下.append(流)#留下
            自身._活流=留下#忘掉已完
            结果=[]#匹配
            for 流 in 自身._活流:#过滤
                if 流.记录.端点!=端点:#端点不符
                    continue#跳过
                if 条件 is None or 条件(流.记录.参数):#过滤
                    结果.append(流)#收下
            return 结果#匹配活流

    def _对每条打开(自身,端点,条件,动作):
        """对每条仍打开的匹配流执行动作，返回条数。"""
        目标=[]#打开中
        for 流 in 自身._匹配(端点,条件):#匹配
            if 流.记录.状态=='open':#仍打开
                目标.append(流)#收下
        for 流 in 目标:#执行
            动作(流)#动作
        return len(目标)#条数

    def _唤醒已打开(自身,端点):
        """兑现已满足次数的打开等待。"""
        已打开=len(自身.日志库.流列表(端点))#已打开次数
        就绪=[]#已满足
        留下=[]#未满足
        for 等待者 in 自身._打开等待表:#扫描
            if 等待者.端点==端点 and 已打开>=等待者.次数:#已满足
                就绪.append(等待者)#收下
            else:#未满足
                留下.append(等待者)#留下
        自身._打开等待表=留下#去掉已满足
        for 等待者 in 就绪:#兑现
            等待者.任务.兑现()#兑现

    def _载体调用(自身,_通道,端点,载荷,信号=None):
        """载体 call：分发；有信号则与中止赛跑。"""
        参数=载荷参数(端点,载荷)#取出位置参数
        def 执行分发():
            """跑分发。"""
            return 自身.分发(端点,参数)#分发
        if 信号 is None:#无信号
            return 执行分发()#直接分发
        return 与中止赛跑(在线程执行(执行分发),信号)#与中止赛跑

    def _载体打开(自身,_通道,端点,载荷,信号=None):
        """载体 open：打开脚本流。"""
        return 自身.打开(端点,载荷参数(端点,载荷),信号)#打开

def 是规则函数(规则):
    """规则是否为位置处理函数。"""
    return callable(规则)#函数即处理函数

def 载荷参数(端点,载荷):
    """从载体载荷取出位置参数：整机代理发送的数组，或 Gateway 自身端点发送的那一个对象。"""
    if isinstance(载荷,dict) and 'args' in 载荷:#有 args
        参数=载荷['args']#取出
        if isinstance(参数,(list,tuple)):#数组
            return list(参数)#原样列表
        if isinstance(参数,dict):#一个对象
            return [参数]#包成单参
    raise 远程模拟错误(f'remote-mock: payload of {端点} must be {{ args: unknown[] | object }}')#非法载荷

def 在线程执行(函数):
    """在工作线程执行并返回任务。"""
    任务=操作任务()#本次任务
    def 执行并结算():
        """执行函数并结算。"""
        try:#执行
            任务.兑现(函数())#兑现同步返回值
        except BaseException as 错误:#失败
            任务.拒绝(错误)#拒绝
    工作=threading.Thread(target=执行并结算)#工作线程
    工作.daemon=True#不挡住退出
    工作.start()
    return 任务#操作任务

def 赛跑(任务列表):
    """最先结算的那路胜出。"""
    胜出=操作任务()#赛跑结果
    锁=threading.Lock()#只结算一次
    def 等待并胜出(任务):
        """等待一路并尝试胜出。"""
        try:#等待
            值=任务.等待()#等待操作任务
            with 锁:#只结算一次
                胜出.兑现(值)#先到先赢
        except BaseException as 错误:#失败
            with 锁:#只结算一次
                胜出.拒绝(错误)#先到先赢
    for 任务 in 任务列表:#每路一线程
        工作=threading.Thread(target=等待并胜出,args=(任务,))#等待线程
        工作.daemon=True#不挡住退出
        工作.start()
    return 胜出.等待()#阻塞取胜者

def 全部并发(任务列表):
    """并发等待全部，一路失败则抛。"""
    if len(任务列表)==0:#空列表
        return []#空结果
    槽表=[操作任务() for 项 in 任务列表]#每路一槽
    def 等待并写入槽(任务,槽):
        """等待一路写入槽。"""
        try:#等待
            槽.兑现(任务.等待())#兑现
        except BaseException as 错误:#失败
            槽.拒绝(错误)#拒绝
    for 任务,槽 in zip(任务列表,槽表):#每路一线程
        工作=threading.Thread(target=等待并写入槽,args=(任务,槽))#工作线程
        工作.daemon=True#不挡住退出
        工作.start()
    return [槽.等待() for 槽 in 槽表]#按原序取出

