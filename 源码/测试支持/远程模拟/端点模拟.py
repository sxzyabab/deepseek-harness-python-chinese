class 间谍函数:
    """记录调用并可覆盖实现的测试间谍。"""

    def __init__(自身,初始实现):
        """用初始实现构造。"""
        自身._初始实现=初始实现#初始实现
        自身._实现=初始实现#当前实现
        自身._队列=[]#一次队列
        自身.调用表=[]#调用记录

    def __call__(自身,*位置参数,**关键字参数):
        """记录本次调用并走一次队列或当前实现。"""
        if '信号' in 关键字参数 and 关键字参数['信号'] is not None:#流调用带取消信号
            自身.调用表.append(位置参数+(关键字参数['信号'],))#末尾记下信号
        else:#一元或无信号
            自身.调用表.append(位置参数)#只记位置参数
        if len(自身._队列)>0:#有一次队列
            动作=自身._队列.pop(0)#取出队头
            return 动作(*位置参数,**关键字参数)#跑一次
        return 自身._实现(*位置参数,**关键字参数)#当前实现

    def 设实现(自身,实现):
        """替换当前实现。"""
        自身._实现=实现#写入
        return 自身#链式

    def 设返回值(自身,值):
        """持续返回给定值。"""
        def 固定(*位置参数,**关键字参数):
            """忽略参数返回固定值。"""
            return 值#固定值
        自身._实现=固定#写入
        return 自身#链式

    def 排队返回值(自身,值):
        """排队一次返回值。"""
        def 一次(*位置参数,**关键字参数):
            """返回排队值一次。"""
            return 值#排队值
        自身._队列.append(一次)#入队
        return 自身#链式

    def 设抛出(自身,错误):
        """持续抛出给定错误。"""
        def 抛(*位置参数,**关键字参数):
            """忽略参数抛错。"""
            raise 错误#抛出
        自身._实现=抛#写入
        return 自身#链式

    def 清除调用(自身):
        """保留实现与队列，只清调用表。"""
        自身.调用表=[]#清空
        return 自身#链式

    def 重置实现(自身):
        """清除覆盖并恢复初始实现。"""
        自身._实现=自身._初始实现#恢复
        自身._队列=[]#清队列
        自身.调用表=[]#清调用
        return 自身#链式

class 活流控制:
    """已登记脚本打开的流的控制与同步；原生覆盖排除在外。"""

    def __init__(自身,模拟):
        """挂上所属模拟。"""
