import threading#取消监听与队列锁
from concurrent.futures import Future as 原生结果#单次操作结果

流结束哨兵=object()#迭代结束哨兵

class 远程模拟错误(Exception):
    """远程模拟包的异常基类。"""

    def __init__(自身,消息,种类=None):
        """记下消息与可选种类。"""
        super().__init__(消息)#错误消息
        自身.种类=种类#按结构识别，无则None

class 操作任务:
    """单次操作的 Future 包装，只留 等待。"""

    def __init__(自身):
        """构造未决任务。"""
        自身._原生结果=原生结果()#底层 Future

    def 兑现(自身,值=None):
        """成功结算。"""
        if not 自身._原生结果.done():#尚未结算
            自身._原生结果.set_result(值)#写入结果
        return 值#返回兑现值

    def 拒绝(自身,错误):
        """失败结算。"""
        if not 自身._原生结果.done():#尚未结算
            if isinstance(错误,BaseException):#已是异常
                自身._原生结果.set_exception(错误)#原样拒绝
            else:#非异常
                包装=远程模拟错误('任务被拒绝')#包装拒绝
                包装.原因=错误#附加信息做成属性
                自身._原生结果.set_exception(包装)#包装拒绝

    def 等待(自身,超时=None):
        """阻塞等到结算。"""
        return 自身._原生结果.result(timeout=超时)#取结果或抛错

class 中止信号:
    """threading.Event 取消通道。原因用异常对象承载，不对外挂第二字段。"""

    def __init__(自身,已中止标志=False):
        """创建一条取消通道。"""
        自身._事件=threading.Event()#中止标志
        自身._异常=None#中止时抛出的异常
        if 已中止标志:#创建时已中止
            自身._事件.set()#置位
            自身._异常=远程模拟错误('aborted')#默认中止异常

    def 触发(自身,原因=None):
        """标记中止。"""
        if 自身._事件.is_set():#只触发一次
            return#已触发
        if isinstance(原因,BaseException):#原因已是异常
            自身._异常=原因#用异常对象承载
        elif 原因 is not None:#非异常原因
            中止异常=远程模拟错误('aborted')#包装
            中止异常.原因=原因#附加属性
            自身._异常=中止异常#记下
        else:#无原因
            自身._异常=远程模拟错误('aborted')#默认
        自身._事件.set()#置位

class 中止控制器:
    """发出中止的控制器。"""

    def __init__(自身):
        """创建配套信号。"""
        自身.信号=中止信号()#本控制器的信号

    def 中止(自身,原因=None):
        """中止配套信号。"""
        自身.信号.触发(原因)#触发一次

def 已中止(信号):
    """信号是否已中止。无信号视为未中止。"""
    if 信号 is None:#无信号
        return False#未中止
    return 信号._事件.is_set()#Event 置位即中止

def 若已中止则抛出(信号):
    """已中止则抛出承载原因的异常。"""
    if 信号 is None:#无信号
        return#无信号
    if not 信号._事件.is_set():#仍活着
        return#仍活着
    if 信号._异常 is not None:#有承载异常
        raise 信号._异常#抛出
    raise 远程模拟错误('aborted')#默认中止

def 转错误(原因):
    """抛出值所代表的错误：本身已是异常则原样，否则用其字符串形式新建。"""
    if isinstance(原因,BaseException):#已是异常
        return 原因#原样
    return 远程模拟错误(str(原因))#包装

def 帧脚本(项表):
    """吐完给定项后结束的脚本。"""
    def 脚本(_参数,流):
        """推入全部项并结束。"""
        for 项 in 项表:#逐项
            流.推入(项)#推入
        流.结束()#结束
    return 脚本#返回脚本

def 打开流脚本(初始=None):
    """吐完初始项后保持打开，供活流继续推。"""
    if 初始 is None:#缺省空
        初始=()#空初始
    def 脚本(_参数,流):
        """推入初始项。"""
        for 项 in 初始:#逐项
            流.推入(项)#推入
    return 脚本#返回脚本

class 模拟流:
    """一条打开的流：脚本推入队列、单一消费方读取；日志条目跟踪其状态。"""

    def __init__(自身,记录,源信号):
        """挂上日志条目与打开方取消信号。"""
        自身.记录=记录#日志条目
        自身._源信号=源信号#打开方信号
        自身._队列=[]#未拉队列
        自身._已定局=None#定局
        自身._等待=None#唯一挂起读取
        自身._排空等待表=[]#排空等待
        自身._锁=threading.Lock()#队列锁
        自身._取消器=中止控制器()#本流取消控制器
        自身.信号=自身._取消器.信号#句柄信号
        if 已中止(源信号):#已中止则立刻取消
            自身._取消(源信号._异常)#立刻取消
        else:#否则听中止
            def 转发取消():
                """源信号置位后取消本流。"""
                源信号._事件.wait()#阻塞到中止
                自身._取消(源信号._异常)#取消
            工作=threading.Thread(target=转发取消)#监听线程
            工作.daemon=True#不挡住退出
            工作.start()#启动

    @property
    def 排队数(自身):
        """已推入但消费方尚未拉取的项数。"""
        return len(自身._队列)#队列长度

    def 推入(自身,项):
        """为消费方排队一项。"""
        with 自身._锁:#串行
            if 自身.记录.状态!='open':#非打开则忽略
                return
            自身.记录.已推数+=1#计数
            if 自身._等待 is not None:#有挂起读取
                等待=自身._等待#取任务
                自身._等待=None#清空挂起
                等待.兑现(项)#直接交给读取
                return
            自身._队列.append(项)#否则入队

    def 结束(自身):
        """排队项排空后结束该流。"""
        自身._定局(('end',), 'ended')#以结束定局

    def 失败(自身,错误):
        """排队项排空后，让消费方的下一次读取以错误失败。"""
        自身._定局(('fail',错误),'failed')#以失败定局

    def 执行脚本(自身,脚本,参数):
        """在本流上启动脚本；同步抛错则流失败。"""
        try:#调用脚本
            脚本(参数,自身)#同步执行
        except BaseException as 错误:#同步抛错
            自身.失败(转错误(错误))#流失败

    def 等到排空(自身):
        """消费方已拉完迄今排队项并等待下一项，或流已不再打开且无未拉项。"""
        with 自身._锁:#串行检查
            if 自身._已排空():#已排空
                return
            等待=操作任务()#新建等待
            自身._排空等待表.append(等待)#登记
        等待.等待()#阻塞

    def __iter__(自身):
        """同步迭代器。"""
        return 自身#自身即迭代器

    def __next__(自身):
        """拉取下一项；结束或取消则停止迭代。"""
        try:#拉取
            值=自身._拉取()#取项或哨兵
        finally:#无论成败
            自身._唤醒排空()#可能排空
        if 值 is 流结束哨兵:#结束或取消
            raise StopIteration#停止
        return 值#下一项

    def close(自身):
        """消费方提前离开则取消。"""
        自身._取消()#取消

    def _拉取(自身):
        """从队列或挂起读取取下一项。"""
        with 自身._锁:#串行
            if len(自身._队列)>0:#有队列
                return 自身._队列.pop(0)#出队
            if 自身._已定局 is not None:#已定局
                return 自身._收尾(自身._已定局)#收尾
            if 自身.记录.状态=='cancelled':#已取消
                return 流结束哨兵#结束
            if 自身._等待 is not None:#已有消费方
                raise 远程模拟错误(f'remote-mock: {自身.记录.端点} stream has one consumer')#第二读取
            自身._等待=操作任务()#挂起唯一读取
            等待=自身._等待#取出
        return 等待.等待()#阻塞到推入或定局

    def _收尾(自身,定局):
        """按定局返回哨兵或抛错。"""
        if 定局[0]=='end':#结束
            return 流结束哨兵#停止迭代
        raise 定局[1]#失败错误

    def _定局(自身,定局,状态):
        """打开中的流定局为结束或失败。"""
        with 自身._锁:#串行
            if 自身.记录.状态!='open':#非打开则忽略
                return
            自身.记录.状态=状态#写状态
            自身._已定局=定局#记定局
            等待=自身._等待#挂起
            自身._等待=None#清空
        自身._唤醒排空()#可能排空
        if 等待 is None:#无挂起
            return
        if 定局[0]=='end':#结束
            等待.兑现(流结束哨兵)#交给挂起读取
        else:#失败
            等待.拒绝(定局[1])#拒绝挂起读取

    def _取消(自身,原因=None):
        """取消打开中的流，并丢掉未拉项。"""
        等待=None#挂起读取
        with 自身._锁:#串行
            if 自身.记录.状态=='open':#仍打开
                自身.记录.状态='cancelled'#记取消
                等待=自身._等待#挂起
                自身._等待=None#清空
                自身._队列[:]=[]#丢队列
                自身._取消器.中止(原因)#中止句柄信号
            自身._队列[:]=[]#丢掉留下的项
        if 等待 is not None:#有挂起读取
            等待.兑现(流结束哨兵)#结束
        自身._唤醒排空()#排空

    def _已排空(自身):
        """空队列且在等下一项或已不定打开。"""
        return len(自身._队列)==0 and (自身._等待 is not None or 自身.记录.状态!='open')#排空判定

    def _唤醒排空(自身):
        """已排空则兑现全部排空等待。"""
        with 自身._锁:#串行
            if not 自身._已排空():#未排空
                return
            等待表=自身._排空等待表#取出
            自身._排空等待表=[]#清空
        for 等待 in 等待表:#全部兑现
            等待.兑现()#兑现
