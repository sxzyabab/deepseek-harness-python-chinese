class 方法空间:
    """已访问方法的缓存表。"""

    def __init__(自身,命名空间,选取):
        """记下命名空间与按端点选取间谍的函数。"""
        自身._命名空间=命名空间#命名空间名
        自身._选取=选取#选取函数
        自身._方法表={}#已访问方法

    def __getattr__(自身,名):
        """首次访问时缓存该端点间谍。"""
        if 名.startswith('_'):#私有名
            raise AttributeError(名)#无此属性
        if 名 not in 自身._方法表:#尚未访问
            自身._方法表[名]=自身._选取(f'{自身._命名空间}/{名}')#选取并缓存
        return 自身._方法表[名]#返回间谍

    def keys(自身):
        """已访问方法名。"""
        return 自身._方法表.keys()#键

class 远程代理:
    """已访问命名空间的缓存表。"""

    def __init__(自身,选取):
        """记下按端点选取间谍的函数。"""
        自身._选取=选取#选取函数
        自身._命名空间表={}#已访问命名空间

    def __getattr__(自身,名):
        """首次访问时缓存命名空间。"""
        if 名.startswith('_'):#私有名
            raise AttributeError(名)#无此属性
        if 名 not in 自身._命名空间表:#尚未访问
            自身._命名空间表[名]=方法空间(名,自身._选取)#建方法空间
        return 自身._命名空间表[名]#返回

    def items(自身):
        """已访问命名空间与方法空间。"""
        return 自身._命名空间表.items()#条目

    def keys(自身):
        """已访问命名空间名。"""
        return 自身._命名空间表.keys()#键

def 创建远程代理(选取):
    """缓存已访问命名空间，并为每个方法暴露当前原生间谍。"""
    return 远程代理(选取)#惰性代理
