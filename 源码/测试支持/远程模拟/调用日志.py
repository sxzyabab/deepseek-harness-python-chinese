class 调用记录:
    """一次一元调用：规则被选中时记入，规则结算时落定。"""

    def __init__(自身,端点,参数,状态,结果,序号):
        """记下端点、参数、状态、结果与序号。"""
        自身.端点=端点#端点名
        自身.参数=参数#位置参数
        自身.状态=状态#pending/answered/failed
        自身.结果=结果#应答或错误
        自身.序号=序号#全局序号

class 流记录:
    """一次流打开及其当前状态。"""

    def __init__(自身,端点,参数,状态,已推数,序号):
        """记下端点、参数、状态、已推数与序号。"""
        自身.端点=端点#端点名
        自身.参数=参数#位置参数
        自身.状态=状态#open/ended/failed/cancelled
        自身.已推数=已推数#已推数
        自身.序号=序号#全局序号

class 漏配记录:
    """一次没有找到规则的请求。"""

    def __init__(自身,端点,模式):
        """记下端点与请求模式。"""
        自身.端点=端点#端点名
        自身.模式=模式#unary或stream

class 调用日志库:
    """mock 的日志库。"""

    def __init__(自身):
        """空日志。"""
        自身._调用条目=[]#调用条目
        自身._流条目=[]#流条目
        自身._漏配条目=[]#漏配条目
        自身._序号=0#序号计数

    def 调用列表(自身,端点=None):
        """一元调用，最旧在前，带实时状态。"""
        return [条目 for 条目 in 自身._调用条目 if 端点 is None or 条目.端点==端点]#按端点过滤

    def 流列表(自身,端点=None):
        """流打开，最旧在前，带实时状态。"""
        return [条目 for 条目 in 自身._流条目 if 端点 is None or 条目.端点==端点]#按端点过滤

    def 请求列表(自身,端点=None):
        """每次一元调用与流打开的第一个位置参数，最旧在前。"""
        条目表=list(自身.调用列表(端点))+list(自身.流列表(端点))#合并调用与流
        结果=[]#过滤后
        for 条目 in 条目表:#逐条
            if 端点 is not None or not 条目.端点.startswith('$'):#无端点时去掉$前缀
                结果.append(条目)#收下
        def 取序号(条目):
            """排序键。"""
            return 条目.序号#全局序号
        结果.sort(key=取序号)#按序号
        首参表=[]#首参
        for 条目 in 结果:#取首参
            首参表.append(条目.参数[0] if len(条目.参数)>0 else None)#空参为None
        return 首参表#请求列表

    def 漏配列表(自身):
        """没有找到规则的请求，最旧在前。"""
        return list(自身._漏配条目)#副本

    def 记调用(自身,端点,参数):
        """记录一次已选中规则的调用，返回可变条目。"""
        自身._序号+=1#递增序号
        记录=调用记录(端点,参数,'pending',None,自身._序号)#新建待定
        自身._调用条目.append(记录)#入列
        return 记录#可变条目

    def 记流(自身,端点,参数):
        """记录一次流打开，返回可变条目。"""
        自身._序号+=1#递增序号
        记录=流记录(端点,参数,'open',0,自身._序号)#新建打开
        自身._流条目.append(记录)#入列
        return 记录#可变条目

    def 记漏配(自身,端点,模式):
        """记录一次没有规则的请求。"""
        自身._漏配条目.append(漏配记录(端点,模式))#入列
