from ...远程模拟 import 远程模拟#远程模拟
from .远程默认应答 import 远程默认应答#远程默认应答
from .测试客户端 import 测试客户端#测试客户端
from .名册 import 客户端测试运行时错误#本包异常

__all__=['客户端测试夹具','创建客户端测试']#仅中文公开名

class 客户端测试夹具:#客户端测试夹具
    """每测一份模拟与惰性、关闭时拆除的客户端。"""

    def __init__(自身,计划,选项=None):#构造
        """创建已装载默认应答的模拟。"""
        if 选项 is None:#缺省
            选项={}#空
        自身.模拟=远程模拟.创建().装载(远程默认应答)#创建并装载默认应答
        自身.远程=自身.模拟.远程#同一模拟的代理
        自身._计划=计划#组装计划
        自身._选项=选项#选项
        自身._客户端=None#已启动客户端
        自身._已关闭=False#夹具是否已关

    def 启动(自身):#启动
        """启动本测拥有的那一个客户端；夹具关闭后拒绝。重复调用共享同一实例。"""
        if 自身._已关闭:#已关
            raise 客户端测试运行时错误('client-test-runtime: start() called after its test fixture closed')#英文诊断
        if 自身._客户端 is None:#尚未启动
            try:#启动
                自身._客户端=测试客户端.启动(自身._计划,自身.模拟,自身._选项)#启动唯一客户端
            except Exception:#启动失败留给调用方
                自身._客户端=None#保持未启动，关闭时仍检查漏配
                raise#原样抛
        return 自身._客户端#共享实例

    def 关闭(自身):#关闭
        """关闭夹具：拆除已启动客户端，并检查漏配。启动失败不在此重抛。"""
        自身._已关闭=True#标记已关
        客户端=自身._客户端#已启动客户端
        try:#拆除
            if 客户端 is not None:#有客户端
                客户端.拆除()#拆除
        finally:#无论拆除成败
            自身.模拟.断言无漏配()#即使从未启动也检查

def 创建客户端测试(计划,选项=None):#创建客户端测试
    """返回每测一份的夹具；调用方用完后关闭。"""
    if 选项 is None:#缺省
        选项={}#空
    return 客户端测试夹具(计划,选项)#新夹具
