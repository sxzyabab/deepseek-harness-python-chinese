class 已中止错误(Exception):
    '操作因中止信号而终止'

class 任务被拒绝错误(Exception):
    '任务被一个不是异常的原因拒绝时的包装，原始原因在 原因 属性'
    def __init__(自身,原因):
        '记下原始原因'
        super().__init__(str(原因))
        自身.原因=原因

class 操作任务:
    '只结算一次的任务（Future 的薄包装）：兑现与拒绝先到先得，之后的结算被忽略'
    def __init__(自身):
        '创建未结算任务'
        自身._未来=未来类()
        自身._锁=锁类()

    def 兑现(自身,值=None):
        '以值结算；已结算则忽略；返回值本身'
        with 自身._锁:#检查与写入必须原子，否则并发结算会抛 InvalidStateError
            if not 自身._未来.done():
                自身._未来.set_result(值)
        return 值

    def 拒绝(自身,错误):
        '以错误结算；错误不是异常时包成任务被拒绝错误；已结算则忽略'
        if not isinstance(错误,BaseException):
            错误=任务被拒绝错误(错误)
        with 自身._锁:
            if not 自身._未来.done():
                自身._未来.set_exception(错误)

    def 已完成(自身)->bool:
        '是否已结算'
        return 自身._未来.done()

    def 等待(自身,超时=None):
        '阻塞到结算：兑现则返回值，拒绝则抛出错误；超时（秒）则抛 TimeoutError'
        return 自身._未来.result(timeout=超时)

class 中止信号:
    '只读的取消通知：被中止后不可恢复，原因以异常对象保存；真正停下工作由观察它的一方负责'
    def __init__(自身):
        '创建未中止的信号'
        自身._事件=事件类()
        自身._锁=锁类()
        自身._原因=None
        自身._回调表=[]

    @property
    def 原因(自身):
        '中止原因异常；未中止为 None'
        return 自身._原因

    def 触发(自身,原因=None):
        '中止信号，只有第一次生效。原因是异常则原样保留，否则包成已中止错误；全部回调都会执行，之后若有回调失败则抛出第一个错误'
        with 自身._锁:
            if 自身._事件.is_set():
                return
            if isinstance(原因,BaseException):
                自身._原因=原因
            elif 原因 is None:
                自身._原因=已中止错误('操作已中止')
            else:
                自身._原因=已中止错误(f'操作已中止：{原因}')
            自身._事件.set()
            待执行回调=自身._回调表
            自身._回调表=[]
        回调错误=[]
        for 回调 in 待执行回调:#锁外执行，回调里可以安全地再操作本信号
            try:
                回调(自身._原因)
            except Exception as 错误:
                回调错误.append(错误)
        if len(回调错误)>0:
            raise 回调错误[0]

    def 已中止(自身)->bool:
        '是否已中止'
        return 自身._事件.is_set()

    def 若已中止则抛出(自身):
        '已中止则抛出中止原因'
        if 自身._事件.is_set():
            raise 自身._原因

    def 等待(自身,超时=None)->bool:
        '阻塞到中止或超时（秒）；返回是否已中止，可当作可中止的休眠'
        return 自身._事件.wait(超时)

    def 登记回调(自身,回调):
        '中止时以原因异常调用回调；登记时已中止则立即调用。返回取消登记的函数'
        with 自身._锁:
            已触发=自身._事件.is_set()
            if not 已触发:
                自身._回调表.append(回调)
        def 取消登记():
            '取消登记；已执行或已取消则无效果'
            with 自身._锁:
                if 回调 in 自身._回调表:
                    自身._回调表.remove(回调)
        if 已触发:
            回调(自身._原因)
        return 取消登记

class 中止控制器:
    '持有并发出一条中止信号'
    def __init__(自身):
        '创建控制器及其配套信号'
        自身.信号=中止信号()

    def 中止(自身,原因=None):
        '中止配套信号，重复调用无效果'
        自身.信号.触发(原因)

def 已中止(信号)->bool:
    '信号是否已中止；没有信号视为未中止'
    return 信号 is not None and 信号.已中止()

def 若已中止则抛出(信号):
    '信号已中止则抛出中止原因；没有信号则什么也不做'
    if 信号 is not None:
        信号.若已中止则抛出()

def 合成信号(*信号列表)->中止信号:
    '得到一条新信号：任一来源中止它就中止，原因取最先中止的来源；None 来源被忽略。合成信号中止后会撤销对其余来源的监听'
    控制器=中止控制器()
    取消登记列表=[]
    def 转发(原因):
        '来源中止后转给合成信号'
        控制器.中止(原因)
    def 撤销监听(原因):
        '合成信号中止后，撤销对所有来源的监听，避免长寿命来源上堆积回调'
        for 取消登记 in 取消登记列表:
            取消登记()
    控制器.信号.登记回调(撤销监听)
    for 来源 in 信号列表:
        if 来源 is None:
            continue
        if 控制器.信号.已中止():
            break
        取消登记列表.append(来源.登记回调(转发))
    return 控制器.信号

def 并发执行全部(函数列表:list)->list:
    '每个无参函数各占一条守护线程并发执行，全部结束后按原顺序返回结果；有失败则抛出顺序最靠前的那个错误'
    结果列表=[None]*len(函数列表)
    错误列表=[None]*len(函数列表)
    def 执行一路(下标,函数):
        '执行一个函数并把结果或错误按下标记下'
        try:
            结果列表[下标]=函数()
        except BaseException as 错误:
            错误列表[下标]=错误
    线程列表=[]
    for 下标,函数 in enumerate(函数列表):
        线程列表.append(启动守护线程(执行一路,下标,函数))
    for 线程 in 线程列表:
        线程.join()
    for 错误 in 错误列表:
        if 错误 is not None:
            raise 错误
    return 结果列表

class 串行执行器:
    '单条守护线程按提交顺序一个一个执行函数，用于需要互斥且有序的操作'
    def __init__(自身):
        '启动工作线程'
        自身._队列=队列类()
        自身._已关闭=False
        自身._线程=启动守护线程(自身._执行循环)

    def _执行循环(自身):
        '工作线程主体：取出任务执行并结算，遇到结束标记退出'
        while True:
            任务,函数=自身._队列.get()
            if 任务 is None:
                自身._队列.task_done()
                return
            try:
                任务.兑现(函数())
            except BaseException as 错误:#错误交给提交方，由 等待 抛出
                任务.拒绝(错误)
            finally:
                自身._队列.task_done()

    def 提交(自身,函数)->操作任务:
        '把无参函数排到此前所有提交之后，返回其结果任务；关闭后不可再提交'
        if 自身._已关闭:
            raise RuntimeError('串行执行器已关闭')
        任务=操作任务()
        自身._队列.put((任务,函数))
        return 任务

    def 等待静止(自身):
        '阻塞到已提交的函数全部执行完'
        自身._队列.join()

    def 关闭(自身):
        '已提交的函数执行完后工作线程退出；重复调用无效果'
        if 自身._已关闭:
            return
        自身._已关闭=True
        自身._队列.put((None,None))
