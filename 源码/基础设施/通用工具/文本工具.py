from os.path import relpath as 相对路径#计算一个路径相对另一个路径的写法
__all__=['utf8字节数','截断utf8字节','保留utf8尾部字节','路径转正斜杠','相对正斜杠路径']#仅中文公开名

def utf8字节数(文本:str)->int:
    '文本按UTF-8编码后的字节数'
    return len(文本.encode('utf-8'))#编码后取长度

def 保留utf8尾部字节(文本:str,最大字节:int)->str:
    '保留文本末尾不超过最大字节的部分，切点落在字符边界；用于只关心最新输出的日志与终端尾部'
    数据=文本.encode('utf-8')#整段编码为字节
    if len(数据)<=最大字节:#未超出预算
        return 文本#原样返回
    切点=len(数据)-最大字节#从预算位置开始寻找字符边界
    while 切点<len(数据) and (数据[切点]&0xC0)==0x80:#切点落在多字节字符的续字节上
        切点+=1#前进到下一个字符的起点
    return 数据[切点:].decode('utf-8')#截取后缀并解码

def 截断utf8字节(文本:str,最大字节:int)->str:
    '按UTF-8字节数截断文本，切点落在字符边界，不劈开码点'
    数据=文本.encode('utf-8')#整段编码为字节
    if len(数据)<=最大字节:#未超出预算
        return 文本#原样返回
    切点=最大字节#从预算位置开始寻找字符边界
    while 切点>0 and (数据[切点]&0xC0)==0x80:#切点落在多字节字符的续字节上
        切点-=1#回退到该字符的起点
    return 数据[:切点].decode('utf-8')#截取前缀并解码

def 路径转正斜杠(路径:str)->str:
    '把路径里的反斜杠换成正斜杠，不做其它规范化'
    return 路径.replace('\\','/')#Windows分隔符统一为正斜杠

def 相对正斜杠路径(路径:str,起点:str)->str:
    '路径相对起点的写法，分隔符统一为正斜杠'
    return 路径转正斜杠(相对路径(路径,起点))#先算相对路径再统一分隔符
