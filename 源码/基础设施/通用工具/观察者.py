'订阅与通知：订阅返回退订函数的观察者集合，以及基于它的可观察状态'
from threading import Lock as 锁类#互斥锁

__all__=['通知失败错误','观察者集合','可观察状态']#仅中文公开名

class 通知失败错误(Exception):
    '通知时有订阅者回调抛出异常；错误列表按回调顺序保存全部失败'
    def __init__(自身,错误列表:list):
        '记下全部失败'
        super().__init__(f'{len(错误列表)} 个订阅者回调失败，首个：{错误列表[0]!r}')
        自身.错误列表=错误列表

class 观察者集合:
    '按订阅顺序保存回调；订阅返回退订函数；通知基于快照，回调里订阅或退订不影响本轮'
    def __init__(自身):
        '创建空集合'
        自身._锁=锁类()
        自身._回调表={}
        自身._下一序号=0

    def __len__(自身)->int:
        '当前订阅数'
        return len(自身._回调表)

    def 订阅(自身,回调):
        '登记回调，返回退订函数；同一回调订阅多次会被通知多次，每次退订只撤销自己那一次'
        with 自身._锁:
            序号=自身._下一序号
            自身._下一序号+=1
            自身._回调表[序号]=回调
        def 退订():
            '撤销本次订阅，重复调用无效果'
            with 自身._锁:
                自身._回调表.pop(序号,None)
        return 退订

    def 通知(自身,*位置参数):
        '以参数依次调用快照中的全部回调；某个回调失败不影响其余，全部执行完后抛出通知失败错误'
        with 自身._锁:
            回调列表=list(自身._回调表.values())
        错误列表=[]
        for 回调 in 回调列表:
            try:
                回调(*位置参数)
            except Exception as 错误:
                错误列表.append(错误)
        if len(错误列表)>0:
            raise 通知失败错误(错误列表)

class 可观察状态:
    '持有一个当前值，值变更后通知订阅者（订阅者无参，需要时用 取快照 读取）'
    def __init__(自身,初值):
        '以初值创建'
        自身._状态=初值
        自身._观察者=观察者集合()

    def 取快照(自身):
        '当前值（引用，不复制）'
        return 自身._状态

    def 订阅(自身,回调):
        '登记变更回调，返回退订函数'
        return 自身._观察者.订阅(回调)

    def 设置(自身,下一值):
        '整值替换并通知'
        自身._状态=下一值
        自身._观察者.通知()

    def 更新(自身,变换):
        '变换接收当前值：返回非 None 则作为新值；返回 None 表示已就地修改。随后通知'
        返回值=变换(自身._状态)
        if 返回值 is not None:
            自身._状态=返回值
        自身._观察者.通知()
