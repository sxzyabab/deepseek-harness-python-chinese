"""按插件配置或标签隔离服务实现。"""
from ..工具 import 获取内部数据#共享标记、以父表为原型的映射与内部数据读取

class 隔离标签:
    "隔离表里用作键的唯一标签，只带一个便于诊断的名字"
    def __init__(自身,名称):
        "保存诊断名"
        自身.名称=名称#诊断名

    def __repr__(自身):
        "展示成带名字的标签"
        return f'隔离标签({自身.名称})'#展示文本

class 领域:
    "一组隔离标签的作用域，按服务名分配标签"
    def __init__(自身):
        "空存储"
        自身.存储={}#服务名到隔离标签

    @property
    def 后缀(自身):
        "标签名后缀，由子类给出"
        raise NotImplementedError('领域的后缀由子类给出')#抽象属性

    @property
    def 数量(自身):
        "已分配标签的服务数"
        return len(自身.存储)#服务数

    def 访问(自身,服务名,创建=False):
        "取出该服务名的隔离标签。创建时写入存储，否则只给一份临时标签。"
        if 服务名 in 自身.存储:
            return 自身.存储[服务名]#已有标签
        标签=隔离标签(服务名+自身.后缀)#新标签
        if 创建:
            自身.存储[服务名]=标签#写入存储
        return 标签#已有或新建

    def 删除(自身,服务名):
        "删掉该服务名的隔离标签"
        自身.存储.pop(服务名,None)#删除

class 本地领域(领域):
    "只属于一份插件配置的隔离域"
    def __init__(自身,插件配置对象):
        "绑到插件配置"
        领域.__init__(自身)#空存储
        自身.插件配置=插件配置对象#所属插件配置

    @property
    def 后缀(自身):
        "按插件配置编号区分"
        return '#'+str(自身.插件配置.选项.get('id'))#插件配置编号

class 全局领域(领域):
    "写了同一个标签的插件配置共享的隔离域"
    def __init__(自身,标签名):
        "保存共享标签名"
        领域.__init__(自身)#空存储
        自身.标签名=标签名#共享标签名

    @property
    def 后缀(自身):
        "按共享标签名区分"
        return '@'+str(自身.标签名)#标签名

def 隔离(上下文,配置=None):
    "安装把插件配置的 isolate 与 intercept 选项落到上下文上的加载器钩子"
    全局域表={}#标签名到全局域
    旗标键表={}#服务名到旗标键

    def 访问标签(插件配置对象,服务名,创建=False):
        "按插件配置的 isolate 选项解析该服务名的隔离标签"
        标签名=(插件配置对象.选项.get('isolate') or {}).get(服务名)#True 表示本层独占
        if not 标签名:
            return None#该服务没有隔离
        if 标签名 is True:
            if 插件配置对象.本地域 is None:
                插件配置对象.本地域=本地领域(插件配置对象)#按需建立本地域
            领域对象=插件配置对象.本地域#本地域
        else:
            领域对象=全局域表.get(标签名)#已有全局域
            if 领域对象 is None and 创建:
                领域对象=全局领域(标签名)#新建全局域
                全局域表[标签名]=领域对象#登记
        if 领域对象 is None:
            return None#还没有对应的域
        return 领域对象.访问(服务名,创建)#取标签

    def 插件配置初始化(插件配置对象):
        "把插件配置上下文的隔离表与拦截表换成以父表为原型的独立层"
        字典=插件配置对象.所属上下文.__dict__#插件配置上下文自有字典
        字典[符号.隔离]=原型映射(获取内部数据(插件配置对象.所属上下文,'属性链')[符号.隔离])#以祖先那张表为原型
        字典[符号.拦截]=原型映射(获取内部数据(插件配置对象.所属上下文,'属性链')[符号.拦截])#以祖先那张表为原型
    上下文.监听('loader/entry-init',插件配置初始化)

    def 补丁上下文(插件配置对象,续体):
        "按 isolate 与 intercept 重建隔离表，重载纤程后把实现迁到新标签"
        新表=原型映射(获取内部数据(插件配置对象.父组.所属上下文,'属性链')[符号.隔离])#以父隔离表为原型
        for 服务名 in (插件配置对象.选项.get('isolate') or {}):
            新表[服务名]=访问标签(插件配置对象,服务名,True)#本层隔离标签
        旧表=获取内部数据(插件配置对象.所属上下文,'属性链')[符号.隔离]#换表前的隔离表
        变动={}#服务名到 旧标签、新标签、本层旗标、实现方旗标
        for 服务名 in dict.fromkeys(新表.键们()+list(旗标键表)):
            新标签=新表.get(服务名)#含原型链，两张表都可能没有该服务
            旧标签=旧表.get(服务名)#含原型链，两张表都可能没有该服务
            if 新标签 is 旧标签:
                continue#该服务的隔离没变
            旗标键=旗标键表.get(服务名)#该服务的旗标键
            if 旗标键 is None:
                旗标键=隔离标签('旗标:'+服务名)#新建旗标键
                旗标键表[服务名]=旗标键#登记
            插件配置对象.所属上下文.__dict__[旗标键]=隔离标签(服务名+'#'+str(插件配置对象.选项.get('id')))#本层旗标
            for 标签 in (旧标签,新标签):
                if 标签 is None:
                    continue#这一侧没有标签
                实现=插件配置对象.所属上下文.反射.存储.get(标签)#按标签取实现
                if 实现 is None or 实现.纤程 is None:
                    continue#该标签下还没有提供方
                本方旗标=获取内部数据(插件配置对象.所属上下文,'属性链').get(旗标键)#本层旗标
                实现方旗标=获取内部数据(实现.纤程.所属上下文,'属性链').get(旗标键)#提供方看到的旗标
                变动[服务名]=(旧标签,新标签,本方旗标,实现方旗标)#记下四元组
                if 本方旗标 is not 实现方旗标:
                    break#提供方在隔离边界外，不再看另一侧
        隔离表=插件配置对象.所属上下文.__dict__[符号.隔离]#当前隔离表
        拦截表=插件配置对象.所属上下文.__dict__[符号.拦截]#当前拦截表
        隔离表.设原型(获取内部数据(插件配置对象.父组.所属上下文,'属性链')[符号.隔离])#重挂到当前父组
        拦截表.设原型(获取内部数据(插件配置对象.父组.所属上下文,'属性链')[符号.拦截])#重挂到当前父组
        隔离表.替换自有(新表)#换上新隔离标签
        拦截表.替换自有(插件配置对象.选项.get('intercept'))#换上新拦截配置
        续体()#按新表重载纤程
        存储=插件配置对象.所属上下文.反射.存储#实现存储
        for 旧标签,新标签,本方旗标,实现方旗标 in 变动.values():
            if 本方旗标 is 实现方旗标 and 存储.get(旧标签) and not 存储.get(新标签):
                存储[新标签]=存储.pop(旧标签)#实现跟着插件配置迁到新标签
        def 过滤器(上下文对象,服务名):
            "只通知隔离标签命中、且旗标关系相对提供方发生了变化的依赖方"
            旧标签,新标签,本方旗标,实现方旗标=变动[服务名]#四元组
            对方标签=获取内部数据(上下文对象,'属性链')[符号.隔离].get(服务名)#对方标签
            对方旗标=获取内部数据(上下文对象,'属性链').get(旗标键表[服务名])#对方旗标
            命中=对方标签 is 旧标签 or 对方标签 is 新标签#标签命中
            return 命中 and (本方旗标 is 对方旗标)!=(本方旗标 is 实现方旗标)#旗标关系变了
        插件配置对象.所属上下文.反射.通知(list(变动),过滤器)#刷新受影响的依赖方
        自有名们=新表.键们()#本层仍在用的服务名
        for 服务名 in list(旗标键表):
            if 服务名 not in 自有名们:
                插件配置对象.所属上下文.__dict__.pop(旗标键表[服务名],None)#清掉多余旗标
    上下文.监听('loader/patch-context',补丁上下文)

    def 部分拆除(插件配置对象,遗留选项,仍活动):
        "插件配置不再引用某个全局域时回收它的标签"
        for 服务名,标签名 in (遗留选项.get('isolate') or {}).items():
            if 标签名 is True:
                continue#本地域跟着插件配置走，不必回收
            if 仍活动 and (插件配置对象.选项.get('isolate') or {}).get(服务名)==标签名:
                continue#还在用同一个标签
            领域对象=全局域表.get(标签名)#全局域
            if 领域对象 is None:
                continue#没有这个域
            for 其它插件配置 in 上下文.加载器.插件配置们():
                if (其它插件配置.选项.get('isolate') or {}).get(服务名)==领域对象.标签名:
                    return#还有插件配置在引用，整段放弃回收
            领域对象.删除(服务名)#去掉该服务的标签
            if not 领域对象.数量:
                全局域表.pop(领域对象.标签名,None)#空域一并删掉
    上下文.监听('loader/partial-dispose',部分拆除)
