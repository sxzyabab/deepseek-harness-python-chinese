"""子插件配置列表的运行时拥有者，以及把它挂成嵌套组的插件。"""
from .. import cordis
from weakref import WeakSet as 弱引用集合#热替换换掉的插件对象自行掉出
from .插件配置 import 插件配置#插件配置节点

_组插件集=弱引用集合()#登记为组载体的插件对象

def 标记为组插件(插件):
    "把插件登记成组载体：它的配置是插件配置列表，不做表达式插值"
    _组插件集.add(插件)#按对象身份登记
    return 插件#原对象

def 是组插件(插件):
    "询问插件是不是组载体"
    return 插件 in _组插件集#按对象身份判断

class 插件组:
    """一列子插件配置的运行时拥有者。"""
    def __init__(自身,上下文,所属树):
        """保存上下文与树，并把自己挂到拥有方插件配置上。"""
        自身.所属上下文=上下文#所属上下文
        自身.事件上下文=上下文#派发框架事件的上下文
        自身.所属树=所属树#所属插件树
        自身.子插件选项=[]#按顺序排列的子插件选项
        插件配置对象=上下文.纤程.插件配置#拥有本组的插件配置
        if 插件配置对象 is not None:
            插件配置对象.子组=自身#挂上子组

    def 创建(自身,选项):
        """确保编号、把插件配置移到本组名下并强制更新一次。"""
        编号=自身.所属树.确保编号(选项)#写入或生成编号
        已有=自身.所属树.插件配置表.get(编号)#同编号的已有插件配置
        插件配置对象=已有 if 已有 is not None else 插件配置(自身.所属上下文.加载器)#复用或新建
        if 已有 is None:
            自身.所属树.插件配置表[编号]=插件配置对象#登记新插件配置
        原父组=插件配置对象.父组#可能来自另一个组
        插件配置对象.父组=自身#改挂到本组
        try:
            插件配置对象.更新(选项,True,True)#创建路径直接换掉选项对象
        except BaseException:
            if 已有 is not None:
                插件配置对象.父组=原父组#复用的插件配置还回原组
            else:
                自身.所属树.插件配置表.pop(编号,None)#新建失败就从表里摘掉
            raise
        return 插件配置对象.编号#完整编号

    def 取消链接(自身,选项):
        """按对象身份从子插件选项里摘掉一条。"""
        for 下标 in range(len(自身.子插件选项)):
            if 自身.子插件选项[下标] is 选项:
                自身.子插件选项.pop(下标)#按身份删除
                return

    def 移除(自身,编号,是拆除=False):
        """停掉该插件配置，从插件配置表删掉，拆除路径不动配置列表。"""
        插件配置对象=自身.所属树.插件配置表.get(编号)#查出插件配置
        if 插件配置对象 is None:
            return#没有这个编号
        插件配置对象._拆除()#停掉纤程
        if not 是拆除:
            自身.取消链接(插件配置对象.选项)#从配置列表摘掉
        自身.所属树.插件配置表.pop(编号,None)#从插件配置表删掉
        自身.事件上下文.广播('loader/partial-dispose',插件配置对象,插件配置对象.选项,False)#通知隔离钩子回收

    def 更新(自身,新配置):
        """按新的子插件配置列表创建与删除，失败时整体回滚。"""
        旧配置=自身.子插件选项#回滚用的旧列表
        编号们=set()#查重
        for 选项 in 新配置:
            编号=自身.所属树.确保编号(选项)#先分配编号
            if 编号 in 编号们:
                raise TypeError('同一组里出现了重复的插件配置编号：'+str(编号))#重复编号
            编号们.add(编号)#记下
        旧编号们=[选项.get('id') for 选项 in 旧配置]#旧列表里的编号，保持配置顺序
        新编号们=[选项.get('id') for 选项 in 新配置]#新列表里的编号
        try:
            失败=[]#创建阶段的失败
            for 选项 in 新配置:
                try:
                    自身.创建(选项)#逐条创建
                except BaseException as 错误:
                    失败.append(错误)#收集失败
            if 自身.所属上下文.纤程.编号 is None:
                return#整棵树已经拆了，不必回滚
            if len(失败)==1:
                raise 失败[0]#单条失败原样抛
            if len(失败)>1:
                raise cordis.聚合错误(失败,'部分插件配置应用失败')#多条失败聚合
            for 编号 in 旧编号们:
                if 编号 not in 新编号们:
                    自身.移除(编号,True)#删掉新配置里没有的旧插件配置
            自身.子插件选项=新配置#提交新列表
        except BaseException as 错误:
            自身._回滚(错误,旧配置,旧编号们,新编号们)#整体回滚

    def _回滚(自身,错误,旧配置,旧编号们,新编号们):
        """拆掉本轮新加的插件配置并把旧的建回来。"""
        回滚失败=[]#回滚阶段的失败
        for 编号 in reversed(新编号们):
            if 编号 in 旧编号们:
                continue#旧配置本来就有，不拆
            try:
                自身.移除(编号,True)#拆掉新加的
            except BaseException as 回滚错误:
                回滚失败.append(回滚错误)#收集失败
        for 选项 in 旧配置:
            try:
                自身.创建(选项)#重建旧插件配置
            except BaseException as 回滚错误:
                回滚失败.append(回滚错误)#收集失败
        自身.子插件选项=旧配置#恢复旧列表
        if 回滚失败:
            raise cordis.聚合错误([错误]+回滚失败,'插件配置回滚失败')#回滚也失败
        raise 错误#只抛原错误

    def 停止(自身):
        """拆掉当前列表里的全部插件配置。"""
        for 选项 in list(自身.子插件选项):
            自身.移除(选项.get('id'),True)#按拆除路径移除

class 组(插件组):
    """把一列嵌套插件配置挂到当前插件配置下的插件。"""
    初始配置=[]#默认是空列表

    def __init__(自身,上下文,配置):
        """挂到拥有方插件配置所在的树上，并接管本纤程的配置更新。"""
        插件组.__init__(自身,上下文,上下文.纤程.插件配置.父组.所属树)#与拥有方插件配置同一棵树
        自身.配置=配置#子插件配置
        自身.__dict__[cordis.服务.初始化]=自身._初始化#依赖就绪后再应用子插件配置
        def 更新监听(纤程,新配置,不保存,续体):
            """组的配置更新走子插件配置对比，不重启组插件本身。"""
            return 自身.更新(新配置)#不调用续体，就此接管
        上下文.监听('internal/update',更新监听)#纤程本地钩子

    def _初始化(自身):
        """先登记停止释放器，再应用子插件配置。"""
        yield 自身.停止#卸载时停掉全部子插件配置
        自身.更新(自身.配置)#应用子插件配置

