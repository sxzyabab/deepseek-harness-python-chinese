"""可变的加载器插件树。持久化由子类提供。"""
import random
from urllib.parse import urljoin as 拼接网址#按基准网址解析相对说明符
from .. import cordis
from .插件组 import 插件组#根组

未传=object()#区分"没传父组"与"传了空表示根组"

class 插件树:
    """可变的加载器插件树。子类实现 写入 决定怎么持久化。"""
    分隔=':'#嵌套插件配置编号的分隔符

    def __init__(自身,上下文):
        """扩展出带自己基准网址的上下文并建立根组。"""
        自身.所属上下文=上下文.扩展({'基准网址':上下文.基准网址})#本树的上下文
        自身.事件上下文=自身.所属上下文#派发框架事件的上下文
        自身.启用日志=None#是否打插件生命周期日志
        自身.插件配置表={}#编号到插件配置
        自身.根组=插件组(自身.所属上下文,自身)#根组
        插件配置对象=自身.所属上下文.纤程.插件配置#拥有本树的插件配置
        if 插件配置对象 is not None:
            插件配置对象.子树=自身#挂上子树

    def 插件配置们(自身):
        """按顺序迭代本树以及嵌套子树里的全部插件配置。"""
        for 插件配置对象 in list(自身.插件配置表.values()):
            yield 插件配置对象#本层插件配置
            if 插件配置对象.子树 is not None:
                yield from 插件配置对象.子树.插件配置们()#嵌套子树

    def 等待(自身):
        """收集各插件配置的启动失败。导入与生命周期都是同步跑完的，没有可等的任务。"""
        失败=[]#各插件配置的启动失败
        for 插件配置对象 in 自身.插件配置们():
            try:
                插件配置对象._等待()#取出该插件配置纤程的启动错误
            except BaseException as 错误:
                失败.append(错误)#收集失败
        if len(失败)==1:
            raise 失败[0]#单条失败原样抛
        if len(失败)>1:
            raise cordis.聚合错误(失败,'部分插件配置启动失败')#多条失败聚合

    #============================== 编号与解析 ==============================
    def 确保编号(自身,选项):
        """没有编号就生成一个本树内不重复的十六进制编号。"""
        while not 选项.get('id'):
            候选=format(random.getrandbits(32),'08x')#八位十六进制
            if 候选 not in 自身.插件配置表:
                选项['id']=候选#不碰撞才用
        return 选项['id']#已有或新生成的编号

    def 解析(自身,编号):
        """按编号找插件配置，嵌套编号按分隔符逐层进入子树。"""
        片段们=编号.split(插件树.分隔)#拆开各层
        末段=片段们.pop()#最后一段是目标
        树=自身#从本树开始
        for 片段 in 片段们:
            插件配置对象=树.插件配置表.get(片段)#中间层插件配置
            树=插件配置对象.子树 if 插件配置对象 is not None else None#进入它的子树
            if 树 is None:
                raise LookupError('找不到插件配置 '+编号)#中间层缺失
        插件配置对象=树.插件配置表.get(末段)#目标插件配置
        if 插件配置对象 is None:
            raise LookupError('找不到插件配置 '+编号)#目标缺失
        return 插件配置对象#命中

    def 解析组(自身,编号):
        """按编号找组，空编号表示根组。"""
        if not 编号:
            return 自身.根组#根组
        插件配置对象=自身.解析(编号)#先找插件配置
        if 插件配置对象.子组 is None:
            raise TypeError('插件配置 '+编号+' 不是组')#不是组
        return 插件配置对象.子组#子组

    #============================== 增删改 ==============================
    def 创建(自身,选项,父组编号=None,位置=None):
        """在根组或某个嵌套组里创建插件配置。"""
        组对象=自身.解析组(父组编号)#目标组
        编号=组对象.创建(选项)#创建插件配置
        插件配置对象=自身.解析(编号)#取出刚建的插件配置
        if 位置 is None:
            组对象.子插件选项.append(插件配置对象.选项)#追加到末尾
        else:
            组对象.子插件选项.insert(位置,插件配置对象.选项)#插到指定位置
        组对象.所属树.写入()#持久化
        return 编号#新插件配置编号

    def 移除(自身,编号):
        """停掉插件配置并从它所在的组删掉。"""
        插件配置对象=自身.解析(编号)#查出插件配置
        插件配置对象.父组.移除(编号)#从组里删掉
        插件配置对象.父组.所属树.写入()#持久化

    def 更新(自身,编号,选项,父组编号=未传,位置=None):
        """更新插件配置，必要时把它移到另一个组。"""
        插件配置对象=自身.解析(编号)#查出插件配置
        源组=插件配置对象.父组#原来所在的组
        源位置=_按身份定位(源组.子插件选项,插件配置对象.选项)#原来的位置
        目标组=源组#默认不移动
        if 父组编号 is not 未传:
            目标组=自身.解析组(父组编号)#空编号表示根组
            源组.取消链接(插件配置对象.选项)#从原组摘掉
            if 位置 is None:
                目标组.子插件选项.append(插件配置对象.选项)#追加到末尾
            else:
                目标组.子插件选项.insert(位置,插件配置对象.选项)#插到指定位置
            插件配置对象.父组=目标组#改父组
        try:
            插件配置对象.更新(选项,False,True)#强制更新一次
        except BaseException as 错误:
            if 父组编号 is not 未传:
                自身._回滚移动(插件配置对象,源组,目标组,源位置,编号,错误)#把插件配置挪回去
            raise
        源组.所属树.写入()#原树持久化
        if 目标组 is not 源组:
            目标组.所属树.写入()#目标树也要持久化

    def _回滚移动(自身,插件配置对象,源组,目标组,源位置,编号,错误):
        """更新失败时把插件配置挪回原来的组与位置。"""
        目标组.取消链接(插件配置对象.选项)#从新组摘掉
        源组.子插件选项.insert(len(源组.子插件选项) if 源位置<0 else 源位置,插件配置对象.选项)#插回原位
        插件配置对象.父组=源组#还回原组
        try:
            插件配置对象.更新({},False,True)#按原位置强制更新一次
        except BaseException as 回滚错误:
            raise cordis.聚合错误([错误,回滚错误],'插件配置 '+编号+' 移动回滚失败')#回滚也失败

    #============================== 导入与持久化 ==============================
    def 导入(自身,名称,外层栈=None):
        """按说明符导入插件模块，cordis: 前缀走内建表。"""
        if 名称.startswith('cordis:'):
            return 自身.所属上下文.加载器.内建表[名称[7:]]#内建插件
        def 回调():
            """按基准网址解析后动态导入。"""
            内部加载器=自身.所属上下文.加载器.内部加载器#Node 内部加载器
            if 内部加载器 is not None:
                return 内部加载器.import_(名称,自身.所属上下文.基准网址,{})#走内部加载器
            目标=拼接网址(str(自身.所属上下文.基准网址 or ''),名称) if 名称.startswith('.') else 名称#相对说明符按基准解析
            return __import__(目标,fromlist=['*'])#导入模块
        return cordis.拼接错误(回调,外层栈)#把配置来源栈挂到错误上

    def 写入(自身):
        """持久化当前树的状态。内存树把它实现成空操作。"""
        raise NotImplementedError('插件树的持久化由子类实现')#抽象方法

def _按身份定位(列表,目标):
    """按对象身份找出目标在列表里的下标，找不到给 -1。"""
    for 下标 in range(len(列表)):
        if 列表[下标] is 目标:
            return 下标#按身份命中
    return -1#不在列表里
