class 热替换(服务):
    """监视源文件，重载受影响的插件入口。"""
    依赖声明=['加载器','定时器']#需要加载器与定时器
    配置模式={
        'base':字符串字段(),#监视基准目录
        'root':列表字段(字符串字段(),默认值=['.']),#监视根
        'ignored':列表字段(字符串字段(),默认值=['**/node_modules','**/.*','cache','data']),#忽略模式
        'debounce':自然数字段(默认值=100),#变更防抖毫秒
    }#配置模式

    def __init__(自身,上下文,配置):
        """登记热替换服务并解析基准目录。"""
        服务.__init__(自身,上下文,'热替换')#登记服务
        自身.配置=配置#插件配置
        自身.__dict__[服务.初始化]=自身._初始化#依赖就绪后才开始监视
        自身.内部加载器=自身.所属上下文.加载器.内部加载器#模块加载缓存与解析
        if 自身.内部加载器 is None:
            raise RuntimeError('热替换需要能访问内部模块加载器')#拿不到模块图就没法重载
        自身.基准目录=解析基准目录(配置.get('base'),上下文.基准网址)#监视基准目录
        自身.配置监视表={}#规范文件名到监视器
        自身.刷新状态表=weakref.WeakKeyDictionary()#刷新键到刷新状态
        自身.暂存集=set()#还没处理的变更网址
        自身.监视器=None#主监视器
        自身.外部集=set()#框架自身的依赖，变了要整进程重启
        自身.接受集=set()#可以热替换的网址
        自身.拒绝集=set()#不能热替换的网址

    ################################ 配置文件监视 ################################
    def 登记配置(自身,文件名,刷新):
        """监视一个精确的配置文件，变化时串行调用刷新。"""
        if 自身.监视器 is None:
            raise RuntimeError('热替换还没启动')#主监视还没开
        文件名=os.path.abspath(os.path.join(自身.基准目录,文件名))#相对基准解析
        目标=寻找监视根(文件名)#已存在的祖先目录
        if 目标.文件名 in 自身.配置监视表:
            raise ValueError('该配置路径已经登记过：'+文件名)#重复登记
        监视器=自身._打开配置监视(目标)#打开监视
        自身.配置监视表[目标.文件名]=监视器#登记
        def 当路径变化(路径):
            """只处理登记的那个文件。"""
            观测=os.path.abspath(路径)#观测到的路径
            if 观测==文件名 or 观测==目标.文件名:
                自身.排队刷新(监视器,文件名,刷新)#串行刷新
        for 事件名 in ('新增','修改','删除'):
            监视器.监听(事件名,当路径变化)#三种变化都要看
        try:
            等待监视器就绪(监视器,自身.所属上下文.日志.警告)#等监视就绪
            return 自身.所属上下文.副作用(自身._建立配置监视拆除体(目标.文件名,监视器),'热替换.登记配置()')#挂到纤程
        except BaseException:
            自身.配置监视表.pop(目标.文件名,None)#登记失败就摘掉
            监视器.关闭()#关掉监视
            raise

    def _打开配置监视(自身,目标):
        """按监视目标打开一个只看该文件的监视器。"""
        选项=dict(自身.配置)#插件配置里的通用项
        选项['cwd']=None#回调里给绝对路径
        选项['depth']=目标.深度#只看到该文件所在的那一层
        选项['ignored']=None#精确监视不做忽略
        选项['ignoreInitial']=False#登记时先扫一遍
        return 文件系统监视器(目标.根,选项)#监视器

    def _建立配置监视拆除体(自身,监视文件名,监视器):
        """返回登记在纤程上的副作用体，拆除时关掉该配置监视。"""
        def 执行体():
            """交出关掉监视的释放器。"""
            def 释放():
                """关掉监视。刷新跑在该监视器自己的线程里，关闭时已经等过它了。"""
                if 自身.配置监视表.get(监视文件名) is 监视器:
                    自身.配置监视表.pop(监视文件名,None)#摘掉登记
                监视器.关闭()#关掉监视
            return 释放#释放器
        return 执行体#副作用体

    def 排队刷新(自身,刷新键,文件名,刷新):
        """把同一个键上的刷新串成单队列，失败只记日志。"""
        状态=自身.刷新状态表.get(刷新键)#已有状态
        if 状态 is None:
            状态=刷新状态()#新建状态
            自身.刷新状态表[刷新键]=状态#登记
        状态.待刷新=True#标记有新变更
        if 状态.进行中:
            return#已有队列在跑，它会看到新标记
        状态.进行中=True#本键进入队列
        try:
            while 状态.待刷新:
                状态.待刷新=False#本轮开始
                自身._刷新一次(文件名,刷新)#刷新
        finally:
            状态.进行中=False#队列结束

    def _刷新一次(自身,文件名,刷新):
        """执行一次配置刷新，失败记日志并通知监听者。"""
        try:
            刷新()#执行刷新
        except Exception as 错误:
            自身.所属上下文.日志.警告('重载配置 %C 失败',文件名)#失败摘要
            自身.所属上下文.日志.警告(错误)#失败详情
            try:
                自身.所属上下文.并发广播('hmr/config-update-failed',文件名,错误)#通知监听者
            except Exception as 通知错误:
                自身.所属上下文.日志.警告(通知错误)#监听者自己也失败了

    ################################ 主监视 ################################
    def _初始化(自身):
        """打开主监视，收集框架自身的依赖。"""
        yield 自身._清理#先交出拆除，之后的失败也能回滚
        os.stat(自身.基准目录)#基准目录不存在就直接失败
        监视基准目录=os.path.realpath(自身.基准目录)#解开符号链接
        自身.外部集=自身._收集框架依赖()#框架自身的依赖
        if 自身.配置.get('base'):
            自身.所属上下文.日志.信息('正在监视 %o，基准目录 %s',自身.配置['root'],自身.基准目录)#带基准
        else:
            自身.所属上下文.日志.信息('正在监视 %o',自身.配置['root'])#不带基准
        自身.监视器=自身._打开主监视(监视基准目录)#打开主监视
        自身._挂上变更处理(监视基准目录)#挂上变更回调
        if 自身.配置['root']:
            等待监视器就绪(自身.监视器,自身.所属上下文.日志.警告)#等监视就绪

    def _清理(自身):
        """关掉全部监视。刷新都跑在监视线程里，关闭时已经等过它们了。"""
        if 自身.监视器 is not None:
            自身.监视器.关闭()#关主监视
        for 监视器 in list(自身.配置监视表.values()):
            监视器.关闭()#关配置监视
        自身.配置监视表.clear()#清空登记

    def _收集框架依赖(自身):
        """从进程入口出发收集框架自身依赖的模块网址。"""
        入口任务=自身.内部加载器.loadCache.get(路径转文件网址(os.path.abspath(sys.argv[0])))#入口模块
        return 自身.收集依赖(入口任务) if 入口任务 is not None else set()#依赖集

    def _打开主监视(自身,监视基准目录):
        """按插件配置打开监视全部根目录的主监视器。"""
        忽略模式们=自身.配置['ignored']#忽略模式
        def 忽略路径(路径):
            """任一忽略模式命中相对路径时为真。"""
            相对=os.path.relpath(路径,监视基准目录).replace('\\','/')#相对监视基准
            return any(通配命中(相对,通配式) for 通配式 in 忽略模式们)#逐个模式试
        选项=dict(自身.配置)#插件配置里的通用项
        选项['cwd']=监视基准目录#回调里给相对路径
        选项['ignored']=忽略路径#忽略判断
        选项['ignoreInitial']=True#启动时不要把已有文件全报一遍
        return 文件系统监视器(自身.配置['root'],选项)#主监视器

    def _挂上变更处理(自身,监视基准目录):
        """把三种文件变化接到配置刷新与模块重载上。"""
        防抖重载=自身.所属上下文.防抖(自身.部分重载,自身.配置['debounce'])#合并同一拍的多次变更
        def 当变更(种类,路径):
            """配置文件走刷新，框架文件走整进程重启，其余暂存后防抖重载。"""
            自身.所属上下文.日志.调试('检测到%s：%C',种类,路径)#变更日志
            if 自身._刷新命中的配置树(监视基准目录,路径):
                return#配置文件不走模块重载
            if 种类!='修改':
                return#只有内容修改才触发模块重载
            网址=路径转文件网址(os.path.abspath(os.path.join(监视基准目录,路径)))#文件网址
            if 网址 in 自身.外部集:
                自身.所属上下文.加载器.退出()#框架自身变了，整进程重启
                return
            if 网址 in 自身.内部加载器.loadCache:
                自身.暂存集.add(网址)#暂存这次变更
                防抖重载()#防抖后一起重载
                return
            自身.所属上下文.广播('hmr/change',网址)#还没被加载过的文件
        for 种类 in ('新增','修改','删除'):
            自身.监视器.监听(种类,lambda 路径,种类=种类:当变更(种类,路径))#三种变化都要看

    def _刷新命中的配置树(自身,监视基准目录,路径):
        """变化的是某棵子树的配置文件时安排刷新，并报告已命中。"""
        文件名=os.path.abspath(os.path.join(监视基准目录,路径))#按监视基准解析
        配置文件名=os.path.abspath(os.path.join(自身.基准目录,路径))#按热替换基准解析
        for 插件配置 in 自身.所属上下文.加载器.插件配置们():
            子树=插件配置.子树#该插件配置挂的子树
            if 子树 is None or getattr(子树,'文件名',None) not in (文件名,配置文件名):
                continue#不是这棵树的配置文件
            自身.排队刷新(子树,子树.文件名,子树.刷新)#串行刷新
            return True#命中配置文件
        return False#不是配置文件

    ################################ 模块图分析 ################################
    def 收集依赖(自身,任务,已忽略=None):
        """从一个模块任务出发，递归收集属于用户代码的依赖网址。"""
        已忽略=已忽略 or set()#不参与收集的网址
        依赖=set()#收集结果
        def 遍历(当前):
            """跳过内建模块与第三方包。"""
            if 当前.url in 已忽略 or 当前.url in 依赖 or 是否外部模块(当前.url):
                return#已经看过，或者不算用户代码
            依赖.add(当前.url)#记入
            for 子 in 当前.linked:
                遍历(子)#递归子模块
        遍历(任务)#从根模块开始
        return 依赖#依赖集

    def 取子模块网址(自身,网址):
        """取出该模块已链接的子模块网址。"""
        任务=自身.内部加载器.loadCache.get(网址)#模块任务
        if 任务 is None:
            return []#还没加载过
        return [项.url for 项 in 任务.linked]#子模块网址

    def 分析变更(自身):
        """把暂存的变更沿依赖方向扩散，分成接受集与拒绝集。"""
        自身.接受集=set(自身.暂存集)#直接改动的文件一定要重载
        自身.拒绝集=set(自身.外部集)#框架自身一律不热替换
        待定=[]#还判不出来的网址
        for 网址 in 自身.暂存集:
            for 子 in 自身.取子模块网址(网址):
                if 子 not in 自身.接受集 and 子 not in 自身.拒绝集 and not 是否外部模块(子):
                    待定.append(子)#先记下来
        while 待定 and 自身._推进分类(待定):
            pass#一直推进到没有新结论
        自身.拒绝集.update(待定)#推不动的一律拒绝

    def _推进分类(自身,待定):
        """扫一遍待定网址，把能定的定下来。返回本轮是否有推进。"""
        有推进=False#本轮是否推进过
        下标=0#扫描位置
        while 下标<len(待定):
            网址=待定[下标]#当前网址
            接受,拒绝,新节点=自身._判定(网址,待定)#判定结果
            if 新节点:
                有推进=True#发现了新的待定节点
            if not 接受 and not 拒绝:
                下标+=1#还判不出来，看下一个
                continue
            待定.pop(下标)#定下来了
            有推进=True#有推进
            (自身.接受集 if 接受 else 自身.拒绝集).add(网址)#归入对应集合
        return 有推进#是否推进过

    def _判定(自身,网址,待定):
        """按子模块的归属判定该网址，顺带把新发现的子模块加进待定。"""
        拒绝=True#暂定全部子模块都已拒绝
        新节点=False#是否发现了新的待定节点
        for 子 in 自身.取子模块网址(网址):
            if 子 in 自身.拒绝集 or 是否外部模块(子):
                continue#这条边不影响判定
            if 子 in 自身.接受集:
                return True,False,新节点#只要有一个子模块要重载，自己就得重载
            拒绝=False#还有子模块没定
            if 子 not in 待定:
                待定.append(子)#新发现的节点
                新节点=True#本轮有推进
        return False,拒绝,新节点#判定结果

    ################################ 重载 ################################
    def 部分重载(自身):
        """清掉接受集的模块缓存，用新代码重挂受影响的插件。"""
        自身.分析变更()#先分类
        重载表=自身._收集待重载插件()#插件到重载信息
        if not 重载表:
            自身.暂存集=set()#没有要重载的，清掉暂存
            return
        备份=自身._清缓存(自身.接受集)#清掉模块缓存并留下备份
        新插件表=自身._重新导入(重载表)#重新导入入口
        if 新插件表 is None:
            备份.回滚()#导入失败，把缓存放回去
            return#暂存集留着，改好之后下一拍再试
        if 自身._换上新插件(重载表,新插件表,备份):
            自身.暂存集=set()#换上了才清掉暂存

    def _收集待重载插件(自身):
        """找出入口模块落在接受集依赖里的插件。"""
        待检查={}#模块任务到插件
        for 基准网址,插件名们 in 自身._按树分组的插件名().items():
            for 插件名 in 插件名们:
                自身._解析入口(待检查,基准网址,插件名)#解析入口模块
        重载表={}#插件到重载信息
        for 任务,插件 in 待检查.items():
            自身.拒绝集.discard(任务.url)#检查自己的依赖时先放开
            依赖=自身.收集依赖(任务,自身.拒绝集)#入口的依赖树
            自身.拒绝集.add(任务.url)#入口本身仍然不参与扩散
            if not (依赖 & 自身.接受集):
                continue#依赖里没有改动过的文件
            自身.接受集.update(依赖)#整条依赖链一起换
            重载表[插件]=重载信息(任务.url,自身.所属上下文.注册表.取(插件))#记下运行时
        return 重载表#待重载插件

    def _按树分组的插件名(自身):
        """把当前全部插件配置的插件名按所属树的基准网址分组。"""
        分组={}#基准网址到插件名集合
        for 插件配置 in 自身.所属上下文.加载器.插件配置们():
            基准=插件配置.父组.所属树.所属上下文.基准网址#该树的解析基准
            分组.setdefault(基准,set()).add(插件配置.选项.get('name'))#登记插件名
        return 分组#分组结果

    def _解析入口(自身,待检查,基准网址,插件名):
        """解析一个插件名对应的入口模块，能重载的记进待检查。"""
        try:
            网址=自身._解析说明符(插件名,基准网址).url#入口模块网址
            if 网址 in 自身.拒绝集:
                return#已经判定不重载
            任务=自身.内部加载器.loadCache.get(网址)#模块任务
            插件=自身.所属上下文.加载器.解开导出(任务.module.getNamespace()) if 任务 is not None else None#插件导出
            if 任务 is None or 插件 is None:
                return#还没加载，或者导出里没有插件
            待检查[任务]=插件#记进待检查
            自身.拒绝集.add(网址)#入口本身不参与扩散
        except Exception as 错误:
            自身.所属上下文.日志.警告(错误)#解析失败

    def _解析说明符(自身,说明符,父网址):
        """按内部加载器的版本解析模块说明符。"""
        if 自身.内部加载器.version=='v1':
            return 自身.内部加载器.resolve(说明符,父网址,{})#v1 解析
        return 自身.内部加载器.resolveSync(父网址,{'specifier':说明符,'attributes':{}})#v2 同步解析

    def _清缓存(自身,网址们):
        """清掉这些网址的模块缓存，交出能放回去的备份。"""
        备份=缓存备份(自身.内部加载器)#备份
        for 网址 in 网址们:
            备份.清掉(网址)#逐个清掉
        return 备份#备份

    def _重新导入(自身,重载表):
        """重新导入每个入口。任一入口失败就整体放弃，返回空值。"""
        新插件表={}#入口网址到新插件
        try:
            for 信息 in 重载表.values():
                导出=自身.所属上下文.加载器.导入(信息.入口网址,[])#重新导入，不给外层栈免得把监视线程的帧挂上去
                新插件表[信息.入口网址]=自身.所属上下文.加载器.解开导出(导出)#解开导出
        except Exception as 原因:
            记录构建失败(自身.所属上下文,原因)#记下失败
            return None#整体放弃
        return 新插件表#新插件

    def _换上新插件(自身,重载表,新插件表,备份):
        """逐个把旧插件换成新插件，任一失败就整体回滚。返回是否换成了。"""
        已换=[]#已经换过的插件
        try:
            for 旧插件,信息 in 重载表.items():
                if 信息.运行时 is None:
                    continue#这个插件没有运行时
                自身._替换一个(旧插件,信息,新插件表[信息.入口网址])#替换
                已换.append((旧插件,信息))#记下，回滚时用
        except Exception:
            备份.回滚()#模块缓存放回去
            自身._回滚插件(已换,新插件表)#插件也换回去
            return False#回滚了
        自身.所属上下文.广播('hmr/reload',重载表)#广播本轮重载
        return True#换上了

    def _替换一个(自身,旧插件,信息,新插件):
        """拆掉旧插件，再用新插件重挂它原来的每一条纤程。"""
        相对路径=os.path.relpath(文件网址转路径(信息.入口网址),自身.基准目录)#日志用的相对路径
        try:
            自身.所属上下文.注册表.删除(旧插件)#拆掉旧插件
        except Exception as 错误:
            自身.所属上下文.日志.警告('拆除插件 %C 失败',相对路径)#拆除失败不挡住重挂
            自身.所属上下文.日志.警告(错误)#详情
        try:
            自身._重挂纤程(新插件,信息.运行时)#装上新插件
            自身.所属上下文.日志.信息('已重载插件 %C',相对路径)#成功
        except Exception as 错误:
            自身.所属上下文.日志.警告('重载插件 %C 失败',相对路径)#失败
            自身.所属上下文.日志.警告(错误)#详情
            raise#触发整体回滚

    def _重挂纤程(自身,插件,运行时):
        """用新插件在每条旧纤程的父上下文上重新启动一遍。"""
        for 旧纤程 in list(运行时.纤程表):
            新纤程=旧纤程.父上下文.注册表.启动插件(插件,旧纤程.原始配置,[])#重挂不给外层栈，免得把监视线程的帧挂上去
            新纤程.插件配置=旧纤程.插件配置#继承插件配置归属
            if 新纤程.插件配置 is not None:
                新纤程.插件配置.纤程=新纤程#插件配置改指向新纤程

    def _回滚插件(自身,已换,新插件表):
        """把已经换上的新插件拆掉，装回原来的插件。"""
        for 旧插件,信息 in 已换:
            try:
                自身.所属上下文.注册表.删除(新插件表[信息.入口网址])#拆掉新插件
                自身._重挂纤程(旧插件,信息.运行时)#装回旧插件
            except Exception as 错误:
                自身.所属上下文.日志.警告(错误)#回滚失败只能记日志

################################ 缓存备份 ################################
class 缓存备份:
    """一轮热替换里被清掉的模块缓存，失败时能原样放回去。"""
    def __init__(自身,内部加载器):
        """记下要操作的加载缓存。"""
        自身._内部加载器=内部加载器#Node 加载缓存
        自身._加载缓存={}#网址到模块任务
        自身._模块表={}#模块名到模块对象

    def 清掉(自身,网址):
        """清掉一个网址在加载缓存与模块表里的记录。"""
        自身._加载缓存[网址]=自身._内部加载器.loadCache.pop(网址,None)#备份并清掉
        规范=os.path.normpath(os.path.abspath(文件网址转路径(网址)))#本地路径
        for 模块名,模块 in list(sys.modules.items()):
            文件=getattr(模块,'__file__',None)#模块文件
            if 文件 and os.path.normpath(os.path.abspath(文件))==规范:
                自身._模块表[模块名]=模块#备份
                del sys.modules[模块名]#清掉

    def 回滚(自身):
        """把备份的模块缓存原样放回去。"""
        for 网址,任务 in 自身._加载缓存.items():
            自身._内部加载器.loadCache[网址]=任务#放回加载缓存
        for 模块名,模块 in 自身._模块表.items():
            sys.modules[模块名]=模块#放回模块表

