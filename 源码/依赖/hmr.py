def 是否构建失败(错误):
    "带 errors 列表、且每条都有 text 的错误来自构建工具"
    列表=getattr(错误,'errors',None)#构建工具给的错误列表
    if not isinstance(列表,list) or not 列表:
        return False#不是构建失败
    return all(isinstance(项,dict) and 项.get('text') for 项 in 列表)#每条都要有文本

def 格式化代码框(源码,行号,列号,消息):
    "按行列拼出带上下文的代码框"
    行表=源码.splitlines()#源码逐行
    起始=max(0,行号-2)#上文起点
    结束=min(len(行表),行号+1)#下文终点
    行号宽=len(str(max(结束,1)))#行号列宽
    片段=[]#输出行
    for 下标 in range(起始,结束):
        是当前行=下标+1==行号#出错的那一行
        片段.append(f'{">" if 是当前行 else " "} {str(下标+1).rjust(行号宽)} | {行表[下标]}')#源码行
        if 是当前行:
            片段.append(f'  {" "*行号宽} | {" "*(max(列号,1)-1)}^ {消息}')#列指针
    return '\n'.join(片段)#代码框

def 记录构建失败(上下文,错误):
    """把构建失败记成警告，有源位置的带上代码框。"""
    if not 是否构建失败(错误):
        上下文.日志.警告(错误)#不是构建失败
        return
    for 项 in 错误.errors:
        位置=项.get('location')#源位置
        if 位置 is None:
            上下文.日志.警告(项.get('text'))#没有位置就只记文本
            continue
        try:
            with open(位置['file'],'r',encoding='utf-8') as 文件:
                源码=文件.read()#读出源码
            代码框=格式化代码框(源码,位置['line'],位置['column'],项.get('text'))#代码框
            上下文.日志.警告(f'文件：{位置["file"]}:{位置["line"]}:{位置["column"]}\n'+代码框)#带位置的警告
        except Exception as 原因:
            上下文.日志.警告(原因)#读源码或拼代码框失败

