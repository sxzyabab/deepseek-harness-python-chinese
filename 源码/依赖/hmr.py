def 路径转文件url(路径):
    "本地路径转file://"
    return Path(路径).absolute().as_uri()

def 文件url转路径(网址):
    "file://转本地路径"
    return str(Path.from_uri(网址))

def 解析基准目录(相对路径,基准网址):
    "按基准网址解析出热替换的监视基准目录"
    if 基准网址:
        文本=str(基准网址)
        基准=Path.from_uri(文本) if 文本.startswith('file:') else Path(文本).absolute()
    else:
        基准=Path.cwd()
    return os.path.normpath(基准/(相对路径 or '.'))

