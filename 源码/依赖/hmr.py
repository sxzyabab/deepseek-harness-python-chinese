class 文件系统监视器:
    """在自己的线程里用内核事件监视文件。"""
    def __init__(自身,路径列表,选项=None):
        """按选项开始监视这些路径。"""
        自身._路径列表=路径列表 if isinstance(路径列表,list) else [路径列表]#监视根
        自身._选项=选项 or {}#工作目录、深度与忽略判断
        自身._监听表={}#事件名到回调列表
        自身._停止=threading.Event()#停止信号
        自身._锁=threading.Lock()#保护监听表
        自身._线程=threading.Thread(target=自身._监视)#监视线程
        自身._已启动=False#登记完监听器才开始监视

    def 启动(自身):
        """开始监视。重复调用是空操作。"""
        if 自身._已启动:
            return#已经在监视
        自身._已启动=True#只启动一次
        自身._线程.start()#启动

    def 监听(自身,事件名,回调):
        """登记一个事件回调。"""
        with 自身._锁:
            自身._监听表.setdefault(事件名,[]).append(回调)#追加
        return 自身#便于链式登记

    def 监听一次(自身,事件名,回调):
        """登记一个跑过一次就自行注销的回调。"""
        def 一次性(*位置参数):
            """先卸掉自己再跑原始回调。"""
            自身._注销(事件名,一次性)#卸掉自己
            回调(*位置参数)#原始回调
        return 自身.监听(事件名,一次性)#登记

    def 关闭(自身):
        """停止监视并等线程结束。"""
        自身._停止.set()#发出停止信号
        if 自身._已启动:
            自身._线程.join()#等线程退出

    def _注销(自身,事件名,回调):
        """按对象身份删掉一个回调。"""
        with 自身._锁:
            自身._监听表[事件名]=[项 for 项 in 自身._监听表.get(事件名) or [] if 项 is not 回调]#过滤掉

    def _发出(自身,事件名,*位置参数):
        """同步调用该事件当前登记的回调。"""
        with 自身._锁:
            回调们=list(自身._监听表.get(事件名) or [])#取一份副本，回调里可以改监听表
        for 回调 in 回调们:
            回调(*位置参数)#逐个调用

    def _对外路径(自身,绝对路径):
        """给了工作目录就交出相对路径。"""
        基准=自身._选项.get('cwd')#工作目录
        return os.path.relpath(绝对路径,基准) if 基准 else 绝对路径#相对或绝对

    def _被忽略(自身,绝对路径):
        """忽略判断命中时为真。"""
        忽略=自身._选项.get('ignored')#忽略判断
        return bool(忽略(绝对路径)) if 忽略 else False#没有判断就都不忽略

    def _现存根(自身):
        """还存在的监视根。"""
        基准=自身._选项.get('cwd') or os.getcwd()#相对路径的基准
        结果=[]#绝对根
        for 根路径 in 自身._路径列表:
            绝对根=os.path.abspath(根路径 if os.path.isabs(根路径) else os.path.join(基准,根路径))#绝对根
            if os.path.exists(绝对根):
                结果.append(绝对根)#还能监视
        return 结果

    def _扫描(自身):
        """扫出监视根下每个已有文件。"""
        结果=[]#文件路径
        for 绝对根 in 自身._现存根():
            if os.path.isfile(绝对根):
                结果.append(绝对根)#根本身就是文件
                continue
            自身._扫描目录(结果,绝对根)#递归扫描目录
        return 结果

    def _扫描目录(自身,结果,绝对根):
        """递归扫描一个监视根下的文件，按深度上限剪枝。"""
        深度上限=自身._选项.get('depth')#深度上限
        for 当前,子目录们,文件们 in os.walk(绝对根):
            相对层=os.path.relpath(当前,绝对根)#当前层相对监视根
            层=0 if 相对层=='.' else 相对层.count(os.sep)+1#当前深度
            if 深度上限 is not None and 层>深度上限:
                子目录们[:]=[]#超出上限就不再下降
                continue#本层文件也不要
            if 深度上限 is not None and 层==深度上限:
                子目录们[:]=[]#到上限了，本层文件仍然要
            子目录们[:]=[项 for 项 in 子目录们 if not 自身._被忽略(os.path.join(当前,项))]#被忽略的目录不下降
            for 文件 in 文件们:
                全路径=os.path.join(当前,文件)#文件路径
                if not 自身._被忽略(全路径):
                    结果.append(os.path.abspath(全路径))#记下路径

    def _过滤变化(自身,种类,路径):
        """忽略判断、目录项与深度上限以外的变化丢掉。"""
        绝对=os.path.abspath(路径)#统一成绝对路径
        基准=自身._选项.get('cwd') or os.getcwd()#相对路径的基准
        深度上限=自身._选项.get('depth')#深度上限
        for 根路径 in 自身._路径列表:
            绝对根=os.path.abspath(根路径 if os.path.isabs(根路径) else os.path.join(基准,根路径))#绝对根
            try:
                相对=os.path.relpath(绝对,绝对根)#相对该根
            except ValueError:
                continue#不在同一盘
            if 相对=='..' or 相对.startswith('..'+os.sep):
                continue#不是这个根下的
            if 深度上限 is not None:
                目录=绝对根 if 相对=='.' else os.path.dirname(绝对)#文件所在目录
                相对层=os.path.relpath(目录,绝对根)#目录相对根
                层=0 if 相对层=='.' else 相对层.count(os.sep)+1#当前深度
                if 层>深度上限:
                    return False#超出上限
            检查=绝对#从文件一路走到根
            while True:
                if 自身._被忽略(检查):
                    return False#自身或祖先被忽略
                if 检查==绝对根:
                    break
                父=os.path.dirname(检查)
                if 父==检查:
                    break
                检查=父
            if 种类!=变化种类.deleted and os.path.isdir(绝对):
                return False#只报文件
            return True#这个根收下了
        return False#不属于任何监视根

    def _监视(自身):
        """先按需报已有文件，再进入内核监视。"""
        try:
            if not 自身._选项.get('ignoreInitial'):
                for 路径 in 自身._扫描():
                    自身._发出('新增',自身._对外路径(路径))#把已有文件也报一遍
        except Exception as 错误:
            自身._发出('错误',错误)#首次扫描失败，等待方要抛出
            return
        自身._发出('就绪')#放行等待方
        while not 自身._停止.is_set():
            根们=自身._现存根()#每次重进时再看根还在不在
            if not 根们:
                自身._停止.wait()#没有可监视的路径，等到关闭
                return
            try:
                for 变更集 in 监视变化(*根们,stop_event=自身._停止,debounce=监视防抖毫秒,watch_filter=自身._过滤变化):
                    for 种类,路径 in 变更集:
                        自身._发出(事件对照[种类],自身._对外路径(os.path.abspath(路径)))#按种类转发
            except Exception as 错误:
                if 自身._停止.is_set():
                    return#关闭引起的退出
                自身._发出('错误',错误)#单轮失败只报告，监视继续
                自身._停止.wait(监视防抖毫秒/1000)#避免空转

def 等待监视器就绪(监视器,记警告):
    """等监视器线程发出就绪。启动阶段的错误抛出，之后的错误只记警告。"""
    已结束=threading.Event()#就绪或启动失败的信号
    启动失败=[None]#启动阶段的失败原因
    def 当就绪():
        """监视器就绪。"""
        已结束.set()#放行等待方
    def 当出错(错误):
        """启动阶段的错误让等待方抛出，之后的只记警告。"""
        if 已结束.is_set():
            记警告(错误)#运行期错误
            return
        启动失败[0]=错误#启动阶段失败
        已结束.set()#放行等待方
    监视器.监听一次('就绪',当就绪)#就绪
    监视器.监听('错误',当出错)#错误
    监视器.启动()#登记完才开始轮询，首次扫描再快也不会漏掉信号
    已结束.wait()#等监视线程给出就绪或失败
    if 启动失败[0] is not None:
        raise 启动失败[0]#启动阶段的失败抛给调用方

