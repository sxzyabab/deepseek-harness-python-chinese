def 通配命中(文本,通配式):
    "按 glob 规则判断相对路径是否命中，支持 **、* 与 ?"
    return PurePosixPath(文本.replace('\\','/')).full_match(通配式.replace('\\','/'))

class 监视目标:
    "一个精确配置文件对应的监视根"
    def __init__(自身,文件名,根,深度):
        "保存规范化后的文件名、监视根与相对深度"
        自身.文件名=文件名#规范化后的文件名
