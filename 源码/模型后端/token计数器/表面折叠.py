"""测量服务的按位置表面折叠。对齐上游 `token-meter/src/surface-fold.ts`。公开面仅中文名。"""
from ...内核.会话 import 事件派生消息#从事件导出消息
from .类型 import 取#读取字段
from .计价 import 计价消息#消息计价

__all__=['折叠表面令牌']#仅中文公开名

def 折叠表面令牌(节点们,事件):#把一条表面事件折到已计价表面上
    """把一条表面事件折到已计价表面上。"""
    消息=事件派生消息(事件)#导出消息
    令牌数=0 if 消息 is None else 计价消息(消息)#无消息则0
    操作=取(事件,'surfaceOp')#表面操作
    if 操作=='append':#追加
        return {'tokens':令牌数,'nodes':[*节点们,{'seq':取(事件,'seq'),'tokens':令牌数}],'deltaTokens':令牌数}#接到尾部
    起点下标=-1#范围起点
    终点下标=-1#范围终点
    下标=0#扫描下标
    起点序号=取(操作,'start')#声明起点
    终点序号=取(操作,'end')#声明终点
    for 节点 in 节点们:#逐个节点
        if 起点下标==-1 and 取(节点,'seq')==起点序号:#命中起点
            起点下标=下标#记下起点
        if 终点下标==-1 and 取(节点,'seq')==终点序号:#命中终点
            终点下标=下标#记下终点
        下标+=1#前进一步
    if 起点下标==-1 or 终点下标==-1 or 起点下标>终点下标:#范围对不上
        raise Exception(f'token surface: replace at seq {取(事件,"seq")} has invalid current range {起点序号}-{终点序号}')#范围非法
    被遮蔽=0#被替换价格
    for 节点 in 节点们[起点下标:终点下标+1]:#含端切片
        被遮蔽+=取(节点,'tokens')#合计被遮蔽价格
    下一=[*节点们[:起点下标],{'seq':取(事件,'seq'),'tokens':令牌数},*节点们[终点下标+1:]]#用本事件替换该范围
    return {'tokens':令牌数,'nodes':下一,'deltaTokens':令牌数-被遮蔽}#价格减去被遮蔽
