"""一次打开的模型步的持久请求路由查找。

对齐上游 `llm-retry/src/history.ts`。公开面仅中文名；无英文别名。
"""
from .类型 import 取#读取字段

__all__=('打开步提供方',)#仅中文公开名

def 打开步提供方(事件们,回合,步):#查找打开步生效的提供方
    """找出当前打开步生效的提供方。

    请求头跨回合边界仍生效，直到更新的完整快照改掉它们；
    每次提供方变更都需要更新的完整快照。
    @param 事件们: 会话事件列表
    @param 回合: 回合号
    @param 步: 步号
    @returns 对该步生效的请求头里的提供方，找不到则为 None
    """
    步开始下标=-1#尚未找到该步的 step/start
    下标=len(事件们)-1#最后一个下标
    while 下标>=0:#从后往前找该步的 step/start
        事件=事件们[下标]#当前事件
        if 取(事件,'type')=='step/start':#先看类型，对齐 && 短路
            载荷=取(事件,'data')#事件载荷
            if 取(载荷,'turn')==回合 and 取(载荷,'step')==步:#命中该步开始
                步开始下标=下标#记下开始
                break#找到即停
        下标-=1#继续往前
    if 步开始下标<0:#没有步开始
        return None#不是打开步
    for 事件 in 事件们[步开始下标+1:]:#步开始之后若已结束则不是打开步
        类型=取(事件,'type')#事件类型
        if 类型=='step/end' or 类型=='turn/end':#已经结束
            return None#不是打开步
    下标=len(事件们)-1#最后一个下标
    while 下标>=0:#从后往前找最近请求头
        事件=事件们[下标]#当前事件
        if 取(事件,'type')=='request/header':#最近的请求头
            载荷=取(事件,'data')#事件载荷
            头=取(载荷,'header')#请求头
            配置=取(头,'config')#调用配置
            return 取(配置,'provider')#提供方
        下标-=1#继续往前
    return None#没有请求头
