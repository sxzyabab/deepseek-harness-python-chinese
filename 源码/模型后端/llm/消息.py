"""消息值类型、身份与不可变构造辅助。

对齐上游 `llm/src/message.ts`。公开面仅中文名；角色／来源 kind／字段键保持上游 wire。
无英文别名。
"""
import uuid#新消息身份
from .品牌 import 消息标识#导入消息 id 品牌
from .调用配置 import 深冻结,结构化克隆#导入深冻结与拆离

__all__=(#仅中文公开名
    '上下文摘要最大字符','截上下文摘要','冻结消息',
    '创建消息','创建用户消息','创建助手消息','创建工具结果消息','是否词增量',
)#公开面结束

上下文摘要最大字符=120#通知摘要最大字符数

def 截上下文摘要(摘要):#截 notice 摘要
    """把一条 notice 摘要限制到上下文摘要最大字符。"""
    if len(摘要)<=上下文摘要最大字符:#未超上限
        return 摘要#原文
    return 摘要[0:上下文摘要最大字符-1]+'…'#截断并加省略号

def 冻结消息(消息):#拆离并深冻结已标识消息
    """拆离并深冻结一条身份已存在的消息。"""
    return 深冻结(结构化克隆(消息))#深拷贝后冻结

def 创建消息(输入):#创建已标识消息并冻结
    """创建一条已标识消息并在发布前冻结。"""
    消息=dict(输入)#调用方字段
    消息['id']=消息标识(str(uuid.uuid4()))#新稳定身份
    return 冻结消息(消息)#冻结后发布

def 创建用户消息(输入):#创建用户角色消息
    """创建一条已标识的用户角色消息并在发布前冻结。"""
    消息=dict(输入)#调用方字段
    消息['role']='user'#固定用户角色
    return 创建消息(消息)#交给通用工厂

def 创建助手消息(输入):#创建模型产出助手消息
    """创建一条已标识的模型产出助手消息并在发布前冻结。"""
    来源={'kind':'model'}#模型产出
    来源.update(输入['source'])#提供方、模型、可选回放
    return 创建消息({#交给通用工厂
        'role':'assistant',#固定助手角色
        'content':输入['content'],#内容块
        'source':来源,#写入模型来源
    })#创建结束

def 创建工具结果消息(输入):#创建工具结果消息
    """创建并冻结一条已标识的工具结果消息。"""
    return 创建用户消息({#以用户角色回传
        'source':{'kind':'tool','callId':输入['callId']},#工具来源
        'content':[{#恰好一块工具结果
            'type':'tool-result',#工具结果块
            'toolCallId':输入['callId'],#关联调用
            'content':输入['content'],#结果内容
            'isError':输入['isError'],#成败
        }],#内容结束
    })#创建结束

def 是否词增量(块):#流块是否携带可见模型输出
    """流块是否携带可见模型输出。"""
    类型=块['type']#块类型
    if 类型=='text-delta' or 类型=='reasoning-delta':#文本或推理增量
        return 块['text']!=''#非空文本才算
    if 类型=='tool-call-delta':#工具调用增量
        return 块['argumentsDelta']!='' or 'name' in 块#参数增量或名字
    return False#其余块不算
