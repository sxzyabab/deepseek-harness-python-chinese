class 截止句柄:#融合上游取消与可识别超时
    '超时或上游先中止时触发自己的信号；释放只停定时器'
    def __init__(自身,上游,超时毫秒,码):#武装截止
        '超时毫秒小于等于 0 时不武装定时器，只转发上游或给出一条永不中止的信号'
        自身.信号=中止信号()#本截止
        自身._定时=None#定时器
        自身._停=threading.Event()#释放
        if 超时毫秒<=0:#内部的无定时哨兵
            if 上游 is not None:#只转发上游
                自身.信号=上游#同一条信号
            return#不武装
        断言定时器延迟(超时毫秒,'deadline timeoutMs')#必须是合法定时器延迟
        def 到期():#到点
            '记上本能力的超时原因'
            自身.信号.触发(超时原因(码,超时毫秒))#超时先写则获胜
        自身._定时=threading.Timer(超时毫秒/1000.0,到期)#定时器
        自身._定时.daemon=True#守护
        自身._定时.start()#武装
        if 上游 is None:#没有上游
            return#只有超时
        def 监视():#抄上游
            '上游先中止则抄下原因并停掉定时器'
            while not 自身._停.is_set():#未释放
                if 已中止(上游):#上游获胜
                    原因=getattr(上游,'_异常',None)#原因
                    自身.信号.触发(原因 if isinstance(原因,BaseException) else None)#不覆盖已写入的超时
                    if 自身._定时 is not None:#还在
                        自身._定时.cancel()#停
                    return#结束
                if 已中止(自身.信号):#超时已写
                    return#结束
                自身._停.wait(0.05)#短等
        threading.Thread(target=监视,daemon=True).start()#监视

    def 释放(自身):#停定时器
        '可重复调用；不停已中止的信号'
        自身._停.set()#停监视
        if 自身._定时 is not None:#有定时器
            自身._定时.cancel()#取消
            自身._定时=None#丢掉

def 可放弃(任务,信号):#只放弃等待
    '信号先中止则拒绝等待；任务继续跑。信号缺席时原样返回任务'
    if 信号 is None:#无人放弃
        return 任务#原任务
    放弃=期约()#放弃回执
    停=threading.Event()#等待结束后停监视
    def 监视():#等信号
        '信号中止则拒绝放弃回执'
        while not 停.is_set():#还在等
            if 已中止(信号):#放弃
                if 放弃.状态=='pending':#尚未结算
                    原因=getattr(信号,'_异常',None)#原因
                    if not isinstance(原因,BaseException):#无异常原因
                        原因=已中止错误()#默认中止
                    放弃.拒绝(原因)#拒绝等待
                return#结束
            停.wait(0.05)#短等
    threading.Thread(target=监视,daemon=True).start()#监视
    竞赛=期约.竞速([任务,放弃])#谁先结算
    def 结束(值=None):#任务获胜
        '停掉监视并交还任务的值'
        停.set()#停
        return 值#原值
    def 结束失败(错误):#放弃或任务失败
        '停掉监视并继续拒绝'
        停.set()#停
        失败=期约()#拒绝回执
        失败.拒绝(错误)#原错误
        return 失败#继续拒绝
    return 竞赛.然后(结束,结束失败)#包装

class 账号模型目录:#一条账号路由的列出缓存
    '每个端点与凭据对有自己的范围'
    def __init__(自身,依赖):#记下宿主输入
        '依赖含 settings、token、load、now、info、warn'
        自身.依赖=依赖#宿主回调
        自身.范围=None#当前凭据范围
        自身.列举=None#最近一次成功列出
        自身.落定时刻=None#最近一次加载落定的时刻
        自身.飞行=None#单飞加载
        自身.请求=None#在飞加载的取消信号
        自身.世代=0#范围与释放代数
        自身.失败中=False#连续失败只警告一次
        自身.已关=False#释放后结果不再发表

    def 当前(自身):#不碰输入输出
        '返回当前范围的登录态与列出'
        return {'signedIn':自身.范围 is not None,'listing':自身.列举}#已发表视图

    def 视图(自身,信号=None):#按当前凭据解析
        """解析当前凭据的视图。一个范围的第一次访问等待其加载，请求截止限制这次等待；之后立刻返回，过期列出在后台刷新。
        信号只放弃这次等待，共享加载继续。
        返回该范围第一次加载落定后的视图
        """
        设置=自身.依赖['settings']()#每次重读
        令牌任务=自身.依赖['token'](设置['url'])#该端点允许的账号令牌
        def 令牌已到(令牌):#令牌已解析
            '中止、换范围，并在需要时等待或后台刷新'
            if 信号 is not None:#调用方带了信号
                若已中止则抛出(信号)#已中止则抛原因
            if 自身.已关:#释放后不再换范围
                return 自身.当前()#冻结视图
            if 令牌 is None:#未登录
                范围=None#无范围
            else:#凭据摘要，不把令牌放进范围字符串
                原文=令牌.encode('utf-8') if type(令牌) is str else 令牌#摘要输入
                范围=设置['url']+'\n'+hashlib.sha256(原文).hexdigest()#端点与凭据
            if 范围!=自身.范围:#换了端点或凭据
                自身.重划范围(范围)#丢掉上一范围
            if 令牌 is not None:#已登录才加载
                if 自身.落定时刻 is None:#这个范围还没有落定过
                    def 加载后(忽略=None):#第一次加载已落定
                        '忽略是加载回执，视图以当前发表为准'
                        return 自身.当前()#落定后的视图
                    return 可放弃(自身.开始(设置,令牌),信号).然后(加载后)#只放弃等待
                if 自身.依赖['now']()-自身.落定时刻>=设置['maxAgeMs']:#列出已过期
                    自身.开始(设置,令牌)#后台刷新，不等
            return 自身.当前()#立刻返回
        def 令牌失败(错误):#取令牌失败
            '原样拒绝'
            失败=期约()#拒绝回执
            失败.拒绝(错误)#原错误
            return 失败#继续拒绝
        return 令牌任务.然后(令牌已到,令牌失败)#令牌到了再解析

    def 释放(自身):#之后的结果与访问都不再改变发表
        '中止在飞加载'
        自身.已关=True#关闭
        自身.世代+=1#使在飞结果作废
        if 自身.请求 is not None:#有在飞请求
            自身.请求.触发(已中止错误())#中止

    def 重划范围(自身,范围):#换成另一个端点或凭据
        '中止上一范围的加载并清空发表'
        if 自身.请求 is not None:#上一范围还在飞
            自身.请求.触发(已中止错误())#中止
        自身.范围=范围#新范围
        自身.列举=None#尚未成功
        自身.落定时刻=None#尚未落定
        自身.飞行=None#不复用上一范围的单飞
        自身.失败中=False#失败串重新计
        自身.世代+=1#使上一范围的回调作废

    def 开始(自身,设置,令牌):#单飞加载
        '已有在飞加载则复用；失败也落定，连续失败只警告第一次'
        if 自身.飞行 is not None:#单飞
            return 自身.飞行#复用
        自身.世代+=1#这次加载的代数
        世代=自身.世代#闭包代数
        请求=中止信号()#这次请求
        自身.请求=请求#记下
        限制=截止句柄(请求,设置['timeoutMs'],列举超时码)#请求截止
        加载=自身.依赖['load'](设置['url'],令牌,限制.信号)#带截止信号
        状态={'收尾':False}#回调可能同步跑完
        链式盒=[None]#收尾时比对的那条期约
        def 成功(列举):#加载成功
            '代数仍是这次才发表'
            if 世代!=自身.世代:#已换范围或已释放
                return None#丢弃
            自身.列举=列举#发表
            自身.落定时刻=自身.依赖['now']()#落定时刻
            自身.失败中=False#失败串结束
            自身.依赖['info']('model listing from '+设置['url']+' loaded '+str(len(列举['entries']))+' model(s), skipped '+str(列举['skipped'])+' row(s)')#报告
            return None#加载期约兑现
        def 失败(错误):#加载失败
            '保留上一份成功列出；连续失败只警告第一次'
            if 世代!=自身.世代:#已换范围或已释放
                return None#丢弃
            if not 自身.失败中:#失败串的第一次
                回退='using the bundled catalog' if 自身.列举 is None else 'keeping the previous catalog'#没有旧目录才回落内置
                自身.依赖['warn']('model listing from '+设置['url']+' failed ('+str(错误)+'); '+回退)#只警告一次
            自身.落定时刻=自身.依赖['now']()#失败也算落定，避免每次访问都等
            自身.失败中=True#进入失败串
            return None#失败不拒绝等待方
        def 收尾(忽略=None):#无论成败
            '释放截止；只清掉仍然指向这次加载的单飞槽'
            限制.释放()#停定时器
            状态['收尾']=True#已收尾
            if 自身.飞行 is 链式盒[0]:#仍是这次
                自身.飞行=None#允许下一次
            return 忽略#保持原结算
        链式=加载.然后(成功,失败).最终(收尾)#单飞期约
        链式盒[0]=链式#供收尾比对
        if 状态['收尾']:#回调已经同步跑完
            自身.飞行=None#不要把已结束的期约留在槽里
        else:#仍在飞
            自身.飞行=链式#占槽
        return 链式#调用方等待这一次
