"""按一代已校验配置选择 DeepSeek 线路实现。"""
from ...llm import 大模型适配器,断言永不#适配器基类与穷尽
from .协议无关.文件仓 import 深求文件仓#文件仓
from .协议.对话补全.适配器 import 对话补全适配器#对话补全
from .协议.消息.适配器 import 深求消息适配器#消息

__all__=('深求适配器',)#仅中文公开名

class 深求适配器(大模型适配器):
    """一条提供方路由：协议局部传输，共享凭证与模型配置。"""
    def __init__(自身,配置):
        """保存插件拥有的操作局部解析钩子。"""
        自身.配置=配置#插件钩子
        if '解析文件仓' in 配置:#调用方给出仓
            自身.文件仓=配置['解析文件仓']()#用钩子
        else:#缺席则新建
            自身.文件仓=深求文件仓()#共享仓

    def 实现(自身):#按当前协议选实现
        """按当前连接事实选出线路实现。"""
        连接=自身.配置['选项']()#当前连接
        协议=连接['protocol']#协议
        if 协议=='messages':#消息
            def 连接回调():#冻结本代
                """返回本代已校验连接。"""
                return 连接#冻结
            def 附件回调():#当前附件仓
                """当前附件仓；缺席对纯文本合法。"""
                if '解析附件' not in 自身.配置:#无钩子
                    return None#缺席
                return 自身.配置['解析附件']()#仓
            def 图片访问回调(引用):#图片访问
                """把附件仓上的宿主路径桥进已挂载的工具执行世界。"""
                if '解析附件' not in 自身.配置:#无仓钩子
                    return None#缺席
                if '解析图片访问' not in 自身.配置:#无访问钩子
                    return None#缺席
                附件=自身.配置['解析附件']()#仓
                if 附件 is None:#无仓
                    return None#缺席
                return 自身.配置['解析图片访问'](附件,引用)#访问
            def 文件回调():#共享仓
                """返回本适配器拥有的文件仓。"""
                return 自身.文件仓#仓
            钩子={
                'connection':连接回调,#冻结本代
                'apiKey':自身.配置['解析接口密钥'],#密钥
                'userId':自身.配置['解析用户标识'],#用户
                'attachments':附件回调,#附件
                'imageAccess':图片访问回调,#访问
                'files':文件回调,#仓
                'prepareExtensions':自身.配置['准备扩展'],#扩展
            }#依赖
            if '回放降级' in 自身.配置:#有降级回调
                钩子['回放降级']=自身.配置['回放降级']#降级
            return 深求消息适配器(钩子)#消息适配器
        if 协议=='chat-completions':#对话补全
            def 选项回调():#冻结本代
                """返回本代已校验连接。"""
                return 连接#冻结
            def 文件仓回调():#共享仓
                """返回本适配器拥有的文件仓。"""
                return 自身.文件仓#仓
            下一=dict(自身.配置)#拆离
            下一['选项']=选项回调#冻结本代
            下一['解析文件仓']=文件仓回调#共享仓
            return 对话补全适配器(下一)#对话补全
        return 断言永不(协议,'DeepSeek protocol')#配置解析已校验协议

    def 提供方信息(自身,提供方):
        """提供方展示。"""
        return 自身.实现().提供方信息(提供方)#转发

    def 提供方重试政策(自身,提供方):
        """提供方政策。"""
        return 自身.实现().提供方重试政策(提供方)#转发

    def 列出模型(自身,提供方):
        """建议目录。"""
        return 自身.实现().列出模型(提供方)#转发

    def 解析模型(自身,提供方,模型,信号=None):
        """解析精确模型。"""
        return 自身.实现().解析模型(提供方,模型,信号)#转发

    def 图片请求定价(自身,提供方,模型):
        """图请求定价。"""
        return 自身.实现().图片请求定价(提供方,模型)#转发

    def 准备调用(自身,提供方,模型,信号=None):
        """把元数据与派发绑到同一代。"""
        return 自身.实现().准备调用(提供方,模型,信号)#转发

    def 流式(自身,选项):
        """流式调用。"""
        return 自身.实现().流式(选项)#转发
