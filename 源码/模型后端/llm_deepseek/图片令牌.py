"""DeepSeek v4 视觉令牌核算。

对齐上游 `llm-deepseek/src/image-tokens.ts`。公开面仅中文名；无英文别名。
verbatim 移植提供方已发布的图片令牌计算器；请求定价按最坏对齐填充收费。
"""
import math#整除与开方

__all__=('深求图片令牌',)#仅中文公开名

补丁尺寸=14#视觉补丁边长，像素
下采样比=3#每轴补丁到令牌的下采样比
最大图片令牌=384#单张请求图的令牌上限
压缩对齐=4#令牌对齐量子
最大宽高比=8#投影网格前宽度钳制到高度的倍数
最小像素=384*384#总像素下限

def 整除(值,除数):#向下整除
    """对齐 Math.floor(value / divisor)。"""
    return math.floor(值/除数)#整除

def 向上整除(值,除数):#向上整除
    """对齐 ceilDiv。"""
    return math.floor((值+除数-1)/除数)#向上整除

def 网格令牌(网格高,网格宽):#网格令牌数
    """一个网格的令牌数，含行分隔与边框。"""
    令牌=网格高*(网格宽+1)+2#基线
    if 网格高%2==1:#奇数行
        令牌+=网格宽+1#加一行
    令牌+=(向上整除(网格高,2)*(网格宽+1)%2)*2#边框填充
    return 令牌#令牌数

def 求解缩放比(高,宽,预算):#求解缩放比
    """在预算令牌内求解保持宽高比的最大网格。"""
    纵横=高/宽#纵横比
    理想网格宽=math.sqrt((预算-2)/纵横+0.25)-0.5#理想宽
    理想网格高=理想网格宽*纵横#理想高
    if 理想网格宽<1:#单列
        求解网格宽=1#单列
        求解网格高=整除(预算-2,求解网格宽+1)#高
        if 求解网格高%2==1:#奇数则减一
            求解网格高-=1#对齐偶
        最佳宽=求解网格宽*补丁尺寸*下采样比#像素宽
        最佳高=求解网格高*补丁尺寸*下采样比#像素高
    elif 理想网格高<2:#不可达偶路径保留
        求解网格高=2#两行
        求解网格宽=整除(预算-2,求解网格高)-1#宽
        if not (求解网格宽>1):#无解
            raise RuntimeError('deepseek image tokens: no grid fits the token budget')#无网格
        最佳宽=求解网格宽*补丁尺寸*下采样比#像素宽
        最佳高=求解网格高*补丁尺寸*下采样比#像素高
    else:#一般路径
        求解网格宽=math.trunc(理想网格宽)#截断宽
        求解网格高=math.trunc(理想网格高)#截断高
        if 求解网格高%2==1:#奇数则减一
            求解网格高-=1#对齐偶
        宽缩放=求解网格宽*补丁尺寸*下采样比/宽#宽缩放
        高缩放=求解网格高*补丁尺寸*下采样比/高#高缩放
        缩放=min(宽缩放,高缩放)#取较小
        最佳宽=math.trunc(宽*缩放/补丁尺寸)*补丁尺寸#对齐补丁
        最佳高=math.trunc(高*缩放/补丁尺寸)*补丁尺寸#对齐补丁
    网格高=向上整除(整除(最佳高,补丁尺寸),下采样比)#网格高
    网格宽=向上整除(整除(最佳宽,补丁尺寸),下采样比)#网格宽
    return {
        'gridHeight':网格高,#网格高
        'gridWidth':网格宽,#网格宽
        'bestHeight':最佳高,#最佳高
        'bestWidth':最佳宽,#最佳宽
        'numTokens':网格令牌(网格高,网格宽),#令牌
    }#结果

def 安全缩放(高,宽,填充高,填充宽):#安全缩放
    """把填充后的像素尺寸投影到预算内最大令牌网格。"""
    网格高=向上整除(整除(填充高,补丁尺寸),下采样比)#网格高
    网格宽=向上整除(整除(填充宽,补丁尺寸),下采样比)#网格宽
    填充=压缩对齐-1#最坏填充
    预算=最大图片令牌-填充#可用预算
    结果={
        'gridHeight':网格高,#网格高
        'gridWidth':网格宽,#网格宽
        'bestHeight':填充高,#最佳高
        'bestWidth':填充宽,#最佳宽
        'numTokens':网格令牌(网格高,网格宽),#令牌
    }#初值
    if 结果['numTokens']>预算:#超预算
        结果=求解缩放比(高,宽,预算)#求解
        缩减=预算#安全网
        while 结果['numTokens']>预算:#仍超
            缩减-=1#再减
            结果=求解缩放比(高,宽,缩减)#重解
    return {**结果,'numTokens':结果['numTokens']+填充}#含填充计价

def 单次缩放(宽,高):#单次缩放
    """一次钳制-缩放-填充-投影。"""
    钳宽=宽#钳制宽
    钳高=高#钳制高
    if 钳宽>钳高*最大宽高比:#过宽
        钳宽=钳高*最大宽高比#钳宽
    像素=钳宽*钳高#总像素
    if 像素<最小像素 and 像素>0:#过小则放大
        缩放=math.sqrt(最小像素/像素)#放大比
        钳宽=math.trunc(钳宽*缩放)#新宽
        钳高=math.trunc(钳高*缩放)#新高
    填充宽=向上整除(钳宽,补丁尺寸)*补丁尺寸#填充宽
    填充高=向上整除(钳高,补丁尺寸)*补丁尺寸#填充高
    return 安全缩放(钳高,钳宽,填充高,填充宽)#投影

def 相同缩放(甲,乙):#是否相同缩放
    """两份网格缩放结果是否全等。"""
    return (
        甲['gridHeight']==乙['gridHeight']
        and 甲['gridWidth']==乙['gridWidth']
        and 甲['bestHeight']==乙['bestHeight']
        and 甲['bestWidth']==乙['bestWidth']
        and 甲['numTokens']==乙['numTokens']
    )#全等

def 深求图片令牌(宽,高):#DeepSeek 图片令牌
    """DeepSeek v4 对给定尺寸的一张请求图按最坏对齐填充收取的视觉令牌。"""
    结果=单次缩放(宽,高)#首次
    for _ in range(1,10):#至多迭代到不动点
        下一=单次缩放(结果['bestWidth'],结果['bestHeight'])#再投影
        if 相同缩放(下一,结果):#不动点
            return 结果['numTokens']#返回
        结果=下一#继续
    raise RuntimeError(f'deepseek image tokens: resize did not converge for {宽}x{高}')#未收敛
