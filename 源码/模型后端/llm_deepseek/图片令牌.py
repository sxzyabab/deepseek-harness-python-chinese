"""DeepSeek v41 视觉令牌核算。

对齐上游 `llm-deepseek/src/image-tokens.ts`。公开面仅中文名；无英文别名。
verbatim 移植提供方已发布的图片令牌计算器的当前 v41 配置。
"""
import math#整除与开方

__all__=('深求图片令牌',)#仅中文公开名

补丁尺寸=14#视觉补丁边长，像素
下采样比=3#每轴补丁到令牌的下采样比
最大图片令牌=1024#单张请求图的令牌上限
最小像素=544*544#总像素下限
单元格尺寸=补丁尺寸*下采样比#任一轴上一个令牌单元格覆盖的像素

def 整除(值,除数):#向下整除
    """对齐 Math.floor(value / divisor)。"""
    return math.floor(值/除数)#整除

def 向上整除(值,除数):#向上整除
    """对齐 ceilDiv。"""
    return math.floor((值+除数-1)/除数)#向上整除

def 网格令牌(网格高,网格宽):#网格令牌数
    """一个网格的令牌数：每行带一个分隔符，外加两个边框令牌。"""
    return 网格高*(网格宽+1)+2#基线加边框

def 网格格数(填充长度):#令牌单元格数
    """一条已填充像素轴上的令牌单元格数。"""
    return 向上整除(整除(填充长度,补丁尺寸),下采样比)#单元格

def 求解缩放比(高,宽,预算):#求解缩放比
    """在预算令牌内求解保持宽高比的最大网格。"""
    纵横=高/宽#纵横比
    理想网格宽=math.sqrt((预算-2)/纵横+0.25)-0.5#理想宽
    理想网格高=理想网格宽*纵横#理想高
    if 理想网格宽<1:#单列
        求解网格宽=1#单列
        求解网格高=整除(预算-2,求解网格宽+1)#高
        最佳宽=求解网格宽*单元格尺寸#像素宽
        最佳高=求解网格高*单元格尺寸#像素高
    elif 理想网格高<1:#单行
        求解网格高=1#单行
        求解网格宽=整除(预算-2,求解网格高)-1#宽
        最佳宽=求解网格宽*单元格尺寸#像素宽
        最佳高=求解网格高*单元格尺寸#像素高
    else:#一般路径
        求解网格宽=math.trunc(理想网格宽)#截断宽
        求解网格高=math.trunc(理想网格高)#截断高
        缩放=min(求解网格宽*单元格尺寸/宽,求解网格高*单元格尺寸/高)#取较小
        最佳宽=math.trunc(宽*缩放/补丁尺寸)*补丁尺寸#对齐补丁
        最佳高=math.trunc(高*缩放/补丁尺寸)*补丁尺寸#对齐补丁
    网格高=网格格数(最佳高)#网格高
    网格宽=网格格数(最佳宽)#网格宽
    return {
        'gridHeight':网格高,#网格高
        'gridWidth':网格宽,#网格宽
        'bestHeight':最佳高,#最佳高
        'bestWidth':最佳宽,#最佳宽
        'numTokens':网格令牌(网格高,网格宽),#令牌
    }#结果

def 安全缩放(高,宽,填充高,填充宽):#安全缩放
    """把填充后的像素尺寸投影到预算内最大令牌网格。"""
    网格高=网格格数(填充高)#网格高
    网格宽=网格格数(填充宽)#网格宽
    直接={
        'gridHeight':网格高,#网格高
        'gridWidth':网格宽,#网格宽
        'bestHeight':填充高,#最佳高
        'bestWidth':填充宽,#最佳宽
        'numTokens':网格令牌(网格高,网格宽),#令牌
    }#直投
    if 直接['numTokens']<=最大图片令牌:#未超预算
        return 直接#直投
    求解=求解缩放比(高,宽,最大图片令牌)#闭合求解
    if 求解['numTokens']>最大图片令牌:#无解
        raise RuntimeError(f'deepseek image tokens: no grid fits the token budget for {宽}x{高}')#无网格
    return 求解#求解结果

def 单次缩放(宽,高):#单次缩放
    """一次缩放-填充-投影。"""
    缩放宽=宽#缩放宽
    缩放高=高#缩放高
    像素=缩放宽*缩放高#总像素
    if 像素<最小像素 and 像素>0:#过小则放大
        缩放=math.sqrt(最小像素/像素)#放大比
        缩放宽=math.trunc(缩放宽*缩放)#新宽
        缩放高=math.trunc(缩放高*缩放)#新高
    填充宽=向上整除(缩放宽,补丁尺寸)*补丁尺寸#填充宽
    填充高=向上整除(缩放高,补丁尺寸)*补丁尺寸#填充高
    return 安全缩放(缩放高,缩放宽,填充高,填充宽)#投影

def 相同缩放(甲,乙):#是否相同缩放
    """两份网格缩放结果是否全等。"""
    return (
        甲['gridHeight']==乙['gridHeight']
        and 甲['gridWidth']==乙['gridWidth']
        and 甲['bestHeight']==乙['bestHeight']
        and 甲['bestWidth']==乙['bestWidth']
        and 甲['numTokens']==乙['numTokens']
    )#全等

def 深求图片令牌(宽,高):#DeepSeek 图片令牌
    """DeepSeek v41 对给定尺寸的一张请求图收取的视觉令牌，至多 1024。"""
    结果=单次缩放(宽,高)#首次
    for _ in range(1,10):#至多迭代到不动点
        下一=单次缩放(结果['bestWidth'],结果['bestHeight'])#再投影
        if 相同缩放(下一,结果):#不动点
            return 结果['numTokens']#返回
        结果=下一#继续
    raise RuntimeError(f'deepseek image tokens: resize did not converge for {宽}x{高}')#未收敛
