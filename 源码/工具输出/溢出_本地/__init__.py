def 取字段(对象,键,缺省=None):#从映射或对象读字段
    """从映射或对象读字段，缺席为缺省。"""
    if 对象 is None:#空对象
        return 缺省#缺席
    if isinstance(对象,dict):#映射
        if 键 in 对象:#自有键
            return 对象[键]#映射键
        return 缺省#缺席
    return getattr(对象,键,缺省)#对象属性

class 本地溢出存储(溢出存储):#本地文件系统溢出后端
    """本地文件系统溢出后端。文件落在 <root>/session-<hash>/…，名字不可预测，独占仅所有者（0600）写入，私有（0700）根——溢出的工具结果不得被其他本地用户读取，也不得经植入的符号链接重定向。"""
    Config=配置模式#插件配置模式
    def __init__(自身,上下文对象,配置):#构造本地存储
        """已解析的绝对溢出根（配置 root，否则私有默认），构造时固定。"""
        super().__init__(上下文对象)#注册spillStore
        根=取字段(配置,'root')#可选配置根
        if 根 is not None:#有配置根
            自身.root=os.path.abspath(根)#解析为绝对路径
        else:#省略则私有默认
            自身.root=私有根()#惰性私有根
        自身.根=自身.root#中文别名

    def 保存文本(自身,输入):#保存文本
        """把过大文本写入会话作用域文件，返回路径定位器、字节数与本地检索提示。"""
        所有者=取字段(输入,'owner')#所有者
        已存=保存文本文件({#写入会话作用域文件
            'root':自身.root,#溢出根
            'sessionId':取字段(所有者,'sessionId'),#会话id
            'suggestedName':取字段(输入,'suggestedName'),#建议名
            'content':取字段(输入,'content'),#全文
        })#保存结束
        return {#溢出引用
            'locator':溢出定位器(已存['path']),#路径定位器
            'bytes':已存['bytes'],#字节数
            'retrievalHint':检索提示,#本地检索提示
        }#返回引用

