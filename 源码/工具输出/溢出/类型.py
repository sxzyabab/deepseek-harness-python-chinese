"""spill 存储 Service Definition 的词汇。仅类型——抽象服务住在包根，实现在兄弟包（先是 `@deepseek-ai/dsh-spill-local`）。"""

def 溢出定位器(定位器):#把字符串品牌化为溢出定位器
    """把字符串品牌化为溢出定位器。一个溢出产物的不透明面向模型句柄。本地后端可用文件系统路径；远程或数据库后端可用 URI 或键。消费方用溢出引用的检索提示渲染它，但不解析它。"""
    return 定位器#运行时值不变，仅打品牌

# 溢出产物保存时的存储命名空间。会话 id 让后端按生产会话分组存储，但返回的溢出定位器才是面向模型的句柄。fork 会话继承种子日志里已有的定位器；那些产物不复制也不改所有者，fork 之后产出的溢出使用子会话 id。
溢出所有者字段=('sessionId',)#会话id

# 产出一个溢出产物的工具与调用——后端记录下来用于可读文件名和检查。不解释为访问控制；纯描述。
溢出来源字段=(#溢出来源字段元组
    'toolName',#其结果被溢出的工具（例如 web_fetch）
    'callId',#结果所属的模型签发调用 id
    'label',#产物的短人类标签（例如 result）
)#溢出来源字段结束

# 把文本持久到溢出产物的一次请求。
保存文本溢出字段=(#保存文本溢出字段元组
    'owner',#所有者（SpillOwner）
    'source',#来源（SpillSource）
    'suggestedName',#调用方建议的基名（例如 web_fetch.txt）；后端在使用前把它清洗成单个安全路径段——它是提示，绝不是路径
    'content',#要持久的全文（UTF-8）
)#保存文本溢出字段结束

# 已保存的溢出产物：其定位器、字节长度，以及后端特有的检索指引。
溢出引用字段=(#溢出引用字段元组
    'locator',#定位器（SpillLocator）
    'bytes',#字节数
    'retrievalHint',#检索提示
)#溢出引用字段结束
