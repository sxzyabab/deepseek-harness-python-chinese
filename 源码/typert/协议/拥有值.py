"""同步 Client Context 解析器返回的通用调用拥有值。"""

__all__=('协议拥有值标记','协议拥有值','是否协议拥有值','构造协议拥有值',)#仅中文公开名

#常量
协议拥有值标记=object()#跨独立打包共享的身份哨兵；Python 无 Symbol.for，用模块单例

class 协议拥有值:
    """借用载荷与调用所有者幂等清理配对。"""
    def __init__(自身,值,释放):
        """记下载荷与释放回调。"""
        自身.值=值#载荷
        自身._释放=释放#释放
        自身._活跃=True#是否仍活跃
        自身.标记=协议拥有值标记#共享标记

    def 拆除(自身):
        """幂等释放。"""
        if not 自身._活跃:#已拆除
            return#忽略
        自身._活跃=False#标记已拆
        自身._释放()#释放

def 构造协议拥有值(值,释放):
    """转移清理所有权，不增加另一份资源引用计数。"""
    return 协议拥有值(值,释放)#拥有值

def 是否协议拥有值(值):
    """用共享标记识别调用拥有值。"""
    return isinstance(值,协议拥有值) and 值.标记 is 协议拥有值标记#标记命中
