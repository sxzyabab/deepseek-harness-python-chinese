def 创建信号(初值):#创建可写内核信号
    """创建一个可写内核信号。"""
    盒={'value':初值}#当前值
    监听者=set()#订阅者
    def 读快照():#读当前值
        """当前值（变更之间引用稳定）。"""
        return 盒['value']#读
    def 订阅(回调):#登记并返回取消
        """订阅变更。"""
        监听者.add(回调)#加入
        def 退订():#取消
            """取消订阅。"""
            监听者.discard(回调)#删除
        return 退订#退订函数
    def 写入(下一值):#写入并通知
        """发布新值并通知订阅者。"""
        盒['value']=下一值#替换
        for 回调 in list(监听者):#快照后逐个通知
            回调()#通知
    return {'getSnapshot':读快照,'subscribe':订阅,'set':写入}#信号面

def 创建加载器状态仓库():#创建加载器状态仓库
    """创建启动状态仓库（启动链投影出行之前为空）。"""
    盒={'value':{}}#当前投影表
    监听者=set()#订阅者
    def 读快照():#读当前表
        """读当前投影表。"""
        return 盒['value']#读
    def 订阅(回调):#登记并返回取消
        """订阅变更。"""
        监听者.add(回调)#加入
        def 退订():#取消
            """取消订阅。"""
            监听者.discard(回调)#删除
        return 退订#退订函数
    def 写入(标识,状态):#写一条条目
        """投影一条条目的状态（写时复制）。"""
        下一=dict(盒['value'])#写时复制
        下一[标识]=状态#写入
        盒['value']=下一#替换
        for 回调 in list(监听者):#通知
            回调()#通知
    return {'getSnapshot':读快照,'subscribe':订阅,'set':写入}#仓库面
