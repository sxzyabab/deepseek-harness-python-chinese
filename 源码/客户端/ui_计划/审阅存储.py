def 初值():
    """空已打开表。"""
    return {'opened':{}}#初值

def 标记已打开(草稿,审阅键):
    """记下已自动打开。"""
    草稿['opened'][审阅键]=True#标记

def 创建计划审阅存储():
    """瞬态 store，实例属会话作用域。"""
    return {#规格
        'init':初值,#初值
        'actions':{'markOpened':标记已打开},#动作
    }#规格结束
