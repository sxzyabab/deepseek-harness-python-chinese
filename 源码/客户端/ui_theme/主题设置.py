"""宿主用户设置文档里持久化的主题偏好。

对齐上游 `ui-theme/src/theme-settings.ts`。公开面仅中文名；偏好字面量与设置键保持上游。
"""
from schemastery import 模式#schemastery 模式库

__all__=[#仅中文公开名
    '主题偏好们',
    '主题设置命名空间',
    '主题偏好字段',
    '默认偏好',
    '主题设置模式',
    '是否主题偏好',
]#公开面结束

主题偏好们=('light','dark','system')#内置偏好：浅色、深色或跟随系统
主题设置命名空间='ui-theme'#主题插件拥有的设置命名空间
主题偏好字段='preference'#所选内置主题偏好字段名
默认偏好='system'#默认跟随系统

主题设置模式=模式.对象({#持久主题设置 schema
    主题偏好字段:模式.联合(list(主题偏好们)).默认(默认偏好),#preference：浅色、深色或跟随系统，默认跟随系统
})#结束主题设置模式

def 是否主题偏好(值):#收窄成可持久化偏好
    """把一条传输或注册表值收窄成可持久化的偏好。"""
    return 值 in 主题偏好们#内置列表含该值则为偏好
