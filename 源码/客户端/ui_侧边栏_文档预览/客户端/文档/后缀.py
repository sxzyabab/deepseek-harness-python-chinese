import re#去前导点

__all__=['归一后缀','文档文件名','匹配后缀长度']#仅中文公开名

去前导点=re.compile(r'^\.',re.ASCII)#声明后缀前的点

def 归一后缀(扩展名):
    """把声明后缀压成小写并无前导点。"""
    return 去前导点.sub('',扩展名.lower(),count=1)#去一点并小写

def 文档文件名(路径):
    """路径里用来比后缀的末段文件名。反斜杠也当分隔。"""
    归一=路径.replace('\\','/').lower()#分隔与大小写
    return 归一[归一.rfind('/')+1:]#末段

def 匹配后缀长度(名,扩展名列表):
    """文件名上最长命中声明后缀的字符数；无一命中则为 0。复合后缀如 tar.gz 可声明。"""
    长度表=[]#命中长度
    for 扩展名 in 扩展名列表:#各声明
        净=归一后缀(扩展名)#归一
        if 名.endswith('.'+净):#以该后缀结尾
            长度表.append(len(净))#记下
    return max([0]+长度表)#无命中为 0
