'预览登记和不可预览名单共用的文件名后缀比较'

__all__=['规范化后缀','文档文件名','匹配后缀长度']

def 规范化后缀(扩展):
    '小写，并去掉一个前导点'
    小写=扩展.lower()
    if 小写.startswith('.'):
        return 小写[1:]
    return 小写

def 文档文件名(路径):
    '用来匹配后缀的文件名：反斜杠也当分隔，取最后一段并小写'
    规范=路径.replace('\\','/').lower()
    return 规范[规范.rfind('/')+1:]

def 匹配后缀长度(名,扩展列表):
    '文件名结尾上最长的已声明后缀。没有则 0'
    最长=0
    for 扩展 in 扩展列表:
        规范=规范化后缀(扩展)
        if 规范!='' and 名.endswith('.'+规范) and len(规范)>最长:
            最长=len(规范)
    return 最长
