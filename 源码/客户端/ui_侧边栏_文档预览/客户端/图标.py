def _画字形(尺寸,类名,路径):
    '把二十四视口字形画成 svg'
    宽=尺寸 if isinstance(尺寸,int) else 16
    类属性=''
    if isinstance(类名,str) and 类名!='':
        类属性=' class="'+类名+'"'
    界面.html(
        '<svg width="'+str(宽)+'" height="'+str(宽)+'" viewBox="0 0 24 24" fill="currentColor" aria-hidden="true"'+类属性+'>'
        '<path d="'+路径+'"/>'
        '</svg>',
        sanitize=False,
    )


