'按标签记住缩放偏好'
from ....存储 import 声明存储
from .类型 import 适应宽度

__all__=['创建缩放存储','默认缩放']

默认缩放=适应宽度

def 创建缩放存储():
    '标签关掉前保留缩放。没有额外的查看状态时用这份'
    def 初值():
        '空表'
        return {'byTab':{}}
    def 缩放(草稿,标签标识,偏好):
        '写下这一标签的偏好'
        草稿['byTab'][标签标识]=偏好
    def 遗忘(草稿,标签标识):
        '标签没了就丢掉'
        留下={}
        for 标识,值 in 草稿['byTab'].items():
            if 标识!=标签标识:
                留下[标识]=值
        草稿['byTab']=留下
    return 声明存储({'init':初值,'actions':{'zoom':缩放,'forget':遗忘}})
