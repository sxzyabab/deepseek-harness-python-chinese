"""组件本地日历日滴答：跨午夜推进本地日席。

对齐上游 `ui-conversation/src/client/chat/use-calendar-day.ts`。公开面仅中文名。
"""
from .消息铬 import 本地日起点,距下一本地午夜毫秒#午夜辅助
import time as 时间模块#墙钟

__all__=['日历日席']#仅中文公开名

class 日历日席:#本地日午夜
    """挂载时预约下一午夜；越过边界推进。"""

    def __init__(自身,现在=None):#构造
        """播种本日。"""
        if 现在 is None:#缺省
            现在=int(时间模块.time()*1000)#毫秒
        自身.日=本地日起点(现在)#午夜
        自身.预约毫秒=距下一本地午夜毫秒(现在)#预约

    def 滴答(自身,现在=None):#检查是否过午夜
        """过界则推进并重预约。"""
        if 现在 is None:#缺省
            现在=int(时间模块.time()*1000)#毫秒
        if 现在<自身.日+自身.预约毫秒:#未到
            return 自身.日#旧
        自身.日=本地日起点(现在)#新日
        自身.预约毫秒=距下一本地午夜毫秒(现在)#再约
        return 自身.日#新

    def 读(自身):#当前日
        """先滴答再读。"""
        return 自身.滴答()#日
