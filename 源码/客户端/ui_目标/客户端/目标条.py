class 目标条:
    '进行中、暂停或受阻目标的条，以及同一条里的编辑'

    def __init__(自身,属性):
        '记下份额和本地编辑态'
        自身.属性=属性 if isinstance(属性,dict) else {}#份额
        自身.根=None#不占布局的外壳
        自身.坞=None#dock
        自身.条=None#bar
        自身.窗口=None#窗口
        自身.文档=None#文档
        自身.模式=None#看或改
        自身.编辑中=False#是否在编辑
        自身.草稿=''#编辑草稿
        自身.待定=False#按钮禁用
        自身.待定锁=False#同一次渲染里挡住连点
        自身.动作错误=None#失败句
        自身.已清标识=None#本地已清除的目标
        自身.已见标识=object()#用来发现目标身份变化
        自身.编辑器=None#内联编辑器
        自身.错误节点=None#错误句
        自身.动作盒=None#动作容器
        自身.动作键=None#当前按钮组合
        自身.按钮列=[]#按钮和是否保存
        自身.提示列=[]#提示泡
        自身.标签节点=None#阶段标题
        自身.陈述节点=None#目标陈述
        自身.绘制中=False#防止重入
        自身.待重画=False#画的时候又脏了
        自身.渲染()#第一次画

    def 更新(自身,属性):
        '换份额。目标身份变化在渲染里清编辑态'
        自身.属性=属性 if isinstance(属性,dict) else {}#份额

    def 拆除(自身):
        '卸掉提示、编辑器和外壳'
        自身.收起内容()#内部
        if 自身.根 is not None and getattr(自身.根,'parentNode',None) is not None:#还挂着
            自身.根.remove()#摘掉
        自身.根=None#清空

    def 确保壳(自身):
        '外壳一直留着，槽位才能在目标后来出现时挂上内容'
        if 自身.根 is not None:#已经有
            return#沿用
        if 'window' in 自身.属性 and 自身.属性['window'] is not None:#份额带了窗口
            窗口=自身.属性['window']#用它
        else:#没有
            窗口=取握手窗口()#当前页
        文档=窗口.document#文档
        根=文档.createElement('div')#外壳
        根.style.display='contents'#不占布局
        自身.根=根#记下
        自身.窗口=窗口#记下
        自身.文档=文档#记下

    def 渲染(自身):
        '加载、缺席、完成和刚清除的目标不画条'
        if 自身.绘制中:#还在画
            自身.待重画=True#等这一轮
            return 自身.根#当前外壳
        自身.绘制中=True#占用
        try:#结束时放开
            自身.确保壳()#外壳
            目标=自身.属性.get('goal')#当前目标
            if isinstance(目标,dict):#有目标
                标识=目标.get('id')#身份
            else:#没有
                目标=None#当缺席
                标识=None#没有身份
            if 标识!=自身.已见标识:#换了一个目标
                自身.编辑中=False#退出编辑
                自身.动作错误=None#清掉错误
                自身.已清标识=None#新目标不再沿用已清
                自身.已见标识=标识#记下
            if 目标 is None or 目标.get('phase')=='complete' or 目标.get('id')==自身.已清标识:#不画
                自身.收起内容()#拿掉条
            else:#要画
                模式='改' if 自身.编辑中 else '看'#编辑或查看
                if 自身.模式!=模式:#结构变了
                    自身.建壳(模式)#新建
                elif 模式=='改':#仍在编辑
                    自身.刷编辑()#刷新
                else:#仍在查看
                    自身.刷查看()#刷新
        finally:#放开
            自身.绘制中=False#结束
        if 自身.待重画:#又脏了
            自身.待重画=False#清标记
            return 自身.渲染()#再画
        return 自身.根#外壳

    def 建壳(自身,模式):
        '查看和编辑各建一条'
        自身.卸提示()#旧提示
        if 自身.编辑器 is not None:#旧编辑器
            拆=getattr(自身.编辑器,'拆除',None)#观察器
            if callable(拆):#有
                拆()#卸
            自身.编辑器=None#清空
        if 自身.坞 is not None and getattr(自身.坞,'parentNode',None) is not None:#旧条还在
            自身.坞.remove()#摘掉
        注入模块样式文件(#样式只插一次
            自身.文档,
            '目标条样式',
            os.path.join(os.path.dirname(__file__),'目标条.module.css'),
            样式模块,
        )#样式结束
        坞=自身.文档.createElement('div')#dock
        坞.className='dock'#dock 类
        标样式模块(坞,样式模块)#接上模块
        坞.setAttribute('data-goal-bar','')#目标条
        条=自身.文档.createElement('div')#bar
        if 模式=='改':#编辑
            条.className='bar editBar'#编辑条
        else:#查看
            条.className='bar'#查看条
        标样式模块(条,样式模块)#接上模块
        坞.appendChild(条)#条进坞
        自身.根.appendChild(坞)#坞进外壳
        自身.坞=坞#记下
        自身.条=条#记下
        自身.模式=模式#记下
        自身.错误节点=None#错误重新挂
        自身.按钮列=[]#按钮重新挂
        自身.动作键=None#按钮组合重新算
        自身.动作盒=None#动作容器重新建
        if 模式=='改':#编辑
            自身.建编辑()#编辑器
        else:#查看
            自身.建查看()#查看

    def 建查看(自身):
        '字形、阶段、陈述，动作随后按阶段填'
        文档=自身.文档#文档
        字形=文档.createElement('span')#字形
        字形.className='goalGlyph'#字形类
        标样式模块(字形,样式模块)#接上模块
        字形.appendChild(自身.画图标(目标路径))#目标图标
        自身.条.appendChild(字形)#放进条
        标签=文档.createElement('span')#阶段
        标签.className='label'#阶段类
        标样式模块(标签,样式模块)#接上模块
        自身.条.appendChild(标签)#放进条
        自身.标签节点=标签#记下
        陈述=文档.createElement('span')#陈述
        陈述.className='objective'#陈述类
        标样式模块(陈述,样式模块)#接上模块
        自身.条.appendChild(陈述)#放进条
        自身.陈述节点=陈述#记下
        动作=文档.createElement('div')#动作
        动作.className='actions'#动作类
        标样式模块(动作,样式模块)#接上模块
        自身.条.appendChild(动作)#放进条
        自身.动作盒=动作#记下
        自身.刷查看()#填上当前目标

    def 建编辑(自身):
        '多行草稿，保存和取消留在最后'
        自身.编辑器=内联编辑器({#编辑器
            'window':自身.窗口,#窗口
            'value':自身.草稿,#草稿
            'label':'目标内容',#无障碍名
            'onChange':自身.改草稿,#草稿变化
            'onSave':自身.保存编辑,#回车保存
            'onCancel':自身.取消编辑,#退出
            'parent':自身.条,#放进条
        })#编辑器结束
        自身.编辑器.渲染()#画出
        动作=自身.文档.createElement('div')#动作
        动作.className='actions'#动作类
        标样式模块(动作,样式模块)#接上模块
        自身.条.appendChild(动作)#放进条
        自身.动作盒=动作#记下
        自身.按钮列=[]#重新收集
        def 点保存(事件):
            '保存草稿'
            自身.保存编辑()#保存
        def 点取消(事件):
            '退出编辑'
            自身.取消编辑()#取消
        动作.appendChild(自身.图标按钮(#保存
            '保存目标',
            点保存,
            图标勾描边常规({'window':自身.窗口,'size':14}),
            True,
        ))#保存结束
        动作.appendChild(自身.图标按钮(#取消
            '取消编辑',
            点取消,
            图标关闭描边常规({'window':自身.窗口,'size':14}),
        ))#取消结束
        自身.刷禁用()#按草稿和待定
        自身.刷错误()#错误句

    def 刷查看(自身):
        '刷新阶段、陈述、标题和该出现的按钮'
        目标=自身.属性['goal']#当前目标
        激活=自身.属性.get('activation')#进程内武装
        if 目标['phase']=='blocked':#受阻才有原因
            原因=目标['blockedReason'] if 'blockedReason' in 目标 else None#原因
            if isinstance(原因,dict) and 'message' in 原因:#有说明
                自身.条.setAttribute('title',原因['message'])#悬停说明
            else:#没有
                自身.条.removeAttribute('title')#不挂标题
        else:#其他阶段
            自身.条.removeAttribute('title')#不挂标题
        if 目标['phase']=='active':#进行中
            if 激活=='disarmed':#未武装
                文='已暂停的目标'#解除武装文案
            else:#武装或还不知道
                文=阶段文案['active']#进行中
        else:#暂停或受阻
            文=阶段文案[目标['phase']]#对应标题
        自身.标签节点.textContent=文#阶段
        自身.陈述节点.textContent=目标['objective']#陈述
        显示暂停=目标['phase']=='active' and 激活=='armed'#可以暂停
        显示恢复=目标['phase']=='paused' or (目标['phase']=='active' and 激活=='disarmed')#可以恢复
        键=(显示暂停,显示恢复)#按钮组合
        if 键!=自身.动作键:#组合变了
            自身.动作键=键#记下
            自身.重建动作(显示暂停,显示恢复)#重做按钮
        else:#组合没变
            自身.刷禁用()#只刷新禁用
        自身.刷错误()#错误句

    def 刷编辑(自身):
        '编辑器留下，只在草稿变了时改文字'
        编辑器=自身.编辑器#编辑器
        编辑器.属性['value']=自身.草稿#草稿
        编辑器.属性['label']='目标内容'#无障碍名
        框=编辑器.根#文本框
        if 框 is not None and 框.value!=自身.草稿:#外部把草稿改了
            框.value=自身.草稿#写上
            if callable(getattr(编辑器,'适配',None)):#有高度适配
                编辑器.适配()#重新量高
        自身.刷禁用()#按钮
        自身.刷错误()#错误句

    def 重建动作(自身,显示暂停,显示恢复):
        '暂停、恢复、编辑、清除按当前阶段重挂'
        自身.卸提示()#旧提示监听
        动作=自身.动作盒#容器
        while 动作.firstChild is not None:#清空
            动作.firstChild.remove()#摘掉
        自身.按钮列=[]#重新收集
        if 显示暂停:#暂停
            def 点暂停(事件):
                '暂停当前目标'
                自身.执行动作(自身.属性['onPause'])#暂停
            动作.appendChild(自身.图标按钮('暂停目标',点暂停,自身.画图标(暂停路径)))#暂停按钮
        if 显示恢复:#恢复
            def 点恢复(事件):
                '恢复当前目标'
                自身.执行动作(自身.属性['onResume'])#恢复
            动作.appendChild(自身.图标按钮('恢复目标',点恢复,自身.画图标(播放路径)))#恢复按钮
        def 点编辑(事件):
            '草稿取当前陈述并进入编辑'
            自身.草稿=自身.属性['goal']['objective']#草稿
            自身.编辑中=True#进入编辑
            自身.渲染()#换成编辑条
        def 点清除(事件):
            '清除成功后按这个身份藏起条'
            标识=自身.属性['goal']['id']#清除前的身份
            def 提交():
                '调用清除'
                return 自身.属性['onClear']()#清除
            结果=自身.执行动作(提交)#跑
            if 结果 is not None and 结果['ok'] is True:#成功
                自身.已清标识=标识#本地藏起
                自身.渲染()#收起
        动作.appendChild(自身.图标按钮('编辑目标',点编辑,自身.画图标(编辑路径)))#编辑
        动作.appendChild(自身.图标按钮('清除目标',点清除,自身.画图标(垃圾桶路径)))#清除
        自身.刷禁用()#禁用

    def 图标按钮(自身,标签,点下,图标节点,是保存=False):
        '底部延迟提示包住图标按钮'
        钮=自身.文档.createElement('button')#按钮
        钮.setAttribute('type','button')#按钮
        钮.className='iconBtn'#按钮类
        标样式模块(钮,样式模块)#接上模块
        钮.setAttribute('aria-label',标签)#无障碍名
        钮.addEventListener('click',点下)#点击
        钮.appendChild(图标节点)#图标
        泡=提示泡({#提示
            'window':自身.窗口,#窗口
            'portal':True,#传到页面
            'label':标签,#提示文字
            'side':'bottom',#下方
            'delayMs':500,#延迟
            'children':钮,#锚是按钮
        })#提示结束
        锚=泡.渲染()#挂上监听
        自身.提示列.append(泡)#留到拆除
        自身.按钮列.append({'钮':钮,'保存':是保存})#留到禁用
        return 锚#放进动作容器

    def 画图标(自身,路径列表):
        '按上游常规描边画 14 像素'
        return 描边图标({'window':自身.窗口,'size':14},'0 0 16 16',路径列表,14,常规描边)#图标

    def 执行动作(自身,动作):
        '同一时刻只接受一个变更。失败句带到条上'
        if 自身.待定锁:#已经在跑
            return None#丢掉这次
        自身.待定锁=True#关上
        自身.待定=True#禁用
        自身.动作错误=None#清掉旧错误
        自身.刷禁用()#按钮
        自身.刷错误()#拿掉旧句
        结果=动作()#同步跑完
        自身.待定锁=False#打开
        自身.待定=False#恢复
        if 结果['ok'] is not True:#失败
            自身.动作错误=str(结果['error']['message'])+' ('+str(结果['error']['code'])+')'#消息和码
        自身.刷禁用()#按钮
        自身.刷错误()#新句
        return 结果#交给调用方

    def 保存编辑(自身):
        '空草稿不提交。成功后回到查看'
        修剪=自身.草稿.strip()#去掉两端空白
        if 修剪=='':#空的
            return#不提交
        def 提交():
            '把修剪后的陈述交出去'
            return 自身.属性['onEdit'](修剪)#编辑
        结果=自身.执行动作(提交)#跑
        if 结果 is not None and 结果['ok'] is True:#成功
            自身.编辑中=False#退出
            自身.渲染()#回到查看

    def 取消编辑(自身):
        '退出编辑，不提交'
        自身.编辑中=False#退出
        自身.渲染()#回到查看

    def 改草稿(自身,文):
        '记下草稿并刷新保存按钮'
        自身.草稿=文#草稿
        if 自身.编辑器 is not None:#编辑器还在
            自身.编辑器.属性['value']=文#对齐份额
        自身.刷禁用()#空草稿不能保存

    def 刷禁用(自身):
        '待定时全部禁用。保存还要草稿里有字'
        待定=自身.待定 is True#正在变更
        空草稿=自身.草稿.strip()==''#没有字
        for 项 in 自身.按钮列:#每个按钮
            if 项['保存'] is True:#保存
                项['钮'].disabled=待定 or 空草稿#待定或空白
            else:#其他
                项['钮'].disabled=待定#只看待定

    def 刷错误(自身):
        '没有错误就拿掉警告，有就放在动作前面'
        if 自身.动作盒 is None:#还没有动作
            return#不画
        if 自身.动作错误 is None:#没有错误
            if 自身.错误节点 is not None:#旧的还在
                自身.错误节点.remove()#拿掉
                自身.错误节点=None#清空
            return#结束
        if 自身.错误节点 is None:#第一次出现
            节点=自身.文档.createElement('span')#警告
            节点.className='error'#错误类
            标样式模块(节点,样式模块)#接上模块
            节点.setAttribute('role','alert')#读出来
            自身.动作盒.parentNode.insertBefore(节点,自身.动作盒)#放在动作前
            自身.错误节点=节点#记下
        自身.错误节点.textContent=自身.动作错误#写上

    def 卸提示(自身):
        '卸掉提示泡挂在文档上的监听'
        for 泡 in 自身.提示列:#每个提示
            卸=getattr(泡,'卸',None)#拆除
            if callable(卸):#有
                卸()#卸
        自身.提示列=[]#清空

    def 收起内容(自身):
        '拿掉条，外壳留着'
        自身.卸提示()#提示
        if 自身.编辑器 is not None:#编辑器
            拆=getattr(自身.编辑器,'拆除',None)#观察器
            if callable(拆):#有
                拆()#卸
            自身.编辑器=None#清空
        if 自身.坞 is not None and getattr(自身.坞,'parentNode',None) is not None:#条还在
            自身.坞.remove()#摘掉
        自身.坞=None#清空
        自身.条=None#清空
        自身.模式=None#没有条
        自身.错误节点=None#清空
        自身.按钮列=[]#清空
        自身.动作键=None#清空
        自身.动作盒=None#清空


class 目标坞:
    '读 goal 投影，并把进程内武装叠到目标条上'

    def __init__(自身,属性):
        '记下份额并画出'
        自身.属性=属性 if isinstance(属性,dict) else {}#份额
        自身.条=None#目标条
        自身.根=None#外壳
        自身.已订=False#是否已订阅
        自身.退订=[]#退订器
        自身.绘制中=False#防止重入
        自身.待重画=False#画的时候又脏了
        自身.渲染()#第一次画

    def 更新(自身,属性):
        '换一份份额'
        自身.属性=属性 if isinstance(属性,dict) else {}#份额

    def 退订全部(自身):
        '卸掉激活和投影订阅'
        for 退 in 自身.退订:#逐个
            if callable(退):#是函数
                退()#退订
        自身.退订=[]#清空
        自身.已订=False#可以再订

    def 拆除(自身):
        '退订并拆掉目标条'
        自身.退订全部()#订阅
        if 自身.条 is not None:#条还在
            自身.条.拆除()#拆
            自身.条=None#清空
        自身.根=None#清空

    def 确保订阅(自身):
        '激活源一订上就开始读。投影钩子有订阅也订上'
        if 自身.已订:#已经订过
            return#沿用
        自身.已订=True#先标记，避免重入再订
        def 变更():
            '快照变了就重画'
            if 自身.绘制中:#还在画
                自身.待重画=True#等
                return#停
            自身.渲染()#重画
        属性=自身.属性#份额
        激活钩=属性.get('useGoalActivation')#激活钩子
        订=getattr(激活钩,'_subscribe',None) if 激活钩 is not None else None#订阅口
        if callable(订):#有
            自身.退订.append(订(变更))#订激活
        投影钩=属性.get('useProjection')#投影钩子
        订投影=getattr(投影钩,'_subscribe',None) if 投影钩 is not None else None#订阅口
        if callable(订投影):#键控钩子如果带了订阅
            自身.退订.append(订投影(变更))#订投影

    def 渲染(自身):
        '没有投影或目标是空时，条自己什么都不画'
        if 自身.绘制中:#还在画
            自身.待重画=True#等
            return 自身.根#当前
        自身.绘制中=True#占用
        try:#结束时放开
            属性=自身.属性#份额
            投影=属性['useProjection']('goal')#goal 投影
            if 投影 is None:#加载或没有
                目标=None#不画
            else:#有投影
                目标=投影['goal']#持久目标
            if 目标 is None:#没有目标
                目标标识=None#没有身份
                修订=None#没有修订
            else:#有目标
                目标标识=目标['id']#身份
                修订=目标['revision']#修订
            def 选择激活(下一份):
                '修订对上才交出武装'
                if 下一份.get('id')==目标标识 and 下一份.get('revision')==修订:#对上
                    return 下一份.get('activation')#武装
                return None#对不上当缺席
            激活值=属性['useGoalActivation'](选择激活)#当前武装
            条属性={#交给目标条
                'goal':目标,#持久目标
                'onEdit':属性.get('onEdit'),#编辑
                'onPause':属性.get('onPause'),#暂停
                'onResume':属性.get('onResume'),#恢复
                'onClear':属性.get('onClear'),#清除
                'window':属性.get('window'),#窗口
            }#份额结束
            if 激活值 is not None:#已经知道武装
                条属性['activation']=激活值#叠上
            if 自身.条 is None:#第一次
                自身.条=目标条(条属性)#建条
            else:#还是这一条
                自身.条.更新(条属性)#换份额
                自身.条.渲染()#重画
            自身.根=自身.条.根#外壳
            自身.确保订阅()#开始听变化
        finally:#放开
            自身.绘制中=False#结束
        if 自身.待重画:#又脏了
            自身.待重画=False#清标记
            return 自身.渲染()#再画
        return 自身.根#外壳
