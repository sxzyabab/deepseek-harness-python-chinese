"""主题样式表装载：基线、设计平台令牌、滚动条、代码高亮、渐变/字号。

对齐上游 `ui-theme/src/styles/*`。令牌大表已拆入本包 `样式/` 目录，禁止再指向上游空引用。
无法在 Python 运行时注入 DOM stylesheet——需浏览器半挂载下列字符串。
"""
import os#读本包样式文件

__all__=[#仅中文公开名
    '基线样式','滚动条样式','设计平台样式','代码高亮样式','渐变阴影样式','字号令牌样式',
    '主题样式合计','样式文件名','说明',
]#公开面结束

说明='本包 `客户端/样式/` 已落盘上游 ui-theme/src/styles 全部分片；浏览器半按序注入 主题样式合计。'#说明

本目录=os.path.dirname(os.path.abspath(__file__))#本模块目录
样式目录=os.path.join(本目录,'样式')#CSS 分片目录

样式文件名=(#装载顺序与上游复合主题一致
    '基线.css',#字体族与动效时长
    '设计平台_静态色.css',#静态色板
    '设计平台_别名令牌.css',#语义别名
    '渐变阴影.css',#渐变与阴影
    '字号令牌.css',#字号复合变量
    '代码高亮.css',#shiki 令牌
    '滚动条.css',#滚动条皮肤
)#结束

def 读样式(文件名):#读本包一个 CSS 分片
    """按 utf-8 读样式目录下的文件全文。"""
    路径=os.path.join(样式目录,文件名)#绝对路径
    with open(路径,'r',encoding='utf-8') as 文件:#打开
        return 文件.read()#全文

基线样式=读样式('基线.css')#base.css
设计平台样式=读样式('设计平台_静态色.css')+'\n'+读样式('设计平台_别名令牌.css')#design-platform 两片
渐变阴影样式=读样式('渐变阴影.css')#gradient/shadow
字号令牌样式=读样式('字号令牌.css')#font tokens
代码高亮样式=读样式('代码高亮.css')#shiki
滚动条样式=读样式('滚动条.css')#scrollbar 全文

主题样式合计='\n'.join([#浏览器半一次注入用
    基线样式,#基线
    设计平台样式,#设计平台
    渐变阴影样式,#渐变阴影
    字号令牌样式,#字号
    代码高亮样式,#代码高亮
    滚动条样式,#滚动条
])#合计结束
