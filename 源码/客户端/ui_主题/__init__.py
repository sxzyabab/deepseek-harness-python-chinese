def 读分区(上下文):#读当前主题分区
    """读取已登记的主题分区；没有设置提供方时用模式默认值。"""
    回退={'preference':默认偏好,'fontSize':默认字号}#无提供方时的回退
    设置服务=上下文.获取服务('settings')#可选 settings 服务
    if 设置服务 is None:#无提供方则用回退
        return 回退#回退
    分区=设置服务.get(主题命名空间)#读主题分区
    if 分区 is None:#无分区则用回退
        return 回退#回退
    偏好=分区['preference'] if 'preference' in 分区 else 默认偏好#已登记偏好
    字号=分区['fontSize'] if 'fontSize' in 分区 else 默认字号#已登记字号
    return {'preference':偏好,'fontSize':字号}#分区

