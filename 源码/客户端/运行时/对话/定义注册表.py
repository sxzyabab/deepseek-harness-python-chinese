"""会话定义注册表共用的生命周期与稳定条目存储。

对齐上游 `runtime/src/client/conversation/definition-registry.ts`。公开面仅中文名。
"""
from ....依赖 import cordis#外部依赖胶水
服务=cordis.服务#Cordis 服务基类

__all__=['会话定义注册表']#仅中文公开名

class 会话定义注册表(服务):#定义注册表基类
    """一个会话定义注册表共用的生命周期与稳定条目存储。"""

    def __init__(自身,上下文,服务名):#绑定上下文
        """按服务名注册进当前上下文。"""
        自身._定义们={}#键 → 定义
        自身._监听们=set()#订阅者
        自身._缓存=()#登记顺序的稳定元组
        super().__init__(上下文,服务名)#登记服务

    def 条目(自身):#读缓存
        """按登记顺序返回引用稳定的定义。"""
        return 自身._缓存#稳定引用

    def 订阅(自身,监听):#登记监听器
        """观察低频注册表变更；返回取消订阅。"""
        自身._监听们.add(监听)#加入集
        def 取消():#取消
            自身._监听们.discard(监听)#删除
        return 取消#取消器

    def _登记定义(自身,键,定义,重复消息,效应名):#登记一条定义
        """在调用方生命周期内登记键唯一的定义；返回幂等 disposer。"""
        if 键 in 自身._定义们:#已被占用
            raise Exception(重复消息)#单占用者
        拥有方=自身.ctx#调用方光纤上下文
        def 效应():#归调用方光纤
            自身._定义们[键]=定义#写入
            自身._刷新()#刷新缓存并通知
            def 拆除():#拆除
                if 自身._定义们.get(键) is not 定义:#已被别人替换
                    return#不动
                自身._定义们.pop(键,None)#删除
                自身._刷新()#刷新
            return 拆除#拆除器
        拆除器=拥有方.effect(效应,效应名)#登记 effect
        def 同步拆除():#包成同步 disposer（对齐 void dispose()）
            if callable(拆除器):#同步拆除器
                拆除器()#调用
        return 同步拆除#disposer

    def _刷新(自身):#刷新
        """刷新缓存条目并同步让订阅者失效。"""
        自身._缓存=tuple(自身._定义们.values())#按插入顺序复制
        for 监听 in list(自身._监听们):#同步通知
            监听()#回调
