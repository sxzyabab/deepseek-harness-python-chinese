"""合并一份权威基线，且不移动客户端已经看见的身份。

对齐上游 `runtime/src/client/ordered-baseline.ts`。公开面仅中文名。
仅出现在基线里的身份插到最近的后续已知身份之前；基线里没有的身份被去掉。
"""

__all__=['合并有序基线']#仅中文公开名

def 合并有序基线(当前,基线,取键):#按身份合并基线顺序
    """取基线值、保留已确立相对顺序的行。

    @param 当前 - 客户端已确立的顺序。
    @param 基线 - 最新权威行。
    @param 取键 - 稳定身份选择器。
    @returns 取基线值、保留已确立相对顺序的行。
    """
    基线按键={}#身份 → 基线行
    for 值 in 基线:#填基线索引
        基线按键[取键(值)]=值#写下标
    合并=[]#先按当前顺序取基线值
    for 值 in 当前:#遍历当前
        行=基线按键.get(取键(值))#换成基线行
        if 行 is not None:#基线仍有该身份
            合并.append(行)#保留
    已保留键=set()#已保留的身份
    for 值 in 合并:#建已保留集
        已保留键.add(取键(值))#记下
    下标=0#基线扫描下标
    while 下标<len(基线):#插入仅基线有的身份
        值=基线[下标]#当前基线行
        if 值 is None or 取键(值) in 已保留键:#空槽或已保留则跳过
            下标+=1#下一个
            continue#继续
        插入位=len(合并)#默认插到末尾
        后续=下标+1#找后续已知身份
        while 后续<len(基线):#向后扫描
            候选=基线[后续]#后续基线行
            if 候选 is None:#空槽
                后续+=1#下一个
                continue#继续
            已知=-1#在合并结果里的位置
            查=0#扫描合并
            while 查<len(合并):#找已知
                if 取键(合并[查])==取键(候选):#命中
                    已知=查#记下
                    break#用最近的后续
                查+=1#下一个
            if 已知!=-1:#找到后续已知身份
                插入位=已知#插到它前面
                break#停
            后续+=1#继续向后
        合并.insert(插入位,值)#插入基线行
        已保留键.add(取键(值))#记下身份
        下标+=1#下一个基线行
    return 合并#合并后的顺序
