from .客户端.随机uuid import 随机uuid
from ...内核.作用域 import 创建作用域

__all__=['操作方对等']

class 操作方对等:
    """本宿主应答的操作方对等体；连接寿命持有，每次 Remote 调用作为 invocation.peer。"""
    def __init__(自身,拥有):
        """作用域纤程挂在连接插件上下文下；实例自身即作用域键。"""
        自身.id=随机uuid()
        自身.作用域=创建作用域(拥有,自身)
        自身.ctx=自身.作用域.上下文

    def 拆除(自身):
        """拆除连接寿命内全部登记；竞态调用共用一次完成。"""
        自身.作用域.拆除()
