"""根入口瞬时布局仓库：面板几何是裸像素宽度。

对齐上游 `ui-layout/src/client/stores.ts`。公开面仅中文名。
"""
from .列宽 import (#列宽约定
    夹紧宽度,详情默认,详情上限,详情下限,
    侧栏默认,侧栏上限,侧栏下限,
)#列宽

__all__=['创建布局仓库','初始布局状态']#仅中文公开名

def 初始布局状态():#冷启动快照
    """默认侧栏开、详情关、非窄视口。"""
    return {'sidebar':侧栏默认,'details':0,'narrow':False,'narrowExpanded':False}#初始

def 创建布局仓库():#创建布局面板仓库句柄
    """返回状态与动作表；动作写草稿映射。"""
    状态=初始布局状态()#可变状态
    订阅们=[]#监听表

    def 通知():#广播变更
        """通知全部订阅者。"""
        for 听 in list(订阅们):#快照
            听()#回调

    def 设侧栏(像素):#写入侧栏宽度
        """拖拽写入侧栏，夹进约定区间。"""
        状态['sidebar']=夹紧宽度(像素,侧栏下限,侧栏上限)#夹紧
        通知()#广播

    def 设详情(像素):#写入详情栏宽度
        """拖拽写入详情栏，夹进约定区间。"""
        状态['details']=夹紧宽度(像素,详情下限,详情上限)#夹紧
        通知()#广播

    def 切换侧栏():#按窄/宽视口选语义
        """窄视口翻覆盖；宽视口 0 与默认互切。"""
        if 状态['narrow']:#窄
            状态['narrowExpanded']=not 状态['narrowExpanded']#翻覆盖
        else:#宽
            状态['sidebar']=侧栏默认 if 状态['sidebar']==0 else 0#互切
        通知()#广播

    def 设窄视口(窄):#同步断点读数
        """越过断点丢掉手动覆盖。"""
        if 状态['narrow']==窄:#未变
            return#短路
        状态['narrow']=窄#写入
        状态['narrowExpanded']=False#清覆盖
        通知()#广播

    def 开详情():#打开详情栏
        """已关才写回约定默认。"""
        if 状态['details']==0:#已关
            状态['details']=详情默认#默认
            通知()#广播

    def 关详情():#关闭详情栏
        """忘掉拖拽宽度。"""
        状态['details']=0#关闭
        通知()#广播

    def 订阅(听):#订阅变更
        """返回拆除函数。"""
        订阅们.append(听)#登记
        def 拆():#拆除
            """去掉监听。"""
            if 听 in 订阅们:#仍在
                订阅们.remove(听)#删
        return 拆#拆除器

    def 取快照():#读当前状态
        """返回状态浅拷贝。"""
        return dict(状态)#拷贝

    return {#仓库句柄
        'getSnapshot':取快照,#快照
        'subscribe':订阅,#订阅
        'actions':{#绑定动作
            'setSidebar':设侧栏,#侧栏
            'setDetails':设详情,#详情
            'toggleSidebar':切换侧栏,#切换侧栏
            'setNarrow':设窄视口,#窄视口
            'openDetails':开详情,#开详情
            'closeDetails':关详情,#关详情
        },#动作结束
    }#句柄结束
