"""三栏 AppFrame 的纯让步链列宽求解器。

对齐上游 `ui-layout/src/client/columns.ts`。公开面仅中文名。
"""

__all__=[#仅中文公开名
    '中栏下限','侧栏下限','侧栏上限','侧栏默认','侧栏折叠',
    '侧栏自动折叠','详情下限','详情上限','详情默认','夹紧宽度','计算列宽',
]#公开面结束

中栏下限=640#中栏下限像素
侧栏下限=264#侧栏拖拽下限
侧栏上限=420#侧栏拖拽上限
侧栏默认=280#侧栏默认宽度
侧栏折叠=56#折叠轨宽度
侧栏自动折叠=1024#侧栏自动折叠断点
详情下限=300#详情栏拖拽下限
详情上限=520#详情栏拖拽上限
详情默认=360#详情栏默认宽度

def 夹紧宽度(像素,下限,上限):#把宽度夹进区间
    """先四舍五入再夹上下限。"""
    return min(上限,max(下限,round(像素)))#夹紧

def 计算列宽(视口,侧栏,详情):#按视口与偏好求解三栏
    """关闭侧栏用折叠轨；详情可派生为零宽。"""
    侧=侧栏折叠 if 侧栏==0 else 夹紧宽度(侧栏,侧栏下限,侧栏上限)#侧栏钉偏好
    详0=0 if 详情==0 else 夹紧宽度(详情,详情下限,详情上限)#详情偏好
    if 侧+详0+中栏下限<=视口:#偏好全放得下
        return {'sidebar':侧,'center':视口-侧-详0,'details':详0}#中栏吃剩余
    详1=0 if 详0==0 else max(详情下限,视口-侧-中栏下限)#收缩详情
    if 侧+详1+中栏下限<=视口:#收缩后放得下
        return {'sidebar':侧,'center':中栏下限,'details':详1}#中栏钉下限
    return {'sidebar':侧,'center':max(0,视口-侧),'details':0}#详情归零
