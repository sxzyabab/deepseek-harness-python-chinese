分割下限={'divider':0,'chip':100,'body':48}#样式表回退像素
拖拽阈值=4#按压变拖拽的像素阈
_抓取偏移左=60#新面板原点相对落点
_抓取偏移上=14#新面板原点相对落点


def 含点(矩形,横,纵):
    """点是否在矩形内（含边）。"""
    return (横>=矩形['x'] and 横<=矩形['x']+矩形['width']
        and 纵>=矩形['y'] and 纵<=矩形['y']+矩形['height'])#含


def 矩形区位(矩形,横,纵,边带=停靠边带份额):
    """相对窗格矩形的停靠边带区位。"""
    if not (矩形['width']>0) or not (矩形['height']>0):#无尺寸
        return 'center'#中
    return 区位((横-矩形['x'])/矩形['width'],(纵-矩形['y'])/矩形['height'],边带)#区位


def 插入下标(标签矩形表,横):
    """按各标签中点比较指针，得条带插入下标（0..len）。"""
    下标=0#累
    for 矩形 in 标签矩形表:#逐片
        if 横<矩形['x']+矩形['width']/2:#落左半
            break#止
        下标+=1#过
    return 下标#槽


def 半格可放(测量,下限=None):
    """等分后两半是否仍可工作（行/列）。未量到正尺寸视为可放。"""
    if 下限 is None:#默认
        下限=分割下限#样式
    窗格=测量['pane']#窗格盒
    条带=测量['strip']#条带盒
    if not (窗格['width']>0) or not (窗格['height']>0) or not (条带['width']>0):#未量
        return {'row':True,'column':True}#可放
    边框=max(0,窗格['width']-条带['width'])#边框宽
    控件宽=测量['splitControlWidth'] if 'splitControlWidth' in 测量 and 测量['splitControlWidth'] is not None else 0#分栏控件足印
    固定=max(0,条带['width']-测量['chipsWidth']-测量['fillWidth']-控件宽)#固定控件宽
    半宽=(窗格['width']-下限['divider'])/2-边框#半宽
    半高=(窗格['height']-下限['divider'])/2-边框#半高
    return {#可放
        'row':半宽>=固定+下限['chip'],
        'column':半高>=条带['height']+下限['body'],
    }#结果结束


def 已过阈值(起横,起纵,横,纵):
    """任一轴位移是否达到拖拽阈值。"""
    return abs(横-起横)>=拖拽阈值 or abs(纵-起纵)>=拖拽阈值#过


def 分割条尺寸(尺寸表,下标,增量):
    """分割条拖后份额：下标与下标+1 吸收全部变化。"""
    if 下标<0 or 下标+1>=len(尺寸表):#越界
        return list(尺寸表)#原样
    前=尺寸表[下标]#前
    后=尺寸表[下标+1]#后
    下一=list(尺寸表)#拷
    下一[下标]=前+增量#前
    下一[下标+1]=后-增量#后
    return 下一#新


def 平移矩形(矩形,横移,纵移):
    """浮动拖移后的矩形；尺寸不变。"""
    下一=dict(矩形)#浅拷
    下一['x']=矩形['x']+横移#x
    下一['y']=矩形['y']+纵移#y
    return 下一#矩形


def 缩放矩形(矩形,横移,纵移,最小):
    """右下角缩放后的矩形；原点不变。"""
    下一=dict(矩形)#浅拷
    下一['width']=max(最小['width'],矩形['width']+横移)#宽
    下一['height']=max(最小['height'],矩形['height']+纵移)#高
    return 下一#矩形


def 落点浮动矩形(横,纵,尺寸):
    """落在停靠区外时新面板矩形：标题栏落在落点下。"""
    return {#矩形
        'x':max(0,横-_抓取偏移左),
        'y':max(0,纵-_抓取偏移上),
        'width':尺寸['width'],
        'height':尺寸['height'],
    }#矩形结束
