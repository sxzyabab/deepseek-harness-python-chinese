"""指针手势：一次跟进至释放或取消。

对齐上游 `ui-dockkit/src/components/pointer.ts`。公开面仅中文名。
无 DOM 捕获 API 时由宿主把移动/抬起事件喂入；本模块只持一份在途手势。
"""

__all__=['手势会话']#仅中文公开名


class 手势会话:
    """组件级一次一根指针；新按压顶替旧手势，结束时调用复位。"""

    def __init__(自身,复位):
        """复位在释放、取消或顶替时清空预览。"""
        自身._复位=复位#回调
        自身._在途=None#当前跟随者

    def 开始(自身,移动,抬起):
        """开始新手势；顶替在途者。返回喂入接口。"""
        自身._结束在途()#顶替
        def 结算():
            """清在途并复位预览。"""
            自身._在途=None#清
            自身._复位()#复位
        def 喂移动(事件):
            """指针移动。"""
            if 自身._在途 is None:#已结束
                return#忽略
            移动(事件)#回调
        def 喂抬起(事件):
            """指针抬起。"""
            if 自身._在途 is None:#已结束
                return#忽略
            结算()#先清预览
            抬起(事件)#再结算意图
        def 喂取消():
            """取消。"""
            if 自身._在途 is None:#已结束
                return#忽略
            结算()#复位
        自身._在途={'move':喂移动,'up':喂抬起,'cancel':喂取消}#登记
        return 自身._在途#喂入

    def _结束在途(自身):
        """顶替时结束旧手势。"""
        if 自身._在途 is None:#无
            return#止
        旧=自身._在途#旧
        自身._在途=None#先清，避免重入
        自身._复位()#复位
        # 旧跟随者不再接收

    def 拆除(自身):
        """卸载：去掉监听，不复位预览。"""
        自身._在途=None#丢
