"""插件页选择：页面自身与跨插件导航共用。"""
from ...存储 import 声明存储#引擎 store

__all__=['创建导航存储']#仅中文公开名

def 初值():
    """默认落在插件列表。"""
    return {'view':{'kind':'list'}}#导航状态

def 设视图(草稿,视图):
    """切换视图：列表 / 组合包 / 官方条目 / 包内行。"""
    草稿['view']=视图#写入视图

def 创建导航存储():
    """在首次页面渲染前创建插件页选择 store。"""
    return 声明存储({#登记拥有的导航 store 句柄
        'init':初值,#默认列表
        'actions':{'setView':设视图},#切换视图
    })#声明结束
