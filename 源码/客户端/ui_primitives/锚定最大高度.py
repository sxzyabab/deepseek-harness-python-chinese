"""底锚浮层 max-height 夹取。

对齐上游 `ui-primitives/src/useAnchoredMaxHeight.ts`。公开面仅中文名。
元素底边布局、向上长高；夹到顶边与视口顶之间的空间。
"""

__all__=['锚定边距','锚定最大高度']#仅中文公开名

锚定边距=12#与视口顶安全距

def 锚定最大高度(底边,设计封顶,边距=锚定边距):#夹取
    """按底边到视口顶的空间夹取；永不超设计封顶。"""
    可用=底边-边距#可用高度
    if 可用<0:#负
        可用=0#地板
    return 设计封顶 if 可用>设计封顶 else 可用#夹
