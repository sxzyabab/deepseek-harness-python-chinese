"""轨迹消费方共用的有界 Markdown→纯文本投影。

对齐上游 `ui-trajectory/src/client/trajectory-preview.ts`。公开面仅中文名。
运行时 primitives 未迁完时本地实现有界纯文本抽取。
"""
import re#空白折叠与简单标记剥离

__all__=['轨迹预览文本']#仅中文公开名

预览源字符上限=2048#截取源文本的字符上限
预览输出字符上限=512#输出预览的字符上限

def 抽取Markdown纯文本(文本):#Markdown 抽纯文本的最小实现
    """去掉常见 Markdown 标记，保留可读正文。"""
    结果=文本#工作副本
    结果=re.sub(r'```[\s\S]*?```',' ',结果)#去掉围栏代码块
    结果=re.sub(r'`([^`]*)`',r'\1',结果)#行内代码
    结果=re.sub(r'!\[([^\]]*)\]\([^)]*\)',r'\1',结果)#图片 alt
    结果=re.sub(r'\[([^\]]*)\]\([^)]*\)',r'\1',结果)#链接文案
    结果=re.sub(r'[*_~#>]+',' ',结果)#常见强调/标题标记
    return 结果#纯文本近似

def 轨迹预览文本(文本):#有界单行预览
    """在不解析完整 Markdown 文档的前提下，生成有界单行预览。"""
    源=文本[:预览源字符上限]#只取源文本前缀
    紧凑=re.sub(r'\s+',' ',抽取Markdown纯文本(源)).strip()#抽纯文本并压成单行
    预览=紧凑[:预览输出字符上限].rstrip()#再截输出上限并去尾空白
    if len(源)<len(文本) or len(预览)<len(紧凑):#源或压实文本被截断
        return 预览+'…'#截断预览加省略号
    return 预览#完整预览
