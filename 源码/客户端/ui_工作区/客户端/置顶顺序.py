from .存储 import 扁平会话顺序键
from .树 import 会话成员标识,未分组键,拥有分组键

__all__=['置顶顺序来源','置顶账本键']

def 置顶顺序来源(工作区列,列表,行态):
    '每个工作区、未分组和扁平列表的完整成员'
    已入账=set()#已经算进工作区的会话
    for 工作区 in 工作区列:#逐个工作区
        for 会话号 in 工作区['sessionIds']:#成员
            已入账.add(会话号)#记下
    未分组=[]#没有工作区的会话
    for 标识 in 列表['ids']:#列表顺序
        if 列表['byId'].get(标识) is not None and 标识 not in 已入账:#有摘要且未入账
            未分组.append(标识)#留下
    成员={}#账本到成员
    for 工作区 in 工作区列:#工作区账本
        成员[工作区['workspaceId']]=工作区['sessionIds']#成员
    成员[未分组键]=未分组#未分组
    成员[扁平会话顺序键]=会话成员标识(列表)#扁平列表含归档
    return {'members':成员,'summaries':列表['byId'],'rowState':行态}#来源

def 置顶账本键(工作区列,会话号):
    '被置顶的会话要领先的账本：它所在的组，以及扁平列表'
    return [拥有分组键(工作区列,会话号),扁平会话顺序键]#两组
