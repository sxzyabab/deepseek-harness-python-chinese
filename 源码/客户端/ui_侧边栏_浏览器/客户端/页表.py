from .视图.内嵌帧呈现形式 import 内嵌帧呈现形式
from .浏览器.内嵌帧实现 import 内嵌帧实现

__all__=['创建内嵌帧页']


def 创建内嵌帧页(选项):
    '组装空闲的内嵌帧提供方和它的文档呈现'
    帧盒=[None]

    def 已加载(修订):
        '这一代文档加载完'
        帧盒[0].处理已加载(修订)

    def 失败(修订):
        '这一代文档加载失败'
        帧盒[0].处理加载失败(修订)

    def 重挂():
        '容器重新挂上后重载'
        帧盒[0].刷新()

    呈现=内嵌帧呈现形式({'loaded':已加载,'failed':失败,'remounted':重挂})
    帧=内嵌帧实现(选项,呈现)
    帧盒[0]=帧
    return {'frame':帧,'presentation':呈现}
