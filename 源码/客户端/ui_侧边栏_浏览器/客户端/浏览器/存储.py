__all__=['初值','替换','遗忘','创建浏览器存储']#仅中文公开名

def 初值():
    """空分桶表。"""
    return {'byTab':{}}#初态

def 替换(草稿,标签标识,状态):
    """写入一标签的导航快照。"""
    草稿['byTab'][标签标识]=状态#替换

def 遗忘(草稿,标签标识):
    """丢掉一标签的状态。"""
    草稿['byTab']={键:值 for 键,值 in 草稿['byTab'].items() if 键!=标签标识}#过滤

def 创建浏览器存储():
    """声明会话作用域浏览器持久化存储规格。"""
    return {#规格
        'init':初值,#播种
        'persist':'dsh.sidebar-browser.v1',#持久化键（线路字面量）
        'actions':{#动作
            'replace':替换,#替换
            'forget':遗忘,#遗忘
        },#动作结束
    }#规格结束
