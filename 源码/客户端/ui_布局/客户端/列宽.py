import math

__all__=[
    '中栏下限','侧栏下限','侧栏上限','侧栏默认','侧栏折叠',
    '侧栏自动折叠','右侧栏下限','右侧栏最大比','右侧栏默认比',
    '取整','夹紧宽度','计算列宽',
]

中栏下限=400#右栏还占轨道时，中列保住的宽度
侧栏下限=264#侧栏拖拽下限
侧栏上限=420#侧栏拖拽上限
侧栏默认=280#还没拖过时的侧栏宽
侧栏折叠=56#收起后的图标轨
侧栏自动折叠=1024#窄于这宽度就自动收起
右侧栏下限=300#右栏拖拽下限
右侧栏最大比=0.7#右栏最多占帧宽的比例
右侧栏默认比=0.45#第一次打开右栏时占帧宽的比例


def 取整(数):
    '对齐 JavaScript Math.round。正数的一半向上'
    return math.floor(数+0.5)


def 夹紧宽度(像素,下限,上限):
    '先取整，再夹进上下限'
    return min(上限,max(下限,取整(像素)))


def 计算列宽(视口,侧栏,右侧栏,折叠宽=侧栏折叠):
    '先缩右栏，放不下就拿掉右轨道。没有右轨道时中列可以到零。折叠宽为 0 时整列藏起'
    if 侧栏==0:
        侧=折叠宽
    else:
        侧=夹紧宽度(侧栏,侧栏下限,侧栏上限)
    可用=视口-侧-中栏下限
    if 右侧栏==0 or 可用<右侧栏下限:
        右=0
    else:
        右=min(可用,夹紧宽度(右侧栏,右侧栏下限,视口*右侧栏最大比))
    return {'sidebar':侧,'center':max(0,视口-侧-右),'rightbar':右}
