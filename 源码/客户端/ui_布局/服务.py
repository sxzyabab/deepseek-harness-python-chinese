import threading

__all__=['布局错误','布局控制器']

class 布局错误(Exception):
    """本包布局面板接线失败。"""

class 布局控制器:#跨插件面板动作面
    """其它插件可触发的面板过渡。"""
    def __init__(自身,面板,有主面板):#构造
        """面板为根入口绑定动作；有主面板检查登记表。"""
        自身.面板=面板#根入口绑定动作
        自身.有主面板=有主面板#主面板是否已登记
        自身.导航=threading.Event()#挂起导航；set 表示已中止

    def 选择面板(自身,面板标识):#选择主面板
        """未登记则抛错并保留当前选择。"""
        if 面板标识 is not None and not 自身.有主面板(面板标识):#未登记
            raise 布局错误('主面板 "'+str(面板标识)+'" 未登记')
        自身.导航.set()#中止挂起导航
        自身.面板['selectPanel'](面板标识)#写入 store

    def 开始导航(自身):#开始异步导航
        """返回新挂起导航的中止事件。"""
        自身.导航.set()#中止旧导航
        自身.导航=threading.Event()#新事件
        return 自身.导航#交出

    def 拆除(自身):#卸载时作废挂起导航
        """中止挂起导航。"""
        自身.导航.set()#中止

    def 切换侧栏(自身):#切换侧栏
        """关闭 ⟷ 约定默认宽度。"""
        自身.面板['toggleSidebar']()#转发

    def 打开右侧栏(自身,要轨,全屏):#报告右侧栏呈现
        """报告右侧栏轨与全屏呈现，不改其展开状态本身。"""
        自身.面板['openRightbar'](要轨,全屏)#转发

    def 关闭右侧栏(自身):#报告右侧栏隐藏
        """报告右侧栏隐藏：无轨、无柄。"""
        自身.面板['closeRightbar']()#转发
