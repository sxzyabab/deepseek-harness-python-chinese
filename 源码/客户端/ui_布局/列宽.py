中栏下限=400#正常右列打开时保护的中列宽度
侧栏下限=264#侧栏拖拽夹紧下限
侧栏上限=420#侧栏拖拽夹紧上限
侧栏默认=280#任何用户拖拽前的侧栏宽度
侧栏折叠=56#关闭侧栏的轨：16px 水平内边距之间的 24px 图标列
侧栏自动折叠=1024#侧栏自动折叠断点（deepsuite LG）
右侧栏下限=300#右列拖拽夹紧下限
右侧栏最大比=0.7#正常右面板最大宽度占帧的比例
右侧栏默认比=0.45#首次打开右面板的偏好占帧的比例

def 夹紧宽度(像素,下限,上限):#把宽度夹进区间
    """先四舍五入再夹上下限。"""
    return min(上限,max(下限,round(像素)))#夹紧

def 计算列宽(视口,侧栏,右侧栏):#按视口与偏好求解三栏
    """收缩或移除右轨道后的实际宽度；无该轨道时中列可低于下限直至零。"""
    侧=侧栏折叠 if 侧栏==0 else 夹紧宽度(侧栏,侧栏下限,侧栏上限)#关闭用轨，否则夹进侧栏区间
    可用=视口-侧-中栏下限#右列可用空间
    右=0 if 右侧栏==0 or 可用<右侧栏下限 else min(可用,夹紧宽度(右侧栏,右侧栏下限,视口*右侧栏最大比))#无请求或放不下则为零
    return {'sidebar':侧,'center':max(0,视口-侧-右),'rightbar':右}#中列吃剩余
