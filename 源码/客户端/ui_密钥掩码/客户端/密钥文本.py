'交互消息在每段末尾提供显示或隐藏这一个值的控件。每次挂载从遮挡开始'
import re
from .凭证掩码 import 掩码字符

掩码段=re.compile('('+re.escape(掩码字符)+'+)')

def 初始记下的原文():
    '每次挂载从遮挡开始，还没有记下原文'
    return None

def 拆遮挡段(遮挡):
    '拆成保留文本和掩码段。空段丢掉，掩码段仍带着原字符'
    段=[]
    for 部分 in 掩码段.split(遮挡):
        if 部分=='':
            continue
        段.append({'遮挡':部分.startswith(掩码字符),'文本':部分})
    return 段

def 是否展开(交互,已展开原文,原文):
    '记下的是原文而不是开关：交互且原文还是这一段才展开'
    return bool(交互) and 已展开原文==原文

def 切换记下的原文(已展开,原文):
    '已展开则清掉，否则记下这一段原文'
    if 已展开:
        return None
    return 原文

def 控件文案键(已展开):
    '展开用隐藏，遮挡用显示'
    if 已展开:
        return 'secret.hide'
    return 'secret.reveal'

def 呈现(节点,原文,交互,已展开原文=None):
    '这一段要画的内容和控件文案键。展开时内容是原文，否则是拆开的遮挡段'
    展开=是否展开(交互,已展开原文,原文)
    if 展开:
        内容=原文
    else:
        内容=拆遮挡段(节点['data']['masked'])
    文案键=None
    if 交互:
        文案键=控件文案键(展开)
    return {'展开':展开,'内容':内容,'文案键':文案键}

__all__=['初始记下的原文','拆遮挡段','是否展开','切换记下的原文','控件文案键','呈现']
