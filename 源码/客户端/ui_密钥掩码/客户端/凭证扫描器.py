密钥槽=0#四对，三段令牌要同时记下三次游程
密钥下一=8
字母数字槽=9
单词槽=11
字母数字横线槽=13
大写字母数字槽=15
用户槽=17
密码槽=19
数字从=21
数字于=22
块从=23
块尾起点=24
块尾=25
候选起点=26#上一回地址检查接受的密码起点
备忘长度=27

密钥游程=re.compile(r'[A-Za-z0-9_-]*')
用户游程=re.compile(r'[^\s/:@?#]*')
密码游程=re.compile(r'[^\s/@?#]*')
非数字=re.compile(r'\D*',re.ASCII)#与不带 u 标志的 \D 一致，只认 ASCII 数字
字母数字游程=re.compile(r'[A-Za-z0-9]*')
单词游程=re.compile(r'\w*',re.ASCII)#与不带 u 标志的 \w 一致
字母数字横线游程=re.compile(r'[A-Za-z0-9-]*')
大写字母数字游程=re.compile(r'[A-Z0-9]*')

def 是宽空白(码):
    'ASCII 以外的 \\s'
    return 码==0xA0 or 码==0x1680 or (0x2000<=码<=0x200A) or 码==0x2028 or 码==0x2029 or 码==0x202F or 码==0x205F or 码==0x3000 or 码==0xFEFF

def 游程终点(模式,文本,起点):
    '粘性星号从起点能吃到的终点。对不上则 0，与 lastIndex 归零一致'
    if 起点>len(文本):
        return 0
    匹配=模式.match(文本,起点)
    if 匹配 is None:
        return 0
    return 匹配.end()

def 取码(文本,下标):
    '越界对应 charCodeAt 的 NaN'
    if 下标<0 or 下标>=len(文本):
        return None
    return ord(文本[下标])

class 凭证扫描器:
    '一次匹配的扫描状态。查询同步且不会重入，备忘留到换成另一段文本'
    def __init__(自身,格式表):
        '抄下格式表，并备好本实例的模式和备忘'
        自身.字符类=格式表['字符类']
        自身.字面量=格式表['字面量']
        自身.字面长度=格式表['字面长度']
        自身.字面种类=格式表['字面种类']
        自身.字面形状=格式表['字面形状']
        自身.字面最小=格式表['字面最小']
        自身.字面最大=格式表['字面最大']
        自身.字面重叠=格式表['字面重叠']
        自身.结尾=格式表['结尾']
        自身.共享结尾=格式表['共享结尾']
        自身.前缀=re.compile(格式表['前缀源'])
        自身.密钥游程=密钥游程
        自身.用户游程=用户游程
        自身.密码游程=密码游程
        自身.非数字=非数字
        模式表={
            字母数字:(字母数字槽,字母数字游程),
            单词:(单词槽,单词游程),
            字母数字横线:(字母数字横线槽,字母数字横线游程),
            大写字母数字:(大写字母数字槽,大写字母数字游程),
        }
        槽列=[]
        模式列=[]
        for 游程位 in 格式表['字面游程']:
            一对=模式表.get(游程位)
            if 一对 is None:#0 表示 [A-Za-z0-9_-]，这一类有四对备忘
                槽列.append(0)
                模式列.append(密钥游程)
            else:
                槽列.append(一对[0])
                模式列.append(一对[1])
        自身.字面槽=槽列
        自身.字面模式=模式列
        自身.掩码=凭证掩码()
        自身.备忘=[-1]*备忘长度#未测过的槽是 -1，正常起点对不上
        自身.文本=''

    def 匹配(自身,文本,起点):
        '从给定起点找出下一段凭证，没有则空'
        if 文本!=自身.文本:
            自身.备忘=[-1]*备忘长度
            自身.文本=文本
        长度=len(文本)
        开始=-1
        结束=-1
        种类=带前缀
        明文=True
        推迟结束=自身.起点前的地址(起点)
        推迟开始=自身.槽(候选起点) if 推迟结束>=0 else -1
        位置=起点
        while True:
            命中=自身.前缀.search(文本,位置)
            if 命中 is None:
                break
            字面终点=命中.end()
            字面=自身.字面结束于(字面终点)
            位于=字面终点-自身.字面长度[字面]
            位置=字面终点-自身.字面重叠[字面]#真后缀可能是下一条字面量的开头
            if 推迟开始>=0 and 推迟开始<=位于:
                if 开始<0:
                    开始=推迟开始
                    结束=推迟结束
                    种类=地址
                elif 推迟开始>=结束:
                    break
                推迟开始=-1
            if 开始>=0 and (位于>=结束 or 结束==长度):
                break
            字面种类=自身.字面种类[字面]
            if 字面种类==地址:
                推迟结束=自身.地址密码(位于)
                推迟开始=自身.槽(候选起点) if 推迟结束>=0 else -1
                continue
            if 字面种类==密钥块:
                候选结束=自身.密钥块终点(位于)
            else:
                候选结束=自身.前缀终点(字面,位于)
            if 候选结束<0:
                continue
            if 开始<0:
                开始=位于
                结束=候选结束
                种类=字面种类
                明文=字面种类==带前缀
            elif 候选结束>结束:
                结束=候选结束#重叠的并进最早的一段，遮挡仍按最早的种类
                if 字面种类!=带前缀:
                    明文=False
        if 开始<0 and 推迟开始>=0:
            开始=推迟开始
            结束=推迟结束
            种类=地址
        if 开始<0:
            return None
        遮挡=自身.掩码.遮挡文本(文本,种类,明文,开始,结束)
        return {'id':'secret','start':开始,'end':结束,'data':{'masked':遮挡}}

    def 槽(自身,下标):
        '备忘里的这一格。布局保证下标都在数组内'
        return 自身.备忘[下标]

    def 位于是单词(自身,下标):
        '下标处是不是 \\w。越界不是'
        if 下标<0 or 下标>=len(自身.文本):
            return False
        码=ord(自身.文本[下标])
        return 码<128 and (自身.字符类[码]&单词)!=0

    def 是用户码(自身,码):
        '单个码元能否出现在用户名里。越界的 NaN 不是'
        if 码 is None:
            return False
        if 码<128:
            return (自身.字符类[码]&用户)!=0
        return not 是宽空白(码)

    def 字面结束于(自身,终点):
        '前缀扫描停住的那个字面量。同一结尾只有一个时不用再对原文'
        文本=自身.文本
        键=ord(文本[终点-2])*128+ord(文本[终点-1])
        字面=自身.结尾[键]
        if 字面>0:
            return 字面-1
        共享=自身.共享结尾[键]
        序号=0
        while 序号<len(共享)-1:
            候选=共享[序号]
            字面起点=终点-自身.字面长度[候选]
            if 文本.startswith(自身.字面量[候选],字面起点):
                break
            序号+=1
        return 共享[序号]

    def 密钥游程终点(自身,起点):
        '[A-Za-z0-9_-]* 的终点，四对备忘轮换'
        槽位=密钥槽
        while 槽位<密钥下一:
            if 自身.槽(槽位)<=起点 and 起点<=自身.槽(槽位+1):
                return 自身.槽(槽位+1)
            槽位+=2
        终点=游程终点(自身.密钥游程,自身.文本,起点)
        下一=(自身.槽(密钥下一)+1)&3
        自身.备忘[密钥下一]=下一
        自身.备忘[密钥槽+2*下一]=起点
        自身.备忘[密钥槽+2*下一+1]=终点
        return 终点

    def 备忘游程终点(自身,模式,起点,槽位):
        '模式在起点的游程终点，记在这一对备忘里'
        if 自身.槽(槽位)<=起点 and 起点<=自身.槽(槽位+1):
            return 自身.槽(槽位+1)
        终点=游程终点(模式,自身.文本,起点)
        自身.备忘[槽位]=起点
        自身.备忘[槽位+1]=终点
        return 终点

    def 下一数字(自身,起点):
        '起点及之后第一个数字的偏移，没有则文本长度'
        if 自身.槽(数字从)<=起点 and 起点<=自身.槽(数字于):
            return 自身.槽(数字于)
        自身.备忘[数字从]=起点
        自身.备忘[数字于]=游程终点(自身.非数字,自身.文本,起点)
        return 自身.槽(数字于)

    def 标签终点(自身,起点):
        '起点处 [A-Z0-9 ]{0,40}PRIVATE KEY----- 之后的偏移，不像则 -1。最多读 52 个字符'
        文本=自身.文本
        限度=起点+52
        if 限度>len(文本):
            限度=len(文本)
        下标=起点
        while 下标<限度:
            码=ord(文本[下标])
            if 码>127 or (自身.字符类[码]&标签)==0:
                break
            下标+=1
        尾=下标-len('PRIVATE KEY')#PRIVATE KEY 本身是标签字符，后面的 - 不是，游程刚好停在它后面
        if 下标<起点+52 and 尾>=起点 and 文本.startswith('PRIVATE KEY-----',尾):
            return 尾+len('PRIVATE KEY-----')
        return -1

    def 密钥块终点(自身,位于):
        '-----BEGIN 块在第一条完整 END 行之后，没有 END 则到文本结尾。头无效则 -1'
        头=自身.标签终点(位于+len('-----BEGIN '))
        if 头<0:
            return -1
        if 自身.槽(块从)<=头 and 头<=自身.槽(块尾起点):
            return 自身.槽(块尾)
        文本=自身.文本
        自身.备忘[块从]=头
        自身.备忘[块尾起点]=len(文本)
        自身.备忘[块尾]=len(文本)
        行=文本.find('-----END ',头)
        while 行>=0:
            终点=自身.标签终点(行+len('-----END '))
            if 终点>=0:
                自身.备忘[块尾起点]=行
                自身.备忘[块尾]=终点
                break
            行=文本.find('-----END ',行+1)
        return 自身.槽(块尾)

    def 方案在前(自身,位于):
        '\\b[a-z][a-z0-9+.-]{1,15} 是否刚好停在位于。最多回看 16 个字符'
        文本=自身.文本
        开始=位于-1
        while 开始>=0 and 开始>=位于-16:
            码=ord(文本[开始])
            位=自身.字符类[码] if 码<128 else 0
            if (位&方案)==0:
                return False
            if (位&小写)!=0 and 位于-开始>=2 and not 自身.位于是单词(开始-1):
                return True
            开始-=1
        return False

    def 地址密码(自身,位于):
        '位于上的 :// 所在地址的密码终点，起点写入备忘。不像则 -1'
        if not 自身.方案在前(位于):
            return -1
        文本=自身.文本
        用户起点=位于+len('://')
        用户结束=自身.备忘游程终点(自身.用户游程,用户起点,用户槽)
        if 用户结束-用户起点>256 or 取码(文本,用户结束)!=58:
            return -1
        开始=用户结束+1
        结束=自身.备忘游程终点(自身.密码游程,开始,密码槽)
        if 结束==开始 or 取码(文本,结束)!=64:
            return -1
        自身.备忘[候选起点]=开始
        return 结束

    def 起点前的地址(自身,起点):
        ':// 起点在查询起点之前、密码却在查询起点之后的那段。先确认后面有冒号、密码和 @ 才往回走'
        文本=自身.文本
        if 起点<3:
            return -1
        if 文本.startswith('://',起点-1):#查询起点落在 :// 里面
            return 自身.地址密码(起点-1)
        if 文本.startswith('://',起点-2):
            return 自身.地址密码(起点-2)
        下标=起点-1
        之前=取码(文本,下标)
        if 之前==58:#密码从查询起点开始，紧跟在用户名的冒号后面
            密码起点=起点
            下标-=1
        elif 自身.是用户码(之前):
            用户结束=自身.备忘游程终点(自身.用户游程,起点,用户槽)
            if 取码(文本,用户结束)!=58:
                return -1
            密码起点=用户结束+1
        else:
            if 文本.startswith('://',起点-3):
                return 自身.地址密码(起点-3)
            return -1
        密码结束=自身.备忘游程终点(自身.密码游程,密码起点,密码槽)
        if 密码结束==密码起点 or 取码(文本,密码结束)!=64:
            return -1
        最低=密码起点-258#用户名最多 256，再加前面的冒号
        if 最低<0:
            最低=0
        while 下标>=最低 and 自身.是用户码(取码(文本,下标)):
            下标-=1
        if 下标>=2 and 文本.startswith('://',下标-2):
            return 自身.地址密码(下标-2)
        return -1

    def 前缀终点(自身,字面,位于):
        '字面量从位于开始的带前缀凭证的终点，不像则 -1'
        if 自身.位于是单词(位于-1):
            return -1
        文本=自身.文本
        开始=位于+自身.字面长度[字面]
        形状=自身.字面形状[字面]
        最小=自身.字面最小[字面]
        if 形状==含数字:
            数字=自身.下一数字(开始)#没有数字的 sk- 在量游程之前就否掉
            if 数字-开始>255:
                return -1
            终点=自身.密钥游程终点(开始)
            if 终点-开始>=最小 and 数字<终点:
                return 终点
            return -1
        槽位=自身.字面槽[字面]
        if 槽位==0:
            终点=自身.密钥游程终点(开始)
        else:
            终点=自身.备忘游程终点(自身.字面模式[字面],开始,槽位)
        长度=终点-开始
        if 长度<最小:
            return -1
        if 形状==整段:
            return 终点
        if 形状==定长:
            return 开始+最小
        if 形状==有界:
            if 长度<=自身.字面最大[字面] and not 自身.位于是单词(终点):
                return 终点
            return -1
        if 长度>自身.字面最大[字面] or not 文本.startswith('.eyJ',终点):
            return -1
        载荷起点=终点+len('.eyJ')
        载荷结束=自身.密钥游程终点(载荷起点)
        if 载荷结束-载荷起点<最小 or 取码(文本,载荷结束)!=46:
            return -1
        签名结束=自身.密钥游程终点(载荷结束+1)
        if 签名结束-(载荷结束+1)>=最小:
            return 签名结束
        return -1

