元字符='.*+?^${}()|[]\\'

def 转义字面(字面):
    '正则元字符前面加反斜杠'
    出=[]
    for 字符 in 字面:
        if 字符 in 元字符:
            出.append('\\')
        出.append(字符)
    return ''.join(出)

def 交替(字面列表):
    '按共享的前导字符合成只含字面量的交替，分组不加量词'
    分组={}
    for 字面 in 字面列表:
        if 字面:
            头=字面[0]
            尾=字面[1:]
        else:
            头=''
            尾=''
        已有=分组.get(头)
        if 已有 is None:
            分组[头]=[尾]
        else:
            已有.append(尾)
    段=[]
    for 头,尾列表 in 分组.items():
        if len(尾列表)==1:
            段.append(转义字面(头+尾列表[0]))
        else:
            段.append(转义字面(头)+'(?:'+交替(尾列表)+')')
    return '|'.join(段)

def 重叠长度(字面,字面列表):
    '最长的真后缀里，同时又是某个字面量前缀的长度。扫描从这里续上'
    长度=len(字面)-1
    while 长度>0:
        后缀=字面[-长度:]
        for 其他 in 字面列表:
            if 其他.startswith(后缀):
                return 长度
        长度-=1
    return 0

def 结尾表(字面列表):
    '按字面量最后两个码元索引。独占的记序号加一，多个则 -1 并列入共享'
    结尾=[0]*(128*128)
    共享=[None]*(128*128)
    序号=0
    while 序号<len(字面列表):
        字面=字面列表[序号]
        键=ord(字面[-2])*128+ord(字面[-1])
        已有=结尾[键]
        if 已有==0:
            结尾[键]=序号+1
        else:
            if 已有>0:
                共享[键]=[已有-1]
                结尾[键]=-1
            共享[键].append(序号)
        序号+=1
    return {'结尾':结尾,'共享结尾':共享}

def 字符类表():
    '每个 ASCII 码元一位类集合'
    类=[0]*128
    for 码 in range(128):
        是大写=65<=码<=90
        是小写=97<=码<=122
        是数字=48<=码<=57
        是字母数字=是大写 or 是小写 or 是数字
        权威=not ((9<=码<=13) or 码==32 or 码==47 or 码==64 or 码==63 or 码==35)
        位=0
        if 是字母数字 or 码==95 or 码==45:
            位|=密钥类
        if 是字母数字:
            位|=字母数字
        if 是字母数字 or 码==95:
            位|=单词
        if 是字母数字 or 码==45:
            位|=字母数字横线
        if 是大写 or 是数字:
            位|=大写字母数字
        if 是大写 or 是数字 or 码==32:
            位|=标签
        if 是小写 or 是数字 or 码==43 or 码==46 or 码==45:
            位|=方案
        if 是小写:
            位|=小写
        if 权威 and 码!=58:
            位|=用户
        if 权威:
            位|=密码
        类[码]=位
    return 类

def 编译格式表():
    '从凭证格式列表编出扫描表'
    字面量=[]
    种类=[]
    形状=[]
    游程=[]
    最小=[]
    最大=[]
    for 项 in 凭证格式列表:
        字面量.append(项['字面'])
        种类.append(项['种类'])
        形状.append(项['形状'])
        游程.append(项['游程'])
        最小.append(项['最小'])
        最大.append(项['最大'])
    结尾=结尾表(字面量)
    长度=[]
    重叠=[]
    for 字面 in 字面量:
        长度.append(len(字面))
        重叠.append(重叠长度(字面,字面量))
    return {
        '字符类':字符类表(),
        '字面量':字面量,
        '字面长度':长度,
        '字面种类':种类,
        '字面形状':形状,
        '字面游程':游程,
        '字面最小':最小,
        '字面最大':最大,
        '字面重叠':重叠,
        '前缀源':交替(字面量),
        '结尾':结尾['结尾'],
        '共享结尾':结尾['共享结尾'],
    }

