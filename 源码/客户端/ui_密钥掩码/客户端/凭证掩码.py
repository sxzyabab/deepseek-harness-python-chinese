'凭证区间的显示形式。掩码从共享串上切，一行一次，多行则每行一次'
import re
from .凭证格式 import 地址,带前缀

掩码字符='*'
可见前缀=8#带前缀的密钥留前八个字符
共享掩码长度=4096
普通=re.compile('[^\r\n\ud800-\udfff]*')

def 取码(文本,下标):
    '越界对应 charCodeAt 的 NaN'
    if 下标<0 or 下标>=len(文本):
        return None
    return ord(文本[下标])

class 凭证掩码:
    '持有共享掩码串和粘性游程'
    def __init__(自身):
        '备好共享掩码串'
        自身.仅掩码=掩码字符*共享掩码长度
        自身.掩码换行=自身.仅掩码+'\n'
        自身.掩码回车=自身.仅掩码+'\r'
        自身.普通=普通

    def 遮挡文本(自身,文本,种类,明文,起点,终点):
        '地址整段遮挡。带前缀的密钥或令牌留前八个字符，明文表示没有换行。密钥块留首尾行'
        if 种类==地址:
            return 自身.范围(文本,起点,终点)
        if 种类==带前缀:
            前缀=文本[起点:起点+可见前缀]
            if 明文:#没有换行，掩码可以一次切片
                return 前缀+自身.掩码若干(终点-起点-可见前缀)
            return 前缀+自身.范围(文本,起点+可见前缀,终点)
        return 自身.密钥块(文本,起点,终点)

    def 掩码若干(自身,个数):
        '个数个掩码。不超过共享串时只切一次'
        if 个数<=共享掩码长度:
            return 自身.仅掩码[:个数]
        return 掩码字符*个数

    def 掩码再换行(自身,个数,码):
        '个数个掩码再加这个换行。码只是 10 或 13'
        if 个数<=共享掩码长度:
            源=自身.掩码换行 if 码==10 else 自身.掩码回车
            return 源[共享掩码长度-个数:]
        if 码==10:
            return 掩码字符*个数+'\n'
        return 掩码字符*个数+'\r'

    def 密钥块(自身,文本,起点,终点):
        '留住 BEGIN 行、存在的 END 行和每个换行。写在一行上的块整段遮挡'
        正文起点=起点
        下标=起点
        while 下标<终点:
            if ord(文本[下标])==10:
                正文起点=下标+1
                break
            下标+=1
        正文终点=终点
        下标=终点-len('\n-----END')
        while 下标>=正文起点:
            if 下标>=0 and ord(文本[下标])==10 and 文本.startswith('-----END',下标+1):#负下标在 Python 会从末尾取
                正文终点=下标
                break
            下标-=1
        收束=取码(文本,正文终点)
        有界=正文终点==len(文本) or 收束==10 or 收束==13#游程会停在换行或文本结尾
        if 有界:
            正文=自身.按行(文本,正文起点,正文终点)
        else:
            正文=自身.范围(文本,正文起点,正文终点)
        return 文本[起点:正文起点]+正文+文本[正文终点:终点]

    def 范围(自身,文本,起点,终点):
        '换行留在原处，其余每个码点一个掩码。代理对算一个'
        遮挡=''
        个数=0
        下标=起点
        while 下标<终点:
            码=ord(文本[下标])
            if 码==10 or 码==13:
                遮挡+=自身.掩码再换行(个数,码)
                个数=0
                下标+=1
                continue
            if 0xD800<=码<=0xDBFF and 下标+1<终点:
                下一=ord(文本[下标+1])
                if 0xDC00<=下一<=0xDFFF:
                    下标+=1
            个数+=1
            下标+=1
        return 遮挡+自身.掩码若干(个数)

    def 按行(自身,文本,起点,终点):
        '正文以换行或文本结尾收束，游程不会读过终点'
        遮挡=''
        个数=0
        下标=起点
        while 下标<终点:
            匹配=自身.普通.match(文本,下标)
            停=匹配.end() if 匹配 is not None else 下标
            if 停>终点:
                停=终点
            个数+=停-下标
            if 停==终点:
                break
            码=ord(文本[停])
            下标=停+1
            if 码==10 or 码==13:
                遮挡+=自身.掩码再换行(个数,码)
                个数=0
                continue
            if 码<=0xDBFF and 下标<终点:#高代理后面的低代理算一个字符
                下一=ord(文本[下标])
                if 0xDC00<=下一<=0xDFFF:
                    下标+=1
            个数+=1
        return 遮挡+自身.掩码若干(个数)

__all__=['掩码字符','凭证掩码']
