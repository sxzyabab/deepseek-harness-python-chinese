def 应用(上下文):
    '设置提供方存在时投影会话偏好。不调用客户端里的应用'
    def 登记(子上下文):
        '关闭自动表单，把这份纤程交给设置配置'
        def 配置设置():
            '按宿主面登记'
            return 子上下文.settings.configure({'auto':False},上下文.fiber)
        return 子上下文.effect(配置设置)
    上下文.inject(['settings'],登记)

apply=应用
