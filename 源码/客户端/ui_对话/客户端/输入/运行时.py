class 作曲器节点:#文档节点
    """根、段落、文本、芯片或换行。"""
    def __init__(自身,编辑器,种,文本='',引用=None,无效=False):
        """记下种与可选文本/芯片字段。"""
        自身.编辑器=编辑器#属主
        自身.键=编辑器.下一键()#节点键
        自身.种=种#root|paragraph|text|chip|linebreak
        自身.子=[]#子
        自身.父=None#父
        自身.文本=文本#文本
        自身.引用=引用 if 引用 is not None else {}#芯片字段
        自身.无效=无效#失败旗

    def 取键(自身):
        """节点键。"""
        return 自身.键#键

    def 是元素(自身):
        """根或段落。"""
        return 自身.种=='root' or 自身.种=='paragraph'#元素

    def 是文本(自身):
        """文本叶。"""
        return 自身.种=='text'#文本

    def 是引用芯片(自身):
        """引用芯片。"""
        return 自身.种=='chip'#芯片

    def 是换行(自身):
        """换行叶。"""
        return 自身.种=='linebreak'#换行

    def 取子(自身):
        """子拷贝。"""
        return list(自身.子)#子

    def 取首子(自身):
        """首子或 None。"""
        return 自身.子[0] if len(自身.子)>0 else None#首子

    def 清空(自身):
        """丢掉子。"""
        自身.子=[]#清

    def 追加(自身,孩):
        """挂上子。"""
        孩.父=自身#父
        自身.子.append(孩)#收下
        return 自身#链式

    def 子数量(自身):
        """子数。"""
        return len(自身.子)#数

    def 取文本内容(自身):
        """芯片用剪贴板投影；元素拼接子。"""
        if 自身.种=='text':#文本
            return 自身.文本#文本
        if 自身.种=='chip':#芯片
            return 自身.引用['clipboardText'] if 'clipboardText' in 自身.引用 else ''#投影
        if 自身.种=='linebreak':#换行
            return '\n'#换行
        出=''#拼接
        for 孩 in 自身.子:#子
            出+=孩.取文本内容()#叠
        return 出#全文

    def 选到末尾(自身):
        """把选区落到本节点内容末尾。"""
        自身.编辑器.选到节点末尾(自身)#选
        return 自身.编辑器.取选区()#选区

    def 取来源(自身):
        """芯片来源。"""
        return 自身.引用['source'] if 'source' in 自身.引用 else None#来源

    def 取引用(自身):
        """芯片 ref。"""
        return 自身.引用['ref'] if 'ref' in 自身.引用 else ''#ref

    def 取标签(自身):
        """芯片标签。"""
        return 自身.引用['label'] if 'label' in 自身.引用 else ''#标签

    def 取外观(自身):
        """可选外观。"""
        return 自身.引用['appearance'] if 'appearance' in 自身.引用 else None#外观

    def 已无效(自身):
        """失败旗。"""
        return 自身.无效 is True#无效

