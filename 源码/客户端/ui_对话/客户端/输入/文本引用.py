from .装饰 import 扫描文本引用#扫描纯文本引用

__all__=['文本引用节点','登记文本引用装饰','重扫文本引用']#仅中文公开名

类型标签='composer-text-ref'#Lexical 节点注册表类型标签

class 文本引用节点:#可编辑文本引用
    """匹配的纯文本引用，带样式且完全可编辑。"""
    def __init__(自身,文本,键=None):
        """记下文本与可选节点键。"""
        自身.文本=文本#文本
        自身.键=键#节点键
        自身.格式=0#格式
        自身.细节=0#细节
        自身.模式=''#模式
        自身.样式=''#样式

    @staticmethod
    def 类型名():
        """节点注册表类型标签。"""
        return 类型标签#标签

    def 克隆(自身):
        """带身份克隆。"""
        return 文本引用节点(自身.文本,自身.键)#同键拷贝

    def 导出(自身):
        """序列化为 JSON 节点形态。"""
        return {'text':自身.文本,'type':类型标签}#形态

    def 创建DOM(自身,基类名,引用类,文本引用类,可点开类):
        """样式化挂载的 span；斜杠前缀带可点开类。"""
        类名=基类名#基
        类名=类名+' '+引用类 if 引用类 not in 类名 else 类名#引用
        类名=类名+' '+文本引用类#文本引用
        if 自身.文本.startswith('/'):#斜杠可点开
            类名=类名+' '+可点开类#可点开
        return {'className':类名,'spellcheck':'false','data-composer-text-ref':''}#DOM 面

    def 是文本实体(自身):
        """实体节点从不与普通兄弟合并。"""
        return True#是

    def 可在前插文本(自身):
        """编辑在内部继续。"""
        return True#可以

def 自json导入(形态):
    """从其 JSON 形态重建一个文本引用。形态为 dict。"""
    节点=文本引用节点(形态['text'])#建节点
    if 'format' in 形态:#格式
        节点.格式=形态['format']#写
    if 'detail' in 形态:#细节
        节点.细节=形态['detail']#写
    if 'mode' in 形态:#模式
        节点.模式=形态['mode']#写
    if 'style' in 形态:#样式
        节点.样式=形态['style']#写
    return 节点#返回

def 登记文本引用装饰(编辑器,取词表,活跃令牌):
    """登记纯文本引用实体变换。认领装饰在前导令牌席优先。"""
    def 取匹配(文本):
        """首个非认领令牌的引用区间。"""
        认领=活跃令牌()#当前认领
        去尾=认领.rstrip() if 认领 is not None else None#去尾空白
        for 区间 in 扫描文本引用(文本,取词表()):#扫描
            片段=文本[区间['start']:区间['end']]#切片
            if 认领 is not None and 区间['start']==0 and 片段==去尾:#跳过认领令牌
                continue#下
            return {'start':区间['start'],'end':区间['end']}#首个匹配
        return None#无匹配
    return 编辑器.登记文本实体(取匹配,文本引用节点)#拆除器

def 重扫文本引用(编辑器):
    """强制重扫整文档：词表变更本身不弄脏任何节点。"""
    def 标脏全部():
        """标脏全部文本。"""
        for 节点 in 编辑器.取根().全部文本节点():#逐个
            节点.标脏()#标脏
    编辑器.更新(标脏全部)#排队而非离散
