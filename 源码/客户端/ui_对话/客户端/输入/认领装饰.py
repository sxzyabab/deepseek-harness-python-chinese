
__all__=['令牌样式','登记认领装饰','刷新认领装饰']#仅中文公开名

令牌样式='color: var(--dsw-alias-state-warn-label)'#警告色样式

def 第一文本叶(编辑器):
    """文档的第一个文本叶；空文档或前导芯片则 None。"""
    块=编辑器.取根().取首子()#首块
    if 块 is None or 块.是元素() is False:#非元素
        return None#缺席
    叶=块.取首子()#首子
    if 叶 is None or 叶.是文本() is False:#非文本
        return None#缺席
    return 叶#文本叶

def 登记认领装饰(编辑器,活跃令牌):
    """登记认领令牌样式变换。活跃令牌() 未认领时为 None。"""
    def 变换(节点):
        """令牌席上色；离开则清过期样式。"""
        第一=第一文本叶(编辑器)#令牌席
        if 第一 is None or 节点 is not 第一:#不在令牌席
            if 节点.取样式()==令牌样式:#过期令牌样式
                节点.设样式('')#清
            return#返回
        文本=节点.取文本()#节点文本
        活跃=活跃令牌()#当前令牌
        去尾=活跃.rstrip() if 活跃 is not None else None#去尾空白
        令牌=文本 if 文本==去尾 else 活跃#本地化令牌可能带尾空格
        if 令牌 is None or 文本.startswith(令牌) is False:#无认领或不匹配
            if 节点.取样式()==令牌样式:#有色
                节点.设样式('')#清
            return#返回
        if len(文本)>len(令牌):#令牌后还有字
            令牌节点=节点.按长度拆分(len(令牌))#拆出令牌段
            if 令牌节点 is not None and 令牌节点.取样式()!=令牌样式:#未上色
                令牌节点.设样式(令牌样式)#上色
            return#返回
        if 节点.取样式()!=令牌样式:#未上色
            节点.设样式(令牌样式)#确保上色
    return 编辑器.登记文本变换(变换)#拆除器

def 刷新认领装饰(编辑器):
    """把令牌席标脏，使变换在认领翻转后重样式。"""
    def 标脏():
        """标脏第一叶。"""
        叶=第一文本叶(编辑器)#第一叶
        if 叶 is not None:#有
            叶.标脏()#标脏
    编辑器.更新(标脏)#排队更新，避免嵌套提交递归
