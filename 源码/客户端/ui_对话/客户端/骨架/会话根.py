from .主面板 import 主面板

__all__=['会话根']

class 会话根:
    '常驻会话骨架。英雄、撰写器位置和输入栏跨无会话切换保持挂载'
    def __init__(自身,属性):
        '把 main.conversation 的份额交给主面板'
        自身.属性=属性
        自身.面板=主面板(属性)
        自身.根=自身.面板.根

    def 渲染(自身):
        '重画主面板'
        自身.面板.属性=自身.属性
        自身.根=自身.面板.渲染()
        return 自身.根
