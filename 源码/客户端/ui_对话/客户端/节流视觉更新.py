"""非必要视觉对齐的按帧节流调度。

对齐上游 `ui-conversation/src/client/chat/use-throttled-visual-update.ts`。公开面仅中文名。
无 React 钩——提供可绑定的调度器类。
"""

__all__=['节流视觉更新','默认间隔帧']#仅中文公开名

默认间隔帧=3#默认等 3 帧

class 节流视觉更新:#按帧合并
    """有排队则合并；到零帧才跑最新对齐。"""

    def __init__(自身,更新,间隔帧=默认间隔帧):#构造
        """记下对齐回调与间隔。"""
        自身.更新=更新#对齐
        自身.间隔帧=间隔帧#帧
        自身.剩余=0#倒计时
        自身.排队中=False#闩

    def 设更新(自身,更新):#换回调
        """每次渲染写最新对齐。"""
        自身.更新=更新#新

    def 调度(自身):#请求一次
        """已有排队则合并。"""
        if 自身.排队中:#已有
            return#合
        自身.排队中=True#闩
        自身.剩余=自身.间隔帧#重置
        自身._推进()#开

    def _推进(自身):#一帧
        """递减；到零执行。"""
        自身.剩余-=1#耗
        if 自身.剩余>0:#还要
            return#等（宿主下帧再调 滴答）
        自身.排队中=False#清
        if callable(自身.更新):#有
            自身.更新()#对齐

    def 滴答(自身):#宿主每帧
        """排队中则推进一帧。"""
        if not 自身.排队中:#无
            return#停
        自身._推进()#推

    def 取消(自身):#卸载
        """清排队。"""
        自身.排队中=False#清
        自身.剩余=0#零
