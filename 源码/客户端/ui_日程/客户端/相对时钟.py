'任务页和详情共用的相对时间时钟'
from ...模块.客户端.通告 import 取握手窗口

__all__=['相对时钟周期毫秒','现在毫秒','安装相对时钟']

相对时钟周期毫秒=30000

def 现在毫秒():
    '读浏览器当前纪元毫秒'
    return int(取握手窗口().Date.now())

def 安装相对时钟(重画,周期毫秒=相对时钟周期毫秒):
    '按周期重采样。返回停止函数，卸下时清掉定时器'
    窗口=取握手窗口()
    def 跳动():
        '到点通知界面重画'
        重画()
    定时=窗口.setInterval(跳动,周期毫秒)
    def 停止():
        '卸下这一只时钟'
        窗口.clearInterval(定时)
    return 停止
