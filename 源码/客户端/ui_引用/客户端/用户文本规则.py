'在原文里认出文件和文件夹，不读事实，也不做发现'
import re#令牌与标点

__all__=['文件引用规则','文件夹引用规则']

令牌表达式=re.compile(r'(?<!\S)(@"[^"\n]+"|@[^\s]+)')#空白边界上的 @ 或 @"
标点尾巴=re.compile(r'[.,;:!?，。；：！？]+$')#句末标点，引号路径不剥

def 下一路径(文本,起点,文件夹):
    '从起点起找下一个文件或目录引用'
    for 匹配 in 令牌表达式.finditer(文本,起点):#起点之后的每个令牌
        令牌=匹配.group(0)#整段匹配
        if 令牌.startswith('@"'):#引号路径保留内部标点
            原始=令牌#整段都算引用
        else:#普通路径
            原始=标点尾巴.sub('',令牌)#句末标点留在引用外面
        if len(原始)<=1:#只剩 @
            continue#再找
        路径=原始[1:]#去掉开头的 @
        if 路径.startswith('"'):#去掉开头引号
            路径=路径[1:]#剥开
        if 路径.endswith('"'):#去掉结尾引号
            路径=路径[:-1]#剥合
        if 路径.endswith('/')!=文件夹:#文件不要尾斜杠，目录必须有
            continue#再找
        段列表=[段名 for 段名 in re.split(r'[\\/]',路径) if 段名]#非空段
        if len(段列表)>0:#有末段
            标签=段列表[-1]#最后一段
        else:#根目录没有末段
            标签=原始[1:]#用去掉 @ 后的原文
        return {#这一处引用
            'start':匹配.start(),#起始
            'end':匹配.start()+len(原始),#不含被剥掉的标点
            'data':{'path':路径,'label':标签},#路径与标签
        }#命中
    return None#没有

def 匹配文件(文本,起点,读取上下文=None):
    '最近一条不带尾斜杠的文件引用。不读事实'
    候选=下一路径(文本,起点,False)#文件
    if 候选 is None:#没有
        return None#无
    结果={'id':'file'}#规则标识
    结果.update(候选)#起点、终点和数据
    return 结果#文件节点

def 匹配文件夹(文本,起点,读取上下文=None):
    '最近一条带尾斜杠的目录引用。不读事实'
    候选=下一路径(文本,起点,True)#目录
    if 候选 is None:#没有
        return None#无
    结果={'id':'folder'}#规则标识
    结果.update(候选)#起点、终点和数据
    return 结果#目录节点

文件引用规则={#原文里的文件
    'id':'file',#标识
    'order':30,#顺序
    'match':匹配文件,#匹配
}#文件规则结束

文件夹引用规则={#原文里的目录
    'id':'folder',#标识
    'order':30,#顺序
    'match':匹配文件夹,#匹配
}#目录规则结束
