__all__=['锚定位置']

def 锚定位置(锚矩形,面板宽,面板高,视口宽,视口高,侧='bottom',对齐='start',间隙=0,边距=0):
    """按锚矩形放置固定层，并夹进视口。"""
    左=锚矩形['right']-面板宽 if 对齐=='end' else 锚矩形['left']
    顶=锚矩形['top']-间隙-面板高 if 侧=='top' else 锚矩形['bottom']+间隙
    if 面板宽>0:
        上限=视口宽-面板宽-边距
        if 左<边距:
            左=边距
        if 左>上限:
            左=上限
    if 面板高>0:
        上限=视口高-面板高-边距
        if 顶<边距:
            顶=边距
        if 顶>上限:
            顶=上限
    return {'left':左,'top':顶}
