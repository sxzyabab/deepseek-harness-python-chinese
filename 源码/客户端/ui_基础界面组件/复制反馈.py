from ..模块.客户端.通告 import 取握手窗口
from .剪贴板 import 写剪贴板#宿主剪贴板

__all__=['复制反馈毫秒','复制反馈']#仅中文公开名

复制反馈毫秒=1000#成功反馈持续

class 复制反馈:#瞬时成功标志+复制处理
    '持有待写文本；反馈窗口内空操作'

    def __init__(自身,文本=''):#构造
        '记下文本'
        自身.文本=文本#待写
        自身.已复制=False#标志
        自身.定时=None#熄灭句柄
        自身.刷新=None#熄灭后重画

    def 置文本(自身,文本):#换文
        '刷新待写文本'
        自身.文本=文本#新

    def 复制(自身):#写入
        '反馈中跳过；拒绝则静默'
        if 自身.已复制:#窗口内
            return False#跳
        if not 写剪贴板(自身.文本):#拒绝
            return False#失败
        自身.已复制=True#点亮
        def 到期():
            '一秒钟后熄灭，并让业主重画'
            自身.已复制=False#熄
            自身.定时=None#清句柄
            if 自身.刷新 is not None:
                自身.刷新()#重画
        自身.定时=取握手窗口().setTimeout(到期,复制反馈毫秒)#一秒钟
        return True#成功

    def 熄灭(自身):#反馈到期
        '宿主定时后调用'
        自身.已复制=False#熄

    def 句柄(自身):#钩返回形
        'copied + onCopy'
        return {'copied':自身.已复制,'onCopy':自身.复制,'feedbackMs':复制反馈毫秒,'clear':自身.熄灭}#句柄
