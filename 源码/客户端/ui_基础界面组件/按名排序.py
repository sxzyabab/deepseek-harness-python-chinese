无匹配=float('-inf')#无匹配哨兵

def 边界加分(名称,下标):
    """名称起点与分隔符边界的额外权重。"""
    if 下标==0:#起点
        return 8#加 8
    前=名称[下标-1]#前一字符
    if 前=='-' or 前=='_':#分隔后
        return 8#加 8
    return 0#不加

def 对齐分(名称,查询):
    """最强有序子序列对齐分。查询不是名称子序列时返回 None。"""
    if len(查询)>len(名称):#查询比名称长
        return None#不可能
    上一=[无匹配]*len(名称)#上一查询字符的行
    首=查询[0]#首查询字符
    序=0#下标
    while 序<len(名称):#首查询字符落点
        if 名称[序]==首:#命中
            上一[序]=1+边界加分(名称,序)-序#首字符分
        序+=1#前进
    查询下标=1#后续查询字符
    while 查询下标<len(查询):#后续
        本行=[无匹配]*len(名称)#本行分数
        左=无匹配#相邻延续分
        再左=无匹配#再前一格分
        最佳空隙=无匹配#最佳带空隙延续
        格=0#名称下标
        while 格<len(名称):#扫名称
            先前=上一[格]#上一行本格
            if 再左!=无匹配:#有再前
                最佳空隙=max(最佳空隙,再左+格-2)#更新带空隙最佳
            if 名称[格]==查询[查询下标]:#本格匹配
                加=1+边界加分(名称,格)#基础分加边界
                分=无匹配#本格候选分
                if 左!=无匹配:#相邻延续
                    分=左+加+4#加 4
                if 最佳空隙!=无匹配:#带空隙
                    分=max(分,最佳空隙+加+1-格)#取强
                本行[格]=分#记下
            再左=左#滑动
            左=先前#本格变下一轮的左
            格+=1#前进
        上一=本行#推进
        查询下标+=1#下一查询字符
    最佳=无匹配#全局最佳
    for 分 in 上一:#取行最大
        最佳=max(最佳,分)#更新
    if 最佳==无匹配:#无匹配
        return None#缺席
    return 最佳#对齐分

def 按名排序(项表,原始查询):
    """按菜单查询对命名项排序。项为含 name、可选 label 的 dict。空查询返回原列表。"""
    查询=原始查询.lower()#规范化查询
    if 查询=='':#空查询
        return 项表#原样
    入选=[]#匹配缓冲
    下标=0#源顺序
    for 项 in 项表:#逐项
        键表=[项['name']]#名称
        if 'label' in 项 and 项['label'] is not None:#有标签
            键表.append(项['label'])#第二检索键
        前缀=False#任一键前缀
        分=None#较强对齐分
        for 键 in 键表:#逐键
            小写=键.lower()#规范化
            键分=对齐分(小写,查询)#该键分
            if 键分 is None:#不是子序列
                continue#下键
            if 小写.startswith(查询):#前缀
                前缀=True#记下
            if 分 is None:#尚无
                分=键分#收下
            else:#取强
                分=max(分,键分)#较强
        if 分 is not None:#入选
            入选.append({'item':项,'index':下标,'prefix':前缀,'score':分})#记下
        下标+=1#前进
    def 排序键(匹配):
        """前缀优先，再分，再源序。"""
        前=1 if 匹配['prefix'] is True else 0#前缀
        return (-前,-匹配['score'],匹配['index'])#降序前缀与分
    入选.sort(key=排序键)#排序
    return [匹配['item'] for 匹配 in 入选]#只返回项
