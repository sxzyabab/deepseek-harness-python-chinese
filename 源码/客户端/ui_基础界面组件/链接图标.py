def 链接画稿(属性,描边宽):
    '按种类画前导图标。url 没有商标路径时退回地球'
    合成=dict(属性 if isinstance(属性,dict) else {})
    if 'size' not in 合成 or 合成['size'] is None:
        合成['size']=14
    种类=合成.get('kind')
    if 种类=='url':
        标=站点字形(合成)
        if 标 is not None:
            return 标
        return 地球描边画稿(合成,描边宽)
    if 种类=='folder':
        return 关文件夹画稿(合成,描边宽)
    if 种类=='code':
        return 代码括号画稿(合成,描边宽)
    if 种类=='image':
        return 照片(合成,描边宽)
    if 种类=='document':
        return 带字纸(合成,描边宽)
    if 种类=='other':
        return 白纸(合成,描边宽)
    raise ValueError('unreachable link icon kind: '+str(种类))

