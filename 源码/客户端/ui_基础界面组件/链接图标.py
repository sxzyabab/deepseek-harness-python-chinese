def 分类链接路径(路径):
    '按扩展名给出链接图标种类。不会返回 url 或 folder'
    类型=分类文件类型(路径)
    扩展名=文件扩展名(路径)
    if 是否代码文件类型(类型):
        if 是否链接代码扩展名(扩展名):
            return 'code'
        return 'other'
    if 扩展名=='':
        return 'other'
    if 类型 in ('code','html'):
        return 'code'
    if 类型=='image':
        return 'image'
    if 类型 in ('excel','pdf','ppt','word'):
        return 'document'
    if 类型 in ('markdown','other','video'):
        return 'other'
    raise ValueError('unreachable link icon kind: '+str(类型))

