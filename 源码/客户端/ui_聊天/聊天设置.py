def 转录视图模式字段(易失=False):
    '当前四档加上两份只读遗留值。认不出的值回落，不拒绝整份设置'
    字段=枚举字段(*转录视图设置值)
    元={'loose':True}
    if 易失:
        元['volatile']=True
    字段.meta=元
    return 字段


def 配置字段():
    '浏览器投影。每一项都是易失单元格，和持久模式不是同一份字段'
    def 易失枚举(常量表,默认值):
        '带默认值的易失枚举'
        字段=枚举字段(*常量表,默认值=默认值)
        字段.meta={'volatile':True}
        return 字段
    return {
        转录视图字段:转录视图模式字段(True),
        折叠时机字段:易失枚举(折叠时机表,默认折叠时机),
        'performanceUsage':易失枚举(性能用量模式表,默认性能用量),
        'linkOpening':易失枚举(链接打开表,默认链接打开),
    }


