"""紧凑与精确 token 计数、缓存命中百分比。

对齐上游 `ui-chat/src/client/chat/token-format.ts`。公开面仅中文名。
"""
import math#舍入

__all__=['格式化令牌','格式化精确令牌','格式化缓存命中百分比']#仅中文公开名

def 缩放显示(候选):#缩放后的显示数字
    """百以上整，否则一位小数。"""
    if 候选>=100:#整
        return str(round(候选))#整
    return str(round(候选*10)/10)#一位

def 格式化令牌(值,翻译):#紧凑格式化 token 数
    """517 / 12.2K / 517K / 1.2M。"""
    if 值<1000:#不足千
        return str(值)#原样
    if 值<1000000:#千量级
        return 翻译('number.thousand',{'value':缩放显示(值/1000)})#千
    return 翻译('number.million',{'value':缩放显示(值/1000000)})#百万

def 格式化精确令牌(值,翻译):#精确分组格式化
    """未四舍五入的显示串。"""
    数字=str(值)#十进制
    组们=[]#三位组
    尾=len(数字)#右端
    while 尾>0:#自右切
        组们.insert(0,数字[max(0,尾-3):尾])#前插
        尾-=3#退
    if len(组们)==1:#单组
        return 组们[0]#原样
    return 翻译('number.groupSeparator').join(组们)#拼接

def 舍入百分单位(缓存读,分母,小数位):#百分单位舍入
    """正平局向上。"""
    单位每百分=1 if 小数位==0 else 10#密度
    刻度=单位每百分*100#满分单位
    双刻度=刻度*2#双倍
    主商=分母//双刻度#主商
    余数=分母%双刻度#余数
    下=0#下界
    上=刻度#上界
    while 下<上:#二分
        候选=(下+上+1)//2#偏上中点
        因子=候选*2-1#阈值因子
        阈值=因子*主商+math.ceil(因子*余数/双刻度)#阈值
        if 缓存读>=阈值:#够
            下=候选#抬
        else:#不够
            上=候选-1#压
    return 下#最大可达

def 显示百分单位(单位,小数位):#百分单位转文本
    """整数或一位小数。"""
    if 小数位==0:#整数
        return str(单位)#整
    整=单位//10#整数部分
    十分=单位%10#十分位
    return str(整) if 十分==0 else f'{整}.{十分}'#省略点

def 格式化缓存命中百分比(缓存读,提示令牌,小数位=0):#缓存命中百分比
    """不会把部分命中舍入成 100%。"""
    if 提示令牌==0:#无输入
        return None#无可报
    未命中=提示令牌-缓存读#未命中
    if 未命中==0:#全命中
        return '100'#满分
    舍入单位=舍入百分单位(缓存读,提示令牌,小数位)#普通舍入
    满分=100 if 小数位==0 else 1000#满分单位
    if 舍入单位<满分:#未触满分
        return 显示百分单位(舍入单位,小数位)#直接显示
    位数=1#区分位数
    双间隙=未命中*200#双倍间隙
    十位商=提示令牌//10#分母十位商
    while 双间隙<=十位商:#扩位
        双间隙*=10#扩
        位数+=1#加
    个位=提示令牌%10#个位
    损失=5#默认损失
    for 候 in range(1,5):#找最小诚实损失
        因子=候*2+1#阈值因子
        阈值=因子*十位商+(因子*个位)//10#阈值
        if 双间隙<=阈值:#落入
            损失=候#采用
            break#停
    return '99.'+'9'*(位数-1)+str(10-损失)#诚实上限
