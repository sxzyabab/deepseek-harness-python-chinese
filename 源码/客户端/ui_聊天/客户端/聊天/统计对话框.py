面板边距=12#视口边距（与 Menu 门户边距一致）
面板间隙=8#触发器顶边与面板底边之间的间距

# 未放置的门户面板：隐藏但仍参与布局，供钳制测量真实尺寸
测量样式={'visibility':'hidden','left':0,'top':0}#测量遍样式

class 统计对话框席:
    """单个统计对话框的打开态、引用与钳制后的放置。"""

    def __init__(自身,受控=None):
        """受控为可选 dict，含 open/setOpen；给出时席位读写该态而非自持。"""
        自身._自持打开=False#自持打开态
        自身._受控=受控#外部互斥槽
        自身.根引用=None#触发根引用
        自身.面板引用=None#面板引用
        自身.放置=None#钳制后放置样式；None 时用测量样式

    def _有效打开(自身):
        """有效打开态。"""
        if 自身._受控 is not None and 'open' in 自身._受控:#受控
            return bool(自身._受控['open'])#外部
        return 自身._自持打开#自持

    def _设打开(自身,打开):
        """设置打开态。"""
        if 自身._受控 is not None and 'setOpen' in 自身._受控:#受控
            自身._受控['setOpen'](bool(打开))#外部
        else:
            自身._自持打开=bool(打开)#自持

    @property
    def 打开(自身):
        """是否打开。"""
        return 自身._有效打开()#有效

    @打开.setter
    def 打开(自身,值):
        """设置是否打开。"""
        自身._设打开(值)#委托

    def 设打开(自身,打开):
        """设置打开（供外点关闭与 Escape）。"""
        自身._设打开(打开)#委托

    def 切换(自身):
        """翻转开合。"""
        自身._设打开(not 自身._有效打开())#翻

    def 外点关闭(自身):
        """外点 pointerdown 关闭（门户面板算内部；由宿主在指针事件上调用）。"""
        if 自身._有效打开():#打开中
            自身._设打开(False)#关

    def Escape关闭(自身):
        """Escape 关闭；仅打开时由宿主挂键监听后调用。"""
        if 自身._有效打开():#打开中
            自身._设打开(False)#关

    def 面板样式(自身):
        """门户面板样式：已放置用放置，否则测量样式。"""
        return 自身.放置 if 自身.放置 is not None else 测量样式#铺样式

    def 渲染(自身):
        """席位快照（对齐钩子返回面）。"""
        return {#席位
            'open':自身._有效打开(),#打开
            'setOpen':自身.设打开,#设置
            'rootRef':自身.根引用,#根
            'panelRef':自身.面板引用,#面板
            'pos':自身.放置,#放置
            'margin':面板边距,#边距
            'gap':面板间隙,#间隙
            'measureStyle':测量样式,#测量
            'panelStyle':自身.面板样式(),#有效样式
            'onToggle':自身.切换,#切换
            'onOutsidePointer':自身.外点关闭,#外点
            'onEscape':自身.Escape关闭,#Escape
        }#结束

    def __call__(自身,受控=None):
        """可调用席位：可选刷新受控槽后回渲染。"""
        if 受控 is not None:#有
            自身._受控=受控#刷
        return 自身.渲染()#渲

def 构造统计对话框席(受控=None):
    """一个锚定触发器的对话框席位：打开态、视口钳制放置、外点关闭。

    受控为可选 dict（open/setOpen），便于兄弟对话框共享互斥槽。
    返回席位；将 pos ?? 测量样式 铺到门户面板上。
    """
    return 统计对话框席(受控)#席位
