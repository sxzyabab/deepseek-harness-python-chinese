__all__=['用披露','绑定披露','披露席位']

class 披露席位:
    """一份初始折叠的独立披露，无外部订阅。"""
    def __init__(自身,世代=0):
        """记下重置世代。"""
        自身.世代=世代
        自身.展开世代=None

    def 是否展开(自身):
        """当前世代是否展开。"""
        return 自身.展开世代==自身.世代

    def 设展开(自身,打开):
        """显式开合。"""
        自身.展开世代=自身.世代 if 打开 else None

    def 切换(自身):
        """在开合之间切换。"""
        自身.展开世代=None if 自身.展开世代==自身.世代 else 自身.世代

def 用披露(世代=0):
    """铸造披露席位。"""
    return 披露席位(世代)

def 绑定披露(重置源):
    """到组件调用前不订阅；每次调用读当前重置世代。"""
    def 用已绑披露():
        """按重置源世代铸造席位。"""
        return 用披露(重置源.getSnapshot())
    return 用已绑披露
