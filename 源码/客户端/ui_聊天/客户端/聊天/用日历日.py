"""每个本地午夜推进的本地日历日纪元。

对齐上游 `ui-chat/src/client/chat/use-calendar-day.ts`。公开面仅中文名。
"""
import time as 时间模块#墙钟
from .消息铬 import 本地日起点,距下一本地午夜毫秒#午夜边界

__all__=['用日历日','日历日席位']#仅中文公开名

def 用日历日(现在=None):#本地日历日席位
    """当前本地日的午夜毫秒。"""
    if 现在 is None:#缺省
        现在=int(时间模块.time()*1000)#墙钟
    return 本地日起点(现在)#当日午夜

class 日历日席位:#可推进日席位
    """挂载后武装午夜定时器的逻辑结构。"""

    def __init__(自身):#构造
        """初始为当日午夜。"""
        自身.日=用日历日()#初始
        自身._定时=None#句柄占位

    def 武装(自身,现在=None):#武装到下一午夜
        """推进日席位并返回距下一午夜毫秒。"""
        if 现在 is None:#缺省
            现在=int(时间模块.time()*1000)#墙钟
        自身.日=本地日起点(现在)#推进
        return 距下一本地午夜毫秒(现在)#延迟

    def 当前(自身):#读当前日
        """当前本地日午夜毫秒。"""
        return 自身.日#日
