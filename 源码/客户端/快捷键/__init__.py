快捷键配置全局键='__DSH_SHORTCUTS_CONFIG__'#页面注入键
默认中止序列毫秒=500#默认间隔
定时器上限毫秒=2147483646#自然数上限

配置=字典字段(字典结构={
    'stopSequenceMs':自然数字段(最小=1,最大=定时器上限毫秒,默认值=默认中止序列毫秒),
})

def 解析快捷键配置(原始):
    """收成带默认值的注入载荷。"""
    表={} if 原始 is None else dict(原始)#表
    毫秒=表['stopSequenceMs'] if 'stopSequenceMs' in 表 and 表['stopSequenceMs'] is not None else 默认中止序列毫秒#间隔
    return {'stopSequenceMs':毫秒}#载荷

def 应用(上下文,配置值=None):
    """把已校验的键盘时序写入页面初始化表。"""
    已解析=解析快捷键配置(配置值)#解析
    def 注入(表):
        """追加一条全局注入。"""
        表.append({'kind':'global','name':快捷键配置全局键,'value':已解析})#注入
    上下文.监听('webserver/index-inject',注入)#登记

apply=应用#框架槽
Config=配置#框架槽
