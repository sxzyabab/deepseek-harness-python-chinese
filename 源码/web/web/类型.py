"""web 能力缝（`ctx.web`）的词汇。搜索与抓取有意共用一个缝，使提供方选择、取消、错误和产品配置只有一个拥有方，同时保留各自的请求与结果类型。"""
from llm import 装备错误#导入harness错误基类

网络搜索请求字段=('query','maxResults')#一次搜索请求：查询字符串，以及可选的返回来源上限
网络搜索结果字段=('content','sources','truncated')#归一化搜索结果：可选提供方生成文本、可引用来源列表、是否被缝截断
网络搜索来源字段=('url','title','snippet','publishedAt')#一条可引用来源：必填URL，可选标题、摘要与ISO-8601发布时间
网络抓取请求字段=('url',)#一次抓取请求：要取回的URL
网络抓取结果字段=('url','statusCode','body','truncated')#归一化抓取结果：最终URL、HTTP状态码、已解码正文、正文是否被提供方截断
网络抓取正文种类=('html','text')#封闭的抓取正文种类：HTML或纯文本；消费方对kind穷尽分支
网络搜索提供方字段=('id','available','search')#搜索提供方：稳定id、本地可用性检查、执行搜索
网络抓取提供方字段=('id','available','fetch')#抓取提供方：稳定id、本地可用性检查、执行抓取

class 网络错误(装备错误):#带机器可路由开放字符串code与链式cause的类型化web错误
    """带机器可路由开放字符串 code 与链式 cause 的类型化 web 错误。消费方必须容忍提供方特有码。共享码覆盖不可用、缺失、歧义或重复提供方、取消以及提供方失败；本地抓取提供方额外区分无效或被拦 URL、重定向、大小与超时限制，以及不支持的内容类型。工具执行把该码暴露在结构化错误元数据里。"""
    def __init__(自身,消息,码,选项=None):#记下稳定code并把cause链到本错误
        """记下稳定 code，并把 cause 链到本错误。"""
        装备错误.__init__(自身,消息,码,选项)#交给装备错误基类
        自身.name='WebError'#与公开类名一致
