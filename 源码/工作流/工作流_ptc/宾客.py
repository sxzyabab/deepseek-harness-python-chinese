from ...基础设施.通用工具 import 启动守护线程
from ...基础设施.js特性 import PromiseEX as 期约#中文期约
from .领域 import 渲染抛出#进度失败文本
from .运行时 import 工作流执行#执行

__all__=['运行工作流宾客']#仅中文公开名

def 运行工作流宾客(宿主):#一次进度批次在飞
    """一次进度批次在飞。
    子拆除与终态结果前排空进度；PTC 与宿主拥有取消与清理。
    宿主是本运行拥有的 JSON 回调。
    初始化失败则抛
    """
    初始化=宿主.开始({})#引导
    排队=[]#未发进度
    在飞=[None]#进行中的进度任务
    进度错误=[None]#进度失败文本
    def 冲刷():#发出一批
        '没有在飞且有排队时发出一批'
        if 在飞[0] is not None or len(排队)==0:#忙或空
            return#忽略
        批次=list(排队)#本批
        排队.clear()#清空
        完成=期约()#本批任务
        在飞[0]=完成#记下
        def 发批次():#后台发
            '发给宿主再冲刷或记下失败'
            try:#发送
                宿主.进度(批次)#一批
                在飞[0]=None#先空出
                冲刷()#下一批先挂上，排空才看得见
                完成.解决(None)#完成
            except BaseException as 错误:#失败
                进度错误[0]=渲染抛出(错误)#记下
                排队.clear()#丢掉
                在飞[0]=None#空出
                完成.解决(None)#进度失败不拒绝宾客主路径
        启动守护线程(发批次)#后台
    def 发送(事件):#一条进度
        '排队并尝试冲刷'
        if 进度错误[0] is not None:#已失败
            return#忽略
        排队.append(事件)#入队
        冲刷()#首批在同步脚本占循环前到达宿主
    def 排空():#等在飞结束
        '返回期约，在飞批次都解决后兑现'
        结局=期约()#排空结果
        def 再看(值=None):#看下一批
            '没有在飞则解决，否则再等'
            if 在飞[0] is None:#没有
                结局.解决(None)#排空
                return#结束
            在飞[0].然后(再看,再看)#等本批
        再看()#开始
        return 结局#期约
    class 观察器:#进度观察
        '把执行进度变成宿主事件'
        def 阶段(自身,标题):#阶段
            '发 phase'
            发送({'type':'phase','title':标题})#阶段
        def 日志(自身,消息):#日志
            '发 log'
            发送({'type':'log','message':消息})#日志
        def 智能体开始(自身,信息):#开始
            '发 agent-start'
            发送({'type':'agent-start','info':信息})#开始
        def 智能体结束(自身,信息):#结束
            '发 agent-end'
            发送({'type':'agent-end','info':信息})#结束
    class 子端口:#子回调
        '经宿主绑定启动、观察与拆除子'
        def 启动智能体(自身,请求):#发布一个子
            '启动并包成宾客句柄'
            引用=宿主.启动子(请求)#发布
            调用标识=引用['callId']#回调 id
            子标识=引用['childId']#子 id
            结果任务=期约()#子结果
            def 等结果():#后台等
                '等宿主子结果'
                try:#取结果
                    值=宿主.子结果({'callId':调用标识})#结果或期约
                except BaseException as 错误:#基础设施
                    结果任务.拒绝(错误)#拒绝
                    return#结束
                def 成功(内值):#子终态
                    '解决子结果'
                    结果任务.解决(内值)#解决
                def 失败(错误):#子拒绝
                    '拒绝子结果'
                    结果任务.拒绝(错误)#拒绝
                然后方法=getattr(值,'然后',None)#期约
                if callable(然后方法):#期约
                    然后方法(成功,失败)#接上
                    return#已接上
                成功(值)#普通值
            启动守护线程(等结果)#启动
            class 句柄:#宾客句柄
                '已发布子句柄'
                def __init__(自身):#钉字段
                    '记下 id 与结果任务'
                    自身.id=子标识#子 id
                    自身.result=结果任务#结果
                def 销毁(自身):#拆除
                    '先排空进度再请宿主拆除，返回期约'
                    def 请拆除(值=None):#进度已排空
                        '请宿主拆除'
                        return 宿主.拆除子({'callId':调用标识})#拆除
                    return 排空().然后(请拆除)#期约
            return 句柄()#句柄
    执行=工作流执行(初始化['meta'],初始化['body'],初始化['args'] if 'args' in 初始化 else None,初始化['limits'],观察器(),子端口())#执行
    结局=期约()#宾客结果
    def 完成驱动(结果):#脚本已落定
        '排空进度后解决宾客结果'
        def 排空之后(值=None):#进度已排空
            '进度失败盖过脚本结果'
            if 进度错误[0] is None:#进度成功
                结局.解决(结果)#脚本结果
                return#结束
            结局.解决({'value':None,'stopReason':'error','error':进度错误[0],'agentsStarted':结果['agentsStarted']})#进度失败
        def 排空失败(错误):#排空拒绝
            '排空失败则拒绝'
            结局.拒绝(错误)#拒绝
        排空().然后(排空之后,排空失败)#终态前排空
    def 驱动失败(错误):#驱动拒绝
        '驱动失败则拒绝'
        结局.拒绝(错误)#拒绝
    执行.驱动().然后(完成驱动,驱动失败)#驱动
    return 结局#期约
