from ...模型后端.llm.异常 import 装备错误#智能体错误基类

class 工作流错误(装备错误):#工作流缝的带类型错误
    """工作流缝失败的带类型错误。
    继承装备错误，因此 code 是可机器路由的分类。
    致命标志决定组合子纪律：parallel()/pipeline() 会再抛出致命错误（写错的选项或触顶的上限必须大声杀掉脚本），并把每项的 null 留给子运行失败和阶段内普通脚本错误。
    每一个工作流错误码都是致命的；该标志存在是为了让每个 catch 点显式区分，而不是靠暗示
    """
    def __init__(自身,消息,码,选项=None):#构造工作流错误
        '记下稳定 code、链式 cause，以及致命标志（未指定时视为致命）'
        装备错误.__init__(自身,消息,码,选项)#交给智能体错误基类
        自身.name='WorkflowError'#固定错误名，对齐 Error.name 习惯
        致命=True#默认致命
        if isinstance(选项,dict) and 'fatal' in 选项:#选项给出 fatal
            致命=选项['fatal']#取显式值
            if 致命 is None:#显式 None 仍按默认
                致命=True#未指定时视为致命
        自身.致命=致命#致命标志
