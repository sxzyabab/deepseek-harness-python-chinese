"""共享请求投影几何。"""
import math#开方
__all__=['请求图像尺寸','长边尺寸']#仅中文公开名

def 请求图像尺寸(宽,高,最大像素):#在硬像素预算内保持纵横比的整数尺寸
    """在硬总像素预算内计算保持纵横比的向内取整尺寸；小图不放大。"""
    缩放=min(1.0,math.sqrt(最大像素/(宽*高)))#总像素缩放因子
    if 缩放==1.0:#无需缩放
        return {'width':宽,'height':高}#原尺寸
    if 宽>=高:#以宽为主导边
        投影宽=max(1,宽*缩放//1)#向内取整宽
        投影高=max(1,round(投影宽*高/宽))#保持比例的高
        while 投影宽*投影高>最大像素 and 投影宽>1:#仍超预算则减宽
            投影宽-=1#减一像素宽
            投影高=max(1,round(投影宽*高/宽))#重算高
        return {'width':投影宽,'height':投影高}#结果
    投影高=max(1,高*缩放//1)#以高为主导边
    投影宽=max(1,round(投影高*宽/高))#保持比例的宽
    while 投影宽*投影高>最大像素 and 投影高>1:#仍超预算则减高
        投影高-=1#减一像素高
        投影宽=max(1,round(投影高*宽/高))#重算宽
    return {'width':投影宽,'height':投影高}#结果

def 长边尺寸(宽,高,长边):
    """按精确长边保持纵横比；短边四舍五入到最近像素，等同编码器只按长边缩放。"""
    if 长边>=max(宽,高):#目标不小于源
        return {'width':宽,'height':高}#原样
    if 宽>=高:#宽是长边
        return {'width':长边,'height':max(1,round(长边*高/宽))}#按宽
    return {'width':max(1,round(长边*宽/高)),'height':长边}#按高
