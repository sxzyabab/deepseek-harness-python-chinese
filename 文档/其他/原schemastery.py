def 解析任意(数据,模式实例,选项,严格=False):
    """任意值原样通过。"""
    return [数据]#原样

def 格式化任意(模式实例,内联=False):
    """any。"""
    return 'any'#类型文本

def 解析常量(数据,模式实例,选项,严格=False):
    """输入必须深等于常量。"""
    if 深入比较(数据,模式实例.常量值):
        return [模式实例.常量值]#命中常量
    raise 校验错误(f'期望 {模式实例.常量值}，实际是 {数据}',选项)#不匹配

def 格式化常量(模式实例,内联=False):
    """常量字面量，字符串带引号。"""
    值=模式实例.常量值#常量取值
    return json.dumps(值,ensure_ascii=False) if isinstance(值,str) else str(值)#字面量文本

def 解析字符串(数据,模式实例,选项,严格=False):
    """校验字符串本身与它的长度。"""
    if not isinstance(数据,str):
        raise 校验错误(f'期望字符串，实际是 {数据}',选项)#类型不符
    检查范围(len(数据),模式实例.元数据,'字符串长度',选项)#长度区间
    return [数据]#通过

def 格式化字符串(模式实例,内联=False):
    """string。"""
    return 'string'#类型文本

def 解析数字(数据,模式实例,选项,严格=False):
    """校验数字、区间与步进。"""
    if isinstance(数据,bool) or not isinstance(数据,(int,float)):
        raise 校验错误(f'期望数字，实际是 {数据}',选项)#类型不符
    检查范围(数据,模式实例.元数据,'数值',选项)#数值区间
    步长=模式实例.元数据.get('步进')#步进约束
    if 步长 and not 是否倍数(数据,模式实例.元数据.get('最小') or 0,步长):
        raise 校验错误(f'期望是 {步长} 的整数倍，实际是 {数据}',选项)#不是整数倍
    return [数据]#通过

def 格式化数字(模式实例,内联=False):
    """number。"""
    return 'number'#类型文本

def 解析布尔(数据,模式实例,选项,严格=False):
    """校验布尔。"""
    if isinstance(数据,bool):
        return [数据]#通过
    raise 校验错误(f'期望布尔值，实际是 {数据}',选项)#类型不符

def 格式化布尔(模式实例,内联=False):
    """boolean。"""
    return 'boolean'#类型文本

def 解析数组(数据,模式实例,选项,严格=False):
    """校验数组长度与每一个元素。"""
    if not isinstance(数据,list):
        raise 校验错误(f'期望数组，实际是 {数据}',选项)#类型不符
    跳过下限=模式实例.内层 is not None and 模式实例.内层.元数据.get('默认') is not None#元素能补默认值就不卡下限
    检查范围(len(数据),模式实例.元数据,'数组长度',选项,跳过下限)#长度区间
    结果=[]#逐项解析结果
    非法下标=[]#自动修复要删掉的下标
    for 下标 in range(len(数据)):
        try:
            结果.append(解析属性(数据,下标,模式实例.内层,选项))#解析一项
        except Exception:
            if not 选项.get('自动修复'):
                raise#不自动修复就把错误抛出去
            非法下标.append(下标)#记下来，逐项解析完再删
            结果.append(模式实例.内层.元数据.get('默认'))#回落到默认值
    for 下标 in reversed(非法下标):
        del 数据[下标]#从后往前删，前面的下标才不会挪位
    return [结果]#逐项解析

def 格式化数组(模式实例,内联=False):
    """元素类型加方括号。"""
    return f'{模式实例.内层.转字符串(True)}[]'#类型文本

def 解析字典(数据,模式实例,选项,严格=False):
    """校验映射的键与值。"""
    if not isinstance(数据,dict):
        raise 校验错误(f'期望对象，实际是 {数据}',选项)#类型不符
    结果={}#归一化输出
    for 键 in list(数据):
        try:
            规范键=模式.解析(键,模式实例.键模式,选项)[0]#键也要过模式
        except Exception:
            if 严格:
                continue#严格模式下丢掉非法键
            raise#非严格就把错误抛出去
        结果[规范键]=解析属性(数据,键,模式实例.内层,选项)#解析值
        if 键!=规范键:
            数据[规范键]=数据.pop(键)#把归一化后的键写回输入
    return [结果]#通过

def 格式化字典(模式实例,内联=False):
    """索引签名形式。"""
    return f'{{ [key: {模式实例.键模式.转字符串()}]: {模式实例.内层.转字符串()} }}'#类型文本

def 解析对象(数据,模式实例,选项,严格=False):
    """按字段表校验对象。"""
    if not isinstance(数据,dict):
        raise 校验错误(f'期望对象，实际是 {数据}',选项)#类型不符
    结果={}#归一化输出
    for 键,字段模式 in (模式实例.字段表 or {}).items():
        值=解析属性(数据,键,字段模式,选项)#解析字段
        if 值 is not None or 键 in 数据:
            结果[键]=值#有值，或者输入里确实写了这个键
    if not 严格:
        补充数据(结果,数据)#未声明的键原样保留
    return [结果]#通过

def 格式化对象(模式实例,内联=False):
    """花括号字段列表。"""
    字段表=模式实例.字段表 or {}#字段模式
    if not 字段表:
        return '{}'#空对象
    片段=[f'{键}{"" if 内层.元数据.get("必填") else "?"}: {内层.转字符串()}' for 键,内层 in 字段表.items()]#逐字段
    return '{ '+', '.join(片段)+' }'#类型文本

def 解析联合(数据,模式实例,选项,严格=False):
    """命中任何一个成员就算通过。"""
    for 内层 in 模式实例.成员表 or []:
        try:
            return 模式.解析(数据,内层,选项,严格)#命中就直接交出
        except Exception:
            continue#这一支不匹配，试下一支
    raise 校验错误(f'期望 {模式实例.转字符串()}，实际是 {json.dumps(数据,default=str,ensure_ascii=False)}',选项)#全都不匹配

def 格式化联合(模式实例,内联=False):
    """竖线分隔的各支。"""
    文本=' | '.join(内层.转字符串() for 内层 in 模式实例.成员表)#各支类型
    return f'({文本})' if 内联 else 文本#内联时加括号

def 定义类型(类型标签,参数名们,解析,格式化):
    """登记一个类型的解析与格式化，并返回建该类型节点的工厂。"""
    _解析器表[类型标签]=解析#解析函数
    _格式化表[类型标签]=格式化#格式化函数
    def 工厂(类,*位置参数):
        """按参数名顺序把位置参数装到新节点上。"""
        节点=模式({'类型':类型标签})#新节点
        for 下标,参数名 in enumerate(参数名们):
            参数=位置参数[下标] if 下标<len(位置参数) else None#对应位置参数
            if 参数名=='键模式':
                节点.键模式=参数 if 参数 is not None else 模式.字符串()#字典键默认是字符串
            elif 参数名=='内层':
                节点.内层=模式.推断(参数)#推断元素模式
            elif 参数名=='成员表':
                节点.成员表=[模式.推断(项) for 项 in 参数]#推断各支模式
            elif 参数名=='字段表':
                节点.字段表=字典值转换(参数,lambda 项,键:模式.推断(项))#推断各字段模式
            else:
                setattr(节点,参数名,参数)#常量值等直接写
        if 类型标签 in ('object','dict'):
            节点.元数据['默认']={}#对象与字典默认是空映射
        elif 类型标签=='array':
            节点.元数据['默认']=[]#数组默认是空列表
        return 节点#新节点
    return 工厂#工厂

