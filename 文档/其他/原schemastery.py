"""配置模式：声明式校验并归一化配置对象。"""
import json,math,re
from cosmokit import 克隆,深入比较,字典值转换#深克隆、深比较与批量变换

_下一序号=0#模式节点序号计数器
_序列化引用=None#转JSON 期间共享的引用表
_解析器表={}#类型标签到解析函数
_格式化表={}#类型标签到格式化函数

class 校验错误(TypeError):
    """配置没通过模式校验。"""
    def __init__(自身,消息,选项):
        """把出错位置的路径拼到消息前面。"""
        前缀=''#出错位置
        for 片段 in 选项.get('路径') or []:
            前缀+=f'[{片段}]' if isinstance(片段,int) else ('.'+str(片段) if 前缀 else str(片段))#下标或键
        super().__init__(f'{前缀} {消息}' if 前缀 else 消息)#带位置的消息
        自身.选项=选项#出错时的解析选项

def 检查范围(数据,元数据,描述,选项,跳过下限=False):
    """按元数据里的最小、最大检查数值区间。"""
    上限=元数据.get('最大')#包含式上限
    if 上限 is not None and 数据>上限:
        raise 校验错误(f'期望{描述}不大于 {上限}，实际是 {数据}',选项)#超过上限
    下限=元数据.get('最小')#包含式下限
    if 下限 is not None and not 跳过下限 and 数据<下限:
        raise 校验错误(f'期望{描述}不小于 {下限}，实际是 {数据}',选项)#低于下限

def 十进制移位(数据,位数):
    """把小数点右移指定位数，避开浮点乘法的精度损失。"""
    文本=str(数据)#数字的十进制文本
    if 'e' in 文本 or 'E' in 文本 or '.' not in 文本:
        return 数据*math.pow(10,位数)#科学计数法与整数拆不出小数部分
    整数,小数=文本.split('.')#拆成两段
    if len(小数)<=位数:
        return float(整数+小数.ljust(位数,'0'))#右边补零
    return float(整数+小数[:位数]+'.'+小数[位数:])#在新位置插回小数点

def 是否倍数(数据,起点,步长):
    """判断数据相对起点是不是步长的整数倍。"""
    步长=abs(步长)#只看大小
    文本=str(步长)#步长的十进制文本
    if not re.match(r'^\d+\.\d+$',文本):
        return (数据-起点)%步长==0#整数步长直接取模
    位数=len(文本.split('.')[1])#小数位数
    return abs(十进制移位(数据,位数)-十进制移位(起点,位数))%十进制移位(步长,位数)==0#整数化后取模

def 有该键(数据,键):
    """数据上是否存在该键。"""
    if isinstance(数据,list):
        return isinstance(键,int) and 0<=键<len(数据)#下标合法
    if isinstance(数据,dict):
        return 键 in 数据#映射有该键
    return False#其它形态没有键

def 整理为二元组(结果):
    """把解析结果整理成 输出值 与 回写值 两项。"""
    if not isinstance(结果,(list,tuple)):
        return 结果,None#单值没有回写
    if len(结果)==1:
        return 结果[0],None#只有输出值
    return 结果[0],结果[1]#输出值与回写值

def 补充数据(目标,数据):
    """把目标里没有声明的键从原数据补上。"""
    for 键 in 数据:
        if 键 not in 目标:
            目标[键]=数据[键]#未声明的键原样保留

def 解析属性(数据,键,模式实例,选项):
    """解析对象或数组上的一个属性，路径带上该键。"""
    try:
        子选项=dict(选项)#不改动调用方的选项
        子选项['路径']=list(选项.get('路径') or [])+[键]#追加当前键
        值,回写=整理为二元组(模式.解析(数据[键] if 有该键(数据,键) else None,模式实例,子选项))#解析
        if 回写 is not None:
            数据[键]=回写#把归一化结果写回输入
        return 值#属性值
    except Exception:
        if not 选项.get('自动修复') or not isinstance(数据,dict):
            raise#不自动修复，或者数组由 解析数组 自己收尾
        数据.pop(键,None)#删掉非法键
        return 模式实例.元数据.get('默认')#回落到默认值

class 模式:
    """可直接调用的模式节点，校验输入并交出归一化输出。"""
    def __new__(类,选项=None):
        """带引用表的选项表示一棵序列化过的模式树，先把它还原回来。"""
        选项=选项 or {}#空选项
        引用表=选项.get('引用') if isinstance(选项,dict) else getattr(选项,'引用',None)#序列化引用表
        if not 引用表:
            return object.__new__(类)#普通构造，交给 __init__ 装配
        还原=字典值转换(引用表,lambda 项,键:模式._直接装配(项))#先各自还原成节点
        for 节点 in 还原.values():
            if 节点.键模式 is not None:
                节点.键模式=还原[str(节点.键模式)]#序号换回节点
            if 节点.内层 is not None:
                节点.内层=还原[str(节点.内层)]#序号换回节点
            if 节点.成员表 is not None:
                节点.成员表=[还原[str(项)] for 项 in 节点.成员表]#序号换回节点
            if 节点.字段表 is not None:
                节点.字段表=字典值转换(节点.字段表,lambda 项,键:还原[str(项)])#序号换回节点
        return 还原[str(选项.get('序号') if isinstance(选项,dict) else 选项.序号)]#根节点

    @staticmethod
    def _直接装配(选项):
        """不走引用还原地建一个节点。"""
        实例=object.__new__(模式)#空实例
        实例._装配(选项 if isinstance(选项,dict) else 选项.__dict__)#装配字段
        return 实例#已装配节点

    def __init__(自身,选项=None):
        """把选项装配到本节点上。"""
        if getattr(自身,'_已装配',False):
            return#引用还原路径已经装配过了
        自身._装配(选项 or {})#装配字段

    def _装配(自身,选项):
        """把选项里的字段写到节点上并分配序号。"""
        global _下一序号#序号计数器
        if isinstance(选项,模式):
            选项=选项._导出选项()#从另一个节点复制
        自身.类型=选项.get('类型')#类型标签
        自身.元数据=dict(选项.get('元数据') or {})#默认值、约束与展示信息
        自身.键模式=选项.get('键模式')#字典的键模式
        自身.内层=选项.get('内层')#数组元素或字典值的模式
        自身.成员表=选项.get('成员表')#联合的成员模式
        自身.字段表=选项.get('字段表')#对象的字段模式
        自身.常量值=选项.get('常量值')#常量模式的取值
        自身.序号=_下一序号#节点序号，序列化时用
        _下一序号+=1#下一个序号
        自身._已装配=True#避免 __init__ 重复装配

    def _导出选项(自身):
        """导出一份可用来复制本节点的选项。"""
        return {
            '类型':自身.类型,#类型标签
            '元数据':dict(自身.元数据),#元数据副本
            '键模式':自身.键模式,#键模式
            '内层':自身.内层,#内层模式
            '成员表':list(自身.成员表) if 自身.成员表 is not None else None,#成员副本
            '字段表':dict(自身.字段表) if 自身.字段表 is not None else None,#字段副本
            '常量值':自身.常量值,#常量取值
        }#选项

    def __call__(自身,数据=None,选项=None):
        """校验输入并交出归一化输出。"""
        return 模式.解析(数据,自身,选项 or {})[0]#只要输出值

    def __str__(自身):
        """收成紧凑的类型文本。"""
        return 自身.转字符串()#默认不内联

    def 转字符串(自身,内联=False):
        """收成紧凑的类型文本，内联时联合会加括号。"""
        格式化=_格式化表.get(自身.类型)#该类型的格式化函数
        return 格式化(自身,内联) if 格式化 else f'模式<{自身.类型}>'#没登记就退回类型标签

    #============================== 元数据 ==============================
    def 额外(自身,键,值):
        """复制一份本节点，并在它的元数据上挂一项。"""
        克隆节点=模式(自身._导出选项())#复制节点
        克隆节点.元数据[键]=值#写入元数据
        return 克隆节点#新节点

    def 必填(自身,值=True):
        """标记空输入非法，除非有默认值能补上。"""
        return 自身.额外('必填',值)#必填

    def 默认(自身,值):
        """设置空输入时的回落值。"""
        return 自身.额外('默认',值)#默认值

    def 描述(自身,文本):
        """挂上给人看的描述文案。"""
        return 自身.额外('描述',文本)#描述

    def 最大(自身,值):
        """设置包含式上限。"""
        return 自身.额外('最大',值)#上限

    def 最小(自身,值):
        """设置包含式下限。"""
        return 自身.额外('最小',值)#下限

    def 步进(自身,值):
        """设置数字的步进约束。"""
        return 自身.额外('步进',值)#步长

    def 角色(自身,角色名,额外=None):
        """挂上界面渲染角色与可选的附加信息。"""
        克隆节点=自身.额外('角色',角色名)#写入角色
        克隆节点.元数据['角色附加']=额外#附加信息
        return 克隆节点#新节点

    #============================== 序列化 ==============================
    def 转JSON(自身):
        """序列化本模式，共享节点与递归引用都收成序号。"""
        global _序列化引用#序列化引用表
        引用键=str(自身.序号)#引用表的键，走一遍 JSON 之后也还是它
        if _序列化引用 is not None:
            if 引用键 not in _序列化引用:
                _序列化引用[引用键]=None#先占位，挡住递归
                _序列化引用[引用键]=自身._可序列化()#再展开
            return 自身.序号#内层只交出序号
        _序列化引用={}#本次序列化的引用表
        try:
            _序列化引用[引用键]=None#先占位，挡住递归
            _序列化引用[引用键]=自身._可序列化()#展开根节点
            return {'序号':自身.序号,'引用':_序列化引用}#带引用表的根
        finally:
            _序列化引用=None#清掉引用表

    def _可序列化(自身):
        """把本节点导出成可 JSON 化的字段，内层模式换成序号。"""
        数据=自身._导出选项()#节点字段
        数据['序号']=自身.序号#带上序号
        数据['键模式']=自身.键模式.转JSON() if 自身.键模式 is not None else None#换成序号
        数据['内层']=自身.内层.转JSON() if 自身.内层 is not None else None#换成序号
        数据['成员表']=[项.转JSON() for 项 in 自身.成员表] if 自身.成员表 is not None else None#换成序号
        数据['字段表']=字典值转换(自身.字段表,lambda 项,键:项.转JSON()) if 自身.字段表 is not None else None#换成序号
        return {键:值 for 键,值 in 数据.items() if not callable(值)}#丢掉不能序列化的函数

    @property
    def 标准协议(自身):
        """Standard Schema V1 适配，供外部校验器直接消费。"""
        def 校验(值):
            """按标准协议返回成功值或问题列表。"""
            try:
                return {'value':模式.解析(值,自身,{})[0]}#校验通过
            except 校验错误 as 错误:
                return {'issues':[{'message':str(错误),'path':错误.选项.get('路径')}]}#校验失败
        return {'version':1,'vendor':'schemastery','validate':校验}#协议对象

    #============================== 解析 ==============================
    @staticmethod
    def 扩展(类型标签,解析):
        """为自定义类型登记解析函数。"""
        _解析器表[类型标签]=解析#登记

    @staticmethod
    def 解析(数据,模式实例,选项=None,严格=False):
        """按模式节点校验，返回 [输出值] 或 [输出值, 回写值]。"""
        选项=选项 if 选项 is not None else {}#默认选项
        if not 模式实例:
            return [数据]#没有模式就原样通过
        忽略=选项.get('忽略')#跳过校验的谓词
        if 忽略 and 忽略(数据,模式实例):
            return [数据]#被谓词跳过
        if 数据 is None:
            if 模式实例.元数据.get('必填'):
                raise 校验错误('缺少必填值',选项)#必填却没给
            回落=模式实例.元数据.get('默认')#默认值
            if 回落 is None:
                return [数据]#没有默认值，空值原样通过
            数据=克隆(回落)#默认值每次都给一份新的
        解析器=_解析器表.get(模式实例.类型)#该类型的解析函数
        if 解析器 is None:
            raise 校验错误(f'不支持的模式类型 "{模式实例.类型}"',选项)#类型没登记
        try:
            return 解析器(数据,模式实例,选项,严格)#解析
        except Exception:
            if not 模式实例.元数据.get('宽松'):
                raise#不宽松就把错误抛出去
            return [模式实例.元数据.get('默认')]#宽松模式回落到默认值

    @staticmethod
    def 推断(源=None):
        """从字面量、内建类型或已有模式推断出模式。"""
        if 源 is None:
            return 模式.任意()#没给就当任意
        if getattr(源,'_已装配',False):
            return 源#已经是模式
        if isinstance(源,type):
            if 源 is str:
                return 模式.字符串().必填()#字符串
            if 源 is bool:
                return 模式.布尔().必填()#布尔
            if 源 is int or 源 is float:
                return 模式.数字().必填()#数字
        elif isinstance(源,(str,bool,int,float)):
            return 模式.常量(源).必填()#字面量当常量
        raise TypeError(f'无法从 {源} 推断出模式')#不认识的形态

    @staticmethod
    def 自然数():
        """非负整数。"""
        return 模式.数字().步进(1).最小(0)#自然数

