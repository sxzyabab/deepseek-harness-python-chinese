"""随纤程生命周期一起拆除的定时器服务。"""
import threading
from . import cordis

class 定时器服务(cordis.服务):
    """混入上下文的定时辅助，登记的定时器随纤程拆除一并取消。"""
    def __init__(自身,上下文,配置=None):
        """把本实例以定时器服务名登记进当前上下文。"""
        cordis.服务.__init__(自身,上下文,'定时器')#登记服务
        自身.上下文.混入成员('定时器',['防抖'])#只挂仓库在用的防抖

    def 防抖(自身,回调,延迟毫秒):
        """返回一个防抖函数：连续调用只保留最后一次，纤程拆除后不再触发。"""
        当前定时器=[None]#等待中的定时器
        已拆除=[False]#纤程是否已经拆掉本防抖
        状态锁=threading.Lock()#定时器线程与调用方共用
        def 执行体():
            """登记拆除时取消等待中的定时器。"""
            def 释放():
                """标记已拆除并取消等待中的定时器。"""
                with 状态锁:
                    已拆除[0]=True#之后的调用不再排队
                    if 当前定时器[0] is not None:
                        当前定时器[0].cancel()#取消等待中的定时器
                        当前定时器[0]=None#清空
            return 释放#释放器
        拆除=自身.上下文.副作用(执行体,'上下文.防抖()')#挂到当前纤程
        def 触发(*位置参数):
            """定时器线程里的触发点，拆除后不再调用回调。"""
            with 状态锁:
                if 已拆除[0]:
                    return#定时器已经启动但纤程先拆了
                当前定时器[0]=None#本拍用掉了
            回调(*位置参数)#跑回调
        def 包装(*位置参数):
            """取消上一拍，按新参数重排一次延迟回调。"""
            with 状态锁:
                if 当前定时器[0] is not None:
                    当前定时器[0].cancel()#清掉上一拍
                    当前定时器[0]=None#清空
                if 已拆除[0]:
                    return#已经拆掉，不再排队
                当前定时器[0]=threading.Timer(延迟毫秒/1000,触发,位置参数)#新的一拍
                当前定时器[0].start()#启动
        包装.拆除=拆除#让调用方能提前取消
        return 包装#防抖函数

默认=定时器服务#模块的默认插件导出
