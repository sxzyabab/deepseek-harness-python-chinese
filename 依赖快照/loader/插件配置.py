def 更新错误(阶段,选项,原因):
    """把插件配置生命周期失败收成一条带原因的错误。"""
    错误=Exception(f'插件配置 {选项.get("id")}（{选项.get("name")}）{阶段}失败：{原因}')#拼接消息
    错误.__cause__=原因 if isinstance(原因,BaseException) else None#保留原因
    return 错误#交给调用方抛出

def 排序键(选项:dict)->dict:
    "把 id、name 提到最前，config 放到最后，其余键按名排序"
    前置=[键 for 键 in ('id','name') if 键 in 选项]#固定在最前的键
    后置=[键 for 键 in ('config',) if 键 in 选项]#固定在最后的键
    其余=sorted(键 for 键 in 选项 if (键 not in 前置) and (键 not in 后置))#其余按名排序
    重排={键:选项[键] for 键 in 前置+其余+后置}
    return 替换键(选项,重排)

def 替换键(目标:dict,源:dict)->dict:
    "将目标的键替换为源的键,不创建新对象"
    目标.clear()
    目标.update(源)
    return 目标

def _合并选项(原选项:dict,新选项:dict)->dict:
    "把新选项合并到原选项的副本上，值为空表示删掉该键"
    候选=dict(原选项)#原选项副本
    for 键,值 in 新选项.items():
        if 值 is None:
            候选.pop(键,None)#空值表示删键
        else:
            候选[键]=值#写入新值
    return 候选#合并结果

class 插件配置:
    键='插件配置'#属性链上登记本对象的键名
    def __init__(自身,加载器):
        "建立插件配置上下文并公布它的创建"
        自身.加载器=加载器#所属加载器
        自身.所属上下文=加载器.所属上下文#带插件配置标记的子上下文
        自身.事件上下文=自身.所属上下文#派发框架事件的上下文
        自身.纤程=None#这份配置当前运行的插件纤程
        自身.父组=None#所属插件组
        自身.选项={}#写在配置文件里的选项
        自身.子组=None#这份配置自身挂的嵌套组
        自身.子树=None#这份配置自身挂的嵌套树
        自身.本地域=None#隔离钩子按需建立的本层隔离域
        自身._拆除中=0#拆除嵌套计数
        自身.事件上下文.广播('loader/entry-init',自身)#通知隔离钩子

    @property
    def 编号(自身):
        "带上祖先树前缀的稳定编号"
        from .插件树 import 插件树#嵌套编号分隔符
        编号=自身.选项['id']#本树内的编号
        祖先配置=自身.父组.所属树.所属上下文.纤程.插件配置#拥有本树的插件配置
        if 祖先配置 is not None:
            编号=祖先配置.编号+插件树.分隔+编号#加上祖先前缀
        return 编号#完整编号

    @property
    def 已禁用(自身):
        "本层或任一拥有它的祖先被禁用时为真"
        return 自身._已禁用(自身.选项)#按当前选项计算

    def _已禁用(自身,选项):
        "按给定选项算出有效禁用态"
        if 选项.get('group'):
            return False#组永远启用
        if 自身._禁用自(选项):
            return True#本层就禁用了
        祖先=自身.父组.所属上下文.纤程.插件配置#父纤程所属插件配置
        while 祖先 is not None:
            if 自身._禁用自(祖先.选项):
                return True#祖先禁用
            祖先=祖先.父组.所属上下文.纤程.插件配置#继续上溯
        return False#没有被禁用

    def _禁用自(自身,选项):
        "算一层的禁用态。表达式节点对照本层上下文求值，写回时仍保留原节点"
        禁用=选项.get('disabled')#禁用项
        if 是否表达式节点(禁用):
            return bool(自身.求值(取表达式(禁用)))#求值后取布尔
        return bool(禁用)#字面量布尔

    def 求值(自身,表达式):
        "对照本层的上下文求值一段表达式"
        return 求值(自身.所属上下文,表达式)#求值

    def 取外层栈(自身):
        "拼出这份配置在文件里的来源栈帧"
        结果=[]#栈行
        当前=自身#从本层上溯
        while 当前 is not None:
            结果.append(f'    at {当前.父组.所属树.所属上下文.基准网址}#{当前.选项.get("id")}')#配置位置
            当前=当前.父组.所属上下文.纤程.插件配置#父插件配置
        return 结果#外层栈

    #============================== 生命周期 ==============================
    def 刷新(自身):
        "还没跑起来、又没被禁用时启动这份配置"
        if 自身.纤程 is not None or 自身.已禁用:
            return#已经在跑，或者被禁用了
        自身.初始化()#导入并启动

    def 初始化(自身):
        "导入并启动已配置的插件，再把它的启动错误取出来"
        自身._导入并启动()#实际导入与启动
        自身._等待()#取出纤程的启动错误

    def _导入并启动(自身):
        "导入插件模块再启动它"
        try:
            插件=自身.加载器.解开导出(自身.父组.所属树.导入(自身.选项.get('name'),自身.取外层栈()))#导入
        except BaseException as 错误:
            raise 更新错误('导入',自身.选项,错误)#导入失败
        try:
            自身._启动(插件)#启动
        except BaseException as 错误:
            raise 更新错误('应用',自身.选项,错误)#启动失败

    def _启动(自身,插件):
        "补丁上下文、启动插件，插件回调在启动插件里同步跑完"
        纤程=None#启动中的纤程
        try:
            自身._补丁上下文([])#先按当前选项补丁上下文
            自身.加载器.显示日志(自身,'apply')#应用日志
            纤程=自身.纤程=自身.所属上下文.注册表.启动插件(插件,自身.选项.get('config'),自身.取外层栈())#启动插件
            纤程.等待()#启动失败就把错误抛出来
        except BaseException:
            自身._拆除(纤程)#启动失败就把半成品拆掉
            raise

    def _等待(自身):
        "取出纤程的启动错误，收成应用错误"
        if 自身.纤程 is None:
            return#没有在跑的纤程
        try:
            自身.纤程.等待()#取出启动错误
        except BaseException as 错误:
            raise 更新错误('应用',自身.选项,错误)#应用失败

    def _拆除(自身,纤程=None):
        "拆掉指定纤程，期间把本层标记为正在拆除"
        纤程=纤程 if 纤程 is not None else 自身.纤程#默认拆当前纤程
        if 纤程 is None:
            return#没有可拆的纤程
        if 自身.纤程 is 纤程:
            自身.纤程=None#先摘掉指针
        自身._拆除中+=1#进入拆除
        try:
            纤程.拆除()#拆除纤程
        finally:
            自身._拆除中-=1#离开拆除

    def _补丁上下文(自身,变化键们):
        "瀑布式补丁本层上下文，必要时把新配置推给纤程"
        def 内建(插件配置对象,续体):
            "瀑布链走完后重挂上下文原型并按需更新配置"
            cordis.设置内部数据(自身.所属上下文,'父上下文',自身.父组.所属上下文)#重挂到当前父组
            纤程=自身.纤程#当前纤程
            if 纤程 is not None and 纤程.编号 is not None and ('config' in 变化键们 or 自身.选项.get('group')):
                纤程.更新(自身.选项.get('config'),True)#更新配置但不写回文件
        自身.事件上下文.链式拦截('loader/patch-context',自身,内建)#允许隔离钩子接管

    #============================== 更新 ==============================
    def 更新(自身,选项,创建=False,强制=False):
        "合并新选项，按变化决定就地补丁还是换插件重启，再由父树持久化"
        原选项=自身.选项#提交前的选项对象
        旧快照=dict(原选项)#变化对比用的快照
        候选=排序键(选项 if 创建 else _合并选项(原选项,选项))#新选项
        变化键们=[键 for 键 in dict.fromkeys(list(候选)+list(旧快照)) if not cosmokit.深入比较(候选.get(键),旧快照.get(键))]#变化的键
        if not 变化键们 and not 强制:
            return#什么都没变
        def 提交():
            "把候选选项落到原选项对象上，保持对象身份"
            if not 创建:
                自身.选项=替换键(原选项,候选)#原地替换键
        旧纤程=自身.纤程 if 自身.纤程 is not None and 自身.纤程.编号 is not None else None#更新前还活着的纤程
        if 旧纤程 is None:
            自身._更新且无旧纤程(候选,原选项,提交)#没有在跑的纤程
            return
        if 自身._已禁用(候选):
            自身._更新至禁用(候选,原选项,旧快照,提交,旧纤程)#新选项要求停掉
            return
        if not any(键 in ('name','inject','group') for 键 in 变化键们):
            自身._更新且就地补丁(候选,原选项,旧快照,提交,变化键们)#插件不用换
            return
        自身._更新且换插件(候选,原选项,旧快照,提交,旧纤程,变化键们)#要换插件

    def _更新且无旧纤程(自身,候选,原选项,提交):
        "更新前没有在跑的纤程，需要的话直接启动"
        自身.纤程=None#丢掉已释放的纤程
        自身.选项=候选#先按候选跑
        try:
            if not 自身._已禁用(候选):
                自身.初始化()#启动
        except BaseException:
            自身.选项=原选项#回滚选项
            raise
        提交()#提交候选

    def _更新至禁用(自身,候选,原选项,旧快照,提交,旧纤程):
        "新选项要求停掉这份配置"
        自身.选项=候选#先按候选跑
        try:
            自身._拆除(旧纤程)#拆掉旧纤程
        except BaseException as 错误:
            自身.选项=原选项#回滚选项
            raise 更新错误('拆除',候选,错误)
        提交()#提交候选
        自身.事件上下文.广播('loader/partial-dispose',自身,旧快照,True)#通知隔离钩子回收

    def _更新且就地补丁(自身,候选,原选项,旧快照,提交,变化键们):
        "插件不用换，只补丁上下文并把新配置推给纤程"
        自身.选项=候选#先按候选跑
        try:
            自身._补丁上下文(变化键们)#就地补丁
        except BaseException as 错误:
            自身.选项=原选项#回滚选项
            try:
                自身._补丁上下文(变化键们)#按旧选项再补一次
            except BaseException as 回滚错误:
                raise 更新错误('回滚',旧快照,cordis.聚合错误([错误,回滚错误]))
            自身.事件上下文.广播('loader/partial-dispose',自身,候选,True)#通知隔离钩子回收
            raise 更新错误('应用',候选,错误)
        提交()#提交候选
        自身.事件上下文.广播('loader/partial-dispose',自身,旧快照,True)#通知隔离钩子回收

    def _更新且换插件(自身,候选,原选项,旧快照,提交,旧纤程,变化键们):
        "插件名或依赖变了，拆掉旧纤程再用新插件启动"
        try:
            if 'name' in 变化键们:
                新插件=自身.加载器.解开导出(自身.父组.所属树.导入(候选.get('name'),自身.取外层栈()))#按新名导入
            else:
                新插件=旧纤程.运行时.回调#插件没换，沿用旧回调
        except BaseException as 错误:
            raise 更新错误('导入',候选,错误)
        旧插件=旧纤程.运行时.回调#回滚时用的旧插件
        自身.选项=候选#先按候选跑
        try:
            自身._拆除(旧纤程)#拆掉旧纤程
        except BaseException as 错误:
            自身.选项=原选项#回滚选项
            raise 更新错误('拆除',候选,错误)
        try:
            自身._启动(新插件)#用新插件启动
        except BaseException as 错误:
            自身.选项=原选项#回滚选项
            try:
                自身._启动(旧插件)#装回旧插件
            except BaseException as 回滚错误:
                raise 更新错误('回滚',旧快照,cordis.聚合错误([错误,回滚错误]))
            自身.事件上下文.广播('loader/partial-dispose',自身,候选,True)#通知隔离钩子回收
            raise 更新错误('应用',候选,错误)
        提交()#提交候选
        自身.事件上下文.广播('loader/partial-dispose',自身,旧快照,True)#通知隔离钩子回收
