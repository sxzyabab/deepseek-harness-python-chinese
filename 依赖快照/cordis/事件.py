"""事件总线：派发模式、监听器登记与上下文过滤。"""
import threading
from .工具 import (
    有序槽位表,#纤程本地钩子表
    聚合错误,#并发派发的失败聚合
    绑定对象,#把接收者绑成回调首参
    设置内部数据,#写内部数据面
    获取内部数据,#读内部数据面
    未传参,#缺成员时抛错而不是给默认值
    调用方上下文壳,#方法里的自身可能是壳
)

class 事件服务:
    """安装为 上下文.事件、并混入每个上下文的事件总线。插件够不着的成员一律放在内部数据面上。"""
    def __init__(自身,上下文):
        """把监听记录表与内部函数写进数据面，再挂上监听分流与本地更新两个内部钩子。"""
        自身.上下文=上下文#所属上下文
        设置内部数据(自身,'追踪器',{'追踪属性':'上下文'})#调用方上下文重绑
        设置内部数据(自身,'监听记录表',{})#事件名到监听记录列表
        设置内部数据(自身,'解析监听器',_解析监听器)#派发前的监听器解析
        自身.监听('internal/listener',_监听分流)#非全局的更新监听改挂纤程本地
        自身.监听('internal/update',_本地更新,{'全局':True,'前置':True})#先跑纤程本地更新钩子

    #============================== 派发 ==============================
    def 广播(自身,*位置参数):
        """同步跑完全部监听器，不看返回值。"""
        参数=list(位置参数)#解析会从中取走接收者与事件名
        for 回调 in _获取内部成员(自身,'解析监听器')(自身,'emit',参数):
            回调(*参数)#逐个同步调用

    def 并发广播(自身,*位置参数):
        """各监听器并发跑，全部结束后把失败聚合抛出。"""
        参数=list(位置参数)#解析会从中取走接收者与事件名
        回调们=_获取内部成员(自身,'解析监听器')(自身,'emit',参数)#本次要跑的回调
        失败们=[]#收集到的错误
        失败锁=threading.Lock()#保护失败列表
        def 跑监听器(回调):
            """在自己的线程里跑一个监听器。"""
            try:
                回调(*参数)#调用监听器
            except Exception as 错误:
                with 失败锁:
                    失败们.append(错误)#收集失败
        线程们=[threading.Thread(target=跑监听器,args=(回调,)) for 回调 in 回调们]#每个监听器一条线程
        for 线程 in 线程们:
            线程.start()#启动
        for 线程 in 线程们:
            线程.join()#等全部结束
        if 失败们:
            raise 聚合错误(失败们)#把失败一并抛出

    def 首个结果(自身,*位置参数):
        """按序跑监听器，谁先给出结果就把它当结果，后面的不再跑。派发模式记作 bail。"""
        参数=list(位置参数)#解析会从中取走接收者与事件名
        for 回调 in _获取内部成员(自身,'解析监听器')(自身,'bail',参数):
            结果=回调(*参数)#调用监听器
            if 结果 is not None and 结果 is not False:
                return 结果#空值与假当没给结果，其余提前给出

    def 链式拦截(自身,*位置参数):
        """把监听器一层层套在最内层续体外面，由监听器决定是否往下走。"""
        参数=list(位置参数)#解析会从中取走接收者与事件名
        回调们=_获取内部成员(自身,'解析监听器')(自身,'waterfall',参数)#由外到内
        内建行为=参数.pop()#最内层续体
        def 续体(*_忽略位置参数):
            """还有监听器就交给下一个，都走完了才进内建行为。"""
            if 回调们:
                return 回调们.pop(0)(*参数)#下一个监听器
            return 内建行为(*参数)#落到内建行为
        参数.append(续体)#监听器的最后一个参数是续体
        return 续体()#从最外层开始

    #============================== 登记 ==============================
    def 监听(自身,事件名,监听器,选项=None):
        """登记一个由当前纤程持有的事件监听器，纤程卸载时自动注销。"""
        选项=选项 if isinstance(选项,dict) else {'前置':bool(选项)}#布尔值解释为前置
        自身.上下文.纤程.断言活动()#已释放的纤程不能再登记
        监听器=自身.上下文.反射.绑定上下文(监听器)#参数追踪到本上下文
        接管释放器=自身.首个结果(自身.上下文,'internal/listener',事件名,监听器,选项)#允许核心接管登记
        if 接管释放器:
            return 接管释放器#接管者交出的释放器
        记录们=_获取内部成员(自身,'监听记录表').setdefault(事件名,[])#该事件的全局监听记录
        登记方=自身.上下文#登记方上下文，自身是壳时读出来就是调用方的
        def 执行体():
            """写入监听记录，返回删掉它的释放器。"""
            记录={'上下文':登记方,'回调':监听器,'全局':bool(选项.get('全局'))}#监听记录
            if 选项.get('前置'):
                记录们.insert(0,记录)#插到最前
            else:
                记录们.append(记录)#追加到最后
            def 释放():
                """纤程卸载时按回调身份删掉这条记录。"""
                for 下标 in range(len(记录们)):
                    if 记录们[下标]['回调'] is 监听器:
                        记录们.pop(下标)#按身份删除
                        return
            return 释放#释放器
        return 登记方.纤程.副作用(执行体,f'上下文.监听({事件名!r})')#作为纤程副作用

    def 监听一次(自身,事件名,监听器,选项=None):
        """登记一个跑过一次就自行注销的监听器。"""
        释放器盒=[]#登记完才能拿到释放器
        def 一次性监听器(*位置参数):
            """先把自己卸掉，再跑原始监听器。"""
            if 释放器盒:
                释放器盒[0]()#卸掉自己
            return 监听器(*位置参数)#跑原始监听器
        释放器=自身.监听(事件名,一次性监听器,选项)#登记
        释放器盒.append(释放器)#让一次性回调能卸掉自己
        return 释放器#也可以提前取消

#============================== 内部函数 ==============================
def _获取内部成员(对象,成员名,默认值=未传参):
    """从内部数据面读出成员。对象是壳时落到它包着的原目标上；不给默认值时缺成员就抛错。"""
    if isinstance(对象,调用方上下文壳):
        对象=object.__getattribute__(对象,'_原目标')#壳自己不存数据
    return 获取内部数据(对象,成员名,默认值)#内部成员

def _解析监听器(总线,派发模式,参数列表):
    """取出派发接收者与事件名，按上下文过滤解析出本次要跑的回调。"""
    派发对象=None#派发接收者
    if 参数列表 and not isinstance(参数列表[0],(str,bytes,bool,int,float)):
        派发对象=参数列表.pop(0)#首参不是原始值就当接收者，空值也算，对应 JavaScript 里的 null
    事件名=参数列表.pop(0)#事件名
    if isinstance(事件名,str) and not 事件名.startswith('internal/'):
        总线.广播('internal/dispatch',派发模式,事件名,list(参数列表),派发对象)#诊断事件
    过滤器=None#接收者自带的过滤器
    if 派发对象 is not None:
        过滤器=_获取内部成员(派发对象,'过滤器',None)#接收者在内部数据面上声明的准入判定
    回调们=[]#本次要跑的回调
    for 记录 in list(_获取内部成员(总线,'监听记录表').get(事件名) or []):
        是否通过=bool(记录.get('全局'))#全局监听不受过滤影响
        if not 是否通过 and 过滤器 is not None:
            是否通过=getattr(过滤器,'__func__',过滤器)(派发对象,记录['上下文'])#让接收者决定
        elif not 是否通过:
            是否通过=True#没有过滤器就都通过
        if 是否通过:
            回调们.append(绑定对象(记录['回调'],派发对象))#绑上接收者
    return 回调们#回调列表

def _监听分流(上下文对象,事件名,监听器,选项):
    """非全局的 internal/update 监听改挂到纤程本地，只对该纤程生效。"""
    if 事件名!='internal/update' or 选项.get('全局'):
        return None#其余走默认登记
    纤程钩子表=获取内部数据(上下文对象.纤程,'钩子表')#该纤程的本地事件钩子
    钩子表=纤程钩子表.get('internal/update')#本事件的钩子表
    if 钩子表 is None:
        钩子表=有序槽位表()#新建
        纤程钩子表['internal/update']=钩子表#挂到纤程
    return 钩子表.前插(监听器) if 选项.get('前置') else 钩子表.压入(监听器)#登记并交出释放器

def _本地更新(纤程对象,配置,不保存,续体):
    """更新瀑布最外层：先跑完该纤程本地的更新钩子，再进内建行为。"""
    本地钩子们=list(获取内部数据(纤程对象,'钩子表').get('internal/update') or [])#本轮的本地钩子
    def 本地续体(*_忽略位置参数):
        """还有本地钩子就交给下一个，都走完了才回到内建续体。"""
        if 本地钩子们:
            return 本地钩子们.pop(0)(纤程对象,配置,不保存,本地续体)#下一个本地钩子
        return 续体()#回到内建续体
    return 本地续体()#从第一个本地钩子开始
