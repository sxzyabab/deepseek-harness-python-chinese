def 带应用方法(插件):
    "对象形态的插件必须带 应用 方法"
    if 插件 is None or isinstance(插件,(str,bytes,bool,int,float)):
        return False#原始值不是插件
    return callable(getattr(插件,'应用',None))#带应用方法

def 声明依赖(服务名,配置=None):
    "在插件类上声明一项服务依赖的装饰器"
    def 装饰器(类):
        if not isinstance(类,type):
            raise TypeError('依赖声明只能用在插件类上')#只支持类
        if '依赖声明' not in 类.__dict__:
            继承=getattr(类,'依赖声明',None)#父类上的依赖声明
            类.依赖声明=dict(继承) if isinstance(继承,dict) else {}#本类新建一份
            类.依赖声明['检查原型']=True#标记需要沿原型链合并
        类.依赖声明[服务名]=配置#该依赖的拦截配置
        return 类#原类
    return 装饰器

def 收成依赖表(声明,结果=None):
    "把列表、映射或类继承来的依赖声明收成 服务名→拦截配置"
    if 结果 is None:
        结果={}#新建结果表
    if not 声明:
        return 结果#没有声明
    if isinstance(声明,list):
        for 服务名 in 声明:
            结果[服务名]=None#列表形态不带拦截配置
        return 结果
    if isinstance(声明,dict):
        for 服务名 in 声明:
            if 服务名=='检查原型':
                continue#跳过合并标记
            结果[服务名]=声明[服务名]#带拦截配置
    return 结果

class 带依赖的插件:
    "把一个回调包成带依赖声明的对象插件"
    def __init__(自身,依赖声明,回调):
        自身.依赖声明=依赖声明#服务依赖
        自身.应用=回调#插件入口
        自身.插件名=getattr(回调,'__name__',None)#显示名

class 插件注册表:
    "安装为 上下文.注册表 的插件登记表"
    def __init__(自身,上下文):
        自身.所属上下文=上下文#所属上下文
        设置内部数据(自身,'追踪器',{'追踪属性':'所属上下文'})#调用方上下文重绑
        自身._编号计数=0#纤程编号计数器
        自身._运行记录表={}#插件回调→运行记录

    @property
    def 下一编号(自身):
        "分配下一个纤程编号，从 1 起"
        自身._编号计数+=1#先自增
        return 自身._编号计数#新编号

    @property
    def 数量(自身):
        "已登记的插件运行记录数"
        return len(自身._运行记录表)

    def 取身份回调(自身,插件):
        "把插件收成用作身份的可执行回调"
        if 带应用方法(插件):
            return 插件.应用#对象插件取应用方法
        if callable(插件):
            return 插件#类插件与函数插件本身就是回调
        return None#不是插件

    def 取运行记录(自身,插件):
        "查出该插件的运行记录"
        回调=自身.取身份回调(插件)#身份回调
        return 自身._运行记录表.get(回调) if 回调 else None

    def 已登记(自身,插件):
        "该插件是否已有运行记录"
        回调=自身.取身份回调(插件)#身份回调
        return bool(回调) and 回调 in 自身._运行记录表

    def 删掉插件(自身,插件):
        "拆掉该插件的全部纤程并删除运行记录"
        回调=自身.取身份回调(插件)#身份回调
        记录=自身._运行记录表.pop(回调,None) if 回调 else None#摘下记录
        if 记录 is None:
            return None#没有登记
        for 一条 in list(记录.纤程表):
            一条.拆除()#逐条卸载
        return 记录

    def 全部回调(自身):
        "已登记的插件回调列表"
        return list(自身._运行记录表)

    def 全部运行记录(自身):
        "已登记的运行记录列表"
        return list(自身._运行记录表.values())

    def 等依赖齐再启动(自身,依赖声明,回调):
        "等所需依赖都可用之后再启动回调"
        return 自身.启动插件(带依赖的插件(依赖声明,回调))#包成对象插件后启动

    def 启动插件(自身,插件,配置=None,外层栈=None):
        "在当前上下文启动插件，返回它的纤程"
        if 外层栈 is None:
            外层栈=构建外层栈()#捕获调用方调用栈
        回调=自身.取身份回调(插件)#身份回调
        if 回调 is None:
            raise TypeError('插件必须是函数、类，或带 应用 方法的对象，收到的是 '+type(插件).__name__)
        自身.所属上下文.纤程.拒绝已失活()#已释放的纤程不能再挂插件
        记录=自身._运行记录表.get(回调)#已有记录
        if 记录 is None:
            名称=getattr(插件,'插件名',None) or getattr(插件,'__name__',None)#显示名
            记录={'名称':名称,'回调':回调,'配置模式':getattr(插件,'配置模式',None)}#新建
            自身._运行记录表[回调]=记录#以身份回调为键登记
        return 纤程(自身.所属上下文,配置,收成依赖表(getattr(插件,'依赖声明',None)),记录,外层栈)#启动新纤程
