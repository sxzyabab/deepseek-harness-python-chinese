"""插件的根容器与子作用域容器。"""
from types import MethodType as 绑定方法#把内部数据面上的函数绑到实例
from ..工具 import (
    差分映射,#本层叠父层的属性字典
    未命中,#沿链查找的未命中哨兵
    私有键清单,#内部槽名
    设置内部数据,获取内部数据,#内部槽读写
    自由点访问空间,是双下划线字符串,#不经反射的.读写
)

def 是上下文(值):
    "传入对象带上下文标记时为真"
    if 值 is None:
        return False#空值
    return 获取内部数据(值,'是上下文',None) is True#品牌

class 上下文(自由点访问空间):
    "插件的根容器与子作用域容器"
    def __init__(自身):
        "创建根上下文并装上内建服务"
        from .纤程 import 纤程#根纤程
        from .反射 import 反射服务#服务读写
        from .注册表 import 插件注册表#插件登记
        from .事件 import 事件服务#事件派发
        from .日志 import 日志服务#日志门面
        属性链=差分映射()#根本层属性字典
        设置内部数据(自身,'属性链',属性链)#挂到内部数据面
        设置内部数据(自身,'是上下文',True)#上下文品牌
        属性链['隔离']=差分映射()#空隔离表
        属性链['拦截']=差分映射()#空拦截表
        根纤程=纤程(自身,{},{},None,[])#根纤程，没有外层调用栈
        属性链['根']=自身#根引用指向自身
        属性链['基准网址']=None#根上下文没有基准网址
        属性链['纤程']=根纤程#根纤程
        属性链['反射']=反射服务(自身)#服务读写
        属性链['注册表']=插件注册表(自身)#插件登记
        属性链['事件']=事件服务(自身)#事件派发
        属性链['日志']=日志服务(自身)#日志门面
        获取内部数据(根纤程,'释放器').清空()#丢掉构造期收集到的副作用

    def __repr__(自身):
        纤程=获取内部数据(自身,'属性链').get('纤程')#所属纤程
        return f'上下文 <{纤程.名称 if 纤程 is not None else "?"}>'#展示文本

    def __getattribute__(自身,属性):
        if 是双下划线字符串(属性):
            return 自由点访问空间.__getattribute__(自身,属性)#双下名走自由点访问
        值=上下文.__dict__.get(属性,未命中)#类上的公开方法
        if 值 is not 未命中:
            return 绑定方法(值,自身)#绑到当前实例再交出
        from .反射 import 反射服务#服务读写
        return 反射服务.取属性(自身,属性)#走服务解析

    def __setattr__(自身,属性,值):
        if 是双下划线字符串(属性):
            自由点访问空间.__setattr__(自身,属性,值)#双下名走自由点访问
            return
        from .反射 import 反射服务#服务读写
        反射服务.写属性(自身,属性,值)#走服务解析

    def __contains__(自身,属性):
        from .反射 import 反射服务#服务读写
        return 反射服务.有属性(自身,属性)#是否可读

    def __getitem__(自身,键):
        if isinstance(键,str) and 键 not in 私有键清单:
            return getattr(自身,键)#公开字符串键走服务解析
        值=获取内部数据(自身,'属性链').get(键,未命中)#内部槽与非字符串键沿属性链取
        if 值 is 未命中:
            raise KeyError(键)#链上没有该键
        return 值#命中值

    def __setitem__(自身,键,值):
        if isinstance(键,str) and 键 not in 私有键清单:
            setattr(自身,键,值)#公开字符串键走服务解析
            return
        获取内部数据(自身,'属性链')[键]=值#内部槽与非字符串键只落本层

    def 扩展(自身,额外属性=None):
        "叠一本连着父表的属性字典，得到子上下文"
        子=object.__new__(上下文)#不走构造
        设置内部数据(子,'父上下文',自身)#保留父上下文引用
        设置内部数据(子,'是上下文',True)#上下文品牌
        父表=获取内部数据(自身,'属性链')#父层字典
        子表=差分映射(父表)#本层叠父表
        设置内部数据(子,'属性链',子表)#挂到内部数据面
        子表['隔离']=差分映射(父表['隔离'])#本层隔离表，键叠祖先
        子表['拦截']=差分映射(父表['拦截'])#本层拦截表，键叠祖先
        for 键 in 额外属性 or {}:
            子表[键]=额外属性[键]#额外自有键落本层
        return 子#子上下文

    def 隔离(自身,服务名,标签=None):
        "开一个把该服务放进独立作用域的子上下文"
        子=自身.扩展()#叠一层
        获取内部数据(子,'属性链')['隔离'][服务名]=标签 if 标签 is not None else object()#写入本层隔离键
        return 子#隔离子上下文

    def 拦截(自身,服务名,配置):
        "开一个给该服务追加拦截配置的子上下文，其下启动的插件可见"
        子=自身.扩展()#叠一层
        获取内部数据(子,'属性链')['拦截'][服务名]=配置#写入本层拦截键
        return 子#拦截子上下文
