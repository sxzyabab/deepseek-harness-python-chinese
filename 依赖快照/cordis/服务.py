"""服务基类：把实例以服务名登记到上下文，并按纤程生命周期注销。"""
from ..工具 import 设置内部数据,获取内部数据#共享标记读写

class 服务:
    """在上下文上暴露具名 API 的服务基类。插件够不着的成员一律放在内部数据面上。"""
    初始化='初始化'#依赖就绪后才跑的初始化方法
    检查='检查'#自报可用性的判断
    调用='调用'#可调用服务的调用体
    追踪器='追踪器'#追踪器元数据

    def __init__(自身,上下文,服务名=None):
        """把本实例以服务名登记进当前上下文。"""
        if 服务名 is None:
            服务名=getattr(type(自身),'提供服务名',None)#回落到类上声明的服务名
        自身.所属上下文=上下文#所属上下文
        自身.名称=服务名#服务名
        设置内部数据(自身,'追踪器',{'关联服务':服务名,'追踪属性':'所属上下文'})#调用方上下文重绑
        设置内部数据(自身,'过滤器',_按隔离过滤)#事件派发到本服务时的准入判定
        设置内部数据(自身,'扩展',_扩展)#派生扩展实例
        设置内部数据(自身,'解析配置',_解析配置)#合并拦截配置
        上下文.反射.提供服务(服务名,自身,获取内部数据(自身,'检查',None))#按纤程生命周期登记

#============================== 内部函数 ==============================
def _按隔离过滤(服务,上下文对象):
    """只接收隔离标签与本服务一致的上下文发来的事件。"""
    对方=获取内部数据(上下文对象,'属性链')['隔离'].get(服务.名称)#对方标签
    本方=获取内部数据(服务.所属上下文,'属性链')['隔离'].get(服务.名称)#本方标签
    return 对方 is 本方#同一隔离作用域

def _扩展(服务,属性表=None):
    """派生一份共享状态、但带额外属性的扩展实例。"""
    子=object.__new__(type(服务))#不走构造
    子.__dict__.update(服务.__dict__)#共享原实例的字段
    子.__dict__.update(属性表 or {})#叠上额外属性
    return 子#扩展实例

def _解析配置(服务,底配置=None,顶配置=None):
    """把祖先的拦截配置与可选的底、顶配置合并成本服务的有效配置。"""
    配置们=[]#由底到顶
    if 底配置:
        配置们.append(底配置)#最先被覆盖
    配置们.extend(获取内部数据(服务.所属上下文,'属性链')['拦截'].清点全链值(服务.名称))#祖先到本层的每一层拦截配置
    if 顶配置:
        配置们.append(顶配置)#覆盖其余
    合并器=getattr(getattr(服务,'配置模式',None),'合并',None)#配置模式自带的合并器
    if 合并器 is not None:
        return 合并器(*配置们)#按模式合并
    结果={}#浅合并结果
    for 项 in 配置们:
        if isinstance(项,dict):
            结果.update(项)#后来的覆盖先前的
    return 结果#有效配置
