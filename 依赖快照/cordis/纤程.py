class 纤程校验错误(TypeError):
    """插件配置没通过 Config 模式校验。"""
    def __init__(自身,问题列表):
        """把逐条问题拼成一条聚合消息。"""
        super().__init__('配置非法：\n'+'\n'.join('  - '+str(项) for 项 in 问题列表))#聚合消息
        自身.问题列表=list(问题列表)#逐条问题

def 纤程解析配置(运行时,配置):
    """插件启动前按 Config 模式校验并归一化配置。"""
    模式实例=运行时.配置模式 if 运行时 is not None else None#插件声明的模式
    if 模式实例 is None:
        return 配置#没有模式，配置原样透传
    try:
        return 模式实例(配置)#校验并归一化
    except Exception as 原因:
        raise 纤程校验错误([原因]) from 原因#收成框架错误

class Cordis错误(Exception):
    """带稳定错误码的框架错误。"""
    码表={'INACTIVE_EFFECT':'不能在已失活的上下文上登记副作用'}#错误码到默认消息

    def __init__(自身,码,消息=None):
        """未传消息时用错误码对应的默认文案。"""
        super().__init__(消息 if 消息 is not None else 自身.码表.get(码,码))#错误消息
        自身.码=码#机器可读错误码

class 纤程状态:
    """一条插件纤程的生命周期状态。"""
    等待=0#依赖还没齐
    加载中=1#正在跑插件回调
    已激活=2#插件在运行
    失败=3#启动时抛了错
    已释放=4#已经拆掉
    卸载中=5#正在跑释放器

