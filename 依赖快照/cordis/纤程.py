def _建立根纤程(纤程对象,父上下文):
    """根纤程一开始就是激活态，只负责收集根上下文的副作用。"""
    纤程对象.编号=0#根编号
    纤程对象.上下文=纤程对象.事件上下文=父上下文#根纤程直接用根上下文
    纤程对象.状态=纤程状态.已激活#根纤程不等依赖
    纤程对象.快照={}#根纤程没有依赖实现
    设置内部数据(纤程对象,'世代','')#空世代表示已激活
    纤程对象.拆除=纤程对象.重启#根纤程的拆除就是重启

def _建立插件纤程(纤程对象,父上下文,依赖表,运行时):
    """分配编号、建插件上下文，再按依赖决定是否立刻加载。"""
    纤程对象.编号=父上下文.注册表.下一编号#分配纤程编号
    纤程对象.上下文=纤程对象.事件上下文=父上下文.扩展({'纤程':纤程对象})#插件上下文
    _写入依赖拦截(纤程对象,依赖表)#把依赖声明里的拦截配置落到上下文
    纤程对象.拆除=父上下文.纤程.副作用(_建立拆除体(纤程对象,运行时),'上下文.启动插件()')#挂到父纤程
    try:
        纤程对象.事件上下文.广播('internal/plugin',纤程对象)#公布纤程创建
    except Exception as 错误:
        try:
            纤程对象.拆除()#创建通知失败，回滚这条纤程
        except Exception as 原因:
            纤程对象.上下文.日志.错误(原因)#回滚也失败，记下后仍抛原错误
        raise 错误
    if 纤程对象.编号 is None or 父上下文.纤程.状态==纤程状态.卸载中:
        return#创建过程中已被拆掉，或父纤程正在卸载
    for 服务名 in list(依赖表):
        _核对实现(纤程对象,服务名)#先核对一遍依赖
    _刷新(纤程对象)#依赖齐了就加载

def _写入依赖拦截(纤程对象,依赖表):
    """把依赖声明里带的拦截配置写进插件上下文的拦截表。"""
    带配置=[(名称,依赖表[名称]) for 名称 in 依赖表 if 依赖表[名称] is not None]#只有带配置的才需要写
    if not 带配置:
        return#依赖都没带拦截配置
    表=获取内部数据(纤程对象.上下文,'属性链')['拦截']#扩展时已叠好的本层差分拦截表
    for 名称,配置项 in 带配置:
        表[名称]=配置项#写入本层拦截配置

def _建立拆除体(纤程对象,运行时):
    """返回登记在父纤程上的拆除体，拆除时卸载本插件。"""
    def 拆除体():
        """把自己登记进插件运行时，返回卸载用的释放器。"""
        摘掉纤程=运行时.纤程表.压入(纤程对象)#登记本纤程
        def 释放():
            """卸载插件，运行时没有存活纤程时一并删掉。"""
            纤程对象.编号=None#标记已释放
            发出插件拆除(纤程对象.事件上下文,纤程对象)#通知观察者
            if 纤程对象.上下文.注册表.有(运行时.回调):
                摘掉纤程()#从运行时的纤程表摘掉
                if not list(运行时.纤程表):
                    纤程对象.上下文.注册表.删除(运行时.回调)#最后一条纤程走了就删运行时
            if 获取内部数据(纤程对象,'世代')==未激活标记 and not 获取内部数据(纤程对象,'过渡中'):
                _卸载(纤程对象)#依赖本来就没齐，世代不会再变，直接排空已登记的副作用
            else:
                _设世代(纤程对象,未激活标记)#切到未激活，触发卸载
        return 释放#释放器
    return 拆除体#拆除体

def _取状态(纤程对象):
    """按当前字段推导生命周期状态。"""
    if 纤程对象.编号 is None:
        return 纤程状态.已释放#编号清空即已释放
    if 获取内部数据(纤程对象,'错误'):
        return 纤程状态.失败#启动时抛过错
    if 获取内部数据(纤程对象,'世代')!=未激活标记:
        return 纤程状态.已激活#世代有效即在运行
    return 纤程状态.等待#依赖还没齐

def _更新状态(纤程对象,指定=None):
    """写入新状态，不指定就按当前字段推导。状态变了就广播并唤醒依赖方。"""
    旧状态=纤程对象.状态#变更前状态
    纤程对象.状态=指定 if 指定 is not None else _取状态(纤程对象)#新状态
    if 旧状态==纤程对象.状态:
        return#状态没变
    纤程对象.事件上下文.广播('internal/status',纤程对象,旧状态)#广播状态变迁
    if 旧状态!=纤程状态.已激活 and 纤程对象.状态!=纤程状态.已激活:
        return#本纤程提供的服务可见性没变
    for 实现 in list(纤程对象.上下文.反射.存储.values()):
        if 实现.纤程 is 纤程对象:
            纤程对象.上下文.反射.通知([实现.名称])#唤醒依赖本纤程所提供服务的插件

def _核对实现(纤程对象,服务名):
    """核对该依赖当前是否可用，结果写进工作快照。"""
    工作快照=获取内部数据(纤程对象,'工作快照')#依赖实现的最新核对结果
    实现=纤程对象.上下文.反射.获取服务实现(服务名,True)#只认已激活的提供方
    if 实现 is None:
        工作快照.pop(服务名,None)#没有提供方
        return
    if 实现.检查 is not None:
        try:
            接收者=套上调用方上下文(纤程对象.上下文,实现.值)#谓词要按依赖方上下文判断，依赖里带的拦截配置才可见
            可用=实现.检查.__func__(接收者) if getattr(实现.检查,'__self__',None) is 实现.值 else 实现.检查()#提供方自报可用性
        except Exception as 错误:
            实现.纤程.上下文.日志.错误(错误)#谓词自身抛错，算作不可用
            工作快照.pop(服务名,None)
            return
        if not 可用:
            工作快照.pop(服务名,None)#提供方自报不可用
            return
    工作快照[服务名]=实现#依赖可用

def _刷新(纤程对象):
    """按工作快照重算世代，决定该加载还是该卸载。"""
    工作快照=获取内部数据(纤程对象,'工作快照')#依赖实现的最新核对结果
    世代=''#从空世代开始
    for 服务名 in list(纤程对象.依赖表):
        实现=工作快照.get(服务名)#该依赖的实现
        if 实现 is None:
            世代=未激活标记#有依赖没齐，不能激活
            break
        世代+=':'+str(实现.纤程.编号)#世代由提供方编号拼成
    _设世代(纤程对象,世代)#按新世代切换

def _设世代(纤程对象,世代):
    """世代变了就启动一次加载或卸载过渡。"""
    旧世代=获取内部数据(纤程对象,'世代')#变更前世代
    if 世代==旧世代:
        return#世代没变
    设置内部数据(纤程对象,'世代',世代)#先写入新世代
    if 获取内部数据(纤程对象,'过渡中'):
        return#已有过渡在跑，它跑完会自己看新写入的世代
    _跑过渡(纤程对象,旧世代)#启动过渡

def _跑过渡(纤程对象,旧世代):
    """交替加载与卸载，直到插件跑的正是当前这一代依赖。插件回调与释放器都在这里同步跑完。"""
    设置内部数据(纤程对象,'过渡中',True)#挡住过渡期间的重入，插件回调与释放器改到的世代由本循环收尾
    已加载=旧世代!=未激活标记#进入过渡时插件是否在运行
    加载世代=旧世代#插件当前跑的是哪一代依赖
    try:
        while True:
            当前世代=获取内部数据(纤程对象,'世代')#插件回调与释放器都可能改到它，每轮重读
            if 已加载:
                if 当前世代==加载世代:
                    return#跑的就是当前这一代，过渡结束
                _更新状态(纤程对象,纤程状态.卸载中)#换代与拆除都要先卸载
                _卸载(纤程对象)#跑释放器
                已加载=False#插件停了
                continue
            if 当前世代==未激活标记:
                return#依赖没齐，本来就该停着，过渡结束
            加载世代=当前世代#记下本轮跑的是哪一代
            _更新状态(纤程对象,纤程状态.加载中)#广播加载态
            _加载(纤程对象)#跑插件回调，失败时它把世代打回未激活，下一轮会卸掉半成品
            已加载=True#插件跑起来了
    finally:
        设置内部数据(纤程对象,'过渡中',False)#过渡结束，之后的世代变化要另起一次过渡
        _更新状态(纤程对象)#按落定后的字段广播状态

def _解析配置(纤程对象,配置):
    """先让监听器改写配置，再按 Config 模式校验。"""
    def 内建(配置,续体):
        """瀑布链走完后交出配置本身。"""
        return 配置#不再改写
    配置=纤程对象.事件上下文.链式拦截(纤程对象,'internal/config',配置,内建)#允许拦截改写
    return 纤程解析配置(纤程对象.运行时,配置)#按模式校验

def _加载(纤程对象):
    """冻结依赖快照，跑插件回调并收集副作用。"""
    def 跑插件回调():
        """按函数插件或类插件的形态调用入口。"""
        回调=纤程对象.运行时.回调#插件入口
        if not isinstance(回调,type):
            return 回调(纤程对象.上下文,纤程对象.配置)#函数插件
        实例=回调(纤程对象.上下文,纤程对象.配置)#类插件先构造
        for 钩子 in 获取内部数据(实例,'初始化钩子',[]):
            钩子()#方法级钩子等依赖就绪后才跑
        初始化=获取内部数据(实例,'初始化',None)#类插件的初始化方法
        return 初始化() if 初始化 else None#初始化本身也可以交出释放器
    纤程对象.快照=dict(获取内部数据(纤程对象,'工作快照'))#冻结本轮依赖实现
    try:
        纤程对象.配置=_解析配置(纤程对象,纤程对象.原始配置)#解析配置
        执行副作用体(跑插件回调,获取内部数据(纤程对象,'外层栈'),获取内部数据(纤程对象,'释放器').压入)#跑插件回调
        设置内部数据(纤程对象,'错误',None)#启动成功，清掉旧错误
    except Exception as 原因:
        纤程对象.上下文.日志.错误(原因)#记下启动错误
        设置内部数据(纤程对象,'错误',原因)#保存供 等待() 重抛
        设置内部数据(纤程对象,'世代',未激活标记)#回到未激活，过渡循环会接着卸载

def _卸载(纤程对象):
    """跑掉全部释放器并清掉加载快照。"""
    外层栈=获取内部数据(纤程对象,'外层栈')#登记点调用栈
    for 释放器 in 获取内部数据(纤程对象,'释放器').清空():
        try:
            运行_自带错误栈(释放器,外层栈)#把登记点的调用栈挂到错误上
        except Exception as 原因:
            纤程对象.上下文.日志.错误(原因)#单个释放器失败，记下后继续卸载其余
    纤程对象.快照=None#清掉加载快照
