def _格式化对象(值,导出器=None,消息=None):
    "按 %o 与 %O 序列化成 JSON，不能序列化的退回文本展示"
    try:
        return json.dumps(值,default=str,ensure_ascii=False)#JSON
    except Exception:
        return str(值)#连 default 都处理不了的对象只能文本展示
截断整数=lambda 值,导出器=None,消息=None: math.trunc(float(值))#%d 与 %i 共用，向零截断
默认格式化器={
    's':lambda 值,导出器=None,消息=None: str(值),#字符串
    'd':截断整数,#整数
    'i':截断整数,#整数
    'f':lambda 值,导出器=None,消息=None: float(值),#浮点
    'o':_格式化对象,#对象
    'O':_格式化对象,#对象
    'c':lambda 值,导出器=None,消息=None: '',#丢掉 CSS 样式
    'C':lambda 值,导出器,消息:日志器.着色(导出器,日志器.色号(消息.名称,导出器.色深),值),#按日志器名着色
}#printf 占位符到格式化函数

################################ 日志器 ################################
class 日志器:
    """某一具名子系统的日志门面。插件够不着的成员一律放在内部数据面上。"""
    @staticmethod
    def 着色(导出器,码,值,装饰=''):
        """导出器开了颜色就用 ANSI 序列包住值。"""
        色深=getattr(导出器,'色深',None)#导出器色深
        if not 色深:
            return str(值)#没开颜色
        前缀=str(码) if 码<8 else '8;5;'+str(码)#16 色或 256 色
        额外=';'+装饰 if 装饰 and 色深>=2 else ''#色深够才加额外样式
        return '\u001b[3'+前缀+额外+'m'+str(值)+'\u001b[0m'#着色文本

    @staticmethod
    def 色号(名称,色深=None):
        """把日志器名散列成稳定的调色板下标。"""
        #把名字压成有符号 32 位散列
        散列=0#多项式散列累加器
        for 字符 in 名称:
            散列=((散列<<3)-散列)+ord(字符)+13#与上游同一套散列
            散列=散列&0xffffffff#截成 32 位
            if 散列>=0x80000000:
                散列-=0x100000000#还原成有符号
        #按色深取色号表，再取模落到表内
        if not 色深:
            return None#没开颜色
        色号表=扩展色号 if 色深>=2 else 基础色号#按色深选色号表
        return 色号表[abs(散列)%len(色号表)]#色号表下标

    @staticmethod
    def 格式化(导出器,消息):
        """按 printf 占位符渲染记录，剩余参数空格拼到末尾。"""
        参数=list(消息.参数)#逐个消耗
        #首参是异常就展开栈；不是格式串就按对象占位
        if 参数 and isinstance(参数[0],BaseException):
            原错=参数[0]#首参是异常
            栈文本=''.join(traceback.format_exception(type(原错),原错,原错.__traceback__))#错误自身的栈
            调用栈=getattr(原错,'调用栈',None)#运行_自带错误栈挂上的副作用登记点调用栈
            参数[0]=栈文本+'登记于：\n'+''.join(调用栈) if 调用栈 else 栈文本#接上登记点
            参数.insert(0,'%s')#按字符串占位
        elif not 参数 or not isinstance(参数[0],str):
            参数.insert(0,'%o')#首参不是格式串就按对象占位
        #按占位符逐个消耗参数
        格式串=参数.pop(0)#取出格式串
        格式化器表=getattr(导出器,'格式化器表',None) or {}#导出器自定义格式化器
        def 替换(匹配):
            """渲染一个占位符。"""
            全文=匹配.group(0)#占位符全文
            字符=匹配.group(1)#占位符字符
            if 全文=='%%':
                return '%'#转义的百分号
            格式化=格式化器表.get(字符) or 默认格式化器.get(字符)#自定义优先
            if 格式化 is None:
                return 全文#不认识的占位符原样保留
            return str(格式化(参数.pop(0) if 参数 else None,导出器,消息))#消耗一个参数
        文本=re.sub(r'%([a-zA-Z%])',替换,格式串)#渲染占位符
        #剩余参数空格拼上，再按行长截断
        对象格式化=格式化器表.get('o') or 默认格式化器['o']#剩余参数按对象渲染
        for 项 in 参数:
            文本+=' '+str(对象格式化(项,导出器,消息) if isinstance(项,(dict,list)) else 项)#空格拼接
        上限=getattr(导出器,'行长上限',None) or 10240#单行长度上限
        return '\n'.join(行[:上限]+'...' if len(行)>上限 else 行 for 行 in 文本.splitlines())#逐行截断

    def __init__(自身,名称,级别,纤程,服务):
        """把本门面绑到日志服务上。"""
        自身.名称=名称#日志器名
        自身.级别=级别#该门面的默认阈值
        设置内部数据(自身,'纤程',纤程)#产生消息的纤程，弱引用
        设置内部数据(自身,'服务',服务)#所属日志服务

    def 错误(自身,*位置参数):
        """记一条错误。"""
        _记录(自身,'E',日志级别.错误,位置参数)#错误级

    def 信息(自身,*位置参数):
        """记一条信息。"""
        _记录(自身,'I',日志级别.信息,位置参数)#信息级

    def 警告(自身,*位置参数):
        """记一条警告。"""
        _记录(自身,'W',日志级别.警告,位置参数)#警告级

    def 调试(自身,*位置参数):
        """记一条调试信息。"""
        _记录(自身,'D',日志级别.调试,位置参数)#调试级

################################ 缓冲导出器 ################################
class 缓冲导出器:
    "保留最近n条记录"
    def __init__(自身,容量):
        """按容量建立环形缓冲。"""
        自身.色深=3#缓冲里保留完整着色
        自身.容量=容量#最多保留的条数
        自身.缓冲=[]#最近的记录

    def 导出(自身,消息):
        """追加记录并截掉超出容量的部分。"""
        自身.缓冲.append(消息)#追加
        if len(自身.缓冲)>自身.容量:
            自身.缓冲=自身.缓冲[-自身.容量:]#不用pop,防止偷偷改容量

################################ 日志服务 ################################
class 日志服务:
    """内建日志服务。调用 上下文.日志(名称) 拿到具名日志门面。插件够不着的成员一律放在内部数据面上。"""
    def __init__(自身,上下文):
        """安装带内存缓冲导出器的日志服务。"""
        自身.所属上下文=上下文#所属上下文
        设置内部数据(自身,'追踪器',{'追踪属性':'所属上下文'})#调用方上下文重绑
        设置内部数据(自身,'消息序号',0)#消息序号计数器
        设置内部数据(自身,'导出器序号',0)#导出器序号计数器
        设置内部数据(自身,'导出器表',{})#序号到导出器
        内建缓冲=缓冲导出器(1000)#最近若干条记录留在内存里
        设置内部数据(自身,'缓冲导出器',内建缓冲)#内建缓冲
        自身.登记导出器(内建缓冲)#登记内建缓冲

    def __call__(自身,名称=None):
        """按名字创建日志门面，不传名字就用当前纤程的显示名。"""
        #合并祖先到本层的日志拦截配置
        配置={}#祖先到本层的日志拦截配置合并结果
        for 项 in 获取内部数据(自身.所属上下文,'属性链')['拦截'].清点全链值('日志'):
            if isinstance(项,dict):
                配置.update(项)#越靠近本层的越晚覆盖
        #按名字或纤程显示名建门面
        纤程=自身.所属上下文.纤程#当前上下文所属纤程
        if 名称 is None:
            名称=配置.get('名称') or 统一为短横分隔(纤程.名称)#拦截配置指定的名字或纤程名
        return 日志器(名称,配置.get('级别'),弱引用(纤程),自身)#具名门面

    def 登记导出器(自身,导出器):
        """登记一个导出器，随当前纤程卸载而注销。"""
        导出器表=获取内部数据(_脱壳(自身),'导出器表')#序号到导出器
        def 执行体():
            """分配序号并登记，返回注销它的释放器。"""
            序号=_下一序号(自身,'导出器序号')#分配本条序号
            导出器表[序号]=导出器#登记
            def 释放():
                """按序号注销该导出器。"""
                导出器表.pop(序号,None)#注销
            return 释放#释放器
        return 自身.所属上下文.副作用(执行体,'上下文.日志.登记导出器()')#作为纤程副作用

    def 错误(自身,*位置参数):
        """用当前纤程的具名门面记一条错误。"""
        自身().错误(*位置参数)#先建门面

    def 信息(自身,*位置参数):
        """用当前纤程的具名门面记一条信息。"""
        自身().信息(*位置参数)#先建门面

    def 警告(自身,*位置参数):
        """用当前纤程的具名门面记一条警告。"""
        自身().警告(*位置参数)#先建门面

    def 调试(自身,*位置参数):
        """用当前纤程的具名门面记一条调试信息。"""
        自身().调试(*位置参数)#先建门面

################################ 内部函数 ################################
def _脱壳(值):
    """壳自己不存数据，取出被它包着的原对象。"""
    if isinstance(值,调用方上下文壳):
        return 获取内部数据(值,'代理目标')#落到被代理对象
    return 值#原对象

def _下一序号(服务,计数器名):
    """自增日志服务的内部计数器并交出新值。"""
    服务=_脱壳(服务)#计数器在原目标的数据面上
    序号=获取内部数据(服务,计数器名)+1#自增
    设置内部数据(服务,计数器名,序号)#写回
    return 序号#新序号

def _记录(门面,标记,级别,位置参数):
    """展开单个错误的成因与子错误，再发给每一个导出器。"""
    参数=list(位置参数)#本条参数
    #单参异常：先成因，再聚合子错误
    if len(参数)==1 and isinstance(参数[0],BaseException):
        成因=参数[0].__cause__#错误的直接成因
        if 成因 is not None:
            _记录(门面,标记,级别,(成因,))#先记成因
        elif isinstance(getattr(参数[0],'错误列表',None),list):
            for 子错误 in 参数[0].错误列表:
                _记录(门面,标记,级别,(子错误,))#逐条记子错误
            return#聚合本身不再输出
    #组装记录并按阈值发给各导出器
    服务=_脱壳(获取内部数据(门面,'服务'))#所属日志服务，建门面时拿到的可能是壳
    消息=日志消息(_下一序号(服务,'消息序号'),int(time.time()*1000),标记,级别,门面.名称,参数,获取内部数据(门面,'纤程'))#组装记录
    for 导出器 in list(获取内部数据(服务,'导出器表').values()):
        阈值表=getattr(导出器,'阈值表',None) or {}#导出器阈值表
        for 候选 in (阈值表.get(门面.名称),阈值表.get('default'),门面.级别,日志级别.信息):
            if 候选 is not None:
                if 候选>=级别:
                    导出器.导出(消息)#发给导出器
                break#按名、按默认、按门面、再信息级，取第一个非空
